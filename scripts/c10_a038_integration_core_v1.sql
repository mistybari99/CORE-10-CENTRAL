-- CORE10 C10-A038 Integration Ports core (v1): provider catalog, per-business accounts (OFF by default),
-- immutable audit, consent-gated outbox with idempotency + retry lease, verified webhook log, usage caps, kill switch.
-- DISPOSABLE PostgreSQL / CI ONLY. NEVER execute on IMG-ERP-SG. Not a production migration.
-- Additive only: no existing table or function is changed. Implements P1 of design/integrations/BUILD_PLAN.md.
--
-- RULES ENFORCED BY THE DATABASE (not by the UI):
--   1. Every account is created with mode='off'. mode<>'off' needs status='connected'.
--      mode='live' additionally needs a PASSED provider test no older than 30 days.
--   2. No secret value is ever stored. Only secret_ref (an opaque name) and non-secret public_config;
--      public_config keys that look like secrets are rejected by a CHECK.
--   3. Only tenant owner / business owner (can_manage) may connect, test-record, change mode, kill, read accounts.
--   4. Outbox: idempotent per (account,key); blocked unless port is on, consent exists, outside quiet hours,
--      and daily cap is not exceeded. dry_run rows are logged but flagged so the worker never calls a provider.
--   5. Webhook events: stored always, applied never when the signature is not verified; unique per provider event.
--   6. Audit and webhook logs are immutable for every role.


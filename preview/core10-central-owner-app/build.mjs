// CORE 10 owner preview for the existing Worker core10-central. Deterministic bundler.
// /live/* = exact git blobs of the pinned trunk commit (SOURCE_DRIFT otherwise). Presentation glue lives in site/.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../..");
export const PIN = "7c460aa9e4404e1a6630f2f14f070cd9e3b9497b"; // ccr-15ed11dd-n3hw5h trunk HEAD

export const LIVE = [
  "core10-owner-control-centre.css", "core10-owner-control-centre-ui.js", "core10-owner-control-client.js",
  "core10-build01.html", "core10-build01.css", "core10-build01.js", "core10-build01-client.js",
  "core10-build01-config.js", "core10-build01-pack02.js", "core10-enterprise-client.js", "core10-control-studio.css",
  "vendor/supabase.js",
  "core10-pack02-workspace.js", "core10-pack02-workspace.css", "core10-pack02-controls.js",
  "docs/preview/c10-np01-canonical-reviewer-preview.html",
  "internal/enterprise-client/c10_np01_reviewer_workspace_v1.mjs",
  "internal/enterprise-client/c10_np01_reviewer_workspace_v1.css",
  "internal/enterprise-client/c10_np01_canonical_review_client_v1.mjs",
];
export const SAMPLES = ["universal-owner", "business-owner-branded", "staff", "controls-central"];
export const FORBIDDEN = ["config.js", "owner.html", "index.html", "core10-shell.js", "core10-control-centre-config.js",
  "core10-owner-control-centre.js", "sql-gateway.cjs", "harness.js", "harness.html", "seed.sql"];

const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8", ".json": "application/json; charset=utf-8", ".png": "image/png", ".svg": "image/svg+xml" };
const git = (...a) => execFileSync("git", a, { cwd: ROOT, encoding: "utf8" }).trim();
const sha256 = (b) => crypto.createHash("sha256").update(b).digest("hex");
const blob = (p) => git("rev-parse", `${PIN}:${p}`);
function pinned(p) {
  const buf = Buffer.from(execFileSync("git", ["cat-file", "blob", blob(p)], { cwd: ROOT }));
  const disk = fs.existsSync(path.join(ROOT, p)) ? fs.readFileSync(path.join(ROOT, p)) : null;
  if (!disk || !disk.equals(buf)) throw new Error("SOURCE_DRIFT " + p);
  return buf;
}
function walk(dir, base = "") {
  return fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((e) => e.isDirectory() ? walk(path.join(dir, e.name), base + e.name + "/") : [base + e.name]);
}

export function build() {
  const files = {}, manifest = [];
  const add = (route, buf, entry) => {
    files[route] = [TYPES[path.extname(route)] || "application/octet-stream", buf.toString("base64")];
    manifest.push({ route, bytes: buf.length, sha256: sha256(buf), ...entry });
  };
  for (const p of LIVE) add("/live/" + p, pinned(p), { kind: "ACTUAL_SOURCE", source: p, git_blob: blob(p) });
  const ws = {};
  for (const n of SAMPLES) ws[n] = JSON.parse(pinned(`tests/pack02/fixtures/${n}.json`).toString("utf8"));
  add("/view/workspace-data.js", Buffer.from("window.CORE10_PREVIEW_WORKSPACE=" + JSON.stringify(ws) + ";\n"),
    { kind: "SAMPLE_DATA", source: SAMPLES.map((n) => `tests/pack02/fixtures/${n}.json@${blob(`tests/pack02/fixtures/${n}.json`)}`).join(", ") });
  const occ = fs.readFileSync(path.join(HERE, "data/occ-owner-replay.json"));
  add("/view/control-data.js", Buffer.from("window.CORE10_PREVIEW_CONTROL=" + occ.toString("utf8") + ";\n"),
    { kind: "SAMPLE_DATA", source: "preview/core10-central-owner-app/data/occ-owner-replay.json" });
  for (const n of walk(path.join(HERE, "site")))
    add("/" + n, fs.readFileSync(path.join(HERE, "site", n)), { kind: "PREVIEW_SHELL", source: "preview/core10-central-owner-app/site/" + n });
  for (const f of FORBIDDEN) if (Object.keys(files).some((r) => r.split("/").pop() === f && r !== "/index.html")) throw new Error("FORBIDDEN_FILE " + f);
  const runtime = fs.readFileSync(path.join(HERE, "worker-runtime.mjs"), "utf8");
  const worker = "// GENERATED by preview/core10-central-owner-app/build.mjs from trunk " + PIN + ". Do not edit.\nconst PIN=" + JSON.stringify(PIN) +
    ";\nconst FILES=" + JSON.stringify(files) + ";\n" + runtime;
  return { worker, manifest: { pin: PIN, worker_sha256: sha256(worker), files: manifest } };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { worker, manifest } = build();
  fs.mkdirSync(path.join(HERE, "dist"), { recursive: true });
  fs.writeFileSync(path.join(HERE, "dist/worker.mjs"), worker);
  fs.writeFileSync(path.join(HERE, "SOURCE_MANIFEST.json"), JSON.stringify(manifest, null, 1) + "\n");
  console.log("worker.mjs " + worker.length + " bytes sha256 " + manifest.worker_sha256);
}

-- enqueue: every gate decided here, in the database. p_now is for deterministic tests (Asia/Dhaka local hour).
CREATE FUNCTION c10_demo.integration_enqueue_v1(p_account bigint,p_key text,p_contact text,p_template text,
 p_params jsonb DEFAULT '{}',p_now timestamptz DEFAULT now())
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE a record;pv record;o record;h int;quiet boolean;used int;st text;v_id bigint;
BEGIN
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'integration_denied'; END IF;
 SELECT * INTO pv FROM c10_demo.integration_provider_v1 WHERE code=a.provider_code;
 IF pv.family<>'messaging' THEN RAISE EXCEPTION 'integration_not_messaging'; END IF;
 -- idempotent retry returns the existing row, never a second one
 SELECT * INTO o FROM c10_demo.integration_outbox_v1 WHERE account_id=p_account AND idempotency_key=p_key;
 IF FOUND THEN RETURN jsonb_build_object('status','duplicate','id',o.id,'state',o.state); END IF;
 h:=extract(hour FROM (p_now AT TIME ZONE 'Asia/Dhaka'))::int;
 quiet:=CASE WHEN a.quiet_start_hour>a.quiet_end_hour THEN (h>=a.quiet_start_hour OR h<a.quiet_end_hour)
             ELSE (h>=a.quiet_start_hour AND h<a.quiet_end_hour) END;
 SELECT COALESCE(sent_count,0) INTO used FROM c10_demo.integration_usage_v1
  WHERE account_id=p_account AND usage_date=(p_now AT TIME ZONE 'Asia/Dhaka')::date;
 used:=COALESCE(used,0);
 st:=CASE
  WHEN a.mode='off' THEN 'blocked_port_off'
  WHEN NOT EXISTS(SELECT 1 FROM c10_demo.integration_consent_v1 c WHERE c.business_id=a.business_id
        AND c.channel=a.provider_code AND c.contact_ref=p_contact AND c.opted_in) THEN 'blocked_no_consent'
  WHEN quiet THEN 'blocked_quiet_hours'
  WHEN used>=a.daily_cap THEN 'blocked_cap'
  ELSE 'queued' END;
 INSERT INTO c10_demo.integration_outbox_v1(tenant_id,business_id,account_id,channel,idempotency_key,contact_ref,
   template_code,params,state,is_dry_run,next_try_at,created_by)
 VALUES(a.tenant_id,a.business_id,p_account,a.provider_code,p_key,p_contact,p_template,COALESCE(p_params,'{}'),
   st,a.mode='dry_run',p_now,c10_demo.actor_uid()) RETURNING id INTO v_id;
 RETURN jsonb_build_object('status',CASE WHEN st='queued' THEN 'queued' ELSE 'blocked' END,'id',v_id,'state',st);
END $$;

-- worker claim with lease (SKIP LOCKED); a crashed worker's expired lease is retried
CREATE FUNCTION c10_demo.integration_claim_v1(p_account bigint,p_limit integer DEFAULT 10,p_now timestamptz DEFAULT now())
RETURNS SETOF c10_demo.integration_outbox_v1 LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE a record;
BEGIN
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'integration_denied'; END IF;
 IF a.mode='off' THEN RETURN; END IF;   -- off port: nothing is ever handed to a worker
 RETURN QUERY
 UPDATE c10_demo.integration_outbox_v1 o SET state='claimed',lease_until=p_now+interval '2 minutes',attempts=o.attempts+1
 WHERE o.id IN(SELECT x.id FROM c10_demo.integration_outbox_v1 x
   WHERE x.account_id=p_account AND x.is_dry_run=(a.mode='dry_run')
     AND ((x.state='queued' AND x.next_try_at<=p_now) OR (x.state='claimed' AND x.lease_until<p_now))
     AND x.attempts<x.max_attempts
   ORDER BY x.id LIMIT LEAST(GREATEST(p_limit,1),100) FOR UPDATE SKIP LOCKED)
 RETURNING o.*;
END $$;

-- worker report: transient errors back off exponentially; permanent errors fail immediately; dry-run never "sends"
CREATE FUNCTION c10_demo.integration_report_v1(p_outbox bigint,p_ok boolean,p_transient boolean DEFAULT false,
 p_provider_ref text DEFAULT NULL,p_error text DEFAULT NULL,p_now timestamptz DEFAULT now())
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE o record;a record;st text;
BEGIN
 SELECT * INTO o FROM c10_demo.integration_outbox_v1 WHERE id=p_outbox FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(o.tenant_id,o.business_id) THEN RAISE EXCEPTION 'integration_denied'; END IF;
 IF o.state<>'claimed' THEN RETURN o.state; END IF;   -- stale/duplicate report cannot move a final state
 IF p_ok THEN
  st:=CASE WHEN o.is_dry_run THEN 'dry_run_logged' ELSE 'sent' END;
  UPDATE c10_demo.integration_outbox_v1 SET state=st,provider_ref=p_provider_ref,lease_until=NULL WHERE id=p_outbox;
  IF NOT o.is_dry_run THEN
   INSERT INTO c10_demo.integration_usage_v1(account_id,usage_date,sent_count)
   VALUES(o.account_id,(p_now AT TIME ZONE 'Asia/Dhaka')::date,1)
   ON CONFLICT(account_id,usage_date) DO UPDATE SET sent_count=c10_demo.integration_usage_v1.sent_count+1;
  END IF;
 ELSIF p_transient AND o.attempts<o.max_attempts THEN
  st:='queued';
  UPDATE c10_demo.integration_outbox_v1 SET state='queued',lease_until=NULL,last_error_code=left(p_error,80),
    next_try_at=p_now+make_interval(secs=>(30*power(2,o.attempts-1))::int) WHERE id=p_outbox;
 ELSE
  st:='failed';
  UPDATE c10_demo.integration_outbox_v1 SET state='failed',lease_until=NULL,last_error_code=left(p_error,80) WHERE id=p_outbox;
 END IF;
 RETURN st;
END $$;

-- webhook receive: signature is decided by the server adapter; bad signatures are logged and never applied
CREATE FUNCTION c10_demo.integration_webhook_receive_v1(p_account bigint,p_event text,p_signature text,p_payload_ref text DEFAULT NULL)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE a record;r text;
BEGIN
 IF p_signature NOT IN('ok','bad','missing') THEN RAISE EXCEPTION 'integration_invalid_signature_status'; END IF;
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'integration_denied'; END IF;
 IF EXISTS(SELECT 1 FROM c10_demo.integration_webhook_event_v1 WHERE account_id=p_account AND event_id=p_event) THEN
  RETURN 'duplicate';
 END IF;
 r:=CASE WHEN p_signature='ok' AND a.mode<>'off' THEN 'applied' ELSE 'ignored_bad_signature' END;
 INSERT INTO c10_demo.integration_webhook_event_v1(tenant_id,business_id,account_id,provider_code,event_id,
   signature_status,payload_ref,result) VALUES(a.tenant_id,a.business_id,p_account,a.provider_code,p_event,p_signature,p_payload_ref,r);
 RETURN r;
END $$;


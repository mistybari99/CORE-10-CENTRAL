-- C10-A021: Owner decision and module-control engine. DISPOSABLE PostgreSQL ONLY.
-- Layered on A018 + A020; no legacy Supabase/IMG mutation or module activation.
-- Role checks are enforced SERVER SIDE from membership tables.
CREATE TABLE c10_demo.owner_module_requests_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 module_code text NOT NULL,
 target_visibility text NOT NULL CHECK(target_visibility IN('locked','hidden','show')),
 reason text NOT NULL CHECK(length(btrim(reason)) BETWEEN 5 AND 500),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 status text NOT NULL DEFAULT 'pending'
  CHECK(status IN('pending','approved','rejected')),
 requested_by uuid NOT NULL,
 reviewed_by uuid,
 reviewed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(business_id,tenant_id)
  REFERENCES c10_demo.businesses(id,tenant_id),
 FOREIGN KEY(business_id,module_code)
  REFERENCES c10_demo.business_module_settings_v1(business_id,module_code),
 CHECK((status='pending' AND reviewed_by IS NULL AND reviewed_at IS NULL)
    OR (status<>'pending' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);
ALTER TABLE c10_demo.owner_module_requests_v1 ENABLE ROW LEVEL SECURITY;
CREATE POLICY owner_module_requests_scoped_v1 ON c10_demo.owner_module_requests_v1
 FOR SELECT TO authenticated USING(
  c10_demo.can_manage(tenant_id,business_id)
  OR (requested_by=c10_demo.actor_uid()
    AND c10_demo.can_business(tenant_id,business_id))
 );
REVOKE ALL ON c10_demo.owner_module_requests_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.owner_module_requests_v1 TO authenticated;

-- Manager may submit a proposal but cannot approve, mutate module state,
-- or inherit tenant owner control. Site staff/investors have no submission right.
CREATE FUNCTION c10_demo.request_module_visibility_v1(
 p_business bigint,p_module text,p_target text,p_reason text,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;v_id bigint;v_old record;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_business IS NULL OR
    p_module IS NULL OR p_target NOT IN('locked','hidden','show') OR
    p_target IS NULL OR p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 5 AND 500 OR
    p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120 THEN
  RAISE EXCEPTION 'invalid_owner_control_request';
 END IF;
 SELECT tenant_id INTO v_tenant FROM c10_demo.businesses WHERE id=p_business;
 IF v_tenant IS NULL OR NOT c10_demo.can_business(v_tenant,p_business) THEN
  RAISE EXCEPTION 'owner_control_request_denied';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM c10_demo.business_module_settings_v1
  WHERE business_id=p_business AND module_code=p_module) THEN
  RAISE EXCEPTION 'unknown_business_module';
 END IF;
 INSERT INTO c10_demo.owner_module_requests_v1(
  tenant_id,business_id,module_code,target_visibility,reason,request_key,requested_by)
 VALUES(v_tenant,p_business,p_module,p_target,btrim(p_reason),p_request,c10_demo.actor_uid())
 ON CONFLICT(business_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_old FROM c10_demo.owner_module_requests_v1
   WHERE business_id=p_business AND request_key=p_request;
  IF NOT FOUND OR v_old.module_code<>p_module OR v_old.target_visibility<>p_target
     OR v_old.reason<>btrim(p_reason) OR v_old.requested_by<>c10_demo.actor_uid()
  THEN RAISE EXCEPTION 'owner_request_idempotency_conflict'; END IF;
  v_id:=v_old.id;
 END IF;
 RETURN v_id;
END $$;

-- Decision is atomic with the module state change; no side effects on
-- stock, revenue, profit or real operational_enabled=false.
CREATE FUNCTION c10_demo.decide_module_visibility_v1(p_id bigint,p_decision text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_request c10_demo.owner_module_requests_v1%ROWTYPE;
 v_setting c10_demo.business_module_settings_v1%ROWTYPE;
 v_certified boolean;
 v_status text;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_id IS NULL OR
    p_decision IS NULL OR p_decision NOT IN('approve','reject')
 THEN RAISE EXCEPTION 'invalid_owner_decision'; END IF;
 SELECT * INTO v_request FROM c10_demo.owner_module_requests_v1
  WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_request.tenant_id,v_request.business_id)
 THEN RAISE EXCEPTION 'owner_decision_denied'; END IF;
 v_status:=CASE WHEN p_decision='approve' THEN 'approved' ELSE 'rejected' END;
 IF v_request.status<>'pending' THEN
  IF v_request.status=v_status THEN RETURN v_request.status; END IF;
  RAISE EXCEPTION 'owner_decision_already_final';
 END IF;
 IF p_decision='approve' THEN
  SELECT * INTO v_setting FROM c10_demo.business_module_settings_v1
   WHERE business_id=v_request.business_id AND module_code=v_request.module_code
   FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'module_configuration_missing'; END IF;
  IF v_request.target_visibility='show' THEN
   -- Never display an uncertified module as operational just because an owner clicked approve.
   SELECT COALESCE(tm.enterprise_certified,false) INTO v_certified
   FROM c10_demo.businesses b JOIN c10_demo.template_modules_v1 tm
     ON tm.template_code=b.template_code
   WHERE b.id=v_request.business_id AND tm.module_code=v_request.module_code;
   IF NOT COALESCE(v_certified,false) OR NOT v_setting.operational_enabled THEN
    RAISE EXCEPTION 'module_not_certified_or_not_enabled';
   END IF;
  END IF;
  UPDATE c10_demo.business_module_settings_v1
   SET visibility=v_request.target_visibility
   WHERE business_id=v_request.business_id
     AND module_code=v_request.module_code;
 END IF;
 UPDATE c10_demo.owner_module_requests_v1
  SET status=v_status,reviewed_by=c10_demo.actor_uid(),reviewed_at=now()
  WHERE id=p_id;
 RETURN v_status;
END $$;

-- RLS-invoker dashboard. Business owner may see only own business,
-- portfolio owner can see their businesses, manager/staff/investor cannot.
CREATE VIEW c10_demo.owner_business_control_board_v1 WITH(security_invoker=true) AS
 SELECT b.tenant_id,b.id AS business_id,b.slug,b.status AS business_status,
  COALESCE(c.display_name,b.slug) AS business_name,
  (SELECT count(*) FROM c10_demo.sites s WHERE s.business_id=b.id) AS site_count,
  (SELECT count(*) FROM c10_demo.business_module_settings_v1 m
   WHERE m.business_id=b.id AND m.visibility='show') AS shown_modules,
  (SELECT count(*) FROM c10_demo.business_module_settings_v1 m
   WHERE m.business_id=b.id AND m.visibility='locked') AS locked_modules,
  (SELECT count(*) FROM c10_demo.owner_module_requests_v1 r
   WHERE r.business_id=b.id AND r.status='pending') AS pending_owner_decisions,
  false::boolean AS production_certified
 FROM c10_demo.businesses b
 LEFT JOIN c10_demo.business_configuration_v1 c ON c.business_id=b.id
 WHERE c10_demo.can_manage(b.tenant_id,b.id);

REVOKE ALL ON c10_demo.owner_business_control_board_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.owner_business_control_board_v1 TO authenticated;
REVOKE EXECUTE ON FUNCTION c10_demo.request_module_visibility_v1(bigint,text,text,text,text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.decide_module_visibility_v1(bigint,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION c10_demo.request_module_visibility_v1(bigint,text,text,text,text) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.decide_module_visibility_v1(bigint,text) TO authenticated;

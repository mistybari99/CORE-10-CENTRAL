-- PACK-01 (A048): one effective site permission source shared with Build01 (active tenant, signed actor, explicit
-- deny, expiry, revocation). Resolves location -> site on the server; a caller's site id is never trusted.
CREATE FUNCTION core10.inventory_action_authorized_v1(p_tenant bigint, p_business bigint, p_location bigint, p_action text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
 SELECT core10.actor_uid() IS NOT NULL AND p_action=ANY(ARRAY['stock.read','stock.post']::text[])
 AND EXISTS(SELECT 1 FROM core10.stock_locations l
   WHERE l.id=p_location AND l.tenant_id=p_tenant AND l.business_id=p_business
     AND core10.can_site(l.tenant_id,l.business_id,l.site_id,p_action))
$$;

CREATE FUNCTION core10._inventory_kind_feature_v1(p_kind text) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path=pg_catalog,core10 AS $$
 SELECT CASE p_kind WHEN 'receive' THEN 'inventory.receive' WHEN 'issue' THEN 'inventory.issue'
  WHEN 'transfer' THEN 'inventory.transfer' WHEN 'adjust_in' THEN 'inventory.adjust' WHEN 'adjust_out' THEN 'inventory.adjust' END
$$;

-- Owner Control for one command: p_master holds the caller's control_check_v1 results for the master switch
-- inventory.stock_event (one per touched site, same order as p_sites); this adds the kind's feature per site. Returns {stages, max_qty, staff_allowed, separate_confirmer, reason_required, allow_cross_site, allow_negative_stock}
-- combined strictly across sites (largest stage count, smallest limit, any "no" wins). Raises CONTROL_DISABLED:<key>.
CREATE FUNCTION core10._inventory_controls_v1(p_business bigint, p_kind text, p_sites bigint[], p_master jsonb) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE i int; s bigint; m jsonb; k jsonb; v_feature text := core10._inventory_kind_feature_v1(p_kind);
 v_stages int := 0; v_max numeric := 1000000; v_staff boolean := true; v_sep boolean := false;
 v_reason boolean := false; v_cross boolean := true; v_neg boolean := false;
BEGIN
 IF jsonb_typeof(p_master)<>'array' OR jsonb_array_length(p_master)<>cardinality(p_sites) THEN RAISE EXCEPTION 'INV_CONTROL_SHAPE'; END IF;
 FOR i IN 1..cardinality(p_sites) LOOP
  s := p_sites[i]; m := p_master->(i-1);
  k := core10.control_check_v1(p_business, v_feature, s);
  v_stages := greatest(v_stages, (m->>'stages')::int, (k->>'stages')::int);
  IF p_kind IN ('adjust_in','adjust_out') THEN
   v_max := least(v_max, (m->'params'->>'max_adjust_qty')::numeric);
  ELSE
   v_max := least(v_max, (k->'params'->>'max_qty')::numeric);
  END IF;
  v_staff := v_staff AND coalesce((k->'params'->>'staff_allowed')::boolean, false);
  v_sep := v_sep OR coalesce((k->'params'->>'separate_confirmer')::boolean, false);
  v_reason := v_reason OR coalesce((k->'params'->>'reason_required')::boolean, false);
  v_cross := v_cross AND coalesce((k->'params'->>'allow_cross_site')::boolean, true);
  v_neg := v_neg OR coalesce((m->'params'->>'allow_negative_stock')::boolean, false);
 END LOOP;
 RETURN jsonb_build_object('stages',v_stages,'max_qty',v_max,'staff_allowed',v_staff,'separate_confirmer',v_sep,
  'reason_required',v_reason,'allow_cross_site',v_cross,'allow_negative_stock',v_neg);
END $$;

-- Who may act on a command of this kind: stock.post on every location it touches (site deny, expiry, revocation
-- respected even for owners), and for non-managers the kind's staff_allowed control.
CREATE FUNCTION core10._inventory_may_act_v1(p_tenant bigint, p_business bigint, p_source bigint, p_destination bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
 SELECT (p_source IS NULL OR core10.inventory_action_authorized_v1(p_tenant,p_business,p_source,'stock.post'))
    AND (p_destination IS NULL OR core10.inventory_action_authorized_v1(p_tenant,p_business,p_destination,'stock.post'))
$$;


-- Block ALL generic stock APIs for tracked SKUs. A quality RPC creates a one-time,
-- exact-payload permit consumed inside the SAME stock insert transaction.
CREATE FUNCTION c10_demo.quality_stock_guard_v1() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_permit bigint;
BEGIN
 IF EXISTS (SELECT 1 FROM c10_demo.quality_tracked_items_v1
            WHERE tenant_id=NEW.tenant_id AND business_id=NEW.business_id AND item_id=NEW.item_id)
 THEN
  SELECT id INTO v_permit FROM c10_demo.quality_stock_permits_v1
   WHERE location_id=NEW.location_id AND request_key=NEW.request_key
     AND tenant_id=NEW.tenant_id AND business_id=NEW.business_id
     AND item_id=NEW.item_id AND delta=NEW.delta AND actor_id=NEW.created_by
     AND NOT consumed FOR UPDATE;
  IF v_permit IS NULL THEN RAISE EXCEPTION 'tracked_item_requires_quality_command'; END IF;
  UPDATE c10_demo.quality_stock_permits_v1 SET consumed=true WHERE id=v_permit;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER c10_quality_stock_guard_v1 BEFORE INSERT ON c10_demo.stock_movements
 FOR EACH ROW EXECUTE FUNCTION c10_demo.quality_stock_guard_v1();

-- Internal idempotency claim, never a public RPC. Requests are business-scoped and
-- actor-bound. A committed started claim is not possible without successful RPC return.
CREATE FUNCTION c10_demo.quality_claim_v1(p_tenant bigint,p_business bigint,p_op text,p_key text,p_payload jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_id bigint; v_old record;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_key IS NULL OR length(btrim(p_key)) NOT BETWEEN 3 AND 120 THEN
  RAISE EXCEPTION 'quality_invalid_request_key';
 END IF;
 INSERT INTO c10_demo.quality_commands_v1(tenant_id,business_id,operation,request_key,payload,actor_id)
 VALUES(p_tenant,p_business,p_op,p_key,p_payload,c10_demo.actor_uid())
 ON CONFLICT(business_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_old FROM c10_demo.quality_commands_v1
   WHERE business_id=p_business AND request_key=p_key FOR UPDATE;
  IF v_old.actor_id<>c10_demo.actor_uid() OR v_old.operation<>p_op OR v_old.payload<>p_payload THEN
   RAISE EXCEPTION 'quality_idempotency_conflict';
  END IF;
  IF v_old.result_id IS NULL THEN RAISE EXCEPTION 'quality_incomplete_request'; END IF;
  RETURN -v_old.id; -- negative signals an exact successful replay
 END IF;
 RETURN v_id;
END $$;
CREATE FUNCTION c10_demo.quality_permit_v1(p_loc bigint,p_item bigint,p_tenant bigint,
 p_business bigint,p_delta numeric,p_key text)

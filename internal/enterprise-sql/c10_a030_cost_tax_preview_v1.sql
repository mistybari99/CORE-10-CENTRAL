  p_label IS NULL OR length(btrim(p_label)) NOT BETWEEN 3 AND 120 OR
  p_rate_bps IS NULL OR p_rate_bps NOT BETWEEN 0 AND 10000 OR
  p_mode IS NULL OR p_mode NOT IN('inclusive','exclusive') OR
  p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_tax_preview_profile'; END IF;
 SELECT tenant_id INTO v_tenant FROM c10_demo.businesses WHERE id=p_business;

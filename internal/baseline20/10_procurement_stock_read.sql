  ORDER BY p.id DESC LIMIT v_limit) x;
 RETURN jsonb_build_object('business_id',p_business,'items',v_rows,'limit',v_limit,
  'next_before_id',CASE WHEN jsonb_array_length(v_rows)=v_limit THEN (v_rows->(v_limit-1)->>'po_id')::bigint END);
END $$;


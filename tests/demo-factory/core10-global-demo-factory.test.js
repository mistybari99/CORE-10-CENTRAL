"use strict";
const assert = require("node:assert/strict");
const { buildFactory, validateFactory, report } = require("../../internal/demo-factory/index.js");
const first = buildFactory(), second = buildFactory();
assert.deepEqual(first, second, "factory must be deterministic");
assert.equal(validateFactory(first), true);
assert.equal(first.structural_sites.length, 303);
assert.equal(first.tenants.length, 2);
for (const pack of ["sweets_bakery", "paint_hardware", "construction"]) assert(first.businesses.some(b => b.pack === pack));
assert.equal(first.golden_scenario.expected.accounts_receivable_minor, 33000);
assert.equal(first.golden_scenario.expected.accounts_payable_minor, 150000);
assert.equal(first.golden_scenario.expected.net_cash_change_minor, -20000);
assert.match(report(first), /database posting\/auth\/provider\/deployment NOT TESTED/);
const tampered = structuredClone(first);
tampered.golden_scenario.journals[0].lines[0].debit_minor += 1;
assert.throws(() => validateFactory(tampered), /unbalanced/);
const badProvenance = structuredClone(first); badProvenance.provenance_sha256 = "0".repeat(64);
assert.throws(() => validateFactory(badProvenance));
console.log("PASS core10 global demo factory: deterministic 2-tenant/6-business/303-site fixture, balanced expected math, negative cases, provenance");

REVOKE EXECUTE ON FUNCTION c10_demo.confirm_operational_document_v1(bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.post_operational_document_v1(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION c10_demo.create_operational_document_v1(
 bigint,bigint,text,text,jsonb,numeric,text) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.confirm_operational_document_v1(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.post_operational_document_v1(bigint) TO authenticated;

-- CORE10 A027: Disposable PostgreSQL only, never execute on IMG-ERP-SG.
-- Server-side BOM/production planner and atomic stock posting. Ingredient "estimated_cost"
-- is a manual planning estimate, NOT inventory valuation or certified COGS.
CREATE TABLE c10_demo.bom_recipes_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 finished_item_id bigint NOT NULL,
 recipe_code text NOT NULL CHECK(length(btrim(recipe_code)) BETWEEN 2 AND 80),
 yield_quantity numeric(15,3) NOT NULL CHECK(yield_quantity>0 AND yield_quantity<=100000 AND yield_quantity=round(yield_quantity,3)),
 overhead_estimate numeric(18,2) NOT NULL CHECK(overhead_estimate>=0),
 ingredients_payload jsonb NOT NULL CHECK(jsonb_typeof(ingredients_payload)='array'),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','approved')),
 created_by uuid NOT NULL,
 approved_by uuid,
 approved_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(id,tenant_id,business_id),
 UNIQUE(business_id,recipe_code),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 FOREIGN KEY(finished_item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id),
 CHECK((status='draft' AND approved_by IS NULL AND approved_at IS NULL) OR
   (status='approved' AND approved_by IS NOT NULL AND approved_at IS NOT NULL))
);
-- Exactly one approved recipe per finished item; changing BOM requires a
-- deliberate versioning/migration workflow, not silent mutation of posted batches.
CREATE UNIQUE INDEX bom_one_approved_recipe_v1 ON c10_demo.bom_recipes_v1
 (business_id,finished_item_id) WHERE status='approved';
CREATE TABLE c10_demo.bom_ingredients_v1(
 bom_id bigint NOT NULL,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 line_no integer NOT NULL CHECK(line_no BETWEEN 1 AND 100),
 ingredient_item_id bigint NOT NULL,
 qty_per_batch numeric(15,3) NOT NULL CHECK(qty_per_batch>0 AND qty_per_batch=round(qty_per_batch,3)),
 estimated_unit_cost numeric(18,2) NOT NULL CHECK(estimated_unit_cost>=0),
 PRIMARY KEY(bom_id,line_no),
 UNIQUE(bom_id,ingredient_item_id),
 FOREIGN KEY(bom_id,tenant_id,business_id) REFERENCES c10_demo.bom_recipes_v1(id,tenant_id,business_id),
 FOREIGN KEY(ingredient_item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id)
);
CREATE TABLE c10_demo.production_batches_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 location_id bigint NOT NULL,
 bom_id bigint NOT NULL,
 multiplier numeric(12,3) NOT NULL CHECK(multiplier>0 AND multiplier<=100000 AND multiplier=round(multiplier,3)),
 expected_output numeric(15,3) NOT NULL CHECK(expected_output>0),
 estimated_total_cost numeric(20,2) NOT NULL CHECK(estimated_total_cost>=0),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','confirmed','posted')),
 created_by uuid NOT NULL,
 confirmed_by uuid,
 confirmed_at timestamptz,
 posted_by uuid,
 posted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(bom_id,tenant_id,business_id) REFERENCES c10_demo.bom_recipes_v1(id,tenant_id,business_id),
 FOREIGN KEY(location_id,tenant_id,business_id,site_id) REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 CHECK((status='draft' AND confirmed_by IS NULL AND confirmed_at IS NULL AND posted_by IS NULL AND posted_at IS NULL)
  OR (status='confirmed' AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL AND posted_by IS NULL AND posted_at IS NULL)
  OR (status='posted' AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL AND posted_by IS NOT NULL AND posted_at IS NOT NULL))
);
ALTER TABLE c10_demo.bom_recipes_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.bom_ingredients_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.production_batches_v1 ENABLE ROW LEVEL SECURITY;
CREATE POLICY bom_read_business_v1 ON c10_demo.bom_recipes_v1
 FOR SELECT TO authenticated USING(c10_demo.can_business(tenant_id,business_id));
CREATE POLICY bom_ingredients_read_business_v1 ON c10_demo.bom_ingredients_v1
 FOR SELECT TO authenticated USING(c10_demo.can_business(tenant_id,business_id));
CREATE POLICY production_batch_read_business_v1 ON c10_demo.production_batches_v1
 FOR SELECT TO authenticated USING(c10_demo.can_business(tenant_id,business_id));
REVOKE ALL ON c10_demo.bom_recipes_v1,c10_demo.bom_ingredients_v1,c10_demo.production_batches_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.bom_recipes_v1,c10_demo.bom_ingredients_v1,c10_demo.production_batches_v1 TO authenticated;

CREATE FUNCTION c10_demo.create_bom_v1(
 p_business bigint,p_finished_item bigint,p_code text,p_yield numeric,
 p_ingredients jsonb,p_overhead numeric,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;v_recipe bigint;v_old record;v_line jsonb;
 v_ix integer:=0;v_item bigint;v_qty numeric;v_cost numeric;v_used bigint[]:='{}';
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_business IS NULL OR p_finished_item IS NULL OR
    p_code IS NULL OR length(btrim(p_code)) NOT BETWEEN 2 AND 80 OR
    p_yield IS NULL OR p_yield<=0 OR p_yield>100000 OR p_yield<>round(p_yield,3) OR
    p_overhead IS NULL OR p_overhead<0 OR p_overhead<>round(p_overhead,2) OR
    p_ingredients IS NULL OR jsonb_typeof(p_ingredients)<>'array' OR
    jsonb_array_length(p_ingredients) NOT BETWEEN 1 AND 100 OR
    p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_bom_request'; END IF;
 SELECT tenant_id INTO v_tenant FROM c10_demo.businesses WHERE id=p_business;
 IF v_tenant IS NULL OR NOT c10_demo.can_manage(v_tenant,p_business)
 THEN RAISE EXCEPTION 'bom_owner_permission_denied'; END IF;
 IF NOT EXISTS(SELECT 1 FROM c10_demo.items WHERE id=p_finished_item
  AND business_id=p_business AND tenant_id=v_tenant)
 THEN RAISE EXCEPTION 'bom_finished_item_scope_denied'; END IF;
 FOR v_line IN SELECT value FROM jsonb_array_elements(p_ingredients) LOOP
   v_ix:=v_ix+1;
   IF jsonb_typeof(v_line)<>'object' OR
      (SELECT count(*) FROM jsonb_object_keys(v_line))<>3 OR
      jsonb_typeof(v_line->'item')<>'number' OR
      jsonb_typeof(v_line->'qty')<>'number' OR
      jsonb_typeof(v_line->'estimated_unit_cost')<>'number'
   THEN RAISE EXCEPTION 'invalid_bom_ingredient'; END IF;
   BEGIN
     v_item:=(v_line->>'item')::bigint;
     v_qty:=(v_line->>'qty')::numeric;
     v_cost:=(v_line->>'estimated_unit_cost')::numeric;
   EXCEPTION WHEN numeric_value_out_of_range OR invalid_text_representation THEN
     RAISE EXCEPTION 'invalid_bom_ingredient';
   END;
   IF v_item=p_finished_item OR v_item=ANY(v_used) OR v_item<=0 OR
      v_qty<=0 OR v_qty<>round(v_qty,3) OR v_qty>100000 OR
      v_cost<0 OR v_cost<>round(v_cost,2) OR
      NOT EXISTS(SELECT 1 FROM c10_demo.items
       WHERE id=v_item AND business_id=p_business AND tenant_id=v_tenant)
   THEN RAISE EXCEPTION 'invalid_bom_ingredient'; END IF;
   v_used:=array_append(v_used,v_item);
 END LOOP;
 INSERT INTO c10_demo.bom_recipes_v1(
   tenant_id,business_id,finished_item_id,recipe_code,yield_quantity,
   overhead_estimate,ingredients_payload,request_key,created_by)
 VALUES(v_tenant,p_business,p_finished_item,btrim(p_code),p_yield,
   p_overhead,p_ingredients,p_request,c10_demo.actor_uid())
 ON CONFLICT DO NOTHING RETURNING id INTO v_recipe;
 IF v_recipe IS NULL THEN
   SELECT * INTO v_old FROM c10_demo.bom_recipes_v1
    WHERE business_id=p_business AND request_key=p_request;
   IF NOT FOUND OR v_old.finished_item_id<>p_finished_item OR
      v_old.recipe_code<>btrim(p_code) OR v_old.yield_quantity<>p_yield OR
      v_old.overhead_estimate<>p_overhead OR v_old.ingredients_payload<>p_ingredients OR
      v_old.created_by<>c10_demo.actor_uid()
   THEN RAISE EXCEPTION 'bom_idempotency_conflict'; END IF;
   RETURN v_old.id;
 END IF;
 v_ix:=0;
 FOR v_line IN SELECT value FROM jsonb_array_elements(p_ingredients) LOOP
   v_ix:=v_ix+1;
   INSERT INTO c10_demo.bom_ingredients_v1(
     bom_id,tenant_id,business_id,line_no,ingredient_item_id,
     qty_per_batch,estimated_unit_cost)
   VALUES(v_recipe,v_tenant,p_business,v_ix,
     (v_line->>'item')::bigint,(v_line->>'qty')::numeric,
     (v_line->>'estimated_unit_cost')::numeric);
 END LOOP;
 RETURN v_recipe;
END $$;

CREATE FUNCTION c10_demo.approve_bom_v1(p_recipe bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_bom c10_demo.bom_recipes_v1%ROWTYPE;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_recipe IS NULL THEN RAISE EXCEPTION 'bom_bad_approval'; END IF;
 SELECT * INTO v_bom FROM c10_demo.bom_recipes_v1 WHERE id=p_recipe FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_bom.tenant_id,v_bom.business_id)
 THEN RAISE EXCEPTION 'bom_approval_denied'; END IF;
 IF v_bom.status='draft' THEN
   UPDATE c10_demo.bom_recipes_v1 SET status='approved',
    approved_by=c10_demo.actor_uid(),approved_at=now() WHERE id=p_recipe;
 END IF;
 RETURN 'approved';
END $$;

CREATE FUNCTION c10_demo.create_production_batch_v1(
 p_bom bigint,p_location bigint,p_multiplier numeric,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_bom c10_demo.bom_recipes_v1%ROWTYPE;v_loc record;
 v_id bigint;v_prev record;v_qty numeric(15,3);v_est numeric(20,2);
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_bom IS NULL OR p_location IS NULL OR
  p_multiplier IS NULL OR p_multiplier<=0 OR p_multiplier>100000 OR
  p_multiplier<>round(p_multiplier,3) OR p_request IS NULL OR
  length(btrim(p_request)) NOT BETWEEN 1 AND 120 THEN
  RAISE EXCEPTION 'invalid_batch_request'; END IF;
 SELECT * INTO v_bom FROM c10_demo.bom_recipes_v1 WHERE id=p_bom;
 SELECT tenant_id,business_id,site_id INTO v_loc FROM c10_demo.stock_locations WHERE id=p_location;
 IF v_bom.id IS NULL OR v_loc.tenant_id IS NULL OR
  v_bom.tenant_id<>v_loc.tenant_id OR v_bom.business_id<>v_loc.business_id OR
  NOT c10_demo.can_business(v_bom.tenant_id,v_bom.business_id) OR
  NOT c10_demo.can_site(v_loc.tenant_id,v_loc.business_id,v_loc.site_id,'stock.post')
 THEN RAISE EXCEPTION 'production_batch_scope_denied'; END IF;
 IF v_bom.status<>'approved' THEN RAISE EXCEPTION 'bom_not_approved'; END IF;
 v_qty:=v_bom.yield_quantity*p_multiplier;
 IF v_qty<=0 OR v_qty>100000000 OR v_qty<>round(v_qty,3)
 THEN RAISE EXCEPTION 'production_output_precision_exceeded'; END IF;
 IF EXISTS(SELECT 1 FROM c10_demo.bom_ingredients_v1 m WHERE m.bom_id=p_bom
  AND (m.qty_per_batch*p_multiplier>100000000 OR
    m.qty_per_batch*p_multiplier<>round(m.qty_per_batch*p_multiplier,3))) THEN
  RAISE EXCEPTION 'production_input_precision_exceeded'; END IF;
 SELECT round((COALESCE(sum(m.qty_per_batch*m.estimated_unit_cost),0)
   +v_bom.overhead_estimate)*p_multiplier,2) INTO v_est
 FROM c10_demo.bom_ingredients_v1 m WHERE m.bom_id=p_bom;
 INSERT INTO c10_demo.production_batches_v1(
  tenant_id,business_id,site_id,location_id,bom_id,multiplier,
  expected_output,estimated_total_cost,request_key,created_by)
 VALUES(v_bom.tenant_id,v_bom.business_id,v_loc.site_id,p_location,p_bom,
  p_multiplier,v_qty,v_est,p_request,c10_demo.actor_uid())
 ON CONFLICT(business_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_prev FROM c10_demo.production_batches_v1
   WHERE business_id=v_bom.business_id AND request_key=p_request;
  IF NOT FOUND OR v_prev.bom_id<>p_bom OR v_prev.location_id<>p_location
    OR v_prev.multiplier<>p_multiplier OR v_prev.created_by<>c10_demo.actor_uid()
  THEN RAISE EXCEPTION 'batch_idempotency_conflict'; END IF;
  RETURN v_prev.id;
 END IF;
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.confirm_production_batch_v1(p_batch bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_batch c10_demo.production_batches_v1%ROWTYPE;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_batch IS NULL THEN RAISE EXCEPTION 'batch_invalid_confirm'; END IF;
 SELECT * INTO v_batch FROM c10_demo.production_batches_v1 WHERE id=p_batch FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_batch.tenant_id,v_batch.business_id)
 THEN RAISE EXCEPTION 'batch_confirm_denied'; END IF;
 IF v_batch.status='draft' THEN
   UPDATE c10_demo.production_batches_v1 SET status='confirmed',
     confirmed_by=c10_demo.actor_uid(),confirmed_at=now() WHERE id=p_batch;
   RETURN 'confirmed';
 END IF;
 RETURN v_batch.status;
END $$;
CREATE FUNCTION c10_demo.post_production_batch_v1(p_batch bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_batch c10_demo.production_batches_v1%ROWTYPE;
 v_line c10_demo.bom_ingredients_v1%ROWTYPE;v_finished bigint;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_batch IS NULL THEN RAISE EXCEPTION 'batch_invalid_post'; END IF;
 SELECT * INTO v_batch FROM c10_demo.production_batches_v1 WHERE id=p_batch FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_batch.tenant_id,v_batch.business_id)
 THEN RAISE EXCEPTION 'batch_post_denied'; END IF;
 IF v_batch.status='posted' THEN RETURN 'posted'; END IF;
 IF v_batch.status<>'confirmed' THEN RAISE EXCEPTION 'batch_not_confirmed'; END IF;
 IF NOT c10_demo.can_site(v_batch.tenant_id,v_batch.business_id,v_batch.site_id,'stock.post')
 THEN RAISE EXCEPTION 'batch_site_stock_denied'; END IF;
 SELECT finished_item_id INTO v_finished FROM c10_demo.bom_recipes_v1 WHERE id=v_batch.bom_id;
 FOR v_line IN SELECT * FROM c10_demo.bom_ingredients_v1
  WHERE bom_id=v_batch.bom_id ORDER BY line_no LOOP
  PERFORM c10_demo.post_stock_event(v_batch.location_id,v_line.ingredient_item_id,
   -v_line.qty_per_batch*v_batch.multiplier,
   'c10-production:'||p_batch||':ingredient:'||v_line.line_no);
 END LOOP;
 PERFORM c10_demo.post_stock_event(v_batch.location_id,v_finished,v_batch.expected_output,
  'c10-production:'||p_batch||':output');
 UPDATE c10_demo.production_batches_v1 SET status='posted',
  posted_by=c10_demo.actor_uid(),posted_at=now() WHERE id=p_batch;
 RETURN 'posted';
END $$;

CREATE VIEW c10_demo.production_cost_estimate_v1 WITH(security_invoker=true) AS
 SELECT b.tenant_id,b.business_id,b.id AS batch_id,b.status,b.bom_id,
  b.location_id,b.expected_output,b.estimated_total_cost,
  round(b.estimated_total_cost/NULLIF(b.expected_output,0),2) AS estimated_cost_per_unit,
  false::boolean AS actual_cogs_certified
 FROM c10_demo.production_batches_v1 b;
REVOKE ALL ON c10_demo.production_cost_estimate_v1 FROM PUBLIC;

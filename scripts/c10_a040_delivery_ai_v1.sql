-- ---------------- DELIVERY FUNCTIONS ----------------
CREATE FUNCTION c10_demo.delivery_create_parcel_v1(p_account bigint,p_key text,p_reference text,p_cod numeric DEFAULT 0)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE a record;pv record;i record;v_id bigint;
BEGIN
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'delivery_denied'; END IF;
 SELECT * INTO pv FROM c10_demo.integration_provider_v1 WHERE code=a.provider_code;
 IF pv.family<>'delivery' THEN RAISE EXCEPTION 'delivery_not_delivery_port'; END IF;
 IF p_cod IS NULL OR p_cod<0 OR p_cod<>round(p_cod,2) THEN RAISE EXCEPTION 'delivery_invalid_amount'; END IF;
 SELECT * INTO i FROM c10_demo.delivery_parcel_v1 WHERE account_id=p_account AND idempotency_key=p_key;
 IF FOUND THEN RETURN jsonb_build_object('status','duplicate','id',i.id,'state',i.state); END IF;
 IF a.mode='off' THEN RETURN jsonb_build_object('status','blocked','reason','port_off'); END IF;
 INSERT INTO c10_demo.delivery_parcel_v1(tenant_id,business_id,account_id,provider_code,idempotency_key,reference,cod_amount,created_by)
 VALUES(a.tenant_id,a.business_id,p_account,a.provider_code,p_key,p_reference,p_cod,c10_demo.actor_uid()) RETURNING id INTO v_id;
 RETURN jsonb_build_object('status','created','id',v_id,'state','created');
END $$;

CREATE FUNCTION c10_demo.delivery_apply_event_v1(p_parcel bigint,p_event text,p_courier_status text,p_signature text,
 p_cod_collected numeric DEFAULT NULL,p_consignment text DEFAULT NULL)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE p record;a record;m text;outc text;rank_old int;rank_new int;
BEGIN
 IF p_signature NOT IN('ok','bad','missing') THEN RAISE EXCEPTION 'delivery_invalid_signature_status'; END IF;
 SELECT * INTO p FROM c10_demo.delivery_parcel_v1 WHERE id=p_parcel FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(p.tenant_id,p.business_id) THEN RAISE EXCEPTION 'delivery_denied'; END IF;
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p.account_id;
 IF EXISTS(SELECT 1 FROM c10_demo.delivery_event_v1 WHERE parcel_id=p_parcel AND event_id=p_event) THEN RETURN 'duplicate'; END IF;
 SELECT mapped_state INTO m FROM c10_demo.delivery_status_map_v1 WHERE provider_code=p.provider_code AND courier_status=p_courier_status;
 IF p_signature<>'ok' OR a.mode='off' THEN outc:='ignored_signature';
 ELSIF m IS NULL THEN outc:='unmapped';
 ELSE
  rank_old:=CASE p.state WHEN 'created' THEN 0 WHEN 'picked_up' THEN 1 WHEN 'in_transit' THEN 2 ELSE 9 END;   -- delivered/returned/cancelled are final
  rank_new:=CASE m WHEN 'picked_up' THEN 1 WHEN 'in_transit' THEN 2 ELSE 9 END;
  IF p.state IN('delivered','returned','cancelled') OR (rank_new<9 AND rank_new<=rank_old) THEN outc:='ignored_backwards';
  ELSE outc:='applied'; END IF;
 END IF;
 INSERT INTO c10_demo.delivery_event_v1(parcel_id,tenant_id,business_id,event_id,courier_status,mapped_state,signature_status,outcome)
 VALUES(p_parcel,p.tenant_id,p.business_id,p_event,p_courier_status,m,p_signature,outc);
 IF outc='applied' THEN
  UPDATE c10_demo.delivery_parcel_v1 SET state=m,consignment_id=COALESCE(p_consignment,consignment_id),
    cod_collected=CASE WHEN m='delivered' THEN COALESCE(LEAST(p_cod_collected,cod_amount),cod_amount) ELSE cod_collected END,
    updated_at=now() WHERE id=p_parcel;
 END IF;
 RETURN outc;
END $$;

-- courier remits collected COD in cash/bank: reduces what the courier owes; bounded by collected
CREATE FUNCTION c10_demo.delivery_record_remittance_v1(p_parcel bigint,p_amount numeric)
RETURNS numeric LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE p record;
BEGIN
 SELECT * INTO p FROM c10_demo.delivery_parcel_v1 WHERE id=p_parcel FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(p.tenant_id,p.business_id) THEN RAISE EXCEPTION 'delivery_denied'; END IF;
 IF p_amount IS NULL OR p_amount<=0 OR p_amount<>round(p_amount,2) THEN RAISE EXCEPTION 'delivery_invalid_amount'; END IF;
 IF p_amount>p.cod_collected-p.cod_remitted THEN RAISE EXCEPTION 'delivery_remittance_exceeds_collected'; END IF;
 UPDATE c10_demo.delivery_parcel_v1 SET cod_remitted=cod_remitted+p_amount,updated_at=now() WHERE id=p_parcel;
 RETURN p.cod_collected-p.cod_remitted-p_amount;
END $$;

CREATE VIEW c10_demo.courier_cod_receivable_v1 WITH(security_invoker=true) AS
SELECT tenant_id,business_id,provider_code,count(*) FILTER(WHERE state='delivered') AS delivered_parcels,
 sum(cod_collected) AS cod_collected,sum(cod_remitted) AS cod_remitted,sum(cod_collected-cod_remitted) AS courier_owes
FROM c10_demo.delivery_parcel_v1 GROUP BY tenant_id,business_id,provider_code;
REVOKE ALL ON c10_demo.courier_cod_receivable_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.courier_cod_receivable_v1 TO authenticated;

-- ---------------- AI GATEWAY FUNCTIONS ----------------
CREATE FUNCTION c10_demo.ai_redact_v1(p_text text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
 SELECT regexp_replace(regexp_replace(regexp_replace(COALESCE(p_text,''),
   '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}','[EMAIL]','g'),
   '(\+?88)?0?1[3-9][0-9]{8}','[PHONE]','g'),
   '[0-9]{9,}','[NUMBER]','g')
$$;

CREATE FUNCTION c10_demo.ai_set_budget_v1(p_account bigint,p_tokens bigint,p_money numeric)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$

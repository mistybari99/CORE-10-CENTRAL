-- CORE10 A047 — disposable PostgreSQL 17 site-group topology, additive to A018/A020.
-- NEVER run against IMG-ERP-SG. Grouping never duplicates Site/Stock Location IDs.
CREATE TABLE c10_demo.site_groups_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 group_key text NOT NULL CHECK (group_key ~ '^[a-z][a-z0-9_]{1,39}$'),
 label text NOT NULL CHECK (length(btrim(label)) BETWEEN 2 AND 90),
 site_kind text NOT NULL CHECK (site_kind IN ('showroom','factory','godown','warehouse','project')),
 is_default boolean NOT NULL DEFAULT false,
 created_by uuid NOT NULL,
 created_request text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (business_id,group_key),
 UNIQUE (business_id,created_request),
 UNIQUE (id,tenant_id,business_id),
 FOREIGN KEY (business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
CREATE UNIQUE INDEX site_groups_one_default_kind_v1
 ON c10_demo.site_groups_v1(business_id,site_kind) WHERE is_default;
CREATE TABLE c10_demo.site_group_members_v1 (
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint PRIMARY KEY,
 group_id bigint NOT NULL,
 version bigint NOT NULL DEFAULT 1 CHECK (version>0),
 changed_by uuid NOT NULL,
 changed_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY (site_id,tenant_id,business_id) REFERENCES c10_demo.sites(id,tenant_id,business_id),
 FOREIGN KEY (group_id,tenant_id,business_id) REFERENCES c10_demo.site_groups_v1(id,tenant_id,business_id)
);
CREATE TABLE c10_demo.site_group_audit_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint,
 from_group_id bigint,
 to_group_id bigint,
 event_kind text NOT NULL CHECK (event_kind IN ('default_group','group_created','bootstrap','site_added','site_moved')),
 before_version bigint,
 after_version bigint,
 request_key text NOT NULL CHECK (length(request_key) BETWEEN 8 AND 120),
 actor uuid NOT NULL,
 reason text NOT NULL CHECK (length(btrim(reason)) BETWEEN 5 AND 300),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (business_id,request_key),
 FOREIGN KEY (business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 FOREIGN KEY (site_id,tenant_id,business_id) REFERENCES c10_demo.sites(id,tenant_id,business_id)
);
ALTER TABLE c10_demo.site_groups_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.site_group_members_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.site_group_audit_v1 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON c10_demo.site_groups_v1,c10_demo.site_group_members_v1,c10_demo.site_group_audit_v1 FROM PUBLIC,anon,authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA c10_demo FROM PUBLIC,anon,authenticated;

CREATE FUNCTION c10_demo.bootstrap_site_groups_v1(p_business bigint,p_request text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint; grp record; s record; n bigint; inserted integer:=0;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF c10_demo.actor_uid() IS NULL OR t IS NULL OR NOT c10_demo.can_manage(t,p_business)
 THEN RAISE EXCEPTION 'topology_manage_denied'; END IF;
 IF p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,100}$'
 THEN RAISE EXCEPTION 'topology_request_invalid'; END IF;
 FOR grp IN SELECT * FROM (VALUES
  ('showroom','Showrooms'),('factory','Factories'),('godown','Godowns'),
  ('warehouse','Warehouses'),('project','Projects')) AS v(kind,caption) LOOP
  INSERT INTO c10_demo.site_groups_v1(tenant_id,business_id,group_key,label,site_kind,is_default,created_by,created_request)
   VALUES(t,p_business,grp.kind,grp.caption,grp.kind,true,c10_demo.actor_uid(),'default-v1-'||grp.kind)
   ON CONFLICT(business_id,group_key) DO NOTHING;
  SELECT id INTO n FROM c10_demo.site_groups_v1
   WHERE business_id=p_business AND group_key=grp.kind AND site_kind=grp.kind AND is_default=true;
  IF n IS NULL THEN RAISE EXCEPTION 'topology_default_group_conflict'; END IF;
  INSERT INTO c10_demo.site_group_audit_v1(tenant_id,business_id,to_group_id,event_kind,request_key,actor,reason)
   VALUES(t,p_business,n,'default_group','default-v1-'||grp.kind,c10_demo.actor_uid(),'Create default site group')
   ON CONFLICT(business_id,request_key) DO NOTHING;
 END LOOP;
 FOR s IN SELECT id,kind FROM c10_demo.sites WHERE business_id=p_business AND tenant_id=t ORDER BY id LOOP
  SELECT id INTO n FROM c10_demo.site_groups_v1 WHERE business_id=p_business AND site_kind=s.kind AND is_default=true;
  INSERT INTO c10_demo.site_group_members_v1(tenant_id,business_id,site_id,group_id,changed_by)
   VALUES(t,p_business,s.id,n,c10_demo.actor_uid()) ON CONFLICT(site_id) DO NOTHING;
  IF FOUND THEN
   inserted:=inserted+1;
   INSERT INTO c10_demo.site_group_audit_v1(tenant_id,business_id,site_id,to_group_id,event_kind,before_version,after_version,request_key,actor,reason)
    VALUES(t,p_business,s.id,n,'bootstrap',0,1,'bootstrap-v1-'||s.id,c10_demo.actor_uid(),'Assign existing canonical site')
    ON CONFLICT(business_id,request_key) DO NOTHING;
  END IF;
 END LOOP;
 RETURN jsonb_build_object('business_id',p_business,'initialized',true,'new_members',inserted,'operationally_certified',false);
END $$;

CREATE FUNCTION c10_demo.create_site_group_v1(p_business bigint,p_kind text,p_key text,p_label text,p_request text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint; g c10_demo.site_groups_v1%ROWTYPE;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF c10_demo.actor_uid() IS NULL OR t IS NULL OR NOT c10_demo.can_manage(t,p_business)
 THEN RAISE EXCEPTION 'topology_manage_denied'; END IF;
 IF p_kind IS NULL OR p_kind NOT IN ('showroom','factory','godown','warehouse','project') OR
    p_key IS NULL OR p_key !~ '^[a-z][a-z0-9_]{1,39}$' OR
    p_key IN ('showroom','factory','godown','warehouse','project') OR
    p_label IS NULL OR length(btrim(p_label)) NOT BETWEEN 2 AND 90 OR
    p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,100}$'
 THEN RAISE EXCEPTION 'topology_invalid_group'; END IF;
 INSERT INTO c10_demo.site_groups_v1(tenant_id,business_id,group_key,label,site_kind,is_default,created_by,created_request)
 VALUES(t,p_business,p_key,btrim(p_label),p_kind,false,c10_demo.actor_uid(),p_request)
 ON CONFLICT DO NOTHING;
 SELECT * INTO g FROM c10_demo.site_groups_v1 WHERE business_id=p_business AND created_request=p_request;
 IF NOT FOUND OR g.group_key<>p_key OR g.site_kind<>p_kind OR g.label<>btrim(p_label) OR
   g.created_by<>c10_demo.actor_uid() OR g.is_default
 THEN RAISE EXCEPTION 'topology_group_idempotency_conflict'; END IF;
 INSERT INTO c10_demo.site_group_audit_v1(tenant_id,business_id,to_group_id,event_kind,request_key,actor,reason)
 VALUES(t,p_business,g.id,'group_created','group-v1-'||p_request,c10_demo.actor_uid(),'Create an operating group')
 ON CONFLICT(business_id,request_key) DO NOTHING;
 RETURN jsonb_build_object('business_id',p_business,'group_id',g.id,'group_key',g.group_key,'kind',g.site_kind,'operationally_certified',false);
END $$;

CREATE FUNCTION c10_demo.create_site_in_group_v1(p_business bigint,p_group bigint,p_label text,p_request text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint; kind text; sid bigint; previous c10_demo.site_group_members_v1%ROWTYPE;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF c10_demo.actor_uid() IS NULL OR t IS NULL OR NOT c10_demo.can_manage(t,p_business)
 THEN RAISE EXCEPTION 'topology_manage_denied'; END IF;
 IF p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,80}$' OR
    p_label IS NULL OR length(btrim(p_label)) NOT BETWEEN 2 AND 120
 THEN RAISE EXCEPTION 'topology_invalid_site'; END IF;
 SELECT site_kind INTO kind FROM c10_demo.site_groups_v1
 WHERE id=p_group AND tenant_id=t AND business_id=p_business;
 IF kind IS NULL THEN RAISE EXCEPTION 'topology_foreign_group_denied'; END IF;
 sid:=c10_demo.provision_site(p_business,kind,btrim(p_label),'topology:'||p_request);
 INSERT INTO c10_demo.site_group_members_v1(tenant_id,business_id,site_id,group_id,changed_by)
 VALUES(t,p_business,sid,p_group,c10_demo.actor_uid()) ON CONFLICT(site_id) DO NOTHING;
 SELECT * INTO previous FROM c10_demo.site_group_members_v1 WHERE site_id=sid;
 IF previous.group_id<>p_group OR previous.tenant_id<>t OR previous.business_id<>p_business
 THEN RAISE EXCEPTION 'topology_site_request_conflict'; END IF;
 INSERT INTO c10_demo.site_group_audit_v1(tenant_id,business_id,site_id,to_group_id,event_kind,before_version,after_version,request_key,actor,reason)
 VALUES(t,p_business,sid,p_group,'site_added',0,1,'site-v1-'||p_request,c10_demo.actor_uid(),'Create and group canonical site')
 ON CONFLICT(business_id,request_key) DO NOTHING;
 RETURN jsonb_build_object('business_id',p_business,'site_id',sid,'group_id',p_group,'version',previous.version,'operationally_certified',false);
END $$;

CREATE FUNCTION c10_demo.move_site_group_v1(p_site bigint,p_group bigint,p_expected_version bigint,p_request text,p_reason text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint; b bigint; k text; g c10_demo.site_groups_v1%ROWTYPE;
 old c10_demo.site_group_members_v1%ROWTYPE; prev c10_demo.site_group_audit_v1%ROWTYPE;
BEGIN
 SELECT tenant_id,business_id,kind INTO t,b,k FROM c10_demo.sites WHERE id=p_site;
 IF c10_demo.actor_uid() IS NULL OR t IS NULL OR NOT c10_demo.can_manage(t,b)
 THEN RAISE EXCEPTION 'topology_manage_denied'; END IF;
 IF p_expected_version IS NULL OR p_expected_version<1 OR
   p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,80}$' OR
   p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 5 AND 300
 THEN RAISE EXCEPTION 'topology_invalid_move'; END IF;
 SELECT * INTO g FROM c10_demo.site_groups_v1
 WHERE id=p_group AND tenant_id=t AND business_id=b AND site_kind=k;
 IF NOT FOUND THEN RAISE EXCEPTION 'topology_foreign_or_mismatched_group'; END IF;
 SELECT * INTO prev FROM c10_demo.site_group_audit_v1
 WHERE business_id=b AND request_key='move-v1-'||p_request;
 IF FOUND THEN
  IF prev.site_id<>p_site OR prev.to_group_id<>p_group OR
    prev.before_version<>p_expected_version OR prev.actor<>c10_demo.actor_uid() OR
    prev.reason<>btrim(p_reason) THEN RAISE EXCEPTION 'topology_move_replay_conflict'; END IF;
  RETURN jsonb_build_object('business_id',b,'site_id',p_site,'group_id',p_group,'version',prev.after_version,'replayed',true);
 END IF;
 SELECT * INTO old FROM c10_demo.site_group_members_v1 WHERE site_id=p_site FOR UPDATE;
 IF NOT FOUND OR old.version<>p_expected_version THEN RAISE EXCEPTION 'topology_stale_version'; END IF;
 IF old.group_id=p_group THEN RAISE EXCEPTION 'topology_noop_move'; END IF;
 UPDATE c10_demo.site_group_members_v1
 SET group_id=p_group,version=old.version+1,changed_by=c10_demo.actor_uid(),changed_at=now()
 WHERE site_id=p_site;
 INSERT INTO c10_demo.site_group_audit_v1(tenant_id,business_id,site_id,from_group_id,to_group_id,event_kind,before_version,after_version,request_key,actor,reason)
 VALUES(t,b,p_site,old.group_id,p_group,'site_moved',old.version,old.version+1,'move-v1-'||p_request,c10_demo.actor_uid(),btrim(p_reason));
 RETURN jsonb_build_object('business_id',b,'site_id',p_site,'group_id',p_group,'version',old.version+1,'replayed',false,'operationally_certified',false);
END $$;

CREATE FUNCTION c10_demo.read_site_topology_v1(p_business bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint; owner_can boolean; groups jsonb; stray jsonb;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF c10_demo.actor_uid() IS NULL OR t IS NULL OR NOT c10_demo.can_see_business(t,p_business)
 THEN RAISE EXCEPTION 'topology_read_denied'; END IF;
 owner_can:=c10_demo.can_manage(t,p_business);
 SELECT COALESCE(jsonb_agg(jsonb_build_object(
   'group_id',g.id,'group_key',g.group_key,'label',g.label,
   'kind',g.site_kind,'default',g.is_default,
   'sites',(SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'site_id',s.id,'label',s.label,'kind',s.kind,'version',m.version,
    'locations',(SELECT COALESCE(jsonb_agg(jsonb_build_object('id',l.id,'code',l.code) ORDER BY l.id),'[]'::jsonb)
      FROM c10_demo.stock_locations l WHERE l.site_id=s.id AND l.business_id=p_business)
   ) ORDER BY s.id),'[]'::jsonb)
    FROM c10_demo.site_group_members_v1 m JOIN c10_demo.sites s ON s.id=m.site_id
    WHERE m.group_id=g.id AND m.business_id=p_business AND c10_demo.can_site(t,p_business,s.id,'stock.read')
   )
 ) ORDER BY g.site_kind,g.id),'[]'::jsonb) INTO groups
 FROM c10_demo.site_groups_v1 g
 WHERE g.business_id=p_business AND
  (owner_can OR EXISTS(
   SELECT 1 FROM c10_demo.site_group_members_v1 m JOIN c10_demo.sites s ON s.id=m.site_id
   WHERE m.group_id=g.id AND m.business_id=p_business AND c10_demo.can_site(t,p_business,s.id,'stock.read')));
 SELECT COALESCE(jsonb_agg(jsonb_build_object('site_id',s.id,'kind',s.kind,'label',s.label) ORDER BY s.id),'[]'::jsonb)
 INTO stray FROM c10_demo.sites s
 WHERE s.business_id=p_business AND owner_can
  AND NOT EXISTS(SELECT 1 FROM c10_demo.site_group_members_v1 m WHERE m.site_id=s.id);
 RETURN jsonb_build_object('business_id',p_business,'tenant_id',t,
  'server_authorized',true,'can_manage',owner_can,'groups',groups,
  'ungrouped',stray,'operationally_certified',false);
END $$;
CREATE FUNCTION c10_demo.read_site_topology_audit_v1(p_business bigint,p_limit integer DEFAULT 50)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint; events jsonb;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF c10_demo.actor_uid() IS NULL OR t IS NULL OR NOT c10_demo.can_manage(t,p_business)
 THEN RAISE EXCEPTION 'topology_audit_denied'; END IF;
 IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 100 THEN RAISE EXCEPTION 'topology_invalid_audit_limit'; END IF;
 SELECT COALESCE(jsonb_agg(to_jsonb(x) ORDER BY x.id DESC),'[]'::jsonb)
 INTO events FROM (SELECT a.id,a.site_id,a.from_group_id,a.to_group_id,
 a.event_kind,a.before_version,a.after_version,a.reason,a.created_at
 FROM c10_demo.site_group_audit_v1 a WHERE a.business_id=p_business
 ORDER BY a.id DESC LIMIT p_limit) x;
 RETURN jsonb_build_object('business_id',p_business,'items',events);
END $$;

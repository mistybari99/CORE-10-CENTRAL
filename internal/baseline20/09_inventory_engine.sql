CREATE FUNCTION core10.create_inventory_command_v1(
 p_business bigint, p_kind text, p_source bigint, p_destination bigint,
 p_item bigint, p_quantity numeric, p_reason text, p_request text)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE v_actor uuid := core10.actor_uid(); t bigint; v_src_site bigint; v_dst_site bigint; v_sites bigint[];
 ctl jsonb; v_master jsonb := '[]'; s bigint; v_sha text;
 r core10.inventory_command_requests_v1%ROWTYPE; c core10.inventory_commands_v1%ROWTYPE;
 v_reason text := nullif(btrim(p_reason),'');
BEGIN
 -- 1. Auth port first: unknown and foreign businesses look the same.
 SELECT tenant_id INTO t FROM core10.businesses WHERE id=p_business;
 IF v_actor IS NULL OR t IS NULL OR NOT core10.can_see_business(t,p_business) THEN RAISE EXCEPTION 'INV_SCOPE'; END IF;
 IF p_kind IS NULL OR p_kind NOT IN ('receive','issue','transfer','adjust_in','adjust_out')
  OR p_quantity IS NULL OR p_quantity::text IN ('NaN','Infinity','-Infinity') OR p_quantity<=0 OR p_quantity>1000000
  OR p_quantity<>round(p_quantity,3) OR p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,100}$'
  OR (v_reason IS NOT NULL AND length(v_reason) NOT BETWEEN 3 AND 300)
 THEN RAISE EXCEPTION 'INV_INVALID_COMMAND'; END IF;
 IF (p_kind='transfer' AND (p_source IS NULL OR p_destination IS NULL OR p_source=p_destination)) OR
    (p_kind IN ('receive','adjust_in') AND (p_source IS NOT NULL OR p_destination IS NULL)) OR
    (p_kind IN ('issue','adjust_out') AND (p_source IS NULL OR p_destination IS NOT NULL))
 THEN RAISE EXCEPTION 'INV_LOCATION_SHAPE'; END IF;
 IF p_source IS NOT NULL THEN
  SELECT site_id INTO v_src_site FROM core10.stock_locations WHERE id=p_source AND tenant_id=t AND business_id=p_business;
  IF v_src_site IS NULL THEN RAISE EXCEPTION 'INV_LOCATION_SCOPE'; END IF;
 END IF;
 IF p_destination IS NOT NULL THEN
  SELECT site_id INTO v_dst_site FROM core10.stock_locations WHERE id=p_destination AND tenant_id=t AND business_id=p_business;
  IF v_dst_site IS NULL THEN RAISE EXCEPTION 'INV_LOCATION_SCOPE'; END IF;
 END IF;
 IF NOT core10._inventory_may_act_v1(t,p_business,p_source,p_destination) THEN RAISE EXCEPTION 'INV_PERMISSION_DENIED'; END IF;
 IF NOT EXISTS(SELECT 1 FROM core10.items WHERE id=p_item AND tenant_id=t AND business_id=p_business)
 THEN RAISE EXCEPTION 'INV_ITEM_SCOPE'; END IF;
 IF NOT core10.master_item_usable_v1(p_business,p_item) THEN RAISE EXCEPTION 'INV_ITEM_NOT_USABLE'; END IF;
 -- 2. Owner Control: master switch, then the kind's feature, on each touched site (also for replays: fail closed).
 v_sites := array_remove(ARRAY[v_src_site, CASE WHEN v_dst_site IS DISTINCT FROM v_src_site THEN v_dst_site END], NULL);
 FOREACH s IN ARRAY v_sites LOOP
  v_master := v_master || jsonb_build_array(core10.control_check_v1(p_business, 'inventory.stock_event', s));
 END LOOP;
 ctl := core10._inventory_controls_v1(p_business, p_kind, v_sites, v_master);
 IF NOT core10.can_manage(t,p_business) AND NOT (ctl->>'staff_allowed')::boolean THEN RAISE EXCEPTION 'INV_PERMISSION_DENIED'; END IF;
 IF p_kind='transfer' AND v_src_site<>v_dst_site AND NOT (ctl->>'allow_cross_site')::boolean THEN RAISE EXCEPTION 'CONTROL_LIMIT:allow_cross_site'; END IF;
 IF p_quantity > (ctl->>'max_qty')::numeric THEN
  RAISE EXCEPTION 'CONTROL_LIMIT:%', CASE WHEN p_kind LIKE 'adjust%' THEN 'max_adjust_qty' ELSE 'max_qty' END;
 END IF;
 IF p_kind LIKE 'adjust%' AND (ctl->>'reason_required')::boolean AND v_reason IS NULL THEN RAISE EXCEPTION 'INV_REASON_REQUIRED'; END IF;
 -- 3. Idempotency: serialize one business+key, then replay or create.
 PERFORM pg_advisory_xact_lock(hashtextextended('c10inv:'||p_business||':'||p_request, 0));
 v_sha := encode(sha256(convert_to(jsonb_build_object('a','create','k',p_kind,'s',p_source,'d',p_destination,
  'i',p_item,'q',p_quantity,'r',v_reason)::text,'UTF8')),'hex');
 SELECT * INTO r FROM core10.inventory_command_requests_v1 WHERE business_id=p_business AND request_key=p_request;
 IF FOUND THEN
  IF r.actor_id<>v_actor OR r.action<>'create' OR r.intent_sha256<>v_sha THEN RAISE EXCEPTION 'INV_REPLAY_CONFLICT'; END IF;
  SELECT * INTO c FROM core10.inventory_commands_v1 WHERE id=r.command_id;
  RETURN core10._inventory_command_json_v1(c, true);
 END IF;
 INSERT INTO core10.inventory_commands_v1(tenant_id,business_id,kind,source_location,source_site_id,destination_location,
  destination_site_id,item_id,quantity,reason,request_key,created_by)
 VALUES (t,p_business,p_kind,p_source,v_src_site,p_destination,v_dst_site,p_item,p_quantity,v_reason,p_request,v_actor)
 RETURNING * INTO c;
 INSERT INTO core10.inventory_command_requests_v1(business_id,request_key,tenant_id,actor_id,command_id,action,expected_version,intent_sha256)
 VALUES (p_business,p_request,t,v_actor,c.id,'create',NULL,v_sha);
 PERFORM core10._append_canonical_audit_v1(t,p_business,'inventory','command:'||c.id||':created','inventory.command_created',
  v_actor,'inventory:'||p_business||':'||p_request,
  jsonb_build_object('command_id',c.id,'kind',p_kind,'item_id',p_item,'quantity',p_quantity,'source_location',p_source,
   'destination_location',p_destination,'reason',v_reason,'stages',(ctl->>'stages')::int));
 RETURN core10._inventory_command_json_v1(c, false);
END $$;

-- confirm (draft -> confirmed), post (confirmed -> posted, moves stock through the 0200 engine), cancel (draft or
-- confirmed -> cancelled). p_version is the version the caller saw; stale versions are refused.
CREATE FUNCTION core10.advance_inventory_command_v1(p_command bigint, p_action text, p_version integer, p_request text)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE v_actor uuid := core10.actor_uid(); c core10.inventory_commands_v1%ROWTYPE; pre core10.inventory_commands_v1%ROWTYPE;
 r core10.inventory_command_requests_v1%ROWTYPE; ctl jsonb := '{}'; v_master jsonb := '[]'; s bigint;
 v_sha text; v_sites bigint[]; v_ref bigint; v_appr jsonb := '{}';
BEGIN
 IF v_actor IS NULL OR p_action IS NULL OR p_action NOT IN ('confirm','post','cancel') OR p_version IS NULL OR p_version<1
  OR p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,100}$' THEN RAISE EXCEPTION 'INV_INVALID_ACTION'; END IF;
 -- Authorize before locking an untrusted row; re-check after the lock.
 SELECT * INTO pre FROM core10.inventory_commands_v1 WHERE id=p_command;
 IF NOT FOUND OR NOT core10.can_see_business(pre.tenant_id,pre.business_id) THEN RAISE EXCEPTION 'INV_SCOPE'; END IF;
 IF NOT core10._inventory_may_act_v1(pre.tenant_id,pre.business_id,pre.source_location,pre.destination_location)
 THEN RAISE EXCEPTION 'INV_PERMISSION_DENIED'; END IF;
 SELECT * INTO c FROM core10.inventory_commands_v1 WHERE id=p_command FOR UPDATE;
 -- Re-validate committed Auth membership/site rights after the row lock: a concurrent revocation must win.
 IF NOT core10.can_see_business(c.tenant_id,c.business_id) THEN RAISE EXCEPTION 'INV_SCOPE'; END IF;
 IF p_action<>'cancel' AND NOT core10._inventory_may_act_v1(c.tenant_id,c.business_id,c.source_location,c.destination_location)
 THEN RAISE EXCEPTION 'INV_PERMISSION_DENIED'; END IF;
 v_sites := array_remove(ARRAY[c.source_site_id, CASE WHEN c.destination_site_id IS DISTINCT FROM c.source_site_id
  THEN c.destination_site_id END], NULL);
 -- Cancel needs no Owner Control (it moves nothing): the creator or a manager may withdraw an unposted command.
 -- Confirm and post re-check the master switch and the kind's feature on every touched site.
 IF p_action='cancel' THEN
  IF c.created_by<>v_actor AND NOT core10.can_manage(c.tenant_id,c.business_id) THEN RAISE EXCEPTION 'INV_PERMISSION_DENIED'; END IF;
 ELSE
  FOREACH s IN ARRAY v_sites LOOP
   v_master := v_master || jsonb_build_array(core10.control_check_v1(c.business_id, 'inventory.stock_event', s));
  END LOOP;
  ctl := core10._inventory_controls_v1(c.business_id, c.kind, v_sites, v_master);
  IF NOT core10.can_manage(c.tenant_id,c.business_id) AND NOT (ctl->>'staff_allowed')::boolean THEN RAISE EXCEPTION 'INV_PERMISSION_DENIED'; END IF;
 END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('c10inv:'||c.business_id||':'||p_request, 0));
 v_sha := encode(sha256(convert_to(jsonb_build_object('a',p_action,'c',p_command,'v',p_version)::text,'UTF8')),'hex');
 SELECT * INTO r FROM core10.inventory_command_requests_v1 WHERE business_id=c.business_id AND request_key=p_request;
 IF FOUND THEN
  IF r.actor_id<>v_actor OR r.command_id<>p_command OR r.action<>p_action OR r.intent_sha256<>v_sha THEN
   RAISE EXCEPTION 'INV_REPLAY_CONFLICT';
  END IF;
  RETURN core10._inventory_command_json_v1(c, true);
 END IF;
 IF c.version<>p_version THEN RAISE EXCEPTION 'INV_STALE_VERSION:%', c.version; END IF;
 IF p_action='confirm' THEN
  IF c.status<>'draft' THEN RAISE EXCEPTION 'INV_INVALID_TRANSITION'; END IF;
  IF (ctl->>'separate_confirmer')::boolean AND c.created_by=v_actor THEN RAISE EXCEPTION 'INV_SAME_ACTOR'; END IF;
  UPDATE core10.inventory_commands_v1 SET status='confirmed',confirmed_by=v_actor,confirmed_at=now(),version=version+1
   WHERE id=c.id RETURNING * INTO c;
 ELSIF p_action='cancel' THEN
  IF c.status NOT IN ('draft','confirmed') THEN RAISE EXCEPTION 'INV_INVALID_TRANSITION'; END IF;
  UPDATE core10.inventory_commands_v1 SET status='cancelled',cancelled_by=v_actor,cancelled_at=now(),version=version+1
   WHERE id=c.id RETURNING * INTO c;
 ELSE
  IF c.status<>'confirmed' THEN RAISE EXCEPTION 'INV_CONFIRM_FIRST'; END IF;
  IF c.kind LIKE 'adjust%' THEN
   IF c.quantity > (ctl->>'max_qty')::numeric THEN RAISE EXCEPTION 'CONTROL_LIMIT:max_adjust_qty'; END IF;
  ELSIF c.quantity > (ctl->>'max_qty')::numeric THEN RAISE EXCEPTION 'CONTROL_LIMIT:max_qty';
  END IF;
  IF c.kind='transfer' AND c.source_site_id<>c.destination_site_id AND NOT (ctl->>'allow_cross_site')::boolean
  THEN RAISE EXCEPTION 'CONTROL_LIMIT:allow_cross_site'; END IF;
  -- Approval port: never self-approve or fabricate a receipt (hook replaced by the GOV-002 adapter in 0202).
  v_appr := core10._inventory_approval_gate_v1(c.id, (ctl->>'stages')::int);
  BEGIN
   IF c.kind='transfer' THEN
    v_ref := core10.transfer_stock_v1(c.source_location,c.destination_location,c.item_id,c.quantity,'c10-inv-cmd-'||c.id);
   ELSE
    v_ref := core10.post_stock_event(coalesce(c.source_location,c.destination_location),c.item_id,
     CASE WHEN c.kind IN ('receive','adjust_in') THEN c.quantity ELSE -c.quantity END,'c10-inv-cmd-'||c.id);
   END IF;
  EXCEPTION WHEN raise_exception THEN
   -- The one ledger never goes below zero; a negative-stock switch cannot change that yet.
   IF SQLERRM='insufficient_stock' AND (ctl->>'allow_negative_stock')::boolean THEN
    RAISE EXCEPTION 'INV_NEGATIVE_STOCK_NOT_CONNECTED';
   END IF;
   RAISE EXCEPTION 'INV_%', upper(SQLERRM);
  END;
  UPDATE core10.inventory_commands_v1 SET status='posted',posted_by=v_actor,posted_at=now(),stock_ref=v_ref,version=version+1
   WHERE id=c.id RETURNING * INTO c;
 END IF;
 INSERT INTO core10.inventory_command_requests_v1(business_id,request_key,tenant_id,actor_id,command_id,action,expected_version,intent_sha256)
 VALUES (c.business_id,p_request,c.tenant_id,v_actor,c.id,p_action,p_version,v_sha);
 PERFORM core10._append_canonical_audit_v1(c.tenant_id,c.business_id,'inventory',
  'command:'||c.id||':'||c.status,'inventory.command_'||c.status,v_actor,'inventory:'||c.business_id||':'||p_request,
  jsonb_build_object('command_id',c.id,'kind',c.kind,'from_version',p_version,'to_version',c.version,'stock_ref',c.stock_ref)
   || v_appr);
 RETURN core10._inventory_command_json_v1(c, false);
END $$;


CREATE FUNCTION c10_demo.a056_consent_state(p_customer bigint,p_channel text,p_purpose text) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $f$
#variable_conflict use_column
DECLARE c c10_demo.a056_customers%ROWTYPE; e c10_demo.a056_consent_events%ROWTYPE; blocked boolean; hashes text[];
BEGIN
 SELECT * INTO c FROM c10_demo.a056_customers WHERE id=p_customer;
 IF NOT FOUND OR c.status<>'active' THEN RETURN jsonb_build_object('can_send',false,'reason','customer_inactive'); END IF;
 hashes:=ARRAY['cust:'||c.id::text];
 IF p_channel='email' AND c.email_norm IS NOT NULL THEN hashes:=hashes||c10_demo.a056_sha('email:'||c.email_norm);
 ELSIF p_channel IN('sms','phone','whatsapp') AND c.phone_norm IS NOT NULL THEN hashes:=hashes||c10_demo.a056_sha('phone:'||c.phone_norm); END IF;
 SELECT EXISTS(SELECT 1 FROM c10_demo.a056_suppressions s WHERE s.business_id=c.business_id AND s.channel=p_channel AND s.lifted_at IS NULL
   AND s.addr_hash=ANY(hashes) AND (s.purpose=p_purpose OR s.purpose='service')) INTO blocked;
 IF blocked THEN RETURN jsonb_build_object('can_send',false,'reason','opt_out_precedence'); END IF;
 SELECT * INTO e FROM c10_demo.a056_consent_events WHERE customer_id=p_customer AND channel=p_channel AND purpose=p_purpose ORDER BY id DESC LIMIT 1;
 IF NOT FOUND THEN RETURN jsonb_build_object('can_send',false,'reason','no_consent'); END IF;
 IF e.status<>'granted' THEN RETURN jsonb_build_object('can_send',false,'reason','revoked'); END IF;
 IF e.valid_until IS NOT NULL AND e.valid_until<=now() THEN RETURN jsonb_build_object('can_send',false,'reason','expired'); END IF;
 RETURN jsonb_build_object('can_send',true,'reason','granted');
END $f$;

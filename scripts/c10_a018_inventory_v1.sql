GRANT EXECUTE ON FUNCTION c10_demo.transfer_stock_v1(bigint,bigint,bigint,numeric,text) TO authenticated;
REVOKE ALL ON c10_demo.inventory_reconciliation_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.inventory_reconciliation_v1 TO authenticated;

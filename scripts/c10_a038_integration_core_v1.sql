-- one-press kill switch for a whole business
CREATE FUNCTION c10_demo.integration_kill_switch_v1(p_business bigint)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint;n integer;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF NOT FOUND OR NOT c10_demo.can_manage(t,p_business) THEN RAISE EXCEPTION 'integration_denied'; END IF;
 UPDATE c10_demo.integration_account_v1 SET mode='off',updated_at=now()
  WHERE business_id=p_business AND mode<>'off';
 GET DIAGNOSTICS n=ROW_COUNT;
 PERFORM c10_demo._integration_audit_v1(t,p_business,NULL,'kill_switch',NULL,jsonb_build_object('turned_off',n));
 RETURN n;
END $$;


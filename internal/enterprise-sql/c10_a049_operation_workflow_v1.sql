CREATE FUNCTION c10_demo.set_operation_profile_v1(p_business bigint,p_sales_staff boolean,p_receive_staff boolean,p_prod_mode text,p_version bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $fn$
DECLARE t bigint; outv bigint;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF c10_demo.actor_uid() IS NULL OR t IS NULL OR NOT c10_demo.can_manage(t,p_business)
 THEN RAISE EXCEPTION 'A049_OWNER_REQUIRED'; END IF;
 IF p_sales_staff IS NULL OR p_receive_staff IS NULL OR
    p_prod_mode NOT IN('manual_preview','bom_assisted_preview') OR
    p_version IS NULL OR p_version<1
 THEN RAISE EXCEPTION 'A049_POLICY_INVALID'; END IF;
 INSERT INTO c10_demo.operation_profiles_v1(tenant_id,business_id,changed_by)
 VALUES(t,p_business,c10_demo.actor_uid()) ON CONFLICT(business_id) DO NOTHING;
 UPDATE c10_demo.operation_profiles_v1 SET sales_staff_enabled=p_sales_staff,
  receiving_staff_enabled=p_receive_staff,production_mode=p_prod_mode,
  changed_by=c10_demo.actor_uid(),changed_at=now(),version=version+1
 WHERE business_id=p_business AND version=p_version RETURNING version INTO outv;
 IF outv IS NULL THEN RAISE EXCEPTION 'A049_POLICY_STALE'; END IF;
 RETURN jsonb_build_object('business_id',p_business,'version',outv);
END; $fn$;
CREATE FUNCTION c10_demo.create_operation_order_v1(p_business bigint,p_location bigint,p_item bigint,p_kind text,p_quantity numeric,p_unit_value numeric,p_external text,p_request text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $fn$
DECLARE loc c10_demo.stock_locations%ROWTYPE; prev c10_demo.operation_orders_v1%ROWTYPE; policy c10_demo.operation_profiles_v1%ROWTYPE;
BEGIN
 SELECT * INTO loc FROM c10_demo.stock_locations WHERE id=p_location;
 IF c10_demo.actor_uid() IS NULL OR loc.id IS NULL OR loc.business_id<>p_business OR
 p_kind IS NULL OR p_kind NOT IN('purchase_receive','sale_issue','production_plan') OR
 p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,100}$' OR
 p_quantity IS NULL OR p_quantity<=0 OR p_quantity>1000000 OR p_quantity<>round(p_quantity,3) OR
 p_unit_value IS NULL OR p_unit_value<0 OR p_unit_value>100000000 OR p_unit_value<>round(p_unit_value,2) OR
 p_external IS NOT NULL AND length(p_external)>120
 THEN RAISE EXCEPTION 'A049_ORDER_INVALID'; END IF;
 IF NOT EXISTS(SELECT 1 FROM c10_demo.items WHERE id=p_item AND tenant_id=loc.tenant_id AND business_id=loc.business_id)
 THEN RAISE EXCEPTION 'A049_ITEM_SCOPE'; END IF;
 INSERT INTO c10_demo.operation_profiles_v1(tenant_id,business_id,changed_by)
 VALUES(loc.tenant_id,p_business,c10_demo.actor_uid()) ON CONFLICT(business_id) DO NOTHING;
 SELECT * INTO policy FROM c10_demo.operation_profiles_v1 WHERE business_id=p_business;
 IF NOT c10_demo.can_manage(loc.tenant_id,p_business) AND
    (p_kind='production_plan' OR
    (p_kind='sale_issue' AND NOT policy.sales_staff_enabled) OR
    (p_kind='purchase_receive' AND NOT policy.receiving_staff_enabled) OR
    NOT c10_demo.inventory_action_authorized_v1(loc.tenant_id,p_business,p_location,'stock.post'))
 THEN RAISE EXCEPTION 'A049_ORDER_DENIED'; END IF;
 INSERT INTO c10_demo.operation_orders_v1(tenant_id,business_id,site_id,location_id,item_id,kind,quantity,estimated_unit_value,external_ref,request_key,created_by)
 VALUES(loc.tenant_id,p_business,loc.site_id,p_location,p_item,p_kind,p_quantity,p_unit_value,p_external,p_request,c10_demo.actor_uid())
 ON CONFLICT (business_id,request_key) DO NOTHING;
 SELECT * INTO prev FROM c10_demo.operation_orders_v1 WHERE business_id=p_business AND request_key=p_request;
 IF prev.created_by<>c10_demo.actor_uid() OR prev.kind<>p_kind OR prev.location_id<>p_location OR prev.item_id<>p_item OR
 prev.quantity<>p_quantity OR prev.estimated_unit_value<>p_unit_value OR prev.external_ref IS DISTINCT FROM p_external
 THEN RAISE EXCEPTION 'A049_REQUEST_REPLAY_CONFLICT'; END IF;
 INSERT INTO c10_demo.operation_audit_v1(tenant_id,business_id,order_id,event,actor,request_key)
 VALUES(loc.tenant_id,p_business,prev.id,'created',c10_demo.actor_uid(),'create-'||p_request)
 ON CONFLICT(business_id,request_key) DO NOTHING;
 RETURN jsonb_build_object('order_id',prev.id,'status',prev.status,'business_id',p_business,'version',prev.version);
END; $fn$;
CREATE FUNCTION c10_demo.advance_operation_order_v1(p_order bigint,p_action text,p_expected bigint,p_request text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $fn$
DECLARE o c10_demo.operation_orders_v1%ROWTYPE; policy c10_demo.operation_profiles_v1%ROWTYPE; command jsonb; inv_id bigint;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_action NOT IN('confirm','post') OR
 p_expected IS NULL OR p_expected<1 OR p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,100}$'
 THEN RAISE EXCEPTION 'A049_ACTION_INVALID'; END IF;
 SELECT * INTO o FROM c10_demo.operation_orders_v1 WHERE id=p_order FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'A049_ORDER_NOT_FOUND'; END IF;
 SELECT * INTO policy FROM c10_demo.operation_profiles_v1 WHERE business_id=o.business_id;
 IF NOT c10_demo.can_manage(o.tenant_id,o.business_id) AND
   ((o.kind='production_plan') OR
   (o.kind='sale_issue' AND NOT policy.sales_staff_enabled) OR
   (o.kind='purchase_receive' AND NOT policy.receiving_staff_enabled) OR
   NOT c10_demo.inventory_action_authorized_v1(o.tenant_id,o.business_id,o.location_id,'stock.post'))
 THEN RAISE EXCEPTION 'A049_ACTION_DENIED'; END IF;
 IF o.status='posted' AND p_action='post' AND o.post_request_key=p_request THEN
  RETURN jsonb_build_object('order_id',o.id,'status','posted','version',o.version,'replayed',true);
 END IF;
 IF o.version<>p_expected THEN RAISE EXCEPTION 'A049_STALE_ORDER'; END IF;
 IF p_action='confirm' THEN
  IF o.status<>'draft' THEN RAISE EXCEPTION 'A049_CONFIRM_TRANSITION'; END IF;
  UPDATE c10_demo.operation_orders_v1 SET status='confirmed',confirmed_by=c10_demo.actor_uid(),version=version+1 WHERE id=o.id;
 ELSE
  IF o.kind='production_plan' THEN RAISE EXCEPTION 'A049_PRODUCTION_REQUIRES_A027_BOM'; END IF;
  IF o.status<>'confirmed' THEN RAISE EXCEPTION 'A049_POST_TRANSITION'; END IF;
  command:=c10_demo.create_inventory_command_v1(o.business_id,
   CASE WHEN o.kind='purchase_receive' THEN 'receive' ELSE 'issue' END,
   CASE WHEN o.kind='sale_issue' THEN o.location_id ELSE NULL END,
   CASE WHEN o.kind='purchase_receive' THEN o.location_id ELSE NULL END,
   o.item_id,o.quantity,'a049-command-'||o.id);
  inv_id:=(command->>'command_id')::bigint;
  PERFORM c10_demo.advance_inventory_command_v1(inv_id,'confirm',1,'a049-confirm-'||o.id);
  PERFORM c10_demo.advance_inventory_command_v1(inv_id,'post',2,'a049-post-'||o.id);
  UPDATE c10_demo.operation_orders_v1 SET status='posted',posted_by=c10_demo.actor_uid(),
    posted_at=now(),version=version+1,linked_inventory_command=inv_id,post_request_key=p_request WHERE id=o.id;
 END IF;
 INSERT INTO c10_demo.operation_audit_v1(tenant_id,business_id,order_id,event,actor,request_key)
 VALUES(o.tenant_id,o.business_id,o.id,CASE WHEN p_action='confirm' THEN 'confirmed' ELSE 'posted' END,
 c10_demo.actor_uid(),'a049-'||p_action||'-'||p_request);
 RETURN jsonb_build_object('order_id',o.id,'status',CASE WHEN p_action='confirm' THEN 'confirmed' ELSE 'posted' END,
 'version',o.version+1,'replayed',false,'inventory_command_id',inv_id,
 'financial_posted',false,'certified_cogs',false);
END; $fn$;
CREATE FUNCTION c10_demo.read_operation_overview_v1(p_business bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $fn$
DECLARE t bigint; r jsonb;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF t IS NULL OR NOT c10_demo.can_see_business(t,p_business) THEN RAISE EXCEPTION 'A049_READ_DENIED'; END IF;
 SELECT COALESCE(jsonb_agg(jsonb_build_object(
  'id',o.id,'kind',o.kind,'status',o.status,'site_id',o.site_id,'location_id',o.location_id,
  'item_id',o.item_id,'quantity',o.quantity,'estimated_unit_value',o.estimated_unit_value,
  'estimate_total',o.quantity*o.estimated_unit_value,'version',o.version,
  'inventory_command_id',o.linked_inventory_command)
  ORDER BY o.id DESC),'[]'::jsonb) INTO r
 FROM c10_demo.operation_orders_v1 o WHERE o.business_id=p_business AND
 c10_demo.can_site(o.tenant_id,o.business_id,o.site_id,'stock.read');
 RETURN jsonb_build_object('business_id',p_business,'server_authorized',true,'items',r,
  'financial_posted',false,'certified_cogs',false,'production_posting_built',false,
  'operationally_certified',false);
END; $fn$;

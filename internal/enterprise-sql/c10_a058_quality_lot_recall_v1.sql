-- CORE10 C10-A058 QUALITY + LOT / EXPIRY / RECALL
-- ADDITIVE DISPOSABLE c10_demo PostgreSQL 17 module only; NEVER run against IMG-ERP-SG.
-- Requires C10-A018 demo backend + c10_a018_inventory_v1.sql. No live data or payment calls.
-- Canonical stock_movements and balances remain the stock source of truth.
-- This module enforces lot-linked commands for items EXPLICITLY enrolled in quality tracking.
-- NOT a production migration, GoTrue certification, accounting/COGS implementation or live release.

CREATE TABLE c10_demo.quality_tracked_items_v1 (
 tenant_id bigint NOT NULL, business_id bigint NOT NULL, item_id bigint NOT NULL,
 enabled_by uuid NOT NULL, enabled_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY(business_id,item_id),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id)
);
CREATE TABLE c10_demo.quality_lots_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL, item_id bigint NOT NULL,
 origin_site_id bigint NOT NULL, lot_code text NOT NULL CHECK(length(btrim(lot_code)) BETWEEN 2 AND 80),
 source_kind text NOT NULL CHECK(source_kind IN('purchase','production','opening','return','adjustment')),
 source_reference text NOT NULL CHECK(length(btrim(source_reference)) BETWEEN 2 AND 120),
 manufacture_date date, expiry_date date,
 status text NOT NULL DEFAULT 'pending_qc'
  CHECK(status IN('pending_qc','released','held','rejected','recalled')),
 created_by uuid NOT NULL, created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 released_inspection_id bigint,
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(id,tenant_id,business_id),
 UNIQUE(id,tenant_id,business_id,item_id),
 UNIQUE(business_id,item_id,lot_code),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id),
 FOREIGN KEY(origin_site_id,tenant_id,business_id) REFERENCES c10_demo.sites(id,tenant_id,business_id),
 CHECK(expiry_date IS NULL OR manufacture_date IS NULL OR expiry_date>=manufacture_date)
);
CREATE TABLE c10_demo.quality_inspections_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL, lot_id bigint NOT NULL,
 result text NOT NULL CHECK(result IN('pass','fail')),
 checks jsonb NOT NULL CHECK(jsonb_typeof(checks)='array' AND jsonb_array_length(checks) BETWEEN 1 AND 30),
 notes text NOT NULL DEFAULT '' CHECK(length(notes)<=1000),
 inspected_by uuid NOT NULL, inspected_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 FOREIGN KEY(lot_id,tenant_id,business_id) REFERENCES c10_demo.quality_lots_v1(id,tenant_id,business_id)
);
ALTER TABLE c10_demo.quality_lots_v1 ADD CONSTRAINT quality_release_inspection_fk
 FOREIGN KEY(released_inspection_id) REFERENCES c10_demo.quality_inspections_v1(id);
CREATE TABLE c10_demo.quality_commands_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL, operation text NOT NULL,
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 3 AND 120),
 payload jsonb NOT NULL, actor_id uuid NOT NULL,
 result_id bigint, created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(business_id,request_key)
);
CREATE TABLE c10_demo.quality_stock_permits_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL,

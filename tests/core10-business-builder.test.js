"use strict";
const assert=require("node:assert/strict");
const c=require("../data/core10_capability_catalog_v1.json"),b=require("../core10-business-builder.js");
const model={name:"Example Food Business",slug:"example-food-business",templateId:"sweets_bakery",
 brandHex:"#315B76",mode:"advanced",sites:[{kind:"showroom",label:"Main"}],modules:["stock"]};
const context={legalId:1,requestKey:"test-request"};
assert.equal(b.validate(c,model).ok,true);
assert.equal(b.validate(c,{...model,templateId:"unknown"}).ok,false);
assert.equal(b.validate(c,{...model,sites:[...model.sites,...model.sites]}).ok,false);
assert.equal(b.validate(c,{...model,modules:["stock","stock"]}).ok,false);
assert.equal(b.validate(c,{...model,modules:["role_admin"]}).ok,false);
assert.equal(b.validate(c,{...model,mode:"quick"}).ok,false);
assert.equal(b.validate(c,{...model,mode:"quick",sites:[]}).ok,true);
assert.equal(b.validate(c,{...model,sites:Array.from({length:301},(_,i)=>({kind:"warehouse",label:"Warehouse "+i}))}).ok,true);
const template=c.templates.find(t=>t.id==="sweets_bakery");
assert.equal(template.source_code,null);
assert.equal(template.source_status,"needs_setup");
assert.equal(template.readiness,"partial");
assert.throws(()=>b.toBackendInput(c,model,context),/TEMPLATE_BACKEND_UNAVAILABLE/);
const unsafe=JSON.parse(JSON.stringify(c)),unsafeT=unsafe.templates.find(t=>t.id==="sweets_bakery");
unsafeT.source_code="food_manufacturing";unsafeT.source_status="available";
assert.throws(()=>b.toBackendInput(unsafe,model,context),/SHARED_TEMPLATE_MUST_USE_INDEPENDENT_ADAPTER/);
const verified=JSON.parse(JSON.stringify(c)),verifiedT=verified.templates.find(t=>t.id==="sweets_bakery");
verifiedT.source_status="available";verifiedT.source_code="verified_independent_food_adapter";
const mapped=b.toBackendInput(verified,model,context);
assert.equal(mapped.template,"verified_independent_food_adapter");assert.equal(mapped.sites.length,1);
const local=b.create({catalog:c});local.update(model);
assert.equal(local.preview().production_ready,false);assert.equal(local.validate().ok,true);
assert.throws(()=>local.update({isAdmin:true}),/UNKNOWN_FIELD/);
async function run(){
 await assert.rejects(()=>local.provision(context),/BUSINESS_SETUP_RELEASE_LOCKED/);
 let called=0;
 const blocked=b.create({catalog:c,releaseEnabled:true,enterpriseClient:{setupBusiness:async()=>{called++;}}});
 blocked.update(model);
 await assert.rejects(()=>blocked.provision(context),/TEMPLATE_BACKEND_UNAVAILABLE/);
 assert.equal(called,0);
 const good=b.create({catalog:verified,releaseEnabled:true,enterpriseClient:{setupBusiness:async payload=>{called++;return payload}}});
 good.update(model);
 await assert.rejects(()=>good.provision({legalId:0,requestKey:"key"}),/AUTHORIZED_LEGAL_ENTITY_REQUIRED/);
 const result=await good.provision({legalId:5,requestKey:"key"});
 assert.equal(result.legalId,5);assert.equal(called,1);
 console.log("PASS: 10-template builder; generic food backend isolated from customized legacy; release remains locked");
}
run().catch(e=>{console.error(e);process.exitCode=1});

-- ---------- internal helpers ----------
CREATE FUNCTION core10._proc_sha_v1(p jsonb) RETURNS text LANGUAGE sql IMMUTABLE SET search_path=pg_catalog,core10 AS $$
 SELECT encode(sha256(convert_to(p::text,'UTF8')),'hex') $$;

-- Serialize one business+key; return the earlier entity for an identical replay, refuse anything else.
CREATE FUNCTION core10._proc_replay_v1(p_business bigint, p_key text, p_action text, p_sha text) RETURNS bigint
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE r core10.procurement_requests_v1%ROWTYPE;
BEGIN
 IF p_key IS NULL OR p_key !~ '^[A-Za-z0-9_-]{8,100}$' THEN RAISE EXCEPTION 'PROC_INVALID_KEY'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('c10proc:'||p_business||':'||p_key, 0));
 SELECT * INTO r FROM core10.procurement_requests_v1 WHERE business_id=p_business AND request_key=p_key;
 IF NOT FOUND THEN RETURN NULL; END IF;
 IF r.actor_id<>core10.actor_uid() OR r.action<>p_action OR r.intent_sha256<>p_sha THEN RAISE EXCEPTION 'PROC_REPLAY_CONFLICT'; END IF;
 RETURN r.entity_id;
END $$;

CREATE FUNCTION core10._proc_record_v1(p_tenant bigint, p_business bigint, p_key text, p_action text, p_id bigint,
 p_sha text, p_ref text, p_payload jsonb) RETURNS void
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
BEGIN
 INSERT INTO core10.procurement_requests_v1(business_id,request_key,tenant_id,actor_id,action,entity_id,intent_sha256)
 VALUES (p_business,p_key,p_tenant,core10.actor_uid(),p_action,p_id,p_sha);
 PERFORM core10._append_canonical_audit_v1(p_tenant,p_business,'procurement',p_ref,'procurement.'||p_action,
  core10.actor_uid(),'procurement:'||p_business||':'||p_key,p_payload);
END $$;

CREATE FUNCTION core10._proc_grn_json_v1(p_grn bigint) RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
 SELECT jsonb_build_object('grn_id',g.id,'po_id',g.po_id,'business_id',g.business_id,'site_id',g.site_id,
  'location_id',g.location_id,'supplier_ref',g.supplier_ref,'status',g.status,'version',g.version,
  'received_by',g.received_by,'received_at',g.received_at,'inspected_by',g.inspected_by,'posted_by',g.posted_by,
  'posted_at',g.posted_at,'lines',coalesce((SELECT jsonb_agg(jsonb_build_object('line_no',l.line_no,'item_id',l.item_id,
   'received_qty',l.received_qty,'accepted_qty',l.accepted_qty,
   'rejected_qty',CASE WHEN l.accepted_qty IS NULL THEN NULL ELSE l.received_qty-l.accepted_qty END,
   'qc_notes',l.qc_notes,'lot_code',l.lot_code,'manufactured_on',l.manufactured_on,'expires_on',l.expires_on,
   'lot_id',l.lot_id,'stock_movement_id',l.stock_movement_id) ORDER BY l.line_no)
   FROM core10.goods_receipt_lines_v1 l WHERE l.grn_id=g.id),'[]'::jsonb))
 FROM core10.goods_receipts_v1 g WHERE g.id=p_grn
$$;

CREATE FUNCTION core10._proc_po_json_v1(p_po bigint) RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
 SELECT jsonb_build_object('po_id',p.id,'business_id',p.business_id,'site_id',p.site_id,'supplier_id',p.supplier_id,
  'supplier_name_en',s.name_en,'supplier_name_bn',s.name_bn,'status',p.status,'version',p.version,
  'expected_on',p.expected_on,'note',p.note,'total_amount',p.total_amount,'created_by',p.created_by,
  'created_at',p.created_at,'approved_by',p.approved_by,
  'lines',coalesce((SELECT jsonb_agg(jsonb_build_object('line_no',l.line_no,'item_id',l.item_id,'sku',i.sku,
    'name_en',i.name_en,'name_bn',i.name_bn,'quantity',l.quantity,'unit_price',l.unit_price,
    'amount',round(l.quantity*l.unit_price,2),'accepted_qty',l.accepted_qty,'rejected_qty',l.rejected_qty) ORDER BY l.line_no)
    FROM core10.purchase_order_lines_v1 l JOIN core10.items i ON i.id=l.item_id WHERE l.po_id=p.id),'[]'::jsonb))
 FROM core10.purchase_orders_v1 p JOIN core10.master_parties_v1 s ON s.id=p.supplier_id WHERE p.id=p_po
$$;

-- Quantity still open on a PO line: ordered minus accepted on posted receipts minus received on unposted ones.
CREATE FUNCTION core10._proc_open_qty_v1(p_po bigint, p_line integer) RETURNS numeric
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
 SELECT l.quantity - coalesce((SELECT sum(CASE WHEN g.status='posted' THEN gl.accepted_qty ELSE gl.received_qty END)
   FROM core10.goods_receipt_lines_v1 gl JOIN core10.goods_receipts_v1 g ON g.id=gl.grn_id
   WHERE gl.po_id=p_po AND gl.line_no=p_line),0)
 FROM core10.purchase_order_lines_v1 l WHERE l.po_id=p_po AND l.line_no=p_line
$$;

-- ---------- purchase orders ----------
-- p_lines: [{"item_id":..,"quantity":..,"unit_price":..}, ...]; p_po NULL + expected_version 0 = create,
-- p_po + expected_version N = edit that draft at version N.
CREATE FUNCTION core10.procurement_save_po_v1(p_business bigint, p_po bigint, p_site bigint, p_supplier bigint, p_lines jsonb,
 p_expected_on date, p_note text, p_expected_version integer, p_key text) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE v_actor uuid := core10.actor_uid(); t bigint; c jsonb; v_sha text; v_id bigint; v_total numeric := 0;
 e jsonb; n int := 0; v_item bigint; v_qty numeric; v_price numeric;
BEGIN
 SELECT tenant_id INTO t FROM core10.businesses WHERE id=p_business;
 IF v_actor IS NULL OR t IS NULL OR NOT core10.can_see_business(t,p_business) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 IF NOT core10.can_business(t,p_business) THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 IF NOT EXISTS(SELECT 1 FROM core10.sites WHERE id=p_site AND business_id=p_business AND tenant_id=t) THEN RAISE EXCEPTION 'PROC_SITE_SCOPE'; END IF;
 c := core10.control_check_v1(p_business, 'procurement.purchase_order', p_site);
 IF NOT core10.can_manage(t,p_business) AND NOT (c->'params'->>'manager_may_create')::boolean THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 v_sha := core10._proc_sha_v1(jsonb_build_object('po',p_po,'s',p_site,'p',p_supplier,'l',p_lines,'d',p_expected_on,'n',p_note,'v',p_expected_version));
 v_id := core10._proc_replay_v1(p_business,p_key,'po_save',v_sha);
 IF v_id IS NOT NULL THEN RETURN core10._proc_po_json_v1(v_id) || '{"replayed":true}'; END IF;
 IF NOT EXISTS(SELECT 1 FROM core10.master_parties_v1 WHERE id=p_supplier AND business_id=p_business AND tenant_id=t
   AND party_kind IN ('supplier','both') AND status='active') THEN RAISE EXCEPTION 'PROC_SUPPLIER_INVALID'; END IF;
 IF p_lines IS NULL OR jsonb_typeof(p_lines)<>'array' OR jsonb_array_length(p_lines)<1 THEN RAISE EXCEPTION 'PROC_LINES_INVALID'; END IF;
 IF jsonb_array_length(p_lines) > (c->'params'->>'max_lines')::int THEN RAISE EXCEPTION 'CONTROL_LIMIT:max_lines'; END IF;
 IF p_note IS NOT NULL AND length(p_note)>500 THEN RAISE EXCEPTION 'PROC_LINES_INVALID'; END IF;
 FOR e IN SELECT value FROM jsonb_array_elements(p_lines) LOOP
  IF jsonb_typeof(e)<>'object' OR jsonb_typeof(e->'item_id')<>'number' OR jsonb_typeof(e->'quantity')<>'number'
   OR jsonb_typeof(e->'unit_price')<>'number' THEN RAISE EXCEPTION 'PROC_LINES_INVALID'; END IF;
  v_item := (e->>'item_id')::bigint; v_qty := (e->>'quantity')::numeric; v_price := (e->>'unit_price')::numeric;
  IF v_qty<=0 OR v_qty>1000000 OR v_qty<>round(v_qty,3) OR v_price<0 OR v_price<>round(v_price,2) THEN RAISE EXCEPTION 'PROC_LINES_INVALID'; END IF;
  IF NOT core10.master_item_usable_v1(p_business,v_item) THEN RAISE EXCEPTION 'PROC_ITEM_NOT_USABLE'; END IF;
  v_total := v_total + round(v_qty*v_price,2);
 END LOOP;
 IF (SELECT count(DISTINCT x->>'item_id') FROM jsonb_array_elements(p_lines) x)<>jsonb_array_length(p_lines)
 THEN RAISE EXCEPTION 'PROC_LINES_DUPLICATE_ITEM'; END IF;
 IF v_total > (c->'params'->>'max_po_amount')::numeric THEN RAISE EXCEPTION 'CONTROL_LIMIT:max_po_amount'; END IF;
 IF p_po IS NULL AND coalesce(p_expected_version,-1)=0 THEN
  INSERT INTO core10.purchase_orders_v1(tenant_id,business_id,site_id,supplier_id,expected_on,note,total_amount,request_key,created_by)
  VALUES (t,p_business,p_site,p_supplier,p_expected_on,p_note,v_total,p_key,v_actor) RETURNING id INTO v_id;
 ELSE
  -- only a draft can be edited, and only by someone who could create it
  UPDATE core10.purchase_orders_v1 SET site_id=p_site,supplier_id=p_supplier,expected_on=p_expected_on,note=p_note,
   total_amount=v_total,version=version+1
  WHERE id=p_po AND business_id=p_business AND status='draft' AND version=p_expected_version
  RETURNING id INTO v_id;
  IF v_id IS NULL THEN RAISE EXCEPTION 'PROC_STALE_OR_NOT_DRAFT'; END IF;
  DELETE FROM core10.purchase_order_lines_v1 WHERE po_id=v_id;
 END IF;
 INSERT INTO core10.purchase_order_lines_v1(po_id,tenant_id,business_id,line_no,item_id,quantity,unit_price)
 SELECT v_id,t,p_business,ord::int,(x->>'item_id')::bigint,(x->>'quantity')::numeric,(x->>'unit_price')::numeric
 FROM jsonb_array_elements(p_lines) WITH ORDINALITY AS a(x,ord);
 PERFORM core10._proc_record_v1(t,p_business,p_key,'po_save',v_id,v_sha,'po:'||v_id||':v'||(SELECT version FROM core10.purchase_orders_v1 WHERE id=v_id),
  jsonb_build_object('po_id',v_id,'site_id',p_site,'supplier_id',p_supplier,'lines',jsonb_array_length(p_lines),'total_amount',v_total));
 RETURN core10._proc_po_json_v1(v_id) || '{"replayed":false}';
END $$;

-- approve (draft -> approved), cancel (draft/approved with no receipt -> cancelled), close (short-close an open PO)
CREATE FUNCTION core10.procurement_advance_po_v1(p_po bigint, p_action text, p_version integer, p_key text) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE v_actor uuid := core10.actor_uid(); p core10.purchase_orders_v1%ROWTYPE; c jsonb; v_sha text; v_id bigint;
BEGIN
 IF v_actor IS NULL OR p_action IS NULL OR p_action NOT IN ('approve','cancel','close') OR p_version IS NULL THEN RAISE EXCEPTION 'PROC_INVALID_ACTION'; END IF;
 SELECT * INTO p FROM core10.purchase_orders_v1 WHERE id=p_po;
 IF NOT FOUND OR NOT core10.can_see_business(p.tenant_id,p.business_id) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 IF NOT core10.can_manage(p.tenant_id,p.business_id) AND NOT (p_action='cancel' AND p.created_by=v_actor)
 THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 SELECT * INTO p FROM core10.purchase_orders_v1 WHERE id=p_po FOR UPDATE;
 -- Re-read Auth after the row lock; permission could have been revoked while waiting.
 IF NOT core10.can_see_business(p.tenant_id,p.business_id) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 IF NOT core10.can_manage(p.tenant_id,p.business_id) AND NOT (p_action='cancel' AND p.created_by=v_actor)
 THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 c := core10.control_check_v1(p.business_id, 'procurement.purchase_order', p.site_id);
 v_sha := core10._proc_sha_v1(jsonb_build_object('po',p_po,'a',p_action,'v',p_version));
 v_id := core10._proc_replay_v1(p.business_id,p_key,'po_'||p_action,v_sha);
 IF v_id IS NOT NULL THEN RETURN core10._proc_po_json_v1(v_id) || '{"replayed":true}'; END IF;
 IF p.version<>p_version THEN RAISE EXCEPTION 'PROC_STALE_VERSION:%', p.version; END IF;
 IF p_action='approve' THEN
  IF p.status<>'draft' THEN RAISE EXCEPTION 'PROC_INVALID_TRANSITION'; END IF;
  IF (c->'params'->>'separate_approver')::boolean AND p.created_by=v_actor THEN RAISE EXCEPTION 'PROC_SAME_ACTOR'; END IF;
  IF (c->>'stages')::int>0 THEN RAISE EXCEPTION 'PROC_APPROVAL_NOT_CONNECTED'; END IF;
  UPDATE core10.purchase_orders_v1 SET status='approved',approved_by=v_actor,approved_at=now(),version=version+1 WHERE id=p.id;
 ELSIF p_action='cancel' THEN
  IF p.status NOT IN ('draft','approved') OR EXISTS(SELECT 1 FROM core10.goods_receipts_v1 WHERE po_id=p.id)
  THEN RAISE EXCEPTION 'PROC_INVALID_TRANSITION'; END IF;
  UPDATE core10.purchase_orders_v1 SET status='cancelled',closed_by=v_actor,closed_at=now(),version=version+1 WHERE id=p.id;
 ELSE
  IF p.status NOT IN ('approved','partially_received') OR EXISTS(SELECT 1 FROM core10.goods_receipts_v1 WHERE po_id=p.id AND status<>'posted')
  THEN RAISE EXCEPTION 'PROC_INVALID_TRANSITION'; END IF;
  UPDATE core10.purchase_orders_v1 SET status='closed',closed_by=v_actor,closed_at=now(),version=version+1 WHERE id=p.id;
 END IF;
 PERFORM core10._proc_record_v1(p.tenant_id,p.business_id,p_key,'po_'||p_action,p.id,v_sha,'po:'||p.id||':'||p_action,
  jsonb_build_object('po_id',p.id,'from_version',p_version));
 RETURN core10._proc_po_json_v1(p.id) || '{"replayed":false}';
END $$;

-- ---------- goods receipt ----------
-- p_lines: [{"line_no":1,"quantity":..,"lot_code":"..","manufactured_on":"YYYY-MM-DD","expires_on":"YYYY-MM-DD"}, ...]
CREATE FUNCTION core10.procurement_receive_v1(p_po bigint, p_location bigint, p_lines jsonb, p_supplier_ref text, p_key text)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE v_actor uuid := core10.actor_uid(); p core10.purchase_orders_v1%ROWTYPE; v_site bigint; c jsonb; v_sha text;
 v_id bigint; e jsonb; v_line int; v_qty numeric; v_open numeric; v_item bigint; v_mfg date; v_exp date; v_lot text;
BEGIN
 IF v_actor IS NULL THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 SELECT * INTO p FROM core10.purchase_orders_v1 WHERE id=p_po;
 IF NOT FOUND OR NOT core10.can_see_business(p.tenant_id,p.business_id) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 SELECT site_id INTO v_site FROM core10.stock_locations WHERE id=p_location AND business_id=p.business_id AND tenant_id=p.tenant_id;
 IF v_site IS NULL OR v_site<>p.site_id THEN RAISE EXCEPTION 'PROC_LOCATION_SCOPE'; END IF;
 IF NOT core10.inventory_action_authorized_v1(p.tenant_id,p.business_id,p_location,'stock.post') THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 SELECT * INTO p FROM core10.purchase_orders_v1 WHERE id=p_po FOR UPDATE;
 -- Re-check signed site/post permission after waiting for an exclusive PO lock.
 IF NOT core10.can_see_business(p.tenant_id,p.business_id) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 IF NOT core10.inventory_action_authorized_v1(p.tenant_id,p.business_id,p_location,'stock.post')
 THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 c := core10.control_check_v1(p.business_id, 'procurement.goods_receipt', p.site_id);
 v_sha := core10._proc_sha_v1(jsonb_build_object('po',p_po,'l',p_location,'x',p_lines,'r',p_supplier_ref));
 v_id := core10._proc_replay_v1(p.business_id,p_key,'grn_receive',v_sha);
 IF v_id IS NOT NULL THEN RETURN core10._proc_grn_json_v1(v_id) || '{"replayed":true}'; END IF;
 IF p.status NOT IN ('approved','partially_received') THEN RAISE EXCEPTION 'PROC_PO_NOT_OPEN'; END IF;
 IF p_lines IS NULL OR jsonb_typeof(p_lines)<>'array' OR jsonb_array_length(p_lines) NOT BETWEEN 1 AND 200
  OR (SELECT count(DISTINCT x->>'line_no') FROM jsonb_array_elements(p_lines) x)<>jsonb_array_length(p_lines)
  OR (p_supplier_ref IS NOT NULL AND length(btrim(p_supplier_ref)) NOT BETWEEN 1 AND 80)
 THEN RAISE EXCEPTION 'PROC_LINES_INVALID'; END IF;
 INSERT INTO core10.goods_receipts_v1(tenant_id,business_id,po_id,site_id,location_id,supplier_ref,status,request_key,received_by,
  inspected_by,inspected_at)
 VALUES (p.tenant_id,p.business_id,p.id,v_site,p_location,nullif(btrim(p_supplier_ref),''),
  CASE WHEN (c->'params'->>'qc_required')::boolean THEN 'received' ELSE 'inspected' END,p_key,v_actor,
  CASE WHEN (c->'params'->>'qc_required')::boolean THEN NULL ELSE v_actor END,
  CASE WHEN (c->'params'->>'qc_required')::boolean THEN NULL ELSE now() END)
 RETURNING id INTO v_id;
 FOR e IN SELECT value FROM jsonb_array_elements(p_lines) LOOP
  IF jsonb_typeof(e)<>'object' OR jsonb_typeof(e->'line_no')<>'number' OR jsonb_typeof(e->'quantity')<>'number'
  THEN RAISE EXCEPTION 'PROC_LINES_INVALID'; END IF;
  v_line := (e->>'line_no')::int; v_qty := (e->>'quantity')::numeric;
  v_lot := nullif(btrim(e->>'lot_code'),'');
  BEGIN v_mfg := (e->>'manufactured_on')::date; v_exp := (e->>'expires_on')::date;
  EXCEPTION WHEN others THEN RAISE EXCEPTION 'PROC_LINES_INVALID'; END;
  SELECT item_id INTO v_item FROM core10.purchase_order_lines_v1 WHERE po_id=p.id AND line_no=v_line;
  IF v_item IS NULL OR v_qty<=0 OR v_qty<>round(v_qty,3) THEN RAISE EXCEPTION 'PROC_LINES_INVALID'; END IF;
  v_open := core10._proc_open_qty_v1(p.id,v_line);
  IF v_qty > v_open + round((SELECT quantity FROM core10.purchase_order_lines_v1 WHERE po_id=p.id AND line_no=v_line)
     * (c->'params'->>'over_receipt_pct')::numeric/100,3) THEN RAISE EXCEPTION 'CONTROL_LIMIT:over_receipt_pct'; END IF;
  IF (c->'params'->>'require_lot')::boolean AND v_lot IS NULL THEN RAISE EXCEPTION 'PROC_LOT_REQUIRED'; END IF;
  IF (c->'params'->>'require_expiry')::boolean AND v_exp IS NULL THEN RAISE EXCEPTION 'PROC_EXPIRY_REQUIRED'; END IF;
  IF v_exp IS NOT NULL AND v_exp<current_date THEN RAISE EXCEPTION 'PROC_LOT_EXPIRED'; END IF;
  IF (v_mfg IS NOT NULL OR v_exp IS NOT NULL) AND v_lot IS NULL THEN RAISE EXCEPTION 'PROC_LOT_REQUIRED'; END IF;
  INSERT INTO core10.goods_receipt_lines_v1(grn_id,tenant_id,business_id,po_id,line_no,item_id,received_qty,accepted_qty,lot_code,manufactured_on,expires_on)
  VALUES (v_id,p.tenant_id,p.business_id,p.id,v_line,v_item,v_qty,
   CASE WHEN (c->'params'->>'qc_required')::boolean THEN NULL ELSE v_qty END,v_lot,v_mfg,v_exp);
 END LOOP;
 PERFORM core10._proc_record_v1(p.tenant_id,p.business_id,p_key,'grn_receive',v_id,v_sha,'grn:'||v_id||':received',
  jsonb_build_object('grn_id',v_id,'po_id',p.id,'location_id',p_location,'lines',jsonb_array_length(p_lines)));
 RETURN core10._proc_grn_json_v1(v_id) || '{"replayed":false}';
END $$;

-- Quality check: p_lines [{"line_no":1,"accepted_qty":..,"notes":".."}] for EVERY line; rejected = received - accepted.
CREATE FUNCTION core10.procurement_inspect_v1(p_grn bigint, p_lines jsonb, p_version integer, p_key text) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE v_actor uuid := core10.actor_uid(); g core10.goods_receipts_v1%ROWTYPE; c jsonb; v_sha text; v_id bigint; e jsonb;
 v_line int; v_acc numeric; v_n int;
BEGIN
 IF v_actor IS NULL OR p_version IS NULL THEN RAISE EXCEPTION 'PROC_INVALID_ACTION'; END IF;
 SELECT * INTO g FROM core10.goods_receipts_v1 WHERE id=p_grn;
 IF NOT FOUND OR NOT core10.can_see_business(g.tenant_id,g.business_id) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 IF NOT core10.inventory_action_authorized_v1(g.tenant_id,g.business_id,g.location_id,'stock.post') THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 SELECT * INTO g FROM core10.goods_receipts_v1 WHERE id=p_grn FOR UPDATE;
 -- Prevent stale permission from surviving an in-flight row-lock wait.
 IF NOT core10.can_see_business(g.tenant_id,g.business_id) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 IF NOT core10.inventory_action_authorized_v1(g.tenant_id,g.business_id,g.location_id,'stock.post')
 THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 c := core10.control_check_v1(g.business_id, 'procurement.goods_receipt', g.site_id);
 v_sha := core10._proc_sha_v1(jsonb_build_object('g',p_grn,'x',p_lines,'v',p_version));
 v_id := core10._proc_replay_v1(g.business_id,p_key,'grn_inspect',v_sha);
 IF v_id IS NOT NULL THEN RETURN core10._proc_grn_json_v1(v_id) || '{"replayed":true}'; END IF;
 IF g.version<>p_version THEN RAISE EXCEPTION 'PROC_STALE_VERSION:%', g.version; END IF;
 IF g.status<>'received' THEN RAISE EXCEPTION 'PROC_INVALID_TRANSITION'; END IF;
 IF (c->'params'->>'separate_inspector')::boolean AND g.received_by=v_actor THEN RAISE EXCEPTION 'PROC_SAME_ACTOR'; END IF;
 SELECT count(*) INTO v_n FROM core10.goods_receipt_lines_v1 WHERE grn_id=g.id;
 IF p_lines IS NULL OR jsonb_typeof(p_lines)<>'array' OR jsonb_array_length(p_lines)<>v_n
  OR (SELECT count(DISTINCT x->>'line_no') FROM jsonb_array_elements(p_lines) x)<>v_n THEN RAISE EXCEPTION 'PROC_QC_LINES_INCOMPLETE'; END IF;
 FOR e IN SELECT value FROM jsonb_array_elements(p_lines) LOOP
  IF jsonb_typeof(e->'line_no')<>'number' OR jsonb_typeof(e->'accepted_qty')<>'number'
   OR (e ? 'notes' AND jsonb_typeof(e->'notes') NOT IN ('string','null')) THEN RAISE EXCEPTION 'PROC_QC_LINES_INCOMPLETE'; END IF;
  v_line := (e->>'line_no')::int; v_acc := (e->>'accepted_qty')::numeric;
  UPDATE core10.goods_receipt_lines_v1 SET accepted_qty=v_acc,qc_notes=left(e->>'notes',500)
   WHERE grn_id=g.id AND line_no=v_line AND v_acc>=0 AND v_acc<=received_qty AND v_acc=round(v_acc,3);
  IF NOT FOUND THEN RAISE EXCEPTION 'PROC_QC_QUANTITY_INVALID'; END IF;
 END LOOP;
 UPDATE core10.goods_receipts_v1 SET status='inspected',inspected_by=v_actor,inspected_at=now(),version=version+1 WHERE id=g.id;
 PERFORM core10._proc_record_v1(g.tenant_id,g.business_id,p_key,'grn_inspect',g.id,v_sha,'grn:'||g.id||':inspected',
  jsonb_build_object('grn_id',g.id,'accepted',(SELECT sum(accepted_qty) FROM core10.goods_receipt_lines_v1 WHERE grn_id=g.id),
   'rejected',(SELECT sum(received_qty-accepted_qty) FROM core10.goods_receipt_lines_v1 WHERE grn_id=g.id)));
 RETURN core10._proc_grn_json_v1(g.id) || '{"replayed":false}';
END $$;

-- Post accepted quantity to stock (the one ledger), register lots, update the PO.
CREATE FUNCTION core10.procurement_post_grn_v1(p_grn bigint, p_version integer, p_key text) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE v_actor uuid := core10.actor_uid(); g core10.goods_receipts_v1%ROWTYPE; v_sha text; v_id bigint; l record;
 v_lot bigint; v_mv bigint; v_open boolean;
BEGIN
 IF v_actor IS NULL OR p_version IS NULL THEN RAISE EXCEPTION 'PROC_INVALID_ACTION'; END IF;
 SELECT * INTO g FROM core10.goods_receipts_v1 WHERE id=p_grn;
 IF NOT FOUND OR NOT core10.can_see_business(g.tenant_id,g.business_id) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 IF NOT core10.inventory_action_authorized_v1(g.tenant_id,g.business_id,g.location_id,'stock.post') THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 PERFORM 1 FROM core10.purchase_orders_v1 WHERE id=g.po_id FOR UPDATE;
 SELECT * INTO g FROM core10.goods_receipts_v1 WHERE id=p_grn FOR UPDATE;
 -- Prevent stale permission from surviving an in-flight row-lock wait.
 IF NOT core10.can_see_business(g.tenant_id,g.business_id) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 IF NOT core10.inventory_action_authorized_v1(g.tenant_id,g.business_id,g.location_id,'stock.post')
 THEN RAISE EXCEPTION 'PROC_PERMISSION_DENIED'; END IF;
 PERFORM core10.control_check_v1(g.business_id, 'procurement.goods_receipt', g.site_id);
 PERFORM core10.control_check_v1(g.business_id, 'inventory.stock_event', g.site_id);
 v_sha := core10._proc_sha_v1(jsonb_build_object('g',p_grn,'v',p_version));
 v_id := core10._proc_replay_v1(g.business_id,p_key,'grn_post',v_sha);
 IF v_id IS NOT NULL THEN RETURN core10._proc_grn_json_v1(v_id) || '{"replayed":true}'; END IF;
 IF g.version<>p_version THEN RAISE EXCEPTION 'PROC_STALE_VERSION:%', g.version; END IF;
 IF g.status<>'inspected' THEN RAISE EXCEPTION 'PROC_INVALID_TRANSITION'; END IF;
 FOR l IN SELECT * FROM core10.goods_receipt_lines_v1 WHERE grn_id=g.id ORDER BY line_no LOOP
  v_lot := NULL; v_mv := NULL;
  IF l.lot_code IS NOT NULL THEN
   INSERT INTO core10.inventory_lots_v1(tenant_id,business_id,item_id,lot_code,manufactured_on,expires_on,source_kind,source_ref,status,created_by)
   VALUES (g.tenant_id,g.business_id,l.item_id,l.lot_code,l.manufactured_on,l.expires_on,'purchase','grn:'||g.id||':'||l.line_no,
    CASE WHEN l.accepted_qty>0 THEN 'released' ELSE 'rejected' END,v_actor)
   ON CONFLICT (business_id,item_id,lot_code) DO NOTHING RETURNING id INTO v_lot;
   IF v_lot IS NULL THEN
    SELECT id INTO v_lot FROM core10.inventory_lots_v1 WHERE business_id=g.business_id AND item_id=l.item_id AND lot_code=l.lot_code
     AND manufactured_on IS NOT DISTINCT FROM l.manufactured_on AND expires_on IS NOT DISTINCT FROM l.expires_on;
    IF v_lot IS NULL THEN RAISE EXCEPTION 'PROC_LOT_CONFLICT'; END IF;
   END IF;
  END IF;
  IF l.accepted_qty>0 THEN
   v_mv := core10.post_stock_event(g.location_id,l.item_id,l.accepted_qty,'c10-grn-'||g.id||'-'||l.line_no);
  END IF;
  UPDATE core10.goods_receipt_lines_v1 SET lot_id=v_lot,stock_movement_id=v_mv WHERE grn_id=g.id AND line_no=l.line_no;
  UPDATE core10.purchase_order_lines_v1 SET accepted_qty=accepted_qty+l.accepted_qty,rejected_qty=rejected_qty+(l.received_qty-l.accepted_qty)
   WHERE po_id=g.po_id AND line_no=l.line_no;
 END LOOP;
 UPDATE core10.goods_receipts_v1 SET status='posted',posted_by=v_actor,posted_at=now(),version=version+1 WHERE id=g.id;
 SELECT EXISTS(SELECT 1 FROM core10.purchase_order_lines_v1 WHERE po_id=g.po_id AND accepted_qty<quantity) INTO v_open;
 UPDATE core10.purchase_orders_v1 SET status=CASE WHEN v_open THEN 'partially_received' ELSE 'received' END,version=version+1
  WHERE id=g.po_id AND status IN ('approved','partially_received');
 PERFORM core10._proc_record_v1(g.tenant_id,g.business_id,p_key,'grn_post',g.id,v_sha,'grn:'||g.id||':posted',
  jsonb_build_object('grn_id',g.id,'po_id',g.po_id,'location_id',g.location_id,
   'stock_movements',(SELECT jsonb_agg(stock_movement_id) FROM core10.goods_receipt_lines_v1 WHERE grn_id=g.id AND stock_movement_id IS NOT NULL)));
 RETURN core10._proc_grn_json_v1(g.id) || '{"replayed":false}';
END $$;

-- ---------- reads (STABLE, scoped, keyset pages <= 200) ----------
CREATE FUNCTION core10.procurement_list_pos_v1(p_business bigint, p_site bigint DEFAULT NULL, p_status text DEFAULT NULL,
 p_before_id bigint DEFAULT NULL, p_limit integer DEFAULT 50) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE t bigint; v_limit int := least(greatest(coalesce(p_limit,50),1),200); v_rows jsonb; v_all boolean;
BEGIN
 SELECT tenant_id INTO t FROM core10.businesses WHERE id=p_business;
 IF core10.actor_uid() IS NULL OR t IS NULL OR NOT core10.can_see_business(t,p_business) THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 IF p_status IS NOT NULL AND p_status NOT IN ('draft','approved','partially_received','received','closed','cancelled') THEN RAISE EXCEPTION 'PROC_INVALID_FILTER'; END IF;
 v_all := core10.can_business(t,p_business);
 SELECT coalesce(jsonb_agg(core10._proc_po_json_v1(x.id) ORDER BY x.id DESC),'[]'::jsonb) INTO v_rows FROM (
  SELECT p.id FROM core10.purchase_orders_v1 p
  WHERE p.business_id=p_business AND (p_site IS NULL OR p.site_id=p_site) AND (p_status IS NULL OR p.status=p_status)
    AND (p_before_id IS NULL OR p.id<p_before_id) AND (v_all OR core10.can_site(t,p_business,p.site_id,'stock.read'))
  ORDER BY p.id DESC LIMIT v_limit) x;
 RETURN jsonb_build_object('business_id',p_business,'items',v_rows,'limit',v_limit,
  'next_before_id',CASE WHEN jsonb_array_length(v_rows)=v_limit THEN (v_rows->(v_limit-1)->>'po_id')::bigint END);
END $$;

CREATE FUNCTION core10.procurement_get_po_v1(p_po bigint) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE p core10.purchase_orders_v1%ROWTYPE;
BEGIN
 SELECT * INTO p FROM core10.purchase_orders_v1 WHERE id=p_po;
 IF core10.actor_uid() IS NULL OR NOT FOUND OR NOT core10.can_see_business(p.tenant_id,p.business_id)
  OR NOT (core10.can_business(p.tenant_id,p.business_id) OR core10.can_site(p.tenant_id,p.business_id,p.site_id,'stock.read'))
 THEN RAISE EXCEPTION 'PROC_SCOPE'; END IF;
 RETURN core10._proc_po_json_v1(p.id) || jsonb_build_object('receipts',coalesce((SELECT jsonb_agg(core10._proc_grn_json_v1(g.id) ORDER BY g.id)
  FROM core10.goods_receipts_v1 g WHERE g.po_id=p.id),'[]'::jsonb));
END $$;


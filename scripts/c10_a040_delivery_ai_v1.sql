CREATE FUNCTION c10_demo.ai_set_grant_v1(p_business bigint,p_agent text,p_granted boolean,p_sharing boolean)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF NOT FOUND OR NOT c10_demo.can_manage(t,p_business) THEN RAISE EXCEPTION 'ai_denied'; END IF;

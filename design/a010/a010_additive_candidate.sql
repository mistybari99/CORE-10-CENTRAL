-- C10-A010 CANDIDATE (NOT APPLIED). Additive Business -> Operating Site -> Location layer.
-- Touches NO existing table/column/policy/grant/function. Idempotent. Single transaction.
-- ASSUMED live shape (verify read-only before any apply): public.org_units(id bigint PK, parent_id, kind text, name, ...),
-- public.locations(id bigint PK, org_unit_id -> org_units.id). Class H: requires Owner go/no-go + staging proof.
BEGIN;

-- 1) Operating sites: one row per physical/operational site of a business.
CREATE TABLE IF NOT EXISTS public.c10_operating_sites (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint  NOT NULL REFERENCES public.org_units(id) ON DELETE RESTRICT,
  code        text    NOT NULL CHECK (code = lower(code) AND code ~ '^[a-z0-9][a-z0-9_-]*$'),
  name        text    NOT NULL,
  active      boolean NOT NULL DEFAULT true,
  is_legacy_default boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (business_id, code),
  UNIQUE (id, business_id)          -- target for the composite FK below
);
-- at most one auto-seeded default site per business
CREATE UNIQUE INDEX IF NOT EXISTS c10_operating_sites_one_default
  ON public.c10_operating_sites (business_id) WHERE is_legacy_default;

-- 2) Location -> site map. location_id PK = a location belongs to exactly one site.
CREATE TABLE IF NOT EXISTS public.c10_location_site_map (
  location_id bigint PRIMARY KEY REFERENCES public.locations(id) ON DELETE RESTRICT,
  site_id     bigint NOT NULL,
  business_id bigint NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (site_id, business_id)
    REFERENCES public.c10_operating_sites (id, business_id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS c10_location_site_map_site_idx ON public.c10_location_site_map (site_id);

-- 3) Derivation helper: walk org_units.parent_id up to the nearest kind='business'.
CREATE OR REPLACE FUNCTION public.c10_business_of_unit(p_unit bigint)
RETURNS bigint LANGUAGE sql STABLE SET search_path = pg_catalog, public AS $$
  WITH RECURSIVE up(id, parent_id, kind, depth) AS (
    SELECT id, parent_id, kind, 0 FROM public.org_units WHERE id = p_unit
    UNION ALL
    SELECT o.id, o.parent_id, o.kind, up.depth + 1
      FROM public.org_units o JOIN up ON o.id = up.parent_id WHERE up.depth < 20)
  SELECT id FROM up WHERE kind = 'business' ORDER BY depth LIMIT 1
$$;

-- 4) Validation triggers (on NEW tables only).
CREATE OR REPLACE FUNCTION public.c10_site_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.org_units WHERE id = NEW.business_id AND kind = 'business') THEN
    RAISE EXCEPTION 'c10_site_not_under_business: org_unit % is not kind=business', NEW.business_id
      USING ERRCODE = '23514';
  END IF;
  IF TG_OP = 'UPDATE' AND NEW.business_id <> OLD.business_id
     AND EXISTS (SELECT 1 FROM public.c10_location_site_map WHERE site_id = OLD.id) THEN
    RAISE EXCEPTION 'c10_site_business_immutable_while_mapped' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS c10_site_guard ON public.c10_operating_sites;
CREATE TRIGGER c10_site_guard BEFORE INSERT OR UPDATE ON public.c10_operating_sites
  FOR EACH ROW EXECUTE FUNCTION public.c10_site_guard();

CREATE OR REPLACE FUNCTION public.c10_map_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE v_unit bigint; v_biz bigint;
BEGIN
  SELECT org_unit_id INTO v_unit FROM public.locations WHERE id = NEW.location_id;
  IF v_unit IS NULL THEN
    RAISE EXCEPTION 'c10_location_unmapped_org_unit: location % has no org_unit_id', NEW.location_id
      USING ERRCODE = '23514';
  END IF;
  v_biz := public.c10_business_of_unit(v_unit);
  IF v_biz IS NULL OR v_biz <> NEW.business_id THEN
    RAISE EXCEPTION 'c10_site_business_mismatch: location % resolves to business %, map says %',
      NEW.location_id, v_biz, NEW.business_id USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS c10_map_guard ON public.c10_location_site_map;
CREATE TRIGGER c10_map_guard BEFORE INSERT OR UPDATE ON public.c10_location_site_map
  FOR EACH ROW EXECUTE FUNCTION public.c10_map_guard();

-- 5) Lock down new objects (Supabase default privileges would otherwise expose them).
ALTER TABLE public.c10_operating_sites  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.c10_location_site_map ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.c10_operating_sites, public.c10_location_site_map FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.c10_business_of_unit(bigint), public.c10_site_guard(), public.c10_map_guard()
  FROM PUBLIC, anon, authenticated;
-- (No policies: only service_role / owner roles reach them until a reviewed RLS design lands.)

-- 6) Legacy seed: one default site per business that has locations; map every legacy location.
--    Ids of locations are never touched. Owner may later split sites (e.g. showroom/factory).
INSERT INTO public.c10_operating_sites (business_id, code, name, is_legacy_default)
SELECT DISTINCT b.id, 'legacy-default', coalesce(b.name, 'business ' || b.id) || ' (legacy default site)', true
  FROM public.locations l
  JOIN public.org_units b ON b.id = public.c10_business_of_unit(l.org_unit_id)
ON CONFLICT (business_id, code) DO NOTHING;

INSERT INTO public.c10_location_site_map (location_id, site_id, business_id)
SELECT l.id, s.id, s.business_id
  FROM public.locations l
  JOIN public.c10_operating_sites s
    ON s.business_id = public.c10_business_of_unit(l.org_unit_id) AND s.is_legacy_default
ON CONFLICT (location_id) DO NOTHING;

-- 7) Views (security_invoker; not granted to API roles).
CREATE OR REPLACE VIEW public.c10_location_hierarchy WITH (security_invoker = true) AS
SELECT l.id AS location_id, m.site_id, s.code AS site_code, m.business_id,
       public.c10_business_of_unit(l.org_unit_id) AS derived_business_id
  FROM public.locations l
  LEFT JOIN public.c10_location_site_map m ON m.location_id = l.id
  LEFT JOIN public.c10_operating_sites s ON s.id = m.site_id;

CREATE OR REPLACE VIEW public.c10_hierarchy_violations WITH (security_invoker = true) AS
SELECT location_id, 'no_site' AS problem FROM public.c10_location_hierarchy WHERE site_id IS NULL
UNION ALL
SELECT location_id, 'business_drift' FROM public.c10_location_hierarchy
 WHERE site_id IS NOT NULL AND business_id IS DISTINCT FROM derived_business_id;
REVOKE ALL ON public.c10_location_hierarchy, public.c10_hierarchy_violations FROM PUBLIC, anon, authenticated;

COMMIT;

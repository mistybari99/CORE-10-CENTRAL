export function cleanFromPreview(worker, indexBase64, appBase64) {
 const lines=worker.split("\n"), pi=lines.findIndex(l=>l.startsWith("const PIN=")), fi=lines.findIndex(l=>l.startsWith("const FILES="));
 if(pi<0||fi<0)throw Error("CLEAN_BASE_INVALID");
 const files=JSON.parse(lines[fi].slice(12,-1)),pins=JSON.parse(lines[pi].slice(10,-1)).split(",").filter(p=>!p.startsWith("pr109=")&&!p.startsWith("pr112="));
 const clean={};
 for(const route of ALLOW){
  if(!Object.hasOwn(files,route))throw Error("CLEAN_MISSING "+route);
  clean[route]=route==="/index.html"?[files[route][0],indexBase64]:route==="/app.js"?[files[route][0],appBase64]:files[route];
 }
 lines[0]="// GENERATED by apps/central/build-clean.mjs. Signed-only CORE10 release.";
 lines[pi]="const PIN="+JSON.stringify([...pins,"clean=1"].join(","))+";";
 lines[fi]="const FILES="+JSON.stringify(clean)+";";
 return lines.join("\n").replace("Read-only preview.\\n","Method not allowed.\\n");
}

-- B-015 / 0502. Material waste is an observation INSIDE recorded consumption.
-- Never post another stock movement, valuation, COGS or financial journal for it.
CREATE TABLE core10.mfg_material_waste_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL, site_id bigint NOT NULL,
 batch_id bigint NOT NULL, bom_id bigint NOT NULL, line_no integer NOT NULL,
 item_id bigint NOT NULL, uom_ref text NOT NULL,
 quantity numeric NOT NULL CHECK(quantity>0 AND quantity<=100000000 AND quantity=round(quantity,6)),
 reason_code text NOT NULL CHECK(reason_code ~ '^[A-Z][A-Z0-9_]{0,63}$'),
 lot_ref text NOT NULL CHECK(length(btrim(lot_ref)) BETWEEN 1 AND 120),
 note text NOT NULL CHECK(length(btrim(note)) BETWEEN 5 AND 500),
 actor_id uuid NOT NULL, recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 audit_event_id bigint NOT NULL UNIQUE REFERENCES core10.canonical_audit_events_v1(id),
 FOREIGN KEY(batch_id,tenant_id,business_id,site_id) REFERENCES core10.production_batches_v1(id,tenant_id,business_id,site_id),
 FOREIGN KEY(bom_id,tenant_id,business_id,site_id) REFERENCES core10.bom_recipes_v1(id,tenant_id,business_id,site_id),
 FOREIGN KEY(bom_id,line_no) REFERENCES core10.bom_ingredients_v1(bom_id,line_no),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES core10.items(id,tenant_id,business_id)
);
CREATE INDEX mfg_material_waste_batch_line_v1 ON core10.mfg_material_waste_v1(batch_id,line_no);
ALTER TABLE core10.mfg_material_waste_v1 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON core10.mfg_material_waste_v1 FROM PUBLIC,authenticated;
CREATE FUNCTION core10._mfg_waste_guard_v1() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,core10 AS $$
BEGIN RAISE EXCEPTION 'MFG_WASTE_IMMUTABLE'; END $$;
REVOKE ALL ON FUNCTION core10._mfg_waste_guard_v1() FROM PUBLIC,authenticated;
CREATE TRIGGER mfg_material_waste_immutable BEFORE UPDATE OR DELETE ON core10.mfg_material_waste_v1
 FOR EACH ROW EXECUTE FUNCTION core10._mfg_waste_guard_v1();
CREATE TRIGGER mfg_material_waste_truncate BEFORE TRUNCATE ON core10.mfg_material_waste_v1
 FOR EACH STATEMENT EXECUTE FUNCTION core10._mfg_waste_guard_v1();

CREATE FUNCTION core10._mfg_waste_codes_v1(p_codes text) RETURNS text[]
LANGUAGE sql IMMUTABLE SET search_path=pg_catalog,core10 AS $$
 SELECT coalesce(array_agg(DISTINCT btrim(code) ORDER BY btrim(code))
  FILTER(WHERE btrim(code) ~ '^[A-Z][A-Z0-9_]{0,63}$'),ARRAY[]::text[])
 FROM unnest(string_to_array(p_codes,',')) code
$$;
REVOKE ALL ON FUNCTION core10._mfg_waste_codes_v1(text) FROM PUBLIC,authenticated;

CREATE FUNCTION core10._mfg_waste_events_v1(p_batch bigint) RETURNS jsonb
LANGUAGE sql STABLE SET search_path=pg_catalog,core10 AS $$
 SELECT coalesce(jsonb_agg(jsonb_build_object('event_id',id,'line_no',line_no,'item_id',item_id,
  'quantity',quantity,'uom_ref',uom_ref,'reason_code',reason_code,'lot_ref',lot_ref,'note',note,
  'actor_id',actor_id,'recorded_at',recorded_at,'audit_event_id',audit_event_id) ORDER BY id),'[]'::jsonb)
 FROM core10.mfg_material_waste_v1 WHERE batch_id=p_batch
$$;
REVOKE ALL ON FUNCTION core10._mfg_waste_events_v1(bigint) FROM PUBLIC,authenticated;

CREATE FUNCTION core10.mfg_record_material_waste_v1(
 p_business bigint,p_site bigint,p_batch bigint,p_line integer,p_quantity numeric,
 p_reason text,p_lot_ref text,p_note text,p_key text
) RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE t bigint; c jsonb; p jsonb; r jsonb; b core10.production_batches_v1%ROWTYPE;
 l core10.bom_ingredients_v1%ROWTYPE; observed jsonb; used numeric; consumed numeric; event_id bigint;
BEGIN
 t:=core10._mfg_scope_v1(p_business,p_site);
 p:=jsonb_build_object('op','material_waste_record','site',p_site,'batch',p_batch,
  'line',p_line,'quantity',p_quantity,'reason',p_reason,'lot_ref',p_lot_ref,'note',p_note);
 PERFORM core10._mfg_lock_command_v1(p_business,p_key);
 SELECT * INTO b FROM core10.production_batches_v1
  WHERE id=p_batch AND business_id=p_business AND site_id=p_site FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'MFG_SCOPE_DENIED'; END IF;
 t:=core10._mfg_scope_v1(p_business,p_site);
 PERFORM core10._mfg_control_fresh_v1(p_business,p_site,'mfg.material_waste');
 c:=core10.control_check_v1(p_business,'mfg.material_waste',p_site);
 r:=core10._mfg_replay_v1(p_business,p_key,p);
 IF r IS NOT NULL THEN RETURN r; END IF;
 IF (c->>'stages')::int>0 THEN RAISE EXCEPTION 'NOT_CONNECTED:APPROVAL_COMPLETION'; END IF;
 IF b.status<>'recorded' THEN RAISE EXCEPTION 'MFG_WASTE_REQUIRES_RECORDED_OUTPUT'; END IF;
 IF p_quantity IS NULL OR p_quantity<=0 OR p_quantity>100000000 OR p_quantity<>round(p_quantity,6)
 THEN RAISE EXCEPTION 'MFG_WASTE_QUANTITY'; END IF;
 IF p_reason IS NULL OR p_reason !~ '^[A-Z][A-Z0-9_]{0,63}$'
  OR NOT (p_reason=ANY(core10._mfg_waste_codes_v1(c->'params'->>'reason_codes')))
 THEN RAISE EXCEPTION 'MFG_WASTE_REASON'; END IF;
 IF p_note IS NULL OR length(btrim(p_note)) NOT BETWEEN 5 AND 500 THEN RAISE EXCEPTION 'MFG_REASON_REQUIRED'; END IF;
 SELECT * INTO l FROM core10.bom_ingredients_v1 WHERE bom_id=b.bom_id AND line_no=p_line;
 IF NOT FOUND THEN RAISE EXCEPTION 'MFG_CONSUMPTION_LINE'; END IF;
 SELECT x INTO observed FROM jsonb_array_elements(b.output_payload->'consumption') x WHERE (x->>'line')::int=p_line;
 IF observed IS NULL THEN RAISE EXCEPTION 'MFG_CONSUMPTION_INCOMPLETE'; END IF;
 IF p_lot_ref IS NULL OR p_lot_ref IS DISTINCT FROM observed->>'lot_ref' THEN RAISE EXCEPTION 'MFG_WASTE_LOT_MISMATCH'; END IF;
 consumed:=(observed->>'qty')::numeric;
 SELECT coalesce(sum(quantity),0) INTO used FROM core10.mfg_material_waste_v1 WHERE batch_id=p_batch AND line_no=p_line;
 IF used+p_quantity>consumed THEN RAISE EXCEPTION 'MFG_WASTE_EXCEEDS_CONSUMPTION'; END IF;
 IF (used+p_quantity)*100>consumed*(c->'params'->>'max_waste_pct')::numeric
 THEN RAISE EXCEPTION 'CONTROL_LIMIT:max_waste_pct'; END IF;
 event_id:=nextval(pg_get_serial_sequence('core10.mfg_material_waste_v1','id'));
 r:=jsonb_build_object('event_id',event_id,'batch_id',p_batch,'line_no',p_line,
  'quantity',p_quantity,'uom_ref',l.uom_ref,'cumulative_waste',used+p_quantity,
  'included_in_consumption',true,'stock_issued',false,'financial_posted',false,
  'lot_validation','NOT_CONNECTED','uom_validation','NOT_CONNECTED');
 -- Audit receipt first, then the domain observation with NOT NULL evidence; both roll back together.
 r:=core10._mfg_receipt_v1(t,p_business,p_site,p_key,p,r);
 INSERT INTO core10.mfg_material_waste_v1(id,tenant_id,business_id,site_id,batch_id,bom_id,line_no,
  item_id,uom_ref,quantity,reason_code,lot_ref,note,actor_id,audit_event_id)
 VALUES(event_id,t,p_business,p_site,p_batch,b.bom_id,p_line,l.ingredient_item_id,l.uom_ref,
  p_quantity,p_reason,p_lot_ref,btrim(p_note),core10.actor_uid(),(r->>'audit_event_id')::bigint);
 RETURN r;
END $$;
REVOKE ALL ON FUNCTION core10.mfg_record_material_waste_v1(bigint,bigint,bigint,integer,numeric,text,text,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION core10.mfg_record_material_waste_v1(bigint,bigint,bigint,integer,numeric,text,text,text,text) TO authenticated;

CREATE FUNCTION core10.mfg_material_waste_report_v1(p_business bigint,p_site bigint,p_batch bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE t bigint; c jsonb; b core10.production_batches_v1%ROWTYPE; lines jsonb;
BEGIN
 t:=core10._mfg_scope_v1(p_business,p_site);
 c:=core10._control_resolve_v1(p_business,'mfg.material_waste',p_site);
 IF NOT (c->>'enabled')::boolean THEN RAISE EXCEPTION 'CONTROL_DISABLED:mfg.material_waste'; END IF;
 SELECT * INTO b FROM core10.production_batches_v1 WHERE id=p_batch AND business_id=p_business AND site_id=p_site;
 IF NOT FOUND THEN RAISE EXCEPTION 'MFG_SCOPE_DENIED'; END IF;
 IF b.status<>'recorded' THEN RAISE EXCEPTION 'MFG_WASTE_REQUIRES_RECORDED_OUTPUT'; END IF;
 SELECT jsonb_agg(jsonb_build_object('line_no',l.line_no,'item_id',l.ingredient_item_id,'sku',i.sku,
  'uom_ref',l.uom_ref,'component_kind',l.component_kind,'consumed_quantity',(x->>'qty')::numeric,
  'lot_ref',x->>'lot_ref','recorded_waste',coalesce(w.quantity,0),
  'unclassified_consumption',(x->>'qty')::numeric-coalesce(w.quantity,0),
  'expected_waste_quantity',round(l.qty_per_batch*b.multiplier*l.expected_waste_pct/100,6),
  'waste_pct',CASE WHEN (x->>'qty')::numeric>0 THEN round(coalesce(w.quantity,0)*100/(x->>'qty')::numeric,4) ELSE NULL END)
 ORDER BY l.line_no) INTO lines
 FROM core10.bom_ingredients_v1 l JOIN core10.items i ON i.id=l.ingredient_item_id
 JOIN LATERAL jsonb_array_elements(b.output_payload->'consumption') x ON (x->>'line')::int=l.line_no
 LEFT JOIN LATERAL(SELECT sum(quantity) quantity FROM core10.mfg_material_waste_v1 WHERE batch_id=p_batch AND line_no=l.line_no) w ON true
 WHERE l.bom_id=b.bom_id;
 RETURN jsonb_build_object('batch_id',p_batch,'recipe_id',b.bom_id,'lines',lines,
  'events',core10._mfg_waste_events_v1(p_batch),'allowed_reason_codes',to_jsonb(core10._mfg_waste_codes_v1(c->'params'->>'reason_codes')),
  'max_waste_pct',(c->'params'->>'max_waste_pct')::numeric,'approval_stages',(c->>'stages')::int,
  'included_in_consumption',true,'additional_stock_movement',false,'financial_posted',false,
  'remaining_is_good_usage',false,'lot_validation','NOT_CONNECTED','uom_validation','NOT_CONNECTED');
END $$;
REVOKE ALL ON FUNCTION core10.mfg_material_waste_report_v1(bigint,bigint,bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION core10.mfg_material_waste_report_v1(bigint,bigint,bigint) TO authenticated;


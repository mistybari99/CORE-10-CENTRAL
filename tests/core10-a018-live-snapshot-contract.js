"use strict";
const assert=require("node:assert/strict");
const snapshot=require("../data/core10_sg_readonly_structure_2026-11-10.json");
const catalog=require("../data/core10_capability_catalog_v1.json");
const registry=require("../core10-capability-registry.js");
const {analyzeLegacyEntitySnapshot:analyze}=require("../core10-entity-compatibility.js");
const clone=x=>JSON.parse(JSON.stringify(x));
assert.equal(snapshot.schema_version,1);
assert.equal(snapshot.source_project,"IMG-ERP-SG");
assert.match(snapshot.captured_at_utc,/^2026-11-\d\dT\d\d:\d\d:\d\dZ$/);
assert.doesNotMatch(JSON.stringify(snapshot),/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i);
assert.ok(snapshot.locations.every(l=>l.code===null||l.code===""||l.code==="loc_"+l.id));
assert.equal(snapshot.org_units.length,4);
assert.equal(snapshot.business_templates.length,7);
assert.equal(snapshot.business_profiles.length,1);
const baseline=JSON.stringify(snapshot);
const verdict=analyze(snapshot,catalog);
assert.equal(verdict.ok,true,verdict.errors.join(", "));
assert.deepEqual(verdict.summary,{org_units:4,businesses:1,locations:8,operating_sites:0,legacy_direct_locations:8,explicit_site_locations:0});
assert.deepEqual(snapshot.locations.map(l=>l.id),[1,2,3,4,5,6,7,9]);
assert.deepEqual(verdict.mappings.map(m=>m.legacy_location_id),snapshot.locations.map(l=>l.id));
assert.ok(verdict.mappings.every(m=>String(m.legacy_org_unit_id)==="3"&&String(m.business_id)==="3"&&String(m.legal_entity_id)==="2"&&String(m.legacy_group_id)==="1"));
assert.ok(verdict.mappings.every(m=>m.operating_site_id===null&&m.tenant_id===null&&m.platform_id===null));
assert.ok(verdict.warnings.includes("OPERATING_SITE_LAYER_MISSING:8"));
assert.ok(verdict.warnings.includes("TENANT_BOUNDARY_NOT_PROVEN"));
assert.ok(verdict.warnings.includes("RLS_RPC_AUTHORIZATION_NOT_TESTED"));
assert.deepEqual(verdict.certifications,{tenant_isolation_verified:false,operating_site_security_verified:false,live_authenticated_tests_passed:false,scale_measured:false,release_ready:false});
for(const t of snapshot.business_templates){
  const primary=registry.findTemplateByLiveCode(catalog,t.code);
  const optional=catalog.optional_packs.find(p=>p.source_code===t.code);
  assert.ok(primary||optional,"Unregistered source code: "+t.code);
  assert.equal((primary||optional).source_status,t.status,"Source status drift: "+t.code);
}
const invalid=clone(snapshot);invalid.locations[0].org_unit_id="4";
const rejected=analyze(invalid,catalog);
assert.equal(rejected.ok,false);
assert.ok(rejected.errors.includes("LOCATION_PARENT_NOT_SITE_OR_BUSINESS:1"));
assert.deepEqual(rejected.mappings,[]);
assert.equal(JSON.stringify(snapshot),baseline,"Snapshot validator must be pure");
console.log("PASS C10-A018: captured read-only SG structural snapshot, legacy ID/ancestry, template state, fail-closed tamper");
console.log("PASS: snapshot date "+snapshot.captured_at_utc+" ONLY. No live-authenticated tenant/security or performance certification.");

CREATE TABLE core10.purchase_orders_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL, site_id bigint NOT NULL,
 supplier_id bigint NOT NULL,
 status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','approved','partially_received','received','closed','cancelled')),
 expected_on date, note text CHECK (note IS NULL OR length(note)<=500),
 total_amount numeric(20,2) NOT NULL CHECK (total_amount>=0),
 version integer NOT NULL DEFAULT 1 CHECK (version>0),
 request_key text NOT NULL CHECK (request_key ~ '^[A-Za-z0-9_-]{8,100}$'),
 created_by uuid NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
 approved_by uuid, approved_at timestamptz, closed_by uuid, closed_at timestamptz,

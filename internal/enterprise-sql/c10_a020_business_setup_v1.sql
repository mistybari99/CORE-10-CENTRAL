CREATE TABLE c10_demo.business_configuration_v1(
 business_id bigint PRIMARY KEY,
 tenant_id bigint NOT NULL,
 display_name text NOT NULL CHECK(length(btrim(display_name)) BETWEEN 1 AND 120),
 brand_hex text NOT NULL CHECK(brand_hex ~ '^#[A-Fa-f0-9]{6}$'),
 setup_mode text NOT NULL CHECK(setup_mode IN('quick','advanced')),
 setup_status text NOT NULL DEFAULT 'draft' CHECK(setup_status='draft'),
 created_by uuid NOT NULL,
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
CREATE TABLE c10_demo.business_module_settings_v1(
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 module_code text NOT NULL,
 visibility text NOT NULL DEFAULT 'locked' CHECK(visibility IN('show','locked','hidden')),
 operational_enabled boolean NOT NULL DEFAULT false CHECK(operational_enabled=false),
 PRIMARY KEY(business_id,module_code),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
CREATE TABLE c10_demo.business_setup_runs_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES c10_demo.tenants(id),
 business_id bigint NOT NULL,
 request_key text NOT NULL,
 payload jsonb NOT NULL,
 created_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(tenant_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);


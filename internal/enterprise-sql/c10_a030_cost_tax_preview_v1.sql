CREATE VIEW c10_demo.posted_sales_cost_preview_v1 WITH(security_invoker=true) AS
 SELECT d.tenant_id,d.business_id,d.id AS document_id,
  d.net_amount AS sale_net_amount_unreconciled,
  COALESCE(sum(round(l.quantity*cr.unit_cost,2)),0)::numeric(20,2) AS estimated_cogs,
  count(*) FILTER(WHERE cr.id IS NULL)::bigint AS missing_cost_rate_lines,
  CASE WHEN count(*) FILTER(WHERE cr.id IS NULL)=0
   THEN (d.net_amount-COALESCE(sum(round(l.quantity*cr.unit_cost,2)),0))::numeric(20,2)
   ELSE NULL::numeric(20,2) END AS estimated_gross_margin,
  false::boolean AS actual_cogs_certified
 FROM c10_demo.operational_documents_v1 d
 JOIN c10_demo.operational_document_lines_v1 l ON l.document_id=d.id
 LEFT JOIN c10_demo.item_cost_rates_v1 cr ON cr.business_id=d.business_id
   AND cr.item_id=l.item_id AND cr.status='approved'
 WHERE d.kind='sale' AND d.status='posted'
  AND c10_demo.can_manage(d.tenant_id,d.business_id)
 GROUP BY d.tenant_id,d.business_id,d.id,d.net_amount;

CREATE VIEW c10_demo.inventory_value_preview_v1 WITH(security_invoker=true) AS
 SELECT b.tenant_id,b.id AS business_id,
  COALESCE(sum(round(sb.on_hand*cr.unit_cost,2)),0)::numeric(20,2)
   AS estimated_stock_value,
  count(*) FILTER(WHERE sb.item_id IS NOT NULL AND cr.id IS NULL)::bigint
   AS unpriced_stock_skus,
  count(DISTINCT sb.item_id)::bigint AS stock_skus,
  false::boolean AS actual_inventory_value_certified
 FROM c10_demo.businesses b
 LEFT JOIN c10_demo.stock_balances_v1 sb ON sb.business_id=b.id
 LEFT JOIN c10_demo.item_cost_rates_v1 cr ON cr.business_id=b.id
  AND cr.item_id=sb.item_id AND cr.status='approved'
 WHERE c10_demo.can_manage(b.tenant_id,b.id)
 GROUP BY b.tenant_id,b.id;

CREATE VIEW c10_demo.posted_sale_tax_preview_v1 WITH(security_invoker=true) AS
 SELECT d.tenant_id,d.business_id,d.id AS document_id,
  d.net_amount AS posted_sale_amount_unreconciled,
  t.rate_bps,t.pricing_mode,
  CASE WHEN t.id IS NULL THEN NULL::numeric(20,2)
   WHEN t.pricing_mode='inclusive'
     THEN round(d.net_amount*t.rate_bps/(10000+t.rate_bps),2)::numeric(20,2)
   ELSE round(d.net_amount*t.rate_bps/10000,2)::numeric(20,2)
  END AS estimated_tax_amount,
  false::boolean AS tax_filing_certified
 FROM c10_demo.operational_documents_v1 d
 LEFT JOIN c10_demo.tax_preview_profiles_v1 t
   ON t.business_id=d.business_id AND t.status='approved'
 WHERE d.kind='sale' AND d.status='posted'
   AND c10_demo.can_manage(d.tenant_id,d.business_id);

CREATE VIEW c10_demo.owner_cost_tax_summary_v1 WITH(security_invoker=true) AS
 SELECT b.tenant_id,b.id AS business_id,b.slug,
  COALESCE(c.sales_count,0)::bigint AS posted_sales,
  COALESCE(c.posted_net,0)::numeric(20,2) AS posted_sales_unreconciled,
  COALESCE(c.estimated_cogs,0)::numeric(20,2) AS estimated_cogs_known_only,
  COALESCE(c.missing_lines,0)::bigint AS missing_cost_lines,
  CASE WHEN COALESCE(c.missing_lines,0)=0
   THEN COALESCE(c.posted_net,0)-COALESCE(c.estimated_cogs,0)
   ELSE NULL::numeric(20,2) END AS estimated_margin_when_fully_costed,
  COALESCE(t.tax_total,0)::numeric(20,2) AS estimated_tax_known_only,
  COALESCE(t.missing_tax,0)::bigint AS posted_sales_without_tax_profile,
  false::boolean AS legally_or_financially_certified
 FROM c10_demo.businesses b
 LEFT JOIN LATERAL (
  SELECT count(*) AS sales_count,
    sum(v.sale_net_amount_unreconciled) AS posted_net,
    sum(v.estimated_cogs) AS estimated_cogs,
    sum(v.missing_cost_rate_lines) AS missing_lines
  FROM c10_demo.posted_sales_cost_preview_v1 v WHERE v.business_id=b.id
 ) c ON true
 LEFT JOIN LATERAL (
  SELECT sum(t.estimated_tax_amount) AS tax_total,
   count(*) FILTER(WHERE t.estimated_tax_amount IS NULL) AS missing_tax
  FROM c10_demo.posted_sale_tax_preview_v1 t WHERE t.business_id=b.id
 ) t ON true
 WHERE c10_demo.can_manage(b.tenant_id,b.id);

REVOKE ALL ON c10_demo.posted_sales_cost_preview_v1,
 c10_demo.inventory_value_preview_v1,c10_demo.posted_sale_tax_preview_v1,
 c10_demo.owner_cost_tax_summary_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.posted_sales_cost_preview_v1,
 c10_demo.inventory_value_preview_v1,c10_demo.posted_sale_tax_preview_v1,
 c10_demo.owner_cost_tax_summary_v1 TO authenticated;

CREATE TABLE core10.inventory_commands_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 kind text NOT NULL CHECK (kind IN ('receive','issue','transfer','adjust_in','adjust_out')),
 source_location bigint,
 source_site_id bigint,
 destination_location bigint,
 destination_site_id bigint,
 item_id bigint NOT NULL,
 quantity numeric(15,3) NOT NULL CHECK (quantity>0 AND quantity<=1000000 AND quantity=round(quantity,3)),
 reason text CHECK (reason IS NULL OR length(btrim(reason)) BETWEEN 3 AND 300),
 status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','confirmed','posted','cancelled')),
 version integer NOT NULL DEFAULT 1 CHECK (version>0),
 request_key text NOT NULL CHECK (request_key ~ '^[A-Za-z0-9_-]{8,100}$'),
 created_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 confirmed_by uuid, confirmed_at timestamptz,
 posted_by uuid, posted_at timestamptz, stock_ref bigint,
 cancelled_by uuid, cancelled_at timestamptz,
 UNIQUE (business_id, request_key),
 UNIQUE (id, tenant_id, business_id),
 FOREIGN KEY (business_id, tenant_id) REFERENCES core10.businesses(id, tenant_id),
 FOREIGN KEY (item_id, tenant_id, business_id) REFERENCES core10.items(id, tenant_id, business_id),
 FOREIGN KEY (source_location, tenant_id, business_id, source_site_id)
  REFERENCES core10.stock_locations(id, tenant_id, business_id, site_id),
 FOREIGN KEY (destination_location, tenant_id, business_id, destination_site_id)
  REFERENCES core10.stock_locations(id, tenant_id, business_id, site_id),
 CHECK ((source_location IS NULL) = (source_site_id IS NULL) AND (destination_location IS NULL) = (destination_site_id IS NULL)),
 CHECK (
  (kind='transfer' AND source_location IS NOT NULL AND destination_location IS NOT NULL AND source_location<>destination_location) OR
  (kind IN ('receive','adjust_in') AND source_location IS NULL AND destination_location IS NOT NULL) OR
  (kind IN ('issue','adjust_out') AND source_location IS NOT NULL AND destination_location IS NULL)),
 CHECK ((confirmed_by IS NULL) = (confirmed_at IS NULL) AND (posted_by IS NULL) = (posted_at IS NULL)
    AND (cancelled_by IS NULL) = (cancelled_at IS NULL)),
 CHECK (
  (status='draft' AND confirmed_by IS NULL AND posted_by IS NULL AND cancelled_by IS NULL) OR
  (status='confirmed' AND confirmed_by IS NOT NULL AND posted_by IS NULL AND cancelled_by IS NULL) OR
  (status='posted' AND confirmed_by IS NOT NULL AND posted_by IS NOT NULL AND stock_ref IS NOT NULL AND cancelled_by IS NULL) OR
  (status='cancelled' AND posted_by IS NULL AND cancelled_by IS NOT NULL))
);

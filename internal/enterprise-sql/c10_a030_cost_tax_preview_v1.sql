  tenant_id,business_id,label,rate_bps,pricing_mode,request_key,created_by)
 VALUES(v_tenant,p_business,btrim(p_label),p_rate_bps,p_mode,p_request,c10_demo.actor_uid())
 ON CONFLICT DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_prev FROM c10_demo.tax_preview_profiles_v1

-- PACK-01 (A048): one effective site permission source shared with Build01 (active tenant, signed actor, explicit
-- deny, expiry, revocation). Resolves location -> site on the server; a caller's site id is never trusted.
CREATE FUNCTION core10.inventory_action_authorized_v1(p_tenant bigint, p_business bigint, p_location bigint, p_action text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
 SELECT core10.actor_uid() IS NOT NULL AND p_action=ANY(ARRAY['stock.read','stock.post']::text[])
 AND EXISTS(SELECT 1 FROM core10.stock_locations l
   WHERE l.id=p_location AND l.tenant_id=p_tenant AND l.business_id=p_business
     AND core10.can_site(l.tenant_id,l.business_id,l.site_id,p_action))
$$;


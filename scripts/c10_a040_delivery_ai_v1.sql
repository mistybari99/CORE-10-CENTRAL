END $$;

-- request: decides allow/block in the DB and returns the REDACTED input for the server function to send
CREATE FUNCTION c10_demo.ai_request_v1(p_account bigint,p_agent text,p_key text,p_input text,p_now timestamptz DEFAULT now())
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE a record;pv record;g record;b record;c record;used_tok bigint;used_money numeric;st text;v_id bigint;red text;
BEGIN
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'ai_denied'; END IF;
 SELECT * INTO pv FROM c10_demo.integration_provider_v1 WHERE code=a.provider_code;
 IF pv.family<>'ai' THEN RAISE EXCEPTION 'ai_not_ai_port'; END IF;
 SELECT * INTO c FROM c10_demo.ai_call_v1 WHERE account_id=p_account AND idempotency_key=p_key;
 IF FOUND THEN RETURN jsonb_build_object('status','duplicate','id',c.id,'state',c.state); END IF;
 red:=c10_demo.ai_redact_v1(p_input);
 SELECT * INTO g FROM c10_demo.ai_agent_grant_v1 WHERE business_id=a.business_id AND agent_code=p_agent;
 SELECT * INTO b FROM c10_demo.ai_budget_v1 WHERE account_id=p_account;
 SELECT COALESCE(sum(tokens_in+tokens_out),0),COALESCE(sum(cost),0) INTO used_tok,used_money FROM c10_demo.ai_call_v1
  WHERE account_id=p_account AND state='done' AND date_trunc('month',created_at AT TIME ZONE 'Asia/Dhaka')=date_trunc('month',p_now AT TIME ZONE 'Asia/Dhaka');
 st:=CASE
  WHEN a.provider_code='ai_local_rules' THEN 'fallback_local'
  WHEN a.mode='off' THEN 'blocked_port_off'
  WHEN g IS NULL OR NOT g.granted THEN 'blocked_no_grant'
  WHEN NOT g.data_sharing THEN 'blocked_no_sharing'
  WHEN b IS NULL OR b.monthly_token_cap=0 OR used_tok>=b.monthly_token_cap OR used_money>=b.monthly_money_cap THEN 'blocked_budget'
  ELSE 'allowed' END;
 INSERT INTO c10_demo.ai_call_v1(tenant_id,business_id,account_id,agent_code,idempotency_key,redacted_input,state,created_by)
 VALUES(a.tenant_id,a.business_id,p_account,p_agent,p_key,red,st,c10_demo.actor_uid()) RETURNING id INTO v_id;
 RETURN jsonb_build_object('status',CASE WHEN st IN('allowed','fallback_local') THEN st ELSE 'blocked' END,'id',v_id,'state',st,
   'input',CASE WHEN st='allowed' THEN red ELSE NULL END);
END $$;

CREATE FUNCTION c10_demo.ai_report_v1(p_call bigint,p_ok boolean,p_in integer DEFAULT 0,p_out integer DEFAULT 0,p_cost numeric DEFAULT 0)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE c record;
BEGIN
 SELECT * INTO c FROM c10_demo.ai_call_v1 WHERE id=p_call FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(c.tenant_id,c.business_id) THEN RAISE EXCEPTION 'ai_denied'; END IF;
 IF c.state<>'allowed' THEN RETURN c.state; END IF;
 UPDATE c10_demo.ai_call_v1 SET state=CASE WHEN p_ok THEN 'done' ELSE 'failed' END,
   tokens_in=GREATEST(p_in,0),tokens_out=GREATEST(p_out,0),cost=GREATEST(p_cost,0) WHERE id=p_call;
 RETURN CASE WHEN p_ok THEN 'done' ELSE 'failed' END;
END $$;


BEGIN
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'ai_denied'; END IF;

-- C10-A022: Tenant-scoped financing/profit entitlement and payment ledger (CI ONLY).
-- NOT production accounting, a bank payout, equity registration or promised return.
-- profit_share_bps=1400 means 14% of APPROVED POSITIVE PERIOD PROFIT, NOT
-- 14% annual interest on principal. Losses across months offset before GREATEST(0).
-- Months are externally/manual-entered, with explicit source_status unverified.
CREATE TABLE c10_demo.finance_months_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 month_start date NOT NULL,
 revenue numeric(18,2) NOT NULL CHECK(revenue>=0 AND revenue::text NOT IN('NaN','Infinity','-Infinity')),
 costs numeric(18,2) NOT NULL CHECK(costs>=0 AND costs::text NOT IN('NaN','Infinity','-Infinity')),
 net_profit numeric(19,2) GENERATED ALWAYS AS (revenue-costs) STORED,
 source_status text NOT NULL DEFAULT 'manual_unverified' CHECK(source_status='manual_unverified'),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','owner_approved')),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 created_by uuid NOT NULL,
 approved_by uuid,
 approved_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,month_start),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 CHECK(month_start=date_trunc('month',month_start::timestamp)::date),
 CHECK((status='draft' AND approved_by IS NULL AND approved_at IS NULL) OR
  (status='owner_approved' AND approved_by IS NOT NULL AND approved_at IS NOT NULL))
);
CREATE TABLE c10_demo.funding_agreements_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 investor_id uuid NOT NULL,
 agreement_code text NOT NULL CHECK(length(btrim(agreement_code)) BETWEEN 2 AND 80),
 agreement_type text NOT NULL DEFAULT 'profit_participation'
  CHECK(agreement_type='profit_participation'),
 principal numeric(18,2) NOT NULL CHECK(principal>0 AND principal::text NOT IN('NaN','Infinity','-Infinity')),
 profit_share_bps integer NOT NULL CHECK(profit_share_bps BETWEEN 1 AND 10000),
 payout_every_months integer NOT NULL CHECK(payout_every_months IN(1,3,6)),
 valid_from date NOT NULL,
 valid_until date NOT NULL,
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','active','closed')),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 created_by uuid NOT NULL,
 activated_by uuid,
 activated_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,agreement_code),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 CHECK(valid_from=date_trunc('month',valid_from::timestamp)::date),
 CHECK(valid_until=date_trunc('month',valid_until::timestamp)::date),
 CHECK(valid_until>valid_from AND valid_until<=valid_from+interval '60 months'),
 CHECK((status='draft' AND activated_by IS NULL AND activated_at IS NULL) OR
  (status IN('active','closed') AND activated_by IS NOT NULL AND activated_at IS NOT NULL))
);
CREATE TABLE c10_demo.funding_entitlements_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 agreement_id bigint NOT NULL REFERENCES c10_demo.funding_agreements_v1(id),
 window_start date NOT NULL,
 window_end date NOT NULL,
 month_count integer NOT NULL CHECK(month_count IN(1,3,6)),
 period_profit numeric(19,2) NOT NULL,
 share_bps integer NOT NULL CHECK(share_bps BETWEEN 1 AND 10000),
 amount numeric(18,2) NOT NULL CHECK(amount>=0),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 calculated_by uuid NOT NULL,
 calculated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(agreement_id,window_start),
 UNIQUE(agreement_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 CHECK(window_end>window_start)
);
CREATE TABLE c10_demo.funding_payments_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 entitlement_id bigint NOT NULL REFERENCES c10_demo.funding_entitlements_v1(id),
 paid_amount numeric(18,2) NOT NULL CHECK(paid_amount>0 AND paid_amount::text NOT IN('NaN','Infinity','-Infinity')),
 evidence_reference text NOT NULL CHECK(length(btrim(evidence_reference)) BETWEEN 4 AND 120),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 recorded_by uuid NOT NULL,
 recorded_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(entitlement_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);

CREATE FUNCTION c10_demo.can_read_funding_v1(
 p_tenant bigint,p_business bigint,p_investor uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT c10_demo.can_manage(p_tenant,p_business)
  OR (p_investor=c10_demo.actor_uid() AND EXISTS(
    SELECT 1 FROM c10_demo.business_members m
    WHERE m.tenant_id=p_tenant AND m.business_id=p_business
     AND m.user_id=p_investor AND m.role='investor' AND m.active
  ))
$$;
ALTER TABLE c10_demo.finance_months_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.funding_agreements_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.funding_entitlements_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.funding_payments_v1 ENABLE ROW LEVEL SECURITY;
CREATE POLICY finance_month_owner_read_v1 ON c10_demo.finance_months_v1
 FOR SELECT TO authenticated USING(c10_demo.can_manage(tenant_id,business_id));
CREATE POLICY funding_agreements_owner_investor_read_v1 ON c10_demo.funding_agreements_v1
 FOR SELECT TO authenticated USING(c10_demo.can_read_funding_v1(tenant_id,business_id,investor_id));
CREATE POLICY funding_entitlements_owner_investor_read_v1 ON c10_demo.funding_entitlements_v1
 FOR SELECT TO authenticated USING(EXISTS(
  SELECT 1 FROM c10_demo.funding_agreements_v1 a
   WHERE a.id=c10_demo.funding_entitlements_v1.agreement_id
    AND a.business_id=c10_demo.funding_entitlements_v1.business_id
    AND a.tenant_id=c10_demo.funding_entitlements_v1.tenant_id
    AND c10_demo.can_read_funding_v1(a.tenant_id,a.business_id,a.investor_id)
 ));
CREATE POLICY funding_payments_owner_investor_read_v1 ON c10_demo.funding_payments_v1
 FOR SELECT TO authenticated USING(EXISTS(
  SELECT 1 FROM c10_demo.funding_entitlements_v1 e
   JOIN c10_demo.funding_agreements_v1 a ON a.id=e.agreement_id
   WHERE e.id=c10_demo.funding_payments_v1.entitlement_id
    AND e.tenant_id=c10_demo.funding_payments_v1.tenant_id
    AND e.business_id=c10_demo.funding_payments_v1.business_id
     AND c10_demo.can_read_funding_v1(a.tenant_id,a.business_id,a.investor_id)
 ));
REVOKE ALL ON c10_demo.finance_months_v1,c10_demo.funding_agreements_v1,
 c10_demo.funding_entitlements_v1,c10_demo.funding_payments_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.finance_months_v1,c10_demo.funding_agreements_v1,
 c10_demo.funding_entitlements_v1,c10_demo.funding_payments_v1 TO authenticated;

CREATE FUNCTION c10_demo.record_finance_month_v1(
 p_business bigint,p_month date,p_revenue numeric,p_costs numeric,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;v_id bigint;v_old record;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_business IS NULL OR p_month IS NULL OR
   p_month<>date_trunc('month',p_month::timestamp)::date OR
   p_revenue IS NULL OR p_costs IS NULL OR
   p_revenue<0 OR p_costs<0 OR
   p_revenue::text IN('NaN','Infinity','-Infinity') OR
   p_costs::text IN('NaN','Infinity','-Infinity') OR
   p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_profit_month'; END IF;
 SELECT tenant_id INTO v_tenant FROM c10_demo.businesses WHERE id=p_business;
 IF v_tenant IS NULL OR NOT c10_demo.can_manage(v_tenant,p_business)
 THEN RAISE EXCEPTION 'finance_not_authorized'; END IF;
 INSERT INTO c10_demo.finance_months_v1(
  tenant_id,business_id,month_start,revenue,costs,request_key,created_by)
 VALUES(v_tenant,p_business,p_month,p_revenue,p_costs,p_request,c10_demo.actor_uid())
 ON CONFLICT DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_old FROM c10_demo.finance_months_v1
   WHERE business_id=p_business AND request_key=p_request;
  IF NOT FOUND OR v_old.month_start<>p_month OR
   v_old.revenue<>p_revenue OR v_old.costs<>p_costs OR
   v_old.created_by<>c10_demo.actor_uid()
  THEN RAISE EXCEPTION 'finance_month_idempotency_conflict'; END IF;
  v_id:=v_old.id;
 END IF;
 RETURN v_id;
END $$;
CREATE FUNCTION c10_demo.approve_finance_month_v1(p_month_id bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_row c10_demo.finance_months_v1%ROWTYPE;
BEGIN
 IF p_month_id IS NULL OR c10_demo.actor_uid() IS NULL THEN
  RAISE EXCEPTION 'finance_month_bad_request'; END IF;
 SELECT * INTO v_row FROM c10_demo.finance_months_v1
   WHERE id=p_month_id FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_row.tenant_id,v_row.business_id)
 THEN RAISE EXCEPTION 'finance_approve_denied'; END IF;
 IF v_row.status='draft' THEN
  UPDATE c10_demo.finance_months_v1
   SET status='owner_approved',approved_by=c10_demo.actor_uid(),approved_at=now()
   WHERE id=p_month_id;
 END IF;
 RETURN 'owner_approved';
END $$;
CREATE FUNCTION c10_demo.create_funding_agreement_v1(
 p_business bigint,p_investor uuid,p_code text,p_principal numeric,
 p_share_bps integer,p_every_months integer,p_from date,p_until date,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;v_id bigint;v_old record;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_business IS NULL OR p_investor IS NULL OR
  p_code IS NULL OR length(btrim(p_code)) NOT BETWEEN 2 AND 80 OR
  p_principal IS NULL OR p_principal<=0 OR
  p_principal::text IN('NaN','Infinity','-Infinity') OR
  p_share_bps IS NULL OR p_share_bps NOT BETWEEN 1 AND 10000 OR
  p_every_months NOT IN(1,3,6) OR p_every_months IS NULL OR
  p_from IS NULL OR p_until IS NULL OR
  p_from<>date_trunc('month',p_from::timestamp)::date OR
  p_until<>date_trunc('month',p_until::timestamp)::date OR
  p_until<=p_from OR p_until>p_from+interval '60 months' OR
  p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_funding_contract'; END IF;
 SELECT tenant_id INTO v_tenant FROM c10_demo.businesses WHERE id=p_business;
 IF v_tenant IS NULL OR NOT c10_demo.can_manage(v_tenant,p_business)
 THEN RAISE EXCEPTION 'funding_create_denied'; END IF;
 IF NOT EXISTS(SELECT 1 FROM c10_demo.business_members m
  WHERE m.tenant_id=v_tenant AND m.business_id=p_business
   AND m.user_id=p_investor AND m.role='investor' AND m.active)
 THEN RAISE EXCEPTION 'investor_not_assigned_to_business'; END IF;
 INSERT INTO c10_demo.funding_agreements_v1(
  tenant_id,business_id,investor_id,agreement_code,principal,
  profit_share_bps,payout_every_months,valid_from,valid_until,request_key,created_by)
 VALUES(v_tenant,p_business,p_investor,btrim(p_code),p_principal,
  p_share_bps,p_every_months,p_from,p_until,p_request,c10_demo.actor_uid())
 ON CONFLICT DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_old FROM c10_demo.funding_agreements_v1
   WHERE business_id=p_business AND request_key=p_request;
  IF NOT FOUND OR v_old.investor_id<>p_investor OR
    v_old.agreement_code<>btrim(p_code) OR v_old.principal<>p_principal OR
    v_old.profit_share_bps<>p_share_bps OR v_old.payout_every_months<>p_every_months OR
    v_old.valid_from<>p_from OR v_old.valid_until<>p_until OR
    v_old.created_by<>c10_demo.actor_uid()
  THEN RAISE EXCEPTION 'funding_contract_idempotency_conflict'; END IF;
  v_id:=v_old.id;
 END IF;
 RETURN v_id;
END $$;
CREATE FUNCTION c10_demo.activate_funding_agreement_v1(p_agreement bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_a c10_demo.funding_agreements_v1%ROWTYPE;v_day date;v_active integer;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_agreement IS NULL
 THEN RAISE EXCEPTION 'invalid_agreement_activation'; END IF;
 SELECT * INTO v_a FROM c10_demo.funding_agreements_v1 WHERE id=p_agreement;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_a.tenant_id,v_a.business_id)
 THEN RAISE EXCEPTION 'agreement_activation_denied'; END IF;
 -- Serialise all activations for one business to avoid concurrent >100% claims.
 PERFORM 1 FROM c10_demo.businesses WHERE id=v_a.business_id FOR UPDATE;
 SELECT * INTO v_a FROM c10_demo.funding_agreements_v1 WHERE id=p_agreement FOR UPDATE;
 IF v_a.status='active' THEN RETURN 'active'; END IF;
 IF v_a.status<>'draft' THEN RAISE EXCEPTION 'agreement_not_draft'; END IF;
 FOR v_day IN SELECT generate_series(v_a.valid_from,v_a.valid_until-interval '1 month',interval '1 month')::date LOOP
  SELECT COALESCE(sum(a.profit_share_bps),0) INTO v_active
   FROM c10_demo.funding_agreements_v1 a
   WHERE a.business_id=v_a.business_id AND a.status='active'
     AND a.valid_from<=v_day AND a.valid_until>v_day;
  IF v_active+v_a.profit_share_bps>10000 THEN
   RAISE EXCEPTION 'profit_shares_exceed_100_percent';
  END IF;
 END LOOP;
 UPDATE c10_demo.funding_agreements_v1
  SET status='active',activated_by=c10_demo.actor_uid(),activated_at=now()
  WHERE id=p_agreement;
 RETURN 'active';
END $$;
CREATE FUNCTION c10_demo.create_funding_entitlement_v1(
 p_agreement bigint,p_window date,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_a c10_demo.funding_agreements_v1%ROWTYPE;
 v_end date;v_months integer;v_profit numeric(19,2);v_count bigint;
 v_id bigint;v_old record;v_month_offset integer;v_amount numeric(18,2);
BEGIN
 IF p_agreement IS NULL OR p_window IS NULL OR
  p_window<>date_trunc('month',p_window::timestamp)::date OR
  c10_demo.actor_uid() IS NULL OR p_request IS NULL OR
  length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_entitlement_request'; END IF;
 SELECT * INTO v_a FROM c10_demo.funding_agreements_v1
  WHERE id=p_agreement FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_a.tenant_id,v_a.business_id)
 THEN RAISE EXCEPTION 'entitlement_not_authorized'; END IF;
 v_months:=v_a.payout_every_months;
 v_end:=(p_window+(v_months||' months')::interval)::date;
 v_month_offset:=((extract(year from p_window)-extract(year from v_a.valid_from))*12+
   extract(month from p_window)-extract(month from v_a.valid_from))::integer;
 IF v_a.status<>'active' OR p_window<v_a.valid_from OR v_end>v_a.valid_until OR
   mod(v_month_offset,v_months)<>0
 THEN RAISE EXCEPTION 'entitlement_outside_agreement_schedule'; END IF;
 SELECT count(*),COALESCE(sum(net_profit),0) INTO v_count,v_profit
 FROM c10_demo.finance_months_v1 m
 WHERE m.business_id=v_a.business_id AND m.month_start>=p_window
  AND m.month_start<v_end AND m.status='owner_approved';
 IF v_count<>v_months THEN RAISE EXCEPTION 'missing_approved_profit_months'; END IF;
 v_amount:=round(greatest(v_profit,0)*v_a.profit_share_bps/10000,2);
 INSERT INTO c10_demo.funding_entitlements_v1(
  tenant_id,business_id,agreement_id,window_start,window_end,month_count,
  period_profit,share_bps,amount,request_key,calculated_by)
 VALUES(v_a.tenant_id,v_a.business_id,p_agreement,p_window,v_end,v_months,
  v_profit,v_a.profit_share_bps,v_amount,p_request,c10_demo.actor_uid())
 ON CONFLICT DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_old FROM c10_demo.funding_entitlements_v1
   WHERE agreement_id=p_agreement AND request_key=p_request;
  IF NOT FOUND OR v_old.window_start<>p_window OR v_old.window_end<>v_end OR
   v_old.period_profit<>v_profit OR v_old.share_bps<>v_a.profit_share_bps OR
   v_old.amount<>v_amount OR v_old.calculated_by<>c10_demo.actor_uid()
  THEN RAISE EXCEPTION 'funding_entitlement_idempotency_conflict'; END IF;
  v_id:=v_old.id;
 END IF;
 RETURN v_id;
END $$;
CREATE FUNCTION c10_demo.record_funding_payment_v1(
 p_entitlement bigint,p_amount numeric,p_evidence text,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_e c10_demo.funding_entitlements_v1%ROWTYPE;
 v_id bigint;v_paid numeric(18,2);v_old record;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_entitlement IS NULL OR
   p_amount IS NULL OR p_amount<=0 OR p_amount::text IN('NaN','Infinity','-Infinity') OR
   p_evidence IS NULL OR length(btrim(p_evidence)) NOT BETWEEN 4 AND 120 OR
   p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_payment_record'; END IF;
 SELECT * INTO v_e FROM c10_demo.funding_entitlements_v1
  WHERE id=p_entitlement FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_e.tenant_id,v_e.business_id)
 THEN RAISE EXCEPTION 'funding_payment_denied'; END IF;
 SELECT * INTO v_old FROM c10_demo.funding_payments_v1
  WHERE entitlement_id=p_entitlement AND request_key=p_request;
 IF FOUND THEN
  IF v_old.paid_amount<>p_amount OR v_old.evidence_reference<>btrim(p_evidence)
    OR v_old.recorded_by<>c10_demo.actor_uid() THEN
   RAISE EXCEPTION 'funding_payment_idempotency_conflict'; END IF;
  RETURN v_old.id;
 END IF;
 SELECT COALESCE(sum(paid_amount),0) INTO v_paid
 FROM c10_demo.funding_payments_v1 WHERE entitlement_id=p_entitlement;
 IF v_paid+p_amount>v_e.amount THEN RAISE EXCEPTION 'payment_exceeds_entitlement'; END IF;
 INSERT INTO c10_demo.funding_payments_v1(
   tenant_id,business_id,entitlement_id,paid_amount,evidence_reference,
   request_key,recorded_by)
 VALUES(v_e.tenant_id,v_e.business_id,p_entitlement,p_amount,btrim(p_evidence),
   p_request,c10_demo.actor_uid()) RETURNING id INTO v_id;
 RETURN v_id;
END $$;

CREATE VIEW c10_demo.investor_statement_v1 WITH(security_invoker=true) AS
 SELECT a.tenant_id,a.business_id,a.id AS agreement_id,
  a.agreement_code,a.investor_id,a.agreement_type,a.principal,
  a.profit_share_bps,a.payout_every_months,a.status AS contract_status,
  e.id AS entitlement_id,e.window_start,e.window_end,
  e.period_profit,e.amount AS allocated_profit,
  COALESCE(p.paid,0)::numeric(18,2) AS recorded_paid,
  (e.amount-COALESCE(p.paid,0))::numeric(18,2) AS unpaid_balance,
  false::boolean AS bank_transfer_verified
 FROM c10_demo.funding_agreements_v1 a
 LEFT JOIN c10_demo.funding_entitlements_v1 e ON e.agreement_id=a.id
 LEFT JOIN LATERAL (
   SELECT sum(pm.paid_amount) AS paid FROM c10_demo.funding_payments_v1 pm
   WHERE pm.entitlement_id=e.id
 ) p ON true;
REVOKE ALL ON c10_demo.investor_statement_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.investor_statement_v1 TO authenticated;


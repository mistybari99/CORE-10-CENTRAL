-- CORE 10 CENTRAL: C10-A018/A019 executable enterprise demo backend v0
-- DISPOSABLE POSTGRES / CI ONLY. NOT a production migration.
-- Proves real SQL/RLS/transaction rules, but has NOT been wired to legacy SG or the deployed UI.
-- All identities are synthetic; use Supabase auth.uid() / signed JWT verification at deployment.
CREATE SCHEMA c10_demo;
CREATE FUNCTION c10_demo.actor_uid() RETURNS uuid
LANGUAGE sql STABLE AS $$
 SELECT COALESCE(NULLIF(current_setting('request.jwt.claims',true),'')::jsonb ->> 'sub',
                 NULLIF(current_setting('request.jwt.claim.sub',true),''))::uuid
$$;

CREATE TABLE c10_demo.tenants (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug text NOT NULL UNIQUE,
 active boolean NOT NULL DEFAULT true
);
CREATE TABLE c10_demo.legal_entities (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES c10_demo.tenants(id),
 label text NOT NULL,
 UNIQUE(id,tenant_id)
);
CREATE TABLE c10_demo.templates(
 code text PRIMARY KEY,
 source_status text NOT NULL CHECK(source_status IN('available','needs_setup','not_implemented')),
 demo_allowed boolean NOT NULL DEFAULT false,
 enterprise_certified boolean NOT NULL DEFAULT false
);
CREATE TABLE c10_demo.businesses(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES c10_demo.tenants(id),
 legal_entity_id bigint NOT NULL,
 slug text NOT NULL,
 template_code text NOT NULL REFERENCES c10_demo.templates(code),
 request_key text NOT NULL,
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','setup_pending','ready','active')),
 UNIQUE(id,tenant_id), UNIQUE(tenant_id,request_key), UNIQUE(tenant_id,slug),
 FOREIGN KEY(legal_entity_id,tenant_id) REFERENCES c10_demo.legal_entities(id,tenant_id)
);
CREATE TABLE c10_demo.sites(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 kind text NOT NULL CHECK(kind IN('showroom','factory','godown','warehouse','project')),
 label text NOT NULL,
 request_key text NOT NULL,
 UNIQUE(id,tenant_id,business_id), UNIQUE(business_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
CREATE TABLE c10_demo.stock_locations(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 code text NOT NULL,
 UNIQUE(id,tenant_id,business_id,site_id), UNIQUE(site_id,code),
 FOREIGN KEY(site_id,tenant_id,business_id) REFERENCES c10_demo.sites(id,tenant_id,business_id)
);
CREATE TABLE c10_demo.items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 sku text NOT NULL,
 UNIQUE(id,tenant_id,business_id), UNIQUE(business_id,sku),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
CREATE TABLE c10_demo.tenant_members(
 tenant_id bigint NOT NULL REFERENCES c10_demo.tenants(id),
 user_id uuid NOT NULL,
 role text NOT NULL CHECK(role='tenant_owner'),
 active boolean NOT NULL DEFAULT true,
 PRIMARY KEY(tenant_id,user_id)
);
CREATE TABLE c10_demo.business_members(
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 user_id uuid NOT NULL,
 role text NOT NULL CHECK(role IN('business_owner','manager','investor')),
 active boolean NOT NULL DEFAULT true,
 PRIMARY KEY(business_id,user_id),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
CREATE TABLE c10_demo.site_grants(
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 user_id uuid NOT NULL,
 actions text[] NOT NULL DEFAULT '{}',
 active boolean NOT NULL DEFAULT true,
 PRIMARY KEY(site_id,user_id),
 FOREIGN KEY(site_id,tenant_id,business_id) REFERENCES c10_demo.sites(id,tenant_id,business_id),
 CHECK(actions <@ ARRAY['stock.read','stock.post']::text[])
);
CREATE TABLE c10_demo.stock_movements(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 location_id bigint NOT NULL,
 item_id bigint NOT NULL,
 delta numeric(15,3) NOT NULL CHECK(delta<>0),
 request_key text NOT NULL,
 created_by uuid NOT NULL DEFAULT c10_demo.actor_uid(),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(location_id,request_key),
 FOREIGN KEY(location_id,tenant_id,business_id,site_id) REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id)
);

-- All authorization is derived from database memberships, not caller-supplied tenant/role JWT metadata.
CREATE FUNCTION c10_demo.can_tenant(p_tenant bigint) RETURNS boolean
LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT EXISTS(
 SELECT 1 FROM c10_demo.tenant_members m
 WHERE m.user_id=c10_demo.actor_uid() AND m.tenant_id=p_tenant
   AND m.role='tenant_owner' AND m.active)
$$;
CREATE FUNCTION c10_demo.can_business(p_tenant bigint,p_business bigint) RETURNS boolean
LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT c10_demo.can_tenant(p_tenant) OR EXISTS(
 SELECT 1 FROM c10_demo.business_members m
 WHERE m.user_id=c10_demo.actor_uid() AND m.tenant_id=p_tenant
   AND m.business_id=p_business AND m.active AND m.role IN('business_owner','manager'))
$$;
CREATE FUNCTION c10_demo.can_manage(p_tenant bigint,p_business bigint) RETURNS boolean
LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT c10_demo.can_tenant(p_tenant) OR EXISTS(
 SELECT 1 FROM c10_demo.business_members m
 WHERE m.user_id=c10_demo.actor_uid() AND m.tenant_id=p_tenant
   AND m.business_id=p_business AND m.active AND m.role='business_owner')
$$;
CREATE FUNCTION c10_demo.can_site(p_tenant bigint,p_business bigint,p_site bigint,p_action text)
RETURNS boolean LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT c10_demo.can_business(p_tenant,p_business) OR EXISTS (
 SELECT 1 FROM c10_demo.site_grants g
 WHERE g.user_id=c10_demo.actor_uid() AND g.active
   AND g.tenant_id=p_tenant AND g.business_id=p_business
   AND g.site_id=p_site AND p_action=ANY(g.actions))
$$;
CREATE FUNCTION c10_demo.can_see_business(p_tenant bigint,p_business bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT c10_demo.can_business(p_tenant,p_business) OR EXISTS (
 SELECT 1 FROM c10_demo.site_grants g
 WHERE g.user_id=c10_demo.actor_uid() AND g.active
 AND g.tenant_id=p_tenant AND g.business_id=p_business AND array_length(g.actions,1)>0)
$$;


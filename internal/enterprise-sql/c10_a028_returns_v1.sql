-- CORE10 A028: returns bound to POSTED purchase/sale lines. PG17 CI ONLY.
-- This does NOT execute actual refunds, vendor credits, VAT corrections, or bank transfers.
CREATE TABLE c10_demo.return_documents_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 original_document_id bigint NOT NULL REFERENCES c10_demo.operational_documents_v1(id),
 location_id bigint NOT NULL,
 site_id bigint NOT NULL,
 return_kind text NOT NULL CHECK(return_kind IN('sale_return','purchase_return')),
 reason text NOT NULL CHECK(length(btrim(reason)) BETWEEN 5 AND 500),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 lines_payload jsonb NOT NULL CHECK(jsonb_typeof(lines_payload)='array'),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','confirmed','posted')),
 created_by uuid NOT NULL,
 confirmed_by uuid,confirmed_at timestamptz,
 posted_by uuid,posted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 FOREIGN KEY(location_id,tenant_id,business_id,site_id)
  REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 CHECK((status='draft' AND confirmed_by IS NULL AND confirmed_at IS NULL AND posted_by IS NULL AND posted_at IS NULL)
 OR (status='confirmed' AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL AND posted_by IS NULL AND posted_at IS NULL)
 OR (status='posted' AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL AND posted_by IS NOT NULL AND posted_at IS NOT NULL))
);
CREATE TABLE c10_demo.return_lines_v1(
 return_id bigint NOT NULL REFERENCES c10_demo.return_documents_v1(id),
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 original_document_id bigint NOT NULL,
 original_line_no integer NOT NULL,
 quantity numeric(15,3) NOT NULL CHECK(quantity>0 AND quantity=round(quantity,3)),
 amount_unsettled numeric(20,2) NOT NULL CHECK(amount_unsettled>=0),
 PRIMARY KEY(return_id,original_line_no),
 FOREIGN KEY(original_document_id,original_line_no)
  REFERENCES c10_demo.operational_document_lines_v1(document_id,line_no),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
ALTER TABLE c10_demo.return_documents_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.return_lines_v1 ENABLE ROW LEVEL SECURITY;
CREATE POLICY return_docs_scoped_v1 ON c10_demo.return_documents_v1
 FOR SELECT TO authenticated USING(c10_demo.can_business(tenant_id,business_id));
CREATE POLICY return_lines_scoped_v1 ON c10_demo.return_lines_v1
 FOR SELECT TO authenticated USING(c10_demo.can_business(tenant_id,business_id));
REVOKE ALL ON c10_demo.return_documents_v1,c10_demo.return_lines_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.return_documents_v1,c10_demo.return_lines_v1 TO authenticated;

CREATE FUNCTION c10_demo.create_return_v1(
 p_original bigint,p_lines jsonb,p_reason text,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_orig c10_demo.operational_documents_v1%ROWTYPE;
 v_line jsonb;v_source c10_demo.operational_document_lines_v1%ROWTYPE;
 v_ix integer:=0;v_no integer;v_qty numeric;v_seen integer[]:='{}';
 v_id bigint;v_previous record;v_amount numeric(20,2);v_kind text;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_original IS NULL OR
  p_lines IS NULL OR jsonb_typeof(p_lines)<>'array' OR
  jsonb_array_length(p_lines) NOT BETWEEN 1 AND 100 OR
  p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 5 AND 500 OR
  p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_return_request'; END IF;
 SELECT * INTO v_orig FROM c10_demo.operational_documents_v1 WHERE id=p_original;
 IF NOT FOUND OR NOT c10_demo.can_business(v_orig.tenant_id,v_orig.business_id)
  OR NOT c10_demo.can_site(v_orig.tenant_id,v_orig.business_id,v_orig.site_id,'stock.post')
 THEN RAISE EXCEPTION 'return_scope_denied'; END IF;
 IF v_orig.status<>'posted' THEN RAISE EXCEPTION 'return_original_not_posted'; END IF;
 v_kind:=CASE WHEN v_orig.kind='sale' THEN 'sale_return' ELSE 'purchase_return' END;
 FOR v_line IN SELECT value FROM jsonb_array_elements(p_lines) LOOP
  v_ix:=v_ix+1;
  IF jsonb_typeof(v_line)<>'object' OR
   (SELECT count(*) FROM jsonb_object_keys(v_line))<>2 OR
   jsonb_typeof(v_line->'line')<>'number' OR
   jsonb_typeof(v_line->'quantity')<>'number'
  THEN RAISE EXCEPTION 'invalid_return_line'; END IF;
  BEGIN
   v_no:=(v_line->>'line')::integer;
   v_qty:=(v_line->>'quantity')::numeric;
  EXCEPTION WHEN numeric_value_out_of_range OR invalid_text_representation THEN
   RAISE EXCEPTION 'invalid_return_line';
  END;
  IF v_no<1 OR v_no=ANY(v_seen) OR v_qty<=0 OR v_qty<>round(v_qty,3)
  THEN RAISE EXCEPTION 'invalid_return_line'; END IF;
  SELECT * INTO v_source FROM c10_demo.operational_document_lines_v1
  WHERE document_id=p_original AND line_no=v_no;
  IF NOT FOUND OR v_source.quantity<v_qty
  THEN RAISE EXCEPTION 'return_exceeds_original_line'; END IF;
  v_seen:=array_append(v_seen,v_no);
 END LOOP;
 INSERT INTO c10_demo.return_documents_v1(
  tenant_id,business_id,original_document_id,location_id,site_id,
  return_kind,reason,request_key,lines_payload,created_by)
 VALUES(v_orig.tenant_id,v_orig.business_id,p_original,v_orig.location_id,v_orig.site_id,
  v_kind,btrim(p_reason),p_request,p_lines,c10_demo.actor_uid())
 ON CONFLICT(business_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_previous FROM c10_demo.return_documents_v1
   WHERE business_id=v_orig.business_id AND request_key=p_request;
  IF NOT FOUND OR v_previous.original_document_id<>p_original OR
     v_previous.reason<>btrim(p_reason) OR v_previous.lines_payload<>p_lines
    OR v_previous.created_by<>c10_demo.actor_uid()
  THEN RAISE EXCEPTION 'return_idempotency_conflict'; END IF;
  RETURN v_previous.id;
 END IF;
 FOR v_line IN SELECT value FROM jsonb_array_elements(p_lines) LOOP
  v_no:=(v_line->>'line')::integer;
  v_qty:=(v_line->>'quantity')::numeric;
  SELECT * INTO v_source FROM c10_demo.operational_document_lines_v1
   WHERE document_id=p_original AND line_no=v_no;
  -- Discount allocated pro-rata. Gross/discount/tax amounts are NOT refund payments.
  v_amount:=round(v_source.unit_price*v_qty*
    (1-v_orig.discount/NULLIF(v_orig.subtotal,0)),2);
  INSERT INTO c10_demo.return_lines_v1(
    return_id,tenant_id,business_id,original_document_id,
    original_line_no,quantity,amount_unsettled)
  VALUES(v_id,v_orig.tenant_id,v_orig.business_id,p_original,v_no,v_qty,v_amount);
 END LOOP;
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.confirm_return_v1(p_return bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_return c10_demo.return_documents_v1%ROWTYPE;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_return IS NULL THEN RAISE EXCEPTION 'return_invalid_confirm'; END IF;
 SELECT * INTO v_return FROM c10_demo.return_documents_v1 WHERE id=p_return FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_return.tenant_id,v_return.business_id)
 THEN RAISE EXCEPTION 'return_confirm_denied'; END IF;
 IF v_return.status='draft' THEN
  UPDATE c10_demo.return_documents_v1 SET status='confirmed',
   confirmed_by=c10_demo.actor_uid(),confirmed_at=now() WHERE id=p_return;
  RETURN 'confirmed';
 END IF;
 RETURN v_return.status;
END $$;
CREATE FUNCTION c10_demo.post_return_v1(p_return bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_return c10_demo.return_documents_v1%ROWTYPE;
 v_orig c10_demo.operational_documents_v1%ROWTYPE;v_line c10_demo.return_lines_v1%ROWTYPE;
 v_source c10_demo.operational_document_lines_v1%ROWTYPE;
 v_posted numeric(15,3);v_delta numeric(15,3);
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_return IS NULL THEN RAISE EXCEPTION 'return_invalid_post'; END IF;
 SELECT * INTO v_return FROM c10_demo.return_documents_v1 WHERE id=p_return FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_return.tenant_id,v_return.business_id)
 THEN RAISE EXCEPTION 'return_post_denied'; END IF;
 IF v_return.status='posted' THEN RETURN 'posted'; END IF;
 IF v_return.status<>'confirmed' THEN RAISE EXCEPTION 'return_not_confirmed'; END IF;
 IF NOT c10_demo.can_site(v_return.tenant_id,v_return.business_id,v_return.site_id,'stock.post')
 THEN RAISE EXCEPTION 'return_stock_permission_denied'; END IF;
 -- Lock original document so different returns cannot over-return concurrently.
 SELECT * INTO v_orig FROM c10_demo.operational_documents_v1
   WHERE id=v_return.original_document_id FOR UPDATE;
 IF v_orig.status<>'posted' OR
   v_orig.tenant_id<>v_return.tenant_id OR v_orig.business_id<>v_return.business_id OR
   v_orig.location_id<>v_return.location_id THEN RAISE EXCEPTION 'return_original_invalid'; END IF;
 FOR v_line IN SELECT * FROM c10_demo.return_lines_v1
  WHERE return_id=p_return ORDER BY original_line_no LOOP
  SELECT * INTO v_source FROM c10_demo.operational_document_lines_v1
    WHERE document_id=v_return.original_document_id AND line_no=v_line.original_line_no;
  SELECT COALESCE(sum(rl.quantity),0) INTO v_posted
  FROM c10_demo.return_lines_v1 rl
  JOIN c10_demo.return_documents_v1 rd ON rd.id=rl.return_id
  WHERE rl.original_document_id=v_return.original_document_id
    AND rl.original_line_no=v_line.original_line_no AND rd.status='posted';
  IF v_posted+v_line.quantity>v_source.quantity
  THEN RAISE EXCEPTION 'return_exceeds_remaining_quantity'; END IF;
  v_delta:=CASE WHEN v_return.return_kind='sale_return' THEN v_line.quantity
            ELSE -v_line.quantity END;
  PERFORM c10_demo.post_stock_event(v_return.location_id,v_source.item_id,v_delta,
    'c10-return:'||p_return||':line:'||v_line.original_line_no);
 END LOOP;
 UPDATE c10_demo.return_documents_v1 SET status='posted',
  posted_by=c10_demo.actor_uid(),posted_at=now() WHERE id=p_return;
 RETURN 'posted';
END $$;

CREATE VIEW c10_demo.operational_net_returns_v1 WITH(security_invoker=true) AS
 SELECT b.tenant_id,b.id AS business_id,
  COALESCE(op.posted_sale_value_unreconciled,0)::numeric(20,2) AS gross_sale_value_unreconciled,
  COALESCE(sale_ret.return_amount,0)::numeric(20,2) AS sale_return_value_unsettled,
  (COALESCE(op.posted_sale_value_unreconciled,0)-COALESCE(sale_ret.return_amount,0))::numeric(20,2)
     AS net_sale_value_unreconciled,
  COALESCE(op.received_purchase_value_unreconciled,0)::numeric(20,2) AS gross_purchase_value_unreconciled,
  COALESCE(buy_ret.return_amount,0)::numeric(20,2) AS purchase_return_value_unsettled,
  (COALESCE(op.received_purchase_value_unreconciled,0)-COALESCE(buy_ret.return_amount,0))::numeric(20,2)
     AS net_purchase_value_unreconciled,
  false::boolean AS actual_refunds_reconciled
 FROM c10_demo.businesses b
 LEFT JOIN c10_demo.operational_business_report_v1 op ON op.business_id=b.id
 LEFT JOIN LATERAL(
  SELECT sum(l.amount_unsettled) AS return_amount FROM c10_demo.return_lines_v1 l
  JOIN c10_demo.return_documents_v1 r ON r.id=l.return_id
  WHERE r.business_id=b.id AND r.return_kind='sale_return' AND r.status='posted'
 ) sale_ret ON true
 LEFT JOIN LATERAL(
  SELECT sum(l.amount_unsettled) AS return_amount FROM c10_demo.return_lines_v1 l
  JOIN c10_demo.return_documents_v1 r ON r.id=l.return_id
  WHERE r.business_id=b.id AND r.return_kind='purchase_return' AND r.status='posted'
 ) buy_ret ON true
 WHERE c10_demo.can_manage(b.tenant_id,b.id);
REVOKE ALL ON c10_demo.operational_net_returns_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.operational_net_returns_v1 TO authenticated;
REVOKE EXECUTE ON FUNCTION c10_demo.create_return_v1(bigint,jsonb,text,text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.confirm_return_v1(bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.post_return_v1(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION c10_demo.create_return_v1(bigint,jsonb,text,text) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.confirm_return_v1(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.post_return_v1(bigint) TO authenticated;

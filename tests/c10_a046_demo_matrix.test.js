writeLeak.personas.find(p=>p.key==="FACTORY_STAFF_A").post_site_ids=[1001];
assert.throws(()=>validate(writeLeak),/post without read/);
const revoked=structuredClone(data);
revoked.personas.find(p=>p.key==="REVOKED_MANAGER_A").business_ids=[101];
assert.throws(()=>validate(revoked),/revoked must deny/);
const fixture=fs.readFileSync(path.join(__dirname,"../internal/enterprise-sql/c10_a046_demo_personas_v1.sql"),"utf8");
assert.match(fixture,/I_CONFIRM_DISPOSABLE_A046/);
assert.match(fixture,/to_regclass\('auth.users'\) IS NOT NULL/);
assert.match(fixture,/ON CONFLICT DO NOTHING/);

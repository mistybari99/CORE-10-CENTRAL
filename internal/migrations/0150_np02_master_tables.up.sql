CREATE TABLE core10.master_uoms_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL,
 code text NOT NULL CHECK (code ~ '^[A-Z][A-Z0-9_]{0,15}$'),
 name_en text NOT NULL CHECK (length(btrim(name_en)) BETWEEN 1 AND 80),
 name_bn text CHECK (name_bn IS NULL OR length(btrim(name_bn)) BETWEEN 1 AND 80),
 dimension text NOT NULL CHECK (dimension IN ('count','mass','volume','length','area','time')),
 decimals smallint NOT NULL DEFAULT 0 CHECK (decimals BETWEEN 0 AND 6),
 active boolean NOT NULL DEFAULT true,
 version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 UNIQUE (business_id, code), UNIQUE (id, tenant_id, business_id), UNIQUE (id, tenant_id, business_id, dimension),
 FOREIGN KEY (business_id, tenant_id) REFERENCES core10.businesses(id, tenant_id)
);

-- Conversions only inside one dimension (enforced by the composite FKs on dimension).
CREATE TABLE core10.master_uom_conversions_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL,
 dimension text NOT NULL,
 from_uom_id bigint NOT NULL, to_uom_id bigint NOT NULL,
 factor numeric(24,12) NOT NULL CHECK (factor > 0 AND factor NOT IN ('NaN'::numeric,'Infinity'::numeric)),
 active boolean NOT NULL DEFAULT true,
 version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 CHECK (from_uom_id <> to_uom_id),
 UNIQUE (business_id, from_uom_id, to_uom_id),
 FOREIGN KEY (from_uom_id, tenant_id, business_id, dimension) REFERENCES core10.master_uoms_v1(id, tenant_id, business_id, dimension),
 FOREIGN KEY (to_uom_id, tenant_id, business_id, dimension) REFERENCES core10.master_uoms_v1(id, tenant_id, business_id, dimension)
);

CREATE TABLE core10.master_item_categories_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL,
 code text NOT NULL CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,31}$'),
 name_en text NOT NULL CHECK (length(btrim(name_en)) BETWEEN 1 AND 120),
 name_bn text CHECK (name_bn IS NULL OR length(btrim(name_bn)) BETWEEN 1 AND 120),
 parent_id bigint,
 active boolean NOT NULL DEFAULT true,
 version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 CHECK (parent_id IS NULL OR parent_id <> id),
 UNIQUE (business_id, code), UNIQUE (id, tenant_id, business_id),
 FOREIGN KEY (business_id, tenant_id) REFERENCES core10.businesses(id, tenant_id),
 FOREIGN KEY (parent_id, tenant_id, business_id) REFERENCES core10.master_item_categories_v1(id, tenant_id, business_id)
);

-- Extend the existing item row (nullable/defaulted, so every existing row and caller stays valid).
ALTER TABLE core10.items
 ADD COLUMN name_en text CHECK (name_en IS NULL OR length(btrim(name_en)) BETWEEN 1 AND 160),
 ADD COLUMN name_bn text CHECK (name_bn IS NULL OR length(btrim(name_bn)) BETWEEN 1 AND 160),
 ADD COLUMN item_kind text NOT NULL DEFAULT 'stock' CHECK (item_kind IN ('stock','service','raw_material','finished_good','packaging')),
 ADD COLUMN category_id bigint,
 ADD COLUMN base_uom_id bigint,
 ADD COLUMN status text NOT NULL DEFAULT 'active' CHECK (status IN ('draft','active','inactive')),
 ADD COLUMN version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
 ADD COLUMN updated_at timestamptz NOT NULL DEFAULT now(),
 ADD COLUMN updated_by uuid,
 ADD CONSTRAINT items_sku_format_chk CHECK (length(btrim(sku)) BETWEEN 1 AND 64),
 ADD CONSTRAINT items_category_fk FOREIGN KEY (category_id, tenant_id, business_id) REFERENCES core10.master_item_categories_v1(id, tenant_id, business_id),
 ADD CONSTRAINT items_base_uom_fk FOREIGN KEY (base_uom_id, tenant_id, business_id) REFERENCES core10.master_uoms_v1(id, tenant_id, business_id);

CREATE TABLE core10.master_item_variants_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL, item_id bigint NOT NULL,
 code text NOT NULL CHECK (length(btrim(code)) BETWEEN 1 AND 64),
 name_en text NOT NULL CHECK (length(btrim(name_en)) BETWEEN 1 AND 160),
 name_bn text CHECK (name_bn IS NULL OR length(btrim(name_bn)) BETWEEN 1 AND 160),
 attributes jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(attributes) = 'object'),
 status text NOT NULL DEFAULT 'active' CHECK (status IN ('draft','active','inactive')),
 version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 UNIQUE (item_id, code), UNIQUE (id, tenant_id, business_id), UNIQUE (id, item_id),
 FOREIGN KEY (item_id, tenant_id, business_id) REFERENCES core10.items(id, tenant_id, business_id)
);

-- One barcode identifies exactly one item (and optionally one variant and pack UOM) per business.
CREATE TABLE core10.master_item_barcodes_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL, item_id bigint NOT NULL,
 variant_id bigint, uom_id bigint,
 barcode text NOT NULL CHECK (barcode ~ '^[0-9A-Za-z.\-/+]{4,64}$'),
 active boolean NOT NULL DEFAULT true,
 version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 UNIQUE (business_id, barcode),
 FOREIGN KEY (item_id, tenant_id, business_id) REFERENCES core10.items(id, tenant_id, business_id),
 FOREIGN KEY (variant_id, item_id) REFERENCES core10.master_item_variants_v1(id, item_id),
 FOREIGN KEY (uom_id, tenant_id, business_id) REFERENCES core10.master_uoms_v1(id, tenant_id, business_id)
);

CREATE TABLE core10.master_parties_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL,
 code text NOT NULL CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,31}$'),
 party_kind text NOT NULL CHECK (party_kind IN ('customer','supplier','both')),
 name_en text NOT NULL CHECK (length(btrim(name_en)) BETWEEN 1 AND 160),
 name_bn text CHECK (name_bn IS NULL OR length(btrim(name_bn)) BETWEEN 1 AND 160),
 phone text CHECK (phone IS NULL OR phone ~ '^\+?[0-9 ()-]{5,24}$'),
 tax_id text CHECK (tax_id IS NULL OR length(btrim(tax_id)) BETWEEN 1 AND 40),
 status text NOT NULL DEFAULT 'active' CHECK (status IN ('draft','active','inactive','blocked')),
 version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 UNIQUE (business_id, code), UNIQUE (id, tenant_id, business_id),
 FOREIGN KEY (business_id, tenant_id) REFERENCES core10.businesses(id, tenant_id)
);

CREATE TABLE core10.master_price_lists_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL,
 code text NOT NULL CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,31}$'),
 name_en text NOT NULL CHECK (length(btrim(name_en)) BETWEEN 1 AND 120),
 name_bn text CHECK (name_bn IS NULL OR length(btrim(name_bn)) BETWEEN 1 AND 120),
 list_kind text NOT NULL CHECK (list_kind IN ('sales','purchase')),
 currency text NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
 site_id bigint,
 effective_from date NOT NULL, effective_to date,
 status text NOT NULL DEFAULT 'active' CHECK (status IN ('draft','active','inactive')),
 version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 CHECK (effective_to IS NULL OR effective_to >= effective_from),
 UNIQUE (business_id, code), UNIQUE (id, tenant_id, business_id),
 FOREIGN KEY (business_id, tenant_id) REFERENCES core10.businesses(id, tenant_id)
);

CREATE TABLE core10.master_price_list_items_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, business_id bigint NOT NULL,
 price_list_id bigint NOT NULL, item_id bigint NOT NULL, variant_id bigint, uom_id bigint NOT NULL,
 unit_price numeric(18,4) NOT NULL CHECK (unit_price >= 0 AND unit_price NOT IN ('NaN'::numeric,'Infinity'::numeric)),
 min_quantity numeric(18,6) NOT NULL DEFAULT 0 CHECK (min_quantity >= 0),
 active boolean NOT NULL DEFAULT true,
 version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 FOREIGN KEY (price_list_id, tenant_id, business_id) REFERENCES core10.master_price_lists_v1(id, tenant_id, business_id),
 FOREIGN KEY (item_id, tenant_id, business_id) REFERENCES core10.items(id, tenant_id, business_id),
 FOREIGN KEY (variant_id, item_id) REFERENCES core10.master_item_variants_v1(id, item_id),
 FOREIGN KEY (uom_id, tenant_id, business_id) REFERENCES core10.master_uoms_v1(id, tenant_id, business_id)
);
CREATE UNIQUE INDEX master_price_list_items_v1_line_uq ON core10.master_price_list_items_v1

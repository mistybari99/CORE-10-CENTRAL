CREATE FUNCTION c10_demo.a056_record_consent_v1(p_customer bigint,p_channel text,p_purpose text,p_status text,p_source text,p_valid_until timestamptz,p_lift_suppression boolean,p_request text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $f$
#variable_conflict use_column
DECLARE c c10_demo.a056_customers%ROWTYPE; h text; prev jsonb; id bigint; hashes text[]; active_supp int; ah text;
BEGIN
 SELECT * INTO c FROM c10_demo.a056_customers WHERE id=p_customer FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'A056_NOT_FOUND'; END IF;
 PERFORM c10_demo.a056_require(c.business_id,c.site_id,'consent.write',false,true);
 h:=c10_demo.a056_h(p_customer::text,p_channel,p_purpose,p_status,p_source,p_valid_until::text,COALESCE(p_lift_suppression,false)::text);
 prev:=c10_demo.a056_idem_check(c.business_id,p_request,'record_consent',h); IF prev IS NOT NULL THEN RETURN prev; END IF;
 IF c.status<>'active' OR p_channel NOT IN('email','sms','phone','whatsapp','post') OR p_purpose NOT IN('marketing','service') OR p_status NOT IN('granted','revoked','opt_out')
 THEN RAISE EXCEPTION 'A056_INVALID'; END IF;
 IF p_valid_until IS NOT NULL AND p_valid_until<=now() AND p_status='granted' THEN RAISE EXCEPTION 'A056_INVALID'; END IF;
 hashes:=ARRAY['cust:'||c.id::text];
 IF p_channel='email' AND c.email_norm IS NOT NULL THEN hashes:=hashes||c10_demo.a056_sha('email:'||c.email_norm);
 ELSIF p_channel IN('sms','phone','whatsapp') AND c.phone_norm IS NOT NULL THEN hashes:=hashes||c10_demo.a056_sha('phone:'||c.phone_norm); END IF;
 IF p_status='opt_out' THEN
  FOREACH ah IN ARRAY hashes LOOP
   INSERT INTO c10_demo.a056_suppressions(tenant_id,business_id,channel,purpose,addr_hash,customer_id) VALUES(c.tenant_id,c.business_id,p_channel,p_purpose,ah,c.id) ON CONFLICT DO NOTHING; END LOOP;
 ELSIF p_status='granted' THEN
  SELECT count(*) INTO active_supp FROM c10_demo.a056_suppressions s WHERE s.business_id=c.business_id AND s.channel=p_channel AND s.lifted_at IS NULL AND s.addr_hash=ANY(hashes) AND (s.purpose=p_purpose OR s.purpose='service');
  IF active_supp>0 THEN
   IF NOT COALESCE(p_lift_suppression,false) THEN RAISE EXCEPTION 'A056_OPT_OUT_PRECEDENCE'; END IF;
   IF NOT c10_demo.a056_authz(c.tenant_id,c.business_id,NULL,'consent.lift_suppression') THEN RAISE EXCEPTION 'A056_DENIED'; END IF;
   UPDATE c10_demo.a056_suppressions SET lifted_at=now(),lifted_by=c10_demo.actor_uid() WHERE business_id=c.business_id AND channel=p_channel AND lifted_at IS NULL AND addr_hash=ANY(hashes) AND (purpose=p_purpose OR purpose='service');
   PERFORM c10_demo.a056_log(c.tenant_id,c.business_id,'consent.suppression_lifted','customer',c.id,p_request,jsonb_build_object('channel',p_channel));
  END IF;
 END IF;
 INSERT INTO c10_demo.a056_consent_events(tenant_id,business_id,site_id,customer_id,channel,purpose,status,source,valid_until,recorded_by,request_key)
 VALUES(c.tenant_id,c.business_id,c.site_id,c.id,p_channel,p_purpose,p_status,c10_demo.a056_txt(p_source,120,true),p_valid_until,c10_demo.actor_uid(),p_request) RETURNING a056_consent_events.id INTO id;
 PERFORM c10_demo.a056_log(c.tenant_id,c.business_id,'consent.'||p_status,'customer',c.id,p_request,jsonb_build_object('channel',p_channel,'purpose',p_purpose));
 RETURN c10_demo.a056_done(c.business_id,p_request,'record_consent',h,jsonb_build_object('event_id',id,'effective',c10_demo.a056_consent_state(c.id,p_channel,p_purpose)));
END $f$;

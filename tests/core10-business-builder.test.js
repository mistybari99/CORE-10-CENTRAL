"use strict";
const assert=require("node:assert/strict");
const c=require("../data/core10_capability_catalog_v1.json"),b=require("../core10-business-builder.js");
const model={name:"Example Bakery",slug:"example-bakery",templateId:"sweets_bakery",brandHex:"#315B76",mode:"advanced",sites:[{kind:"showroom",label:"Main"}],modules:["stock"]};
const ctx={legalId:1,requestKey:"test-key-123"};
assert.equal(b.validate(c,model).ok,true);
assert.equal(b.validate(c,{...model,templateId:"unknown"}).ok,false);
assert.equal(b.validate(c,{...model,sites:[...model.sites,...model.sites]}).ok,false);
assert.equal(b.validate(c,{...model,modules:["stock","stock"]}).ok,false);
assert.equal(b.validate(c,{...model,modules:["role_admin"]}).ok,false);
assert.equal(b.validate(c,{...model,mode:"quick"}).ok,false);
assert.equal(b.validate(c,{...model,mode:"quick",sites:[]}).ok,true);
assert.equal(b.validate(c,{...model,sites:Array.from({length:301},(_,i)=>({kind:"warehouse",label:"Warehouse "+i}))}).ok,true);
assert.equal(c.templates.find(t=>t.id==="sweets_bakery").source_status,"needs_setup");
assert.throws(()=>b.toBackendInput(c,model,ctx),/TEMPLATE_BACKEND_UNAVAILABLE/);
const isolated=JSON.parse(JSON.stringify(c));
const verified=isolated.templates.find(t=>t.id==="sweets_bakery");
verified.source_status="available";verified.source_code="verified_generic_factory_adapter";
const input=b.toBackendInput(isolated,model,ctx);
assert.equal(input.template,"verified_generic_factory_adapter");assert.equal(input.sites.length,1);
const x=b.create({catalog:c});x.update(model);
assert.equal(x.preview().production_ready,false);assert.equal(x.validate().ok,true);
assert.throws(()=>x.update({isAdmin:true}),/UNKNOWN_FIELD/);
async function test(){
 await assert.rejects(()=>x.provision(ctx),/BUSINESS_SETUP_RELEASE_LOCKED/);
 let called=0;
 const blocked=b.create({catalog:c,releaseEnabled:true,enterpriseClient:{setupBusiness:async()=>{called++;}}});
 blocked.update(model);
 await assert.rejects(()=>blocked.provision(ctx),/TEMPLATE_BACKEND_UNAVAILABLE/);
 assert.equal(called,0,"No old business-specific backend is called");
 const released=b.create({catalog:isolated,releaseEnabled:true,enterpriseClient:{setupBusiness:async request=>{called++;return request}}});
 released.update(model);
 await assert.rejects(()=>released.provision({legalId:0,requestKey:"key"}),/AUTHORIZED_LEGAL_ENTITY_REQUIRED/);
 const out=await released.provision({legalId:5,requestKey:"key"});
 assert.equal(out.legalId,5);assert.equal(called,1);
 console.log("PASS: 10-industry validation; no legacy template provisioning; isolated adapter contract");
}
test().catch(e=>{console.error(e);process.exitCode=1});

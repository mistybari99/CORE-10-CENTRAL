 bigint,text,text,text,text,jsonb,text,text) TO authenticated;
REVOKE ALL ON c10_demo.business_setup_overview_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.business_setup_overview_v1 TO authenticated;

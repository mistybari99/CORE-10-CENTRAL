#!/usr/bin/env bash
# NP06: test the SPECIFIC 0400 and 0401 rollback guards, not run.sh down's
# highest-installed migration (which may be Sales 0304 / Manufacturing 0504).
# Does not alter production migration runner or schema_migrations.
set -euo pipefail
cd "$(dirname "$0")/../.."
case "${PGHOST:-}" in
  localhost|127.0.0.1) ;;
  *) echo "FIN_ROLLBACK_LOCAL_PG17_REQUIRED" >&2; exit 2 ;;
esac
if [[ -n "${DATABASE_URL:-}" ]]; then
  echo "FIN_ROLLBACK_DATABASE_URL_FORBIDDEN" >&2
  exit 2
fi
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Require an actual recorded 0400/0401 migration, its exact applied checksum,
# and the already-posted fixture generated by the existing TWO-session races.
for v in 400 401; do
  case "$v" in
    400) name=0400_np06_finance_foundation ;;
    401) name=0401_np06_journal_reversal ;;
  esac
  actual="$(psql -X -At -v ON_ERROR_STOP=1 -c "SELECT checksum FROM core10.schema_migrations WHERE version=$v AND name='$name'")"
  expected="$(sha256sum "internal/migrations/$name.up.sql" | cut -d' ' -f1)"
  [[ "$actual" == "$expected" ]] || {
    echo "FIN_ROLLBACK_APPLIED_CHECKSUM_MISMATCH_$v" >&2
    exit 1
  }
done

# Snapshot both canonical history and the entire migration ledger, including
# any unrelated higher migrations. A rejected rollback MUST NOT alter either.
snapshot() {
  psql -X -At -v ON_ERROR_STOP=1 <<'SQL'
SELECT
 (SELECT count(*) FROM core10.finance_journals_v1 WHERE business_id=9711 AND status='posted')||':'||
 (SELECT count(*) FROM core10.finance_journal_lines_v1 WHERE journal_id IN
     (SELECT id FROM core10.finance_journals_v1 WHERE business_id=9711))||':'||
 (SELECT count(*) FROM core10.finance_reversals_v1 WHERE business_id=9711)||':'||
 (SELECT count(*) FROM core10.canonical_audit_events_v1 WHERE business_id=9711)||':'||
 (SELECT count(*) FROM core10.control_setting_versions_v1
     WHERE business_id=9711 AND feature_key LIKE 'finance.%')||':'||
 (SELECT md5(coalesce(string_agg(version::text||'/'||name||'/'||checksum,',' ORDER BY version), ''))
  FROM core10.schema_migrations)||':'||
 (SELECT count(*) FROM core10.schema_migrations)||':'||
 (to_regprocedure('core10.finance_reverse_posted_journal_v1(bigint,date,text,text)') IS NOT NULL)::text;
SQL
}
before="$(snapshot)"
[[ "$before" =~ ^2:[0-9]+:1:[0-9]+:[0-9]+:[0-9a-f]{32}:[0-9]+:true$ ]] || {
  echo "FIN_ROLLBACK_POSTED_FIXTURE_INVALID:$before" >&2
  exit 1
}
test "$(psql -X -At -v ON_ERROR_STOP=1 -c "SELECT count(*) FROM core10.canonical_audit_events_v1 WHERE business_id=9711 AND action='finance.journal_reverse'")" = "1" || {
  echo FIN_ROLLBACK_REVERSAL_AUDIT_MISSING >&2; exit 1;
}

# Use READ ONLY for defense in depth: if a guard were accidentally weakened,
# subsequent DDL cannot execute; this is NEVER an actual rollback attempt.
# Each exact .down.sql is invoked explicitly, independently of schema_migrations
# order. Fail on any error other than the relevant original Finance guard code.
guard() {
  local version="$1" path="$2" expected="$3" log="$tmp/$1.log"
  if psql -X -q -v ON_ERROR_STOP=1 \
       -c 'BEGIN READ ONLY' -f "$path" -c 'ROLLBACK' >"$log" 2>&1; then
    cat "$log" >&2
    echo "FIN_ROLLBACK_${version}_UNEXPECTEDLY_ALLOWED" >&2
    exit 1
  fi
  if ! grep -Fq "$expected" "$log"; then
    cat "$log" >&2
    echo "FIN_ROLLBACK_${version}_GUARD_NOT_REACHED" >&2
    exit 1
  fi
  [[ "$(snapshot)" == "$before" ]] || {
    echo "FIN_ROLLBACK_${version}_HISTORY_OR_SCHEMA_MIGRATION_CHANGED" >&2
    exit 1
  }
  echo "FIN_ROLLBACK_${version}_EXACT_GUARD_PASS"
}
guard 0401 internal/migrations/0401_np06_journal_reversal.down.sql FIN_REVERSAL_ROLLBACK_DENIED_HISTORY
guard 0400 internal/migrations/0400_np06_finance_foundation.down.sql FIN_ROLLBACK_DENIED_PERSISTED_HISTORY

# The canonical audit checksum should still verify after both refused attempts.
test "$(psql -X -At -v ON_ERROR_STOP=1 -c "SELECT (core10.verify_canonical_audit_v1(9711)->>'ok')::boolean")" = "t" || {
  echo FIN_ROLLBACK_CANONICAL_AUDIT_CHAIN_CHANGED >&2; exit 1;
}
echo "FIN_ROLLBACK_0400_0401_TARGETED_HISTORY_LEDGER_AUDIT_PASS"

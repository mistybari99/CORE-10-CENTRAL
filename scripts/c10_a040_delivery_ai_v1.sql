-- CORE10 C10-A040 Delivery/courier + AI gateway engine (v1). Builds on A038. DISPOSABLE PostgreSQL / CI ONLY.
-- NEVER execute on IMG-ERP-SG. Additive only.
--
-- DELIVERY
--   * parcel per (account, idempotency key); courier status mapped onto a fixed internal state set, forward-only.
--   * COD: the courier collects cash => a RECEIVABLE from the courier; "remitted" amounts reduce it. The view
--     shows what each courier still owes. Delivered-with-COD never creates income by itself.
-- AI GATEWAY
--   * a call is allowed only when the ai port is on, a monthly budget is not exhausted, and the agent is granted.
--   * input is redacted (phone numbers, e-mail, long digit runs) BEFORE it is stored or returned for sending.
--   * budget/usage are kept in the database; local_rules (no-network) is the fallback when blocked.

CREATE TABLE c10_demo.delivery_parcel_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 account_id bigint NOT NULL,
 provider_code text NOT NULL,
 idempotency_key text NOT NULL CHECK(length(btrim(idempotency_key)) BETWEEN 1 AND 160),
 reference text NOT NULL CHECK(length(btrim(reference)) BETWEEN 1 AND 120),
 cod_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK(cod_amount>=0),
 cod_collected numeric(14,2) NOT NULL DEFAULT 0 CHECK(cod_collected>=0),
 cod_remitted numeric(14,2) NOT NULL DEFAULT 0 CHECK(cod_remitted>=0),
 state text NOT NULL DEFAULT 'created' CHECK(state IN('created','picked_up','in_transit','delivered','returned','cancelled')),
 consignment_id text,
 created_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(account_id,idempotency_key),
 CHECK(cod_collected<=cod_amount),
 CHECK(cod_remitted<=cod_collected),
 FOREIGN KEY(account_id,tenant_id,business_id) REFERENCES c10_demo.integration_account_v1(id,tenant_id,business_id)
);
CREATE TABLE c10_demo.delivery_event_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 parcel_id bigint NOT NULL REFERENCES c10_demo.delivery_parcel_v1(id),
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 event_id text NOT NULL,
 courier_status text NOT NULL,
 mapped_state text,
 signature_status text NOT NULL CHECK(signature_status IN('ok','bad','missing')),
 outcome text NOT NULL CHECK(outcome IN('applied','ignored_signature','ignored_backwards','unmapped','duplicate')),
 at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(parcel_id,event_id)
);
CREATE TABLE c10_demo.delivery_status_map_v1(
 provider_code text NOT NULL REFERENCES c10_demo.integration_provider_v1(code),
 courier_status text NOT NULL,
 mapped_state text NOT NULL CHECK(mapped_state IN('picked_up','in_transit','delivered','returned','cancelled')),
 PRIMARY KEY(provider_code,courier_status)
);

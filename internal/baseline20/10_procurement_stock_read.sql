 FOREIGN KEY (site_id, tenant_id, business_id) REFERENCES core10.sites(id, tenant_id, business_id),
 FOREIGN KEY (supplier_id, tenant_id, business_id) REFERENCES core10.master_parties_v1(id, tenant_id, business_id)
);

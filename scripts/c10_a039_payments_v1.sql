-- CORE10 C10-A039 Payments engine (v1): intent state machine, verified-event-only "paid", amount-match,
-- refunds, immutable payment ledger, reconciliation view. Builds on A038 (accounts/webhooks).
-- DISPOSABLE PostgreSQL / CI ONLY. NEVER execute on IMG-ERP-SG. Additive only.
--
-- RULES
--   * An intent can only be created on a payments-family port that is not OFF (and not for COD/manual without owner action).
--   * "paid" is reachable ONLY from a verified (signature ok) event whose amount equals the intent amount.
--     Amount mismatch -> needs_review (no ledger entry). Bad/missing signature -> logged, never applied.
--   * Terminal states never move backwards (paid cannot become failed; refunded cannot become paid).
--   * Each (intent, provider event) is applied at most once. Ledger entries are immutable and idempotent.
--   * Refund bounded by (paid - already refunded). Card data is never stored (no card columns exist).

CREATE TABLE c10_demo.payment_intent_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 account_id bigint NOT NULL,
 provider_code text NOT NULL,
 reference text NOT NULL CHECK(length(btrim(reference)) BETWEEN 1 AND 120),
 idempotency_key text NOT NULL CHECK(length(btrim(idempotency_key)) BETWEEN 1 AND 160),
 amount numeric(14,2) NOT NULL CHECK(amount>0),
 currency text NOT NULL DEFAULT 'BDT' CHECK(currency='BDT'),
 state text NOT NULL DEFAULT 'created' CHECK(state IN('created','redirected','pending','paid','failed','cancelled',
   'expired','needs_review','partially_refunded','refunded')),
 provider_ref text,
 paid_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK(paid_amount>=0),
 refunded_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK(refunded_amount>=0),
 expires_at timestamptz NOT NULL DEFAULT now()+interval '1 day',
 created_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(account_id,idempotency_key),
 UNIQUE(id,tenant_id,business_id),
 CHECK(refunded_amount<=paid_amount),
 CHECK(state NOT IN('paid','partially_refunded','refunded') OR paid_amount>0),
 FOREIGN KEY(account_id,tenant_id,business_id) REFERENCES c10_demo.integration_account_v1(id,tenant_id,business_id)
);
CREATE TABLE c10_demo.payment_event_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 intent_id bigint NOT NULL REFERENCES c10_demo.payment_intent_v1(id),
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 event_id text NOT NULL,
 event_type text NOT NULL CHECK(event_type IN('redirected','pending','paid','failed','cancelled','expired')),
 amount numeric(14,2),
 signature_status text NOT NULL CHECK(signature_status IN('ok','bad','missing')),
 outcome text NOT NULL CHECK(outcome IN('applied','ignored_signature','ignored_terminal','needs_review','duplicate')),
 at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(intent_id,event_id)
);
CREATE TABLE c10_demo.payment_ledger_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 intent_id bigint NOT NULL REFERENCES c10_demo.payment_intent_v1(id),
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 kind text NOT NULL CHECK(kind IN('receipt','refund')),
 amount numeric(14,2) NOT NULL CHECK(amount<>0),
 source_key text NOT NULL,
 created_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK((kind='receipt' AND amount>0) OR (kind='refund' AND amount<0)),
 UNIQUE(intent_id,source_key)
);

CREATE FUNCTION c10_demo.payment_immutable_v1() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'payment_log_is_immutable' USING ERRCODE='42501'; END $$;
CREATE TRIGGER payment_event_no_change_v1 BEFORE UPDATE OR DELETE ON c10_demo.payment_event_v1 FOR EACH ROW EXECUTE FUNCTION c10_demo.payment_immutable_v1();
CREATE TRIGGER payment_event_no_truncate_v1 BEFORE TRUNCATE ON c10_demo.payment_event_v1 FOR EACH STATEMENT EXECUTE FUNCTION c10_demo.payment_immutable_v1();
CREATE TRIGGER payment_ledger_no_change_v1 BEFORE UPDATE OR DELETE ON c10_demo.payment_ledger_v1 FOR EACH ROW EXECUTE FUNCTION c10_demo.payment_immutable_v1();
CREATE TRIGGER payment_ledger_no_truncate_v1 BEFORE TRUNCATE ON c10_demo.payment_ledger_v1 FOR EACH STATEMENT EXECUTE FUNCTION c10_demo.payment_immutable_v1();

ALTER TABLE c10_demo.payment_intent_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.payment_event_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.payment_ledger_v1 ENABLE ROW LEVEL SECURITY;
CREATE POLICY payment_intent_owner_read_v1 ON c10_demo.payment_intent_v1 FOR SELECT TO authenticated USING(c10_demo.can_manage(tenant_id,business_id));
CREATE POLICY payment_event_owner_read_v1 ON c10_demo.payment_event_v1 FOR SELECT TO authenticated USING(c10_demo.can_manage(tenant_id,business_id));
CREATE POLICY payment_ledger_owner_read_v1 ON c10_demo.payment_ledger_v1 FOR SELECT TO authenticated USING(c10_demo.can_manage(tenant_id,business_id));
REVOKE ALL ON c10_demo.payment_intent_v1,c10_demo.payment_event_v1,c10_demo.payment_ledger_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.payment_intent_v1,c10_demo.payment_event_v1,c10_demo.payment_ledger_v1 TO authenticated;

CREATE FUNCTION c10_demo.payment_create_intent_v1(p_account bigint,p_key text,p_reference text,p_amount numeric,
 p_expires timestamptz DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE a record;pv record;i record;v_id bigint;
BEGIN
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'payment_denied'; END IF;
 SELECT * INTO pv FROM c10_demo.integration_provider_v1 WHERE code=a.provider_code;
 IF pv.family<>'payments' THEN RAISE EXCEPTION 'payment_not_payments_port'; END IF;
 IF p_amount IS NULL OR p_amount<=0 OR p_amount<>round(p_amount,2) THEN RAISE EXCEPTION 'payment_invalid_amount'; END IF;
 SELECT * INTO i FROM c10_demo.payment_intent_v1 WHERE account_id=p_account AND idempotency_key=p_key;
 IF FOUND THEN RETURN jsonb_build_object('status','duplicate','id',i.id,'state',i.state); END IF;
 IF a.mode='off' THEN RETURN jsonb_build_object('status','blocked','reason','port_off'); END IF;
 INSERT INTO c10_demo.payment_intent_v1(tenant_id,business_id,account_id,provider_code,reference,idempotency_key,amount,
   expires_at,created_by)
 VALUES(a.tenant_id,a.business_id,p_account,a.provider_code,p_reference,p_key,p_amount,
   COALESCE(p_expires,now()+interval '1 day'),c10_demo.actor_uid()) RETURNING id INTO v_id;
 RETURN jsonb_build_object('status','created','id',v_id,'state','created');
END $$;

-- apply one provider event. Allowed forward moves only; "paid" only from a verified, amount-exact event.
CREATE FUNCTION c10_demo.payment_apply_event_v1(p_intent bigint,p_event text,p_type text,p_amount numeric,p_signature text,
 p_provider_ref text DEFAULT NULL)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE i record;a record;outc text;newstate text;
BEGIN
 IF p_type NOT IN('redirected','pending','paid','failed','cancelled','expired') OR p_signature NOT IN('ok','bad','missing')
 THEN RAISE EXCEPTION 'payment_invalid_event'; END IF;
 SELECT * INTO i FROM c10_demo.payment_intent_v1 WHERE id=p_intent FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(i.tenant_id,i.business_id) THEN RAISE EXCEPTION 'payment_denied'; END IF;
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=i.account_id;
 IF EXISTS(SELECT 1 FROM c10_demo.payment_event_v1 WHERE intent_id=p_intent AND event_id=p_event) THEN RETURN 'duplicate'; END IF;
 IF p_signature<>'ok' OR a.mode='off' THEN outc:='ignored_signature';
 ELSIF i.state IN('paid','partially_refunded','refunded','failed','cancelled','expired') THEN outc:='ignored_terminal';
 ELSIF p_type='paid' AND (p_amount IS NULL OR p_amount<>i.amount) THEN
  outc:='needs_review'; newstate:='needs_review';
 ELSE
  outc:='applied';
  newstate:=CASE p_type WHEN 'paid' THEN 'paid' ELSE p_type END;
  -- redirected/pending must not move a needs_review or beyond-pending intent backwards
  IF i.state='needs_review' AND p_type IN('redirected','pending') THEN outc:='ignored_terminal'; newstate:=NULL; END IF;
  IF i.state='pending' AND p_type='redirected' THEN outc:='ignored_terminal'; newstate:=NULL; END IF;
 END IF;
 INSERT INTO c10_demo.payment_event_v1(intent_id,tenant_id,business_id,event_id,event_type,amount,signature_status,outcome)
 VALUES(p_intent,i.tenant_id,i.business_id,p_event,p_type,p_amount,p_signature,outc);
 IF newstate IS NOT NULL THEN
  UPDATE c10_demo.payment_intent_v1 SET state=newstate,provider_ref=COALESCE(p_provider_ref,provider_ref),
    paid_amount=CASE WHEN newstate='paid' THEN p_amount ELSE paid_amount END,updated_at=now() WHERE id=p_intent;
  IF newstate='paid' THEN
   INSERT INTO c10_demo.payment_ledger_v1(intent_id,tenant_id,business_id,kind,amount,source_key,created_by)
   VALUES(p_intent,i.tenant_id,i.business_id,'receipt',p_amount,'event:'||p_event,c10_demo.actor_uid());
  END IF;
 END IF;
 RETURN outc;
END $$;

-- owner resolves a needs_review intent after checking with the provider: confirm exact paid amount or reject
CREATE FUNCTION c10_demo.payment_resolve_review_v1(p_intent bigint,p_accept boolean,p_paid numeric DEFAULT NULL)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE i record;
BEGIN
 SELECT * INTO i FROM c10_demo.payment_intent_v1 WHERE id=p_intent FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(i.tenant_id,i.business_id) THEN RAISE EXCEPTION 'payment_denied'; END IF;
 IF i.state<>'needs_review' THEN RAISE EXCEPTION 'payment_not_in_review'; END IF;
 IF p_accept THEN
  IF p_paid IS NULL OR p_paid<=0 OR p_paid<>round(p_paid,2) THEN RAISE EXCEPTION 'payment_invalid_amount'; END IF;
  UPDATE c10_demo.payment_intent_v1 SET state='paid',paid_amount=p_paid,updated_at=now() WHERE id=p_intent;
  INSERT INTO c10_demo.payment_ledger_v1(intent_id,tenant_id,business_id,kind,amount,source_key,created_by)
  VALUES(p_intent,i.tenant_id,i.business_id,'receipt',p_paid,'review:accept',c10_demo.actor_uid());
  RETURN 'paid';
 END IF;
 UPDATE c10_demo.payment_intent_v1 SET state='failed',updated_at=now() WHERE id=p_intent;
 RETURN 'failed';
END $$;

CREATE FUNCTION c10_demo.payment_refund_v1(p_intent bigint,p_amount numeric,p_key text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE i record;st text;
BEGIN
 SELECT * INTO i FROM c10_demo.payment_intent_v1 WHERE id=p_intent FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(i.tenant_id,i.business_id) THEN RAISE EXCEPTION 'payment_denied'; END IF;
 IF i.state NOT IN('paid','partially_refunded') THEN RAISE EXCEPTION 'payment_not_refundable'; END IF;
 IF p_amount IS NULL OR p_amount<=0 OR p_amount<>round(p_amount,2) THEN RAISE EXCEPTION 'payment_invalid_amount'; END IF;
 IF EXISTS(SELECT 1 FROM c10_demo.payment_ledger_v1 WHERE intent_id=p_intent AND source_key='refund:'||p_key)
 THEN RETURN jsonb_build_object('status','duplicate'); END IF;
 IF p_amount>i.paid_amount-i.refunded_amount THEN RAISE EXCEPTION 'payment_refund_exceeds_paid'; END IF;
 st:=CASE WHEN i.refunded_amount+p_amount=i.paid_amount THEN 'refunded' ELSE 'partially_refunded' END;
 UPDATE c10_demo.payment_intent_v1 SET refunded_amount=refunded_amount+p_amount,state=st,updated_at=now() WHERE id=p_intent;
 INSERT INTO c10_demo.payment_ledger_v1(intent_id,tenant_id,business_id,kind,amount,source_key,created_by)
 VALUES(p_intent,i.tenant_id,i.business_id,'refund',-p_amount,'refund:'||p_key,c10_demo.actor_uid());
 RETURN jsonb_build_object('status','refunded','state',st);
END $$;

-- polling fallback: non-terminal intents past a threshold (missed webhooks)
CREATE FUNCTION c10_demo.payment_poll_candidates_v1(p_account bigint,p_older interval DEFAULT interval '10 minutes',
 p_now timestamptz DEFAULT now())
RETURNS SETOF c10_demo.payment_intent_v1 LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE a record;
BEGIN
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'payment_denied'; END IF;
 IF a.mode='off' THEN RETURN; END IF;
 RETURN QUERY SELECT * FROM c10_demo.payment_intent_v1 i WHERE i.account_id=p_account
  AND i.state IN('created','redirected','pending') AND i.updated_at<=p_now-p_older ORDER BY i.id;
END $$;

-- expire stale unpaid intents
CREATE FUNCTION c10_demo.payment_expire_v1(p_business bigint,p_now timestamptz DEFAULT now())
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint;n integer;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF NOT FOUND OR NOT c10_demo.can_manage(t,p_business) THEN RAISE EXCEPTION 'payment_denied'; END IF;
 UPDATE c10_demo.payment_intent_v1 SET state='expired',updated_at=now()
  WHERE business_id=p_business AND state IN('created','redirected','pending') AND expires_at<=p_now;
 GET DIAGNOSTICS n=ROW_COUNT;
 RETURN n;
END $$;

-- reconciliation: ledger must equal paid - refunded for every intent
CREATE VIEW c10_demo.payment_reconciliation_v1 WITH(security_invoker=true) AS
SELECT i.tenant_id,i.business_id,i.id AS intent_id,i.reference,i.state,i.amount,i.paid_amount,i.refunded_amount,
 COALESCE(l.net,0) AS ledger_net,
 CASE WHEN i.state='needs_review' THEN 'needs_review'
      WHEN COALESCE(l.net,0)=i.paid_amount-i.refunded_amount THEN 'reconciled' ELSE 'mismatch' END AS recon_state
FROM c10_demo.payment_intent_v1 i
LEFT JOIN(SELECT intent_id,sum(amount) net FROM c10_demo.payment_ledger_v1 GROUP BY intent_id) l ON l.intent_id=i.id;
REVOKE ALL ON c10_demo.payment_reconciliation_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.payment_reconciliation_v1 TO authenticated;


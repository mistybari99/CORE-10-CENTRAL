BEGIN
 INSERT INTO c10_demo.a056_idem(business_id,request_key,action,arg_hash,actor,response)
 VALUES(p_business,p_key,p_action,p_hash,c10_demo.actor_uid(),p_resp);
 RETURN p_resp||jsonb_build_object('replayed',false);
END $f$;

-- C10-A026: Purchase / Sales operational document lifecycle. Disposable PG17 ONLY.
-- Builds on A018 non-negative journal and existing membership guards. No real
-- cash capture, VAT/taxes, COGS, customer invoice, returns or production certification.
-- Same DRAFT -> CONFIRMED -> POSTED state machine for purchase and sale.
CREATE TABLE c10_demo.operational_documents_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 location_id bigint NOT NULL,
 kind text NOT NULL CHECK(kind IN('purchase','sale')),
 counterparty text NOT NULL CHECK(length(btrim(counterparty)) BETWEEN 2 AND 120),
 subtotal numeric(20,2) NOT NULL CHECK(subtotal>0),
 discount numeric(20,2) NOT NULL DEFAULT 0 CHECK(discount>=0 AND discount<=subtotal),
 net_amount numeric(20,2) GENERATED ALWAYS AS (subtotal-discount) STORED,
 lines_payload jsonb NOT NULL CHECK(jsonb_typeof(lines_payload)='object'
  AND jsonb_typeof(lines_payload->'lines')='array'),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','confirmed','posted')),
 created_by uuid NOT NULL,
 confirmed_by uuid,
 confirmed_at timestamptz,
 posted_by uuid,
 posted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(location_id,tenant_id,business_id,site_id)
  REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 CHECK((status='draft' AND confirmed_by IS NULL AND confirmed_at IS NULL AND posted_by IS NULL AND posted_at IS NULL)
  OR (status='confirmed' AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL AND posted_by IS NULL AND posted_at IS NULL)
  OR (status='posted' AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL AND posted_by IS NOT NULL AND posted_at IS NOT NULL))
);
CREATE TABLE c10_demo.operational_document_lines_v1(
 document_id bigint NOT NULL REFERENCES c10_demo.operational_documents_v1(id),
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 line_no integer NOT NULL CHECK(line_no BETWEEN 1 AND 100),
 item_id bigint NOT NULL,
 quantity numeric(15,3) NOT NULL CHECK(quantity>0 AND quantity::text NOT IN('NaN','Infinity','-Infinity')),
 unit_price numeric(18,2) NOT NULL CHECK(unit_price>=0 AND unit_price::text NOT IN('NaN','Infinity','-Infinity')),
 amount numeric(20,2) GENERATED ALWAYS AS (round(quantity*unit_price,2)) STORED,
 PRIMARY KEY(document_id,line_no),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id)
);
ALTER TABLE c10_demo.operational_documents_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.operational_document_lines_v1 ENABLE ROW LEVEL SECURITY;
CREATE POLICY operating_docs_business_read_v1 ON c10_demo.operational_documents_v1
 FOR SELECT TO authenticated USING(c10_demo.can_business(tenant_id,business_id));
CREATE POLICY operating_lines_business_read_v1 ON c10_demo.operational_document_lines_v1
 FOR SELECT TO authenticated USING(c10_demo.can_business(tenant_id,business_id));
REVOKE ALL ON c10_demo.operational_documents_v1,c10_demo.operational_document_lines_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.operational_documents_v1,c10_demo.operational_document_lines_v1 TO authenticated;

CREATE FUNCTION c10_demo.create_operational_document_v1(
 p_business bigint,p_location bigint,p_kind text,p_counterparty text,
 p_lines jsonb,p_discount numeric,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_loc record;v_id bigint;v_old record;v_line jsonb;
 v_ix integer:=0;v_item bigint;v_qty numeric;v_price numeric;
 v_subtotal numeric(20,2):=0;v_canonical jsonb;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_business IS NULL OR p_location IS NULL OR
   p_kind IS NULL OR p_kind NOT IN('purchase','sale') OR
   p_counterparty IS NULL OR length(btrim(p_counterparty)) NOT BETWEEN 2 AND 120 OR
   p_lines IS NULL OR jsonb_typeof(p_lines)<>'array' OR
   jsonb_array_length(p_lines) NOT BETWEEN 1 AND 100 OR
   p_discount IS NULL OR p_discount<0 OR
   p_discount::text IN('NaN','Infinity','-Infinity') OR
   p_discount<>round(p_discount,2) OR
   p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_operational_document'; END IF;
 SELECT tenant_id,business_id,site_id INTO v_loc
  FROM c10_demo.stock_locations WHERE id=p_location;
 IF NOT FOUND OR v_loc.business_id<>p_business OR
   NOT c10_demo.can_business(v_loc.tenant_id,p_business) OR
   NOT c10_demo.can_site(v_loc.tenant_id,p_business,v_loc.site_id,'stock.post')
 THEN RAISE EXCEPTION 'operational_scope_denied'; END IF;
 FOR v_line IN SELECT value FROM jsonb_array_elements(p_lines) LOOP
  v_ix:=v_ix+1;
  IF jsonb_typeof(v_line)<>'object' OR
    (SELECT count(*) FROM jsonb_object_keys(v_line))<>3 OR
    jsonb_typeof(v_line->'item')<>'number' OR
    jsonb_typeof(v_line->'quantity')<>'number' OR
    jsonb_typeof(v_line->'unit_price')<>'number' THEN
   RAISE EXCEPTION 'invalid_operational_line';
  END IF;
  v_item:=(v_line->>'item')::bigint;
  v_qty:=(v_line->>'quantity')::numeric;
  v_price:=(v_line->>'unit_price')::numeric;
  IF v_item<=0 OR v_qty<=0 OR v_qty<>round(v_qty,3) OR
    v_price<0 OR v_price<>round(v_price,2) OR
    v_qty::text IN('NaN','Infinity','-Infinity') OR
    v_price::text IN('NaN','Infinity','-Infinity') OR
    NOT EXISTS(SELECT 1 FROM c10_demo.items i WHERE i.id=v_item
      AND i.business_id=p_business AND i.tenant_id=v_loc.tenant_id)
  THEN RAISE EXCEPTION 'invalid_operational_line'; END IF;
  v_subtotal:=v_subtotal+round(v_qty*v_price,2);
 END LOOP;
 IF v_subtotal<=0 OR p_discount>v_subtotal THEN
  RAISE EXCEPTION 'invalid_operational_total'; END IF;
 -- JSONB key order canonicalized. Exact duplicate request is idempotent.
 v_canonical:=jsonb_build_object('business',p_business,'location',p_location,
  'kind',p_kind,'counterparty',btrim(p_counterparty),'lines',p_lines,
  'discount',p_discount);
 INSERT INTO c10_demo.operational_documents_v1(
  tenant_id,business_id,site_id,location_id,kind,counterparty,
  subtotal,discount,lines_payload,request_key,created_by)
 VALUES(v_loc.tenant_id,p_business,v_loc.site_id,p_location,p_kind,
   btrim(p_counterparty),v_subtotal,p_discount,v_canonical,p_request,c10_demo.actor_uid())
 ON CONFLICT(business_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_old FROM c10_demo.operational_documents_v1
  WHERE business_id=p_business AND request_key=p_request;
  IF NOT FOUND OR v_old.lines_payload<>v_canonical OR
    v_old.created_by<>c10_demo.actor_uid() OR v_old.subtotal<>v_subtotal
  THEN RAISE EXCEPTION 'operational_request_idempotency_conflict'; END IF;
  RETURN v_old.id;
 END IF;
 v_ix:=0;
 FOR v_line IN SELECT value FROM jsonb_array_elements(p_lines) LOOP
  v_ix:=v_ix+1;
  INSERT INTO c10_demo.operational_document_lines_v1(
   document_id,tenant_id,business_id,line_no,item_id,quantity,unit_price)
  VALUES(v_id,v_loc.tenant_id,p_business,v_ix,(v_line->>'item')::bigint,
   (v_line->>'quantity')::numeric,(v_line->>'unit_price')::numeric);
 END LOOP;
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.confirm_operational_document_v1(p_document bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_doc c10_demo.operational_documents_v1%ROWTYPE;
BEGIN
 IF p_document IS NULL OR c10_demo.actor_uid() IS NULL
 THEN RAISE EXCEPTION 'operational_confirm_invalid'; END IF;
 SELECT * INTO v_doc FROM c10_demo.operational_documents_v1
  WHERE id=p_document FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_doc.tenant_id,v_doc.business_id)
 THEN RAISE EXCEPTION 'operational_confirm_denied'; END IF;
 IF v_doc.status='draft' THEN
  UPDATE c10_demo.operational_documents_v1
   SET status='confirmed',confirmed_by=c10_demo.actor_uid(),confirmed_at=now()
   WHERE id=p_document;
  RETURN 'confirmed';
 END IF;
 RETURN v_doc.status;
END $$;
CREATE FUNCTION c10_demo.post_operational_document_v1(p_document bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_doc c10_demo.operational_documents_v1%ROWTYPE;
 v_line c10_demo.operational_document_lines_v1%ROWTYPE;
 v_delta numeric(15,3);
BEGIN
 IF p_document IS NULL OR c10_demo.actor_uid() IS NULL
 THEN RAISE EXCEPTION 'operational_post_invalid'; END IF;
 SELECT * INTO v_doc FROM c10_demo.operational_documents_v1
  WHERE id=p_document FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_doc.tenant_id,v_doc.business_id)
 THEN RAISE EXCEPTION 'operational_post_denied'; END IF;
 IF v_doc.status='posted' THEN RETURN 'posted'; END IF;
 IF v_doc.status<>'confirmed' THEN RAISE EXCEPTION 'operational_not_confirmed'; END IF;
 IF NOT c10_demo.can_site(v_doc.tenant_id,v_doc.business_id,v_doc.site_id,'stock.post')
 THEN RAISE EXCEPTION 'operational_stock_permission_denied'; END IF;
 FOR v_line IN SELECT * FROM c10_demo.operational_document_lines_v1
  WHERE document_id=p_document ORDER BY line_no LOOP
  v_delta:=CASE WHEN v_doc.kind='purchase' THEN v_line.quantity ELSE -v_line.quantity END;
  PERFORM c10_demo.post_stock_event(v_doc.location_id,v_line.item_id,v_delta,
    'c10-op:'||p_document||':line:'||v_line.line_no);
 END LOOP;
 UPDATE c10_demo.operational_documents_v1
  SET status='posted',posted_by=c10_demo.actor_uid(),posted_at=now()
  WHERE id=p_document;
 RETURN 'posted';
END $$;

CREATE VIEW c10_demo.operational_business_report_v1 WITH(security_invoker=true) AS
 SELECT b.tenant_id,b.id AS business_id,
  COUNT(d.id) FILTER(WHERE d.kind='purchase' AND d.status='posted')::bigint
    AS posted_purchase_docs,
  COUNT(d.id) FILTER(WHERE d.kind='sale' AND d.status='posted')::bigint
    AS posted_sale_docs,
  COALESCE(sum(d.net_amount) FILTER(WHERE d.kind='purchase' AND d.status='posted'),0)::numeric(20,2)
    AS received_purchase_value_unreconciled,
  COALESCE(sum(d.net_amount) FILTER(WHERE d.kind='sale' AND d.status='posted'),0)::numeric(20,2)
    AS posted_sale_value_unreconciled,
  COUNT(d.id) FILTER(WHERE d.status IN('draft','confirmed'))::bigint
    AS unposted_documents,
  false::boolean AS cash_or_invoice_certified
 FROM c10_demo.businesses b
 LEFT JOIN c10_demo.operational_documents_v1 d ON d.business_id=b.id
 WHERE c10_demo.can_manage(b.tenant_id,b.id)
 GROUP BY b.tenant_id,b.id;
REVOKE ALL ON c10_demo.operational_business_report_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.operational_business_report_v1 TO authenticated;

"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {readManifest,validate,sqlMatrix,list}=require("../internal/demo-identity-program/index.js");
const data=readManifest();
assert(validate(data));
assert.equal(data.personas.length,16);
assert.equal(new Set(data.personas.map(p=>p.uid)).size,16);
assert.equal(new Set(data.personas.map(p=>p.key)).size,16);
const generated=sqlMatrix(data);
assert.match(generated,/SET LOCAL ROLE authenticated/);
assert.equal((generated.match(/DO \$check\$ DECLARE bb/g)||[]).length,16);
assert.match(generated,/SET LOCAL ROLE anon/);
assert.match(generated,/C10_A046_DISPOSABLE_DATABASE_ONLY/);
assert.match(generated,/REVOKED_MANAGER_A/);
const publicList=list(data);
assert.match(publicList,/TENANT_OWNER_A/);
assert.match(publicList,/FACTORY_STAFF_A/);
assert(!/password|service_role|sb_secret_/i.test(publicList));
const duplicate=structuredClone(data);
duplicate.personas[13].uid=duplicate.personas[0].uid;
assert.throws(()=>validate(duplicate),/duplicate identity/);
const crossover=structuredClone(data);
crossover.personas.find(p=>p.key==="BRANCH_STAFF_B").read_site_ids=[2001];
assert.throws(()=>validate(crossover),/cross-business site/);

 actor_id uuid NOT NULL, consumed boolean NOT NULL DEFAULT false,
 UNIQUE(location_id,request_key)
);
CREATE TABLE c10_demo.quality_balances_v1 (
 tenant_id bigint NOT NULL, business_id bigint NOT NULL, site_id bigint NOT NULL,

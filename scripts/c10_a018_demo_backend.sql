-- Atomic inside the caller transaction; a repeated request key reuses the existing identity.
-- Business remains DRAFT until full feature readiness and operational security gates pass.
CREATE FUNCTION c10_demo.provision_business(p_legal bigint,p_slug text,p_template text,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $
DECLARE v_tenant bigint; v_id bigint; v_existing record;
BEGIN
 IF p_slug IS NULL OR btrim(p_slug)='' OR p_request IS NULL OR btrim(p_request)='' THEN
  RAISE EXCEPTION 'invalid_business_request';
 END IF;
 SELECT tenant_id INTO v_tenant FROM legal_entities WHERE id=p_legal;
 IF v_tenant IS NULL OR NOT can_tenant(v_tenant) THEN RAISE EXCEPTION 'business_provision_not_authorized'; END IF;
 IF NOT EXISTS (SELECT 1 FROM templates t WHERE t.code=p_template AND t.demo_allowed) THEN
  RAISE EXCEPTION 'business_template_not_implemented';
 END IF;
 INSERT INTO businesses(tenant_id,legal_entity_id,slug,template_code,request_key,status)
 VALUES(v_tenant,p_legal,p_slug,p_template,p_request,'draft')
 ON CONFLICT(tenant_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT id,legal_entity_id,slug,template_code INTO v_existing
   FROM businesses WHERE tenant_id=v_tenant AND request_key=p_request;
  IF NOT FOUND OR v_existing.legal_entity_id<>p_legal OR v_existing.slug<>p_slug OR v_existing.template_code<>p_template THEN
   RAISE EXCEPTION 'idempotency_key_payload_conflict';
  END IF;
  v_id:=v_existing.id;
 END IF;
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.provision_site(p_business bigint,p_kind text,p_label text,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;v_id bigint;v_prev record;
BEGIN
 IF p_kind NOT IN ('showroom','factory','godown','warehouse','project') OR
  p_label IS NULL OR btrim(p_label)='' OR p_request IS NULL OR btrim(p_request)='' THEN
  RAISE EXCEPTION 'invalid_site_request';
 END IF;
 SELECT tenant_id INTO v_tenant FROM businesses WHERE id=p_business;
 IF v_tenant IS NULL OR NOT can_manage(v_tenant,p_business) THEN RAISE EXCEPTION 'site_provision_not_authorized'; END IF;
 INSERT INTO sites(tenant_id,business_id,kind,label,request_key)
 VALUES(v_tenant,p_business,p_kind,p_label,p_request)
 ON CONFLICT(business_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT id,kind,label INTO v_prev FROM sites WHERE business_id=p_business AND request_key=p_request;
  IF NOT FOUND OR v_prev.kind<>p_kind OR v_prev.label<>p_label THEN RAISE EXCEPTION 'idempotency_key_payload_conflict'; END IF;
  v_id:=v_prev.id;
 END IF;
 INSERT INTO stock_locations(tenant_id,business_id,site_id,code)
 VALUES(v_tenant,p_business,v_id,'MAIN')
 ON CONFLICT(site_id,code) DO NOTHING;
 RETURN v_id;
END $$;

-- Append-only stock event. Actual balance/valuation/negative-stock guards are a separate
-- required implementation: this demo does not certify live inventory accuracy.
CREATE FUNCTION c10_demo.post_stock_event(p_location bigint,p_item bigint,p_delta numeric,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_loc record;v_id bigint;v_prev record;
BEGIN
 IF p_delta IS NULL OR p_delta=0 OR p_request IS NULL OR btrim(p_request)='' THEN RAISE EXCEPTION 'invalid_stock_event'; END IF;
 SELECT tenant_id,business_id,site_id INTO v_loc FROM stock_locations WHERE id=p_location;
 IF NOT FOUND OR NOT can_site(v_loc.tenant_id,v_loc.business_id,v_loc.site_id,'stock.post') THEN
  RAISE EXCEPTION 'stock_post_not_authorized';
 END IF;
 INSERT INTO stock_movements(tenant_id,business_id,site_id,location_id,item_id,delta,request_key)
 VALUES(v_loc.tenant_id,v_loc.business_id,v_loc.site_id,p_location,p_item,p_delta,p_request)
 ON CONFLICT(location_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT id,item_id,delta,created_by INTO v_prev FROM stock_movements
   WHERE location_id=p_location AND request_key=p_request;
  IF NOT FOUND OR v_prev.item_id<>p_item OR v_prev.delta<>p_delta OR v_prev.created_by<>actor_uid()
   THEN RAISE EXCEPTION 'idempotency_key_payload_conflict'; END IF;
  v_id:=v_prev.id;
 END IF;
 RETURN v_id;
END $$;

CREATE VIEW c10_demo.stock_summary WITH(security_invoker=true) AS
 SELECT tenant_id,business_id,site_id,location_id,item_id,sum(delta) AS net_movement
 FROM c10_demo.stock_movements GROUP BY tenant_id,business_id,site_id,location_id,item_id;


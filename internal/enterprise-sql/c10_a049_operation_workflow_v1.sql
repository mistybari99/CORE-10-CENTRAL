CREATE TABLE c10_demo.operation_profiles_v1(
 tenant_id bigint NOT NULL,
 business_id bigint PRIMARY KEY,
 sales_staff_enabled boolean NOT NULL DEFAULT false,
 receiving_staff_enabled boolean NOT NULL DEFAULT true,
 production_mode text NOT NULL DEFAULT 'manual_preview' CHECK(production_mode IN('manual_preview','bom_assisted_preview')),
 version bigint NOT NULL DEFAULT 1,
 changed_by uuid NOT NULL,
 changed_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
CREATE TABLE c10_demo.operation_orders_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 location_id bigint NOT NULL,
 item_id bigint NOT NULL,
 kind text NOT NULL CHECK(kind IN('purchase_receive','sale_issue','production_plan')),
 quantity numeric(15,3) NOT NULL CHECK(quantity>0 AND quantity<=1000000 AND quantity=round(quantity,3)),
 estimated_unit_value numeric(18,2) NOT NULL DEFAULT 0 CHECK(estimated_unit_value>=0 AND estimated_unit_value<=100000000 AND estimated_unit_value=round(estimated_unit_value,2)),
 currency text NOT NULL DEFAULT 'BDT' CHECK(currency='BDT'),
 external_ref text,
 request_key text NOT NULL CHECK(request_key ~ '^[A-Za-z0-9_-]{8,100}$'),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','confirmed','posted')),
 version bigint NOT NULL DEFAULT 1 CHECK(version>0),
 created_by uuid NOT NULL,
 confirmed_by uuid,
 posted_by uuid,
 linked_inventory_command bigint REFERENCES c10_demo.inventory_commands_v1(id),
 post_request_key text,
 created_at timestamptz NOT NULL DEFAULT now(),
 posted_at timestamptz,
 UNIQUE(business_id,request_key),
 UNIQUE(id,tenant_id,business_id),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 FOREIGN KEY(location_id,tenant_id,business_id,site_id) REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id),
 CHECK((status='draft' AND confirmed_by IS NULL AND posted_by IS NULL AND linked_inventory_command IS NULL)
 OR (status='confirmed' AND confirmed_by IS NOT NULL AND posted_by IS NULL AND linked_inventory_command IS NULL)
 OR (status='posted' AND confirmed_by IS NOT NULL AND posted_by IS NOT NULL AND linked_inventory_command IS NOT NULL AND posted_at IS NOT NULL))
);
CREATE TABLE c10_demo.operation_audit_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 order_id bigint NOT NULL,
 event text NOT NULL CHECK(event IN('created','confirmed','posted')),
 actor uuid NOT NULL,
 request_key text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(order_id,tenant_id,business_id) REFERENCES c10_demo.operation_orders_v1(id,tenant_id,business_id)
);
ALTER TABLE c10_demo.operation_profiles_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.operation_orders_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.operation_audit_v1 ENABLE ROW LEVEL SECURITY;

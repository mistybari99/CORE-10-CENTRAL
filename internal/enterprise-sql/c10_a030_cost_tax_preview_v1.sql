-- CORE10 A030: Cost Rate + configurable Tax PREVIEW for posted sales.
-- DISPOSABLE CI ONLY: prices and tax rates are explicitly manual/unverified.
-- This is NOT an actual COGS valuation, VAT filing, GST/VAT rate database,
-- certified revenue statement, or automatic tax collection.
CREATE TABLE c10_demo.item_cost_rates_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 item_id bigint NOT NULL,
 unit_cost numeric(18,2) NOT NULL CHECK(unit_cost>=0),
 source_status text NOT NULL DEFAULT 'manual_unverified' CHECK(source_status='manual_unverified'),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','approved')),
 created_by uuid NOT NULL,
 approved_by uuid,
 approved_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id),
 CHECK((status='draft' AND approved_by IS NULL AND approved_at IS NULL)
  OR (status='approved' AND approved_by IS NOT NULL AND approved_at IS NOT NULL))
);
CREATE UNIQUE INDEX c10_one_approved_cost_per_item_v1
 ON c10_demo.item_cost_rates_v1(business_id,item_id) WHERE status='approved';
CREATE TABLE c10_demo.tax_preview_profiles_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 label text NOT NULL CHECK(length(btrim(label)) BETWEEN 3 AND 120),
 rate_bps integer NOT NULL CHECK(rate_bps BETWEEN 0 AND 10000),
 pricing_mode text NOT NULL CHECK(pricing_mode IN('inclusive','exclusive')),
 source_status text NOT NULL DEFAULT 'manual_unverified'
  CHECK(source_status='manual_unverified'),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','approved')),
 created_by uuid NOT NULL,
 approved_by uuid,
 approved_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 CHECK((status='draft' AND approved_by IS NULL AND approved_at IS NULL)
 OR (status='approved' AND approved_by IS NOT NULL AND approved_at IS NOT NULL))
);
CREATE UNIQUE INDEX c10_one_approved_tax_profile_v1
 ON c10_demo.tax_preview_profiles_v1(business_id) WHERE status='approved';
ALTER TABLE c10_demo.item_cost_rates_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.tax_preview_profiles_v1 ENABLE ROW LEVEL SECURITY;
CREATE POLICY c10_item_rate_owner_read_v1 ON c10_demo.item_cost_rates_v1
 FOR SELECT TO authenticated USING(c10_demo.can_manage(tenant_id,business_id));
CREATE POLICY c10_tax_profile_owner_read_v1 ON c10_demo.tax_preview_profiles_v1
 FOR SELECT TO authenticated USING(c10_demo.can_manage(tenant_id,business_id));
REVOKE ALL ON c10_demo.item_cost_rates_v1,c10_demo.tax_preview_profiles_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.item_cost_rates_v1,c10_demo.tax_preview_profiles_v1 TO authenticated;

CREATE FUNCTION c10_demo.create_cost_rate_v1(
 p_business bigint,p_item bigint,p_cost numeric,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;v_id bigint;v_prev record;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_business IS NULL OR p_item IS NULL OR
  p_cost IS NULL OR p_cost<0 OR p_cost<>round(p_cost,2) OR
  p_cost::text IN('NaN','Infinity','-Infinity') OR
  p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_manual_cost_rate'; END IF;
 SELECT tenant_id INTO v_tenant FROM c10_demo.businesses WHERE id=p_business;
 IF v_tenant IS NULL OR NOT c10_demo.can_manage(v_tenant,p_business)
 THEN RAISE EXCEPTION 'cost_rate_owner_denied'; END IF;
 IF NOT EXISTS(SELECT 1 FROM c10_demo.items WHERE id=p_item
  AND tenant_id=v_tenant AND business_id=p_business)
 THEN RAISE EXCEPTION 'cost_item_scope_denied'; END IF;
 INSERT INTO c10_demo.item_cost_rates_v1(
  tenant_id,business_id,item_id,unit_cost,request_key,created_by)
 VALUES(v_tenant,p_business,p_item,p_cost,p_request,c10_demo.actor_uid())
 ON CONFLICT DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_prev FROM c10_demo.item_cost_rates_v1
    WHERE business_id=p_business AND request_key=p_request;
  IF NOT FOUND OR v_prev.item_id<>p_item OR v_prev.unit_cost<>p_cost OR
    v_prev.created_by<>c10_demo.actor_uid()
  THEN RAISE EXCEPTION 'cost_rate_idempotency_conflict'; END IF;
  RETURN v_prev.id;
 END IF;
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.approve_cost_rate_v1(p_id bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_rate c10_demo.item_cost_rates_v1%ROWTYPE;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_id IS NULL THEN RAISE EXCEPTION 'invalid_cost_approval'; END IF;
 SELECT * INTO v_rate FROM c10_demo.item_cost_rates_v1 WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_rate.tenant_id,v_rate.business_id)
 THEN RAISE EXCEPTION 'cost_approval_denied'; END IF;
 IF v_rate.status='draft' THEN
  UPDATE c10_demo.item_cost_rates_v1
   SET status='approved',approved_by=c10_demo.actor_uid(),approved_at=now()
  WHERE id=p_id;
 END IF;
 RETURN 'approved';
END $$;


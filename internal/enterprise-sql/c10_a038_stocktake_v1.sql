-- C10-A038 / CORE 10 CENTRAL: Physical Stocktake -> Approval -> Adjustment.
-- DISPOSABLE PostgreSQL 17 CI ONLY, AFTER A018 demo backend + inventory_v1.
-- NEVER execute this file on live IMG-ERP-SG. No customer data, sales or valuation.
-- Counted quantity is user-entered; expected quantity is server-snapshotted at submit.
-- Posting refuses ANY intervening stock change (stale count). No automatic write-off.
-- Separation of duties: counter cannot approve their own count; only scoped business
-- owner/tenant owner can approve, post or void. Stock ledger and balances are atomic.

CREATE TABLE c10_demo.stocktakes_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 location_id bigint NOT NULL,
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 count_manifest jsonb NOT NULL CHECK(jsonb_typeof(count_manifest)='array'),
 status text NOT NULL DEFAULT 'draft'
  CHECK(status IN('draft','submitted','approved','posted','voided')),
 counted_by uuid NOT NULL,
 submitted_at timestamptz,
 reviewed_by uuid,
 reviewed_at timestamptz,
 posted_by uuid,
 posted_at timestamptz,
 voided_by uuid,
 voided_at timestamptz,
 void_reason text,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(id,tenant_id,business_id,site_id,location_id),
 UNIQUE(tenant_id,business_id,request_key),
 FOREIGN KEY(location_id,tenant_id,business_id,site_id)
  REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 CHECK(status<>'approved' OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
 CHECK(status<>'posted' OR (reviewed_by IS NOT NULL AND posted_by IS NOT NULL AND posted_at IS NOT NULL)),
 CHECK(status<>'voided' OR (voided_by IS NOT NULL AND voided_at IS NOT NULL AND length(btrim(void_reason))>=5))
);
CREATE TABLE c10_demo.stocktake_lines_v1(
 stocktake_id bigint NOT NULL,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 location_id bigint NOT NULL,
 item_id bigint NOT NULL,
 counted_quantity numeric(15,3) NOT NULL
   CHECK(counted_quantity>=0 AND counted_quantity::text NOT IN('NaN','Infinity','-Infinity')),
 expected_quantity numeric(15,3)
   CHECK(expected_quantity>=0 AND expected_quantity::text NOT IN('NaN','Infinity','-Infinity')),
 adjustment_movement_id bigint UNIQUE REFERENCES c10_demo.stock_movements(id),
 PRIMARY KEY(stocktake_id,item_id),
 FOREIGN KEY(stocktake_id,tenant_id,business_id,site_id,location_id)
  REFERENCES c10_demo.stocktakes_v1(id,tenant_id,business_id,site_id,location_id),
 FOREIGN KEY(item_id,tenant_id,business_id)
  REFERENCES c10_demo.items(id,tenant_id,business_id)
);
CREATE TABLE c10_demo.stocktake_audit_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 stocktake_id bigint NOT NULL REFERENCES c10_demo.stocktakes_v1(id),
 event text NOT NULL CHECK(event IN('draft','submitted','approved','posted','voided')),
 actor_uid uuid NOT NULL,
 occurred_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE c10_demo.stocktakes_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.stocktake_lines_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.stocktake_audit_v1 ENABLE ROW LEVEL SECURITY;
CREATE POLICY stocktake_read_scoped_v1 ON c10_demo.stocktakes_v1
 FOR SELECT TO authenticated USING(c10_demo.can_site(tenant_id,business_id,site_id,'stock.read'));
CREATE POLICY stocktake_lines_read_scoped_v1 ON c10_demo.stocktake_lines_v1
 FOR SELECT TO authenticated USING(EXISTS(
   SELECT 1 FROM c10_demo.stocktakes_v1 t WHERE t.id=stocktake_id
 ));
CREATE POLICY stocktake_audit_read_scoped_v1 ON c10_demo.stocktake_audit_v1
 FOR SELECT TO authenticated USING(EXISTS(
   SELECT 1 FROM c10_demo.stocktakes_v1 t WHERE t.id=stocktake_id
 ));
REVOKE ALL ON c10_demo.stocktakes_v1,c10_demo.stocktake_lines_v1,
 c10_demo.stocktake_audit_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.stocktakes_v1,c10_demo.stocktake_lines_v1,
 c10_demo.stocktake_audit_v1 TO authenticated;

CREATE FUNCTION c10_demo.create_stocktake_v1(
 p_location bigint,p_counts jsonb,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_loc record;v_item jsonb;v_item_id bigint;v_qty numeric;
 v_seen bigint[]:=ARRAY[]::bigint[];v_id bigint;v_prev record;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_location IS NULL OR
    p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120 OR
    p_counts IS NULL OR jsonb_typeof(p_counts)<>'array' OR
    jsonb_array_length(p_counts) NOT BETWEEN 1 AND 500 THEN
  RAISE EXCEPTION 'invalid_stocktake_request';
 END IF;
 SELECT tenant_id,business_id,site_id INTO v_loc
 FROM c10_demo.stock_locations WHERE id=p_location;
 IF NOT FOUND OR NOT c10_demo.can_site(
   v_loc.tenant_id,v_loc.business_id,v_loc.site_id,'stock.read') THEN
  RAISE EXCEPTION 'stocktake_scope_denied';
 END IF;
 FOR v_item IN SELECT value FROM jsonb_array_elements(p_counts) LOOP
  IF jsonb_typeof(v_item)<>'object' OR
    (SELECT count(*) FROM jsonb_object_keys(v_item))<>2 OR
    jsonb_typeof(v_item->'item_id')<>'number' OR
    jsonb_typeof(v_item->'counted')<>'number' THEN
    RAISE EXCEPTION 'invalid_stocktake_item';
  END IF;
  v_item_id:=(v_item->>'item_id')::bigint;
  v_qty:=(v_item->>'counted')::numeric;
  IF v_item_id<=0 OR v_qty<0 OR v_qty::text IN('NaN','Infinity','-Infinity') OR
     v_qty<>round(v_qty,3) OR v_qty>999999999999.999 OR
     v_item_id=ANY(v_seen) THEN RAISE EXCEPTION 'invalid_stocktake_item'; END IF;
  IF NOT EXISTS(SELECT 1 FROM c10_demo.items
    WHERE id=v_item_id AND tenant_id=v_loc.tenant_id AND business_id=v_loc.business_id) THEN
    RAISE EXCEPTION 'stocktake_item_business_mismatch';
  END IF;
  v_seen:=array_append(v_seen,v_item_id);
 END LOOP;
 INSERT INTO c10_demo.stocktakes_v1(
  tenant_id,business_id,site_id,location_id,request_key,count_manifest,counted_by)
 VALUES(v_loc.tenant_id,v_loc.business_id,v_loc.site_id,p_location,
   p_request,p_counts,c10_demo.actor_uid())
 ON CONFLICT(tenant_id,business_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_prev FROM c10_demo.stocktakes_v1
   WHERE tenant_id=v_loc.tenant_id AND business_id=v_loc.business_id
     AND request_key=p_request;
  IF NOT FOUND OR v_prev.location_id<>p_location OR
     v_prev.counted_by<>c10_demo.actor_uid() OR v_prev.count_manifest<>p_counts THEN
    RAISE EXCEPTION 'stocktake_idempotency_conflict';
  END IF;
  RETURN v_prev.id;
 END IF;
 FOR v_item IN SELECT value FROM jsonb_array_elements(p_counts) LOOP
  INSERT INTO c10_demo.stocktake_lines_v1(
   stocktake_id,tenant_id,business_id,site_id,location_id,item_id,counted_quantity)
  VALUES(v_id,v_loc.tenant_id,v_loc.business_id,v_loc.site_id,p_location,
    (v_item->>'item_id')::bigint,(v_item->>'counted')::numeric);
 END LOOP;
 INSERT INTO c10_demo.stocktake_audit_v1(stocktake_id,event,actor_uid)
 VALUES(v_id,'draft',c10_demo.actor_uid());
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.submit_stocktake_v1(p_id bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_doc c10_demo.stocktakes_v1%ROWTYPE;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_id IS NULL THEN
   RAISE EXCEPTION 'invalid_stocktake_id'; END IF;
 SELECT * INTO v_doc FROM c10_demo.stocktakes_v1 WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR v_doc.counted_by<>c10_demo.actor_uid() OR
    NOT c10_demo.can_site(v_doc.tenant_id,v_doc.business_id,v_doc.site_id,'stock.read') THEN
   RAISE EXCEPTION 'stocktake_submit_denied'; END IF;
 IF v_doc.status='submitted' THEN RETURN 'submitted'; END IF;
 IF v_doc.status<>'draft' THEN RAISE EXCEPTION 'stocktake_not_draft'; END IF;
 -- Server-owned snapshot; caller never provides claimed stock quantity.
 UPDATE c10_demo.stocktake_lines_v1 l
  SET expected_quantity=COALESCE((
    SELECT b.on_hand FROM c10_demo.stock_balances_v1 b
     WHERE b.location_id=v_doc.location_id AND b.item_id=l.item_id),0)
 WHERE l.stocktake_id=p_id;
 UPDATE c10_demo.stocktakes_v1 SET status='submitted',submitted_at=now() WHERE id=p_id;
 INSERT INTO c10_demo.stocktake_audit_v1(stocktake_id,event,actor_uid)
 VALUES(p_id,'submitted',c10_demo.actor_uid());
 RETURN 'submitted';
END $$;

CREATE FUNCTION c10_demo.approve_stocktake_v1(p_id bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_doc c10_demo.stocktakes_v1%ROWTYPE;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_id IS NULL THEN
  RAISE EXCEPTION 'invalid_stocktake_id'; END IF;
 SELECT * INTO v_doc FROM c10_demo.stocktakes_v1 WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_doc.tenant_id,v_doc.business_id)
  THEN RAISE EXCEPTION 'stocktake_approval_denied'; END IF;
 IF v_doc.status='approved' THEN RETURN 'approved'; END IF;
 IF v_doc.status<>'submitted' THEN RAISE EXCEPTION 'stocktake_not_submitted'; END IF;
 IF v_doc.counted_by=c10_demo.actor_uid() THEN
  RAISE EXCEPTION 'stocktake_self_approval_forbidden'; END IF;
 IF EXISTS(SELECT 1 FROM c10_demo.stocktake_lines_v1
  WHERE stocktake_id=p_id AND expected_quantity IS NULL) THEN
  RAISE EXCEPTION 'stocktake_snapshot_missing'; END IF;
 UPDATE c10_demo.stocktakes_v1 SET status='approved',reviewed_by=c10_demo.actor_uid(),
  reviewed_at=now() WHERE id=p_id;
 INSERT INTO c10_demo.stocktake_audit_v1(stocktake_id,event,actor_uid)
 VALUES(p_id,'approved',c10_demo.actor_uid());
 RETURN 'approved';
END $$;

CREATE FUNCTION c10_demo.post_stocktake_v1(p_id bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_doc c10_demo.stocktakes_v1%ROWTYPE;v_line record;
 v_delta numeric(15,3);v_movement bigint;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_id IS NULL THEN
  RAISE EXCEPTION 'invalid_stocktake_id'; END IF;
 SELECT * INTO v_doc FROM c10_demo.stocktakes_v1 WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_doc.tenant_id,v_doc.business_id)
  THEN RAISE EXCEPTION 'stocktake_post_denied'; END IF;
 IF v_doc.status='posted' THEN RETURN 'posted'; END IF;
 IF v_doc.status<>'approved' THEN RAISE EXCEPTION 'stocktake_not_approved'; END IF;
 -- Materialize zero balances and acquire ordered locks BEFORE stale checks.
 -- Existing stock/transfer RPCs serialize on the same balance rows.
 INSERT INTO c10_demo.stock_balances_v1(
  tenant_id,business_id,site_id,location_id,item_id,on_hand)
 SELECT l.tenant_id,l.business_id,l.site_id,l.location_id,l.item_id,0
 FROM c10_demo.stocktake_lines_v1 l WHERE l.stocktake_id=p_id
 ON CONFLICT(location_id,item_id) DO NOTHING;
 PERFORM 1 FROM c10_demo.stock_balances_v1 b
 JOIN c10_demo.stocktake_lines_v1 l
  ON l.location_id=b.location_id AND l.item_id=b.item_id
 WHERE l.stocktake_id=p_id ORDER BY b.location_id,b.item_id FOR UPDATE;
 FOR v_line IN
  SELECT l.item_id,l.expected_quantity,l.counted_quantity,b.on_hand
  FROM c10_demo.stocktake_lines_v1 l
  JOIN c10_demo.stock_balances_v1 b
    ON b.location_id=l.location_id AND b.item_id=l.item_id
  WHERE l.stocktake_id=p_id ORDER BY l.item_id
 LOOP
  IF v_line.expected_quantity IS NULL OR v_line.on_hand<>v_line.expected_quantity THEN
   RAISE EXCEPTION 'stocktake_stale_recount_required';
  END IF;
 END LOOP;
 FOR v_line IN SELECT item_id,expected_quantity,counted_quantity
   FROM c10_demo.stocktake_lines_v1 WHERE stocktake_id=p_id ORDER BY item_id LOOP
  v_delta:=v_line.counted_quantity-v_line.expected_quantity;
  IF v_delta<>0 THEN
   UPDATE c10_demo.stock_balances_v1
    SET on_hand=v_line.counted_quantity
    WHERE location_id=v_doc.location_id AND item_id=v_line.item_id;
   -- Unique movement key rejects a forged/pre-existing journal row, rather
   -- than pretending a cached idempotent event is a new stocktake posting.
   INSERT INTO c10_demo.stock_movements(
    tenant_id,business_id,site_id,location_id,item_id,delta,request_key,created_by)
   VALUES(v_doc.tenant_id,v_doc.business_id,v_doc.site_id,
    v_doc.location_id,v_line.item_id,v_delta,
    'c10-stocktake:'||p_id||':'||v_line.item_id,c10_demo.actor_uid())
   RETURNING id INTO v_movement;
   UPDATE c10_demo.stocktake_lines_v1
    SET adjustment_movement_id=v_movement
    WHERE stocktake_id=p_id AND item_id=v_line.item_id;
  END IF;
 END LOOP;
 UPDATE c10_demo.stocktakes_v1 SET status='posted',posted_by=c10_demo.actor_uid(),
   posted_at=now() WHERE id=p_id;
 INSERT INTO c10_demo.stocktake_audit_v1(stocktake_id,event,actor_uid)
 VALUES(p_id,'posted',c10_demo.actor_uid());
 RETURN 'posted';
END $$;

CREATE FUNCTION c10_demo.void_stocktake_v1(p_id bigint,p_reason text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_doc c10_demo.stocktakes_v1%ROWTYPE;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_id IS NULL OR p_reason IS NULL OR
    length(btrim(p_reason)) NOT BETWEEN 5 AND 500 THEN
  RAISE EXCEPTION 'invalid_stocktake_void_request'; END IF;
 SELECT * INTO v_doc FROM c10_demo.stocktakes_v1 WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_doc.tenant_id,v_doc.business_id)
  THEN RAISE EXCEPTION 'stocktake_void_denied'; END IF;
 IF v_doc.status='posted' THEN RAISE EXCEPTION 'posted_stocktake_immutable'; END IF;
 IF v_doc.status='voided' THEN
  IF v_doc.void_reason=btrim(p_reason) THEN RETURN 'voided'; END IF;
  RAISE EXCEPTION 'stocktake_void_reason_conflict';
 END IF;
 UPDATE c10_demo.stocktakes_v1 SET status='voided',
  voided_by=c10_demo.actor_uid(),voided_at=now(),void_reason=btrim(p_reason)
  WHERE id=p_id;
 INSERT INTO c10_demo.stocktake_audit_v1(stocktake_id,event,actor_uid)
 VALUES(p_id,'voided',c10_demo.actor_uid());
 RETURN 'voided';
END $$;

CREATE VIEW c10_demo.stocktake_discrepancy_v1 WITH(security_invoker=true) AS
 SELECT t.tenant_id,t.business_id,t.site_id,t.location_id,t.id AS stocktake_id,
  t.status,t.counted_by,t.reviewed_by,t.posted_by,l.item_id,
  l.expected_quantity,l.counted_quantity,
  CASE WHEN l.expected_quantity IS NULL THEN NULL
       ELSE l.counted_quantity-l.expected_quantity END AS difference,
  l.adjustment_movement_id
 FROM c10_demo.stocktakes_v1 t JOIN c10_demo.stocktake_lines_v1 l
   ON l.stocktake_id=t.id;


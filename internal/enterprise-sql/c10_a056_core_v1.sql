CREATE FUNCTION c10_demo.a056_read_settings_v1(p_business bigint) RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $f$
#variable_conflict use_column
DECLARE t bigint; s c10_demo.a056_settings%ROWTYPE;
BEGIN
 IF c10_demo.actor_uid() IS NULL THEN RAISE EXCEPTION 'A056_SIGNED_USER_REQUIRED'; END IF;
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF t IS NULL OR NOT c10_demo.can_see_business(t,p_business) THEN RAISE EXCEPTION 'A056_DENIED'; END IF;
 SELECT * INTO s FROM c10_demo.a056_settings WHERE business_id=p_business;
 RETURN jsonb_build_object('business_id',p_business,'enabled',COALESCE(s.enabled,false),'version',COALESCE(s.version,0),
  'config',COALESCE(s.config,c10_demo.a056_default_config()),'defaults',c10_demo.a056_default_config(),'persisted',FOUND);
END $f$;
CREATE FUNCTION c10_demo.a056_set_settings_v1(p_business bigint,p_enabled boolean,p_config jsonb,p_expected bigint,p_request text,p_reason text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $f$
#variable_conflict use_column
DECLARE t bigint; prev jsonb; h text; cur c10_demo.a056_settings%ROWTYPE; nv bigint; resp jsonb; bad text;
BEGIN
 t:=c10_demo.a056_require(p_business,NULL,'settings.write');
 IF p_enabled IS NULL OR p_expected IS NULL OR p_expected<0 THEN RAISE EXCEPTION 'A056_INVALID'; END IF;
 h:=c10_demo.a056_h(p_enabled::text,p_config::text,p_expected::text);
 prev:=c10_demo.a056_idem_check(p_business,p_request,'set_settings',h); IF prev IS NOT NULL THEN RETURN prev; END IF;
 p_config:=COALESCE(p_config,c10_demo.a056_default_config());
 PERFORM c10_demo.a056_validate_config(p_config);
 SELECT s INTO bad FROM (SELECT o.stage_code s FROM c10_demo.a056_opportunities o WHERE o.business_id=p_business AND o.status='open'
   AND NOT o.stage_code IN(SELECT x->>'code' FROM jsonb_array_elements(p_config->'stages') x) LIMIT 1) q;
 IF bad IS NOT NULL THEN RAISE EXCEPTION 'A056_STAGE_IN_USE'; END IF;

-- INTERNAL applier: never granted to API roles. Callers hold the valuation row lock (FOR UPDATE).
CREATE FUNCTION c10_demo._cost_apply_v1(
 p_tenant bigint,p_business bigint,p_site bigint,p_location bigint,p_item bigint,
 p_type text,p_qty numeric,p_value numeric,p_source_type text,p_source_id bigint,
 p_source_line integer,p_snapshot jsonb,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_id bigint;v_unit numeric;
BEGIN
 v_unit:=CASE WHEN p_qty=0 THEN 0 ELSE round(abs(p_value)/abs(p_qty),6) END;
 INSERT INTO c10_demo.cost_events_v1(tenant_id,business_id,site_id,location_id,item_id,
   event_type,quantity,unit_cost,value,source_type,source_id,source_line,source_snapshot,
   request_key,created_by)
 VALUES(p_tenant,p_business,p_site,p_location,p_item,p_type,p_qty,v_unit,p_value,
   p_source_type,p_source_id,p_source_line,p_snapshot,p_request,c10_demo.actor_uid())
 RETURNING id INTO v_id;
 UPDATE c10_demo.cost_valuation_v1
  SET quantity=quantity+p_qty,total_value=total_value+p_value
  WHERE location_id=p_location AND item_id=p_item;
 RETURN v_id;
END $$;

-- Lock (creating if needed) valuation rows in a fixed order so concurrent postings cannot deadlock.
CREATE FUNCTION c10_demo._cost_lock_v1(
 p_tenant bigint,p_business bigint,p_site bigint,p_location bigint,p_item bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
BEGIN
 INSERT INTO c10_demo.cost_valuation_v1(tenant_id,business_id,site_id,location_id,item_id)
 VALUES(p_tenant,p_business,p_site,p_location,p_item) ON CONFLICT(location_id,item_id) DO NOTHING;
 PERFORM 1 FROM c10_demo.cost_valuation_v1 WHERE location_id=p_location AND item_id=p_item FOR UPDATE;
END $$;

-- Issue value at weighted average; when the whole costed quantity leaves, the remaining value leaves
-- with it (no rounding residue, no negative or orphan value).
CREATE FUNCTION c10_demo._cost_issue_value_v1(p_location bigint,p_item bigint,p_qty numeric)
RETURNS numeric LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v record;
BEGIN
 SELECT quantity,total_value INTO v FROM c10_demo.cost_valuation_v1
  WHERE location_id=p_location AND item_id=p_item;
 IF NOT FOUND OR v.quantity<p_qty THEN RETURN NULL; END IF;
 IF v.quantity=p_qty THEN RETURN v.total_value; END IF;
 RETURN round(p_qty*v.total_value/v.quantity,4);
END $$;

-- 1) PURCHASE RECEIPT COSTING ---------------------------------------------------------------
CREATE FUNCTION c10_demo.post_purchase_receipt_cost_v1(p_document bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE d c10_demo.operational_documents_v1%ROWTYPE;l record;v_alloc numeric;v_sum numeric:=0;
 v_n integer;v_i integer:=0;v_value numeric;v_events jsonb:='[]'::jsonb;v_id bigint;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_document IS NULL THEN RAISE EXCEPTION 'cost_invalid_request'; END IF;
 SELECT * INTO d FROM c10_demo.operational_documents_v1 WHERE id=p_document FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(d.tenant_id,d.business_id)
 THEN RAISE EXCEPTION 'cost_post_denied'; END IF;
 IF d.kind<>'purchase' THEN RAISE EXCEPTION 'cost_source_not_purchase'; END IF;
 IF d.status<>'posted' THEN
  RETURN jsonb_build_object('status','blocked','reasons',
   jsonb_build_array(jsonb_build_object('reason','purchase_document_not_posted')));
 END IF;
 IF EXISTS(SELECT 1 FROM c10_demo.cost_events_v1 WHERE source_type='operational_document'
    AND source_id=p_document AND event_type='purchase_receipt') THEN
  RETURN jsonb_build_object('status','already_costed','document_id',p_document);
 END IF;
 SELECT count(*) INTO v_n FROM c10_demo.operational_document_lines_v1 WHERE document_id=p_document;
 FOR l IN SELECT * FROM c10_demo.operational_document_lines_v1
   WHERE document_id=p_document ORDER BY item_id,line_no LOOP
  PERFORM c10_demo._cost_lock_v1(d.tenant_id,d.business_id,d.site_id,d.location_id,l.item_id);
 END LOOP;
 -- re-check after locks: a concurrent twin may have posted while we waited
 IF EXISTS(SELECT 1 FROM c10_demo.cost_events_v1 WHERE source_type='operational_document'
    AND source_id=p_document AND event_type='purchase_receipt') THEN
  RETURN jsonb_build_object('status','already_costed','document_id',p_document);
 END IF;
 FOR l IN SELECT * FROM c10_demo.operational_document_lines_v1
   WHERE document_id=p_document ORDER BY line_no LOOP
  v_i:=v_i+1;
  IF v_i=v_n THEN v_value:=d.net_amount-v_sum;
  ELSE v_value:=round(l.amount*d.net_amount/d.subtotal,4); END IF;
  v_sum:=v_sum+v_value;
  v_id:=c10_demo._cost_apply_v1(d.tenant_id,d.business_id,d.site_id,d.location_id,l.item_id,
   'purchase_receipt',l.quantity,v_value,'operational_document',p_document,l.line_no,
   jsonb_build_object('document_id',p_document,'line_no',l.line_no,'kind',d.kind,
     'counterparty',d.counterparty,'quantity',l.quantity,'unit_price',l.unit_price,
     'line_amount',l.amount,'document_subtotal',d.subtotal,'document_discount',d.discount,
     'document_net',d.net_amount,'allocated_value',v_value,'posted_at',d.posted_at),
   'c10-cost:purchase:'||p_document||':'||l.line_no);
  v_events:=v_events||to_jsonb(v_id);
 END LOOP;
 RETURN jsonb_build_object('status','costed','document_id',p_document,'events',v_events,'value',v_sum);
END $$;

-- 2) SALE COGS SNAPSHOT --------------------------------------------------------------------
CREATE FUNCTION c10_demo.post_sale_cogs_v1(p_document bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE d c10_demo.operational_documents_v1%ROWTYPE;l record;v_reasons jsonb:='[]'::jsonb;
 v_value numeric;v_id bigint;v_events jsonb:='[]'::jsonb;v_total numeric:=0;v_avail numeric;
 v_taken jsonb:='{}'::jsonb;v_need numeric;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_document IS NULL THEN RAISE EXCEPTION 'cost_invalid_request'; END IF;
 SELECT * INTO d FROM c10_demo.operational_documents_v1 WHERE id=p_document FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(d.tenant_id,d.business_id)
 THEN RAISE EXCEPTION 'cost_post_denied'; END IF;
 IF d.kind<>'sale' THEN RAISE EXCEPTION 'cost_source_not_sale'; END IF;
 IF d.status<>'posted' THEN
  RETURN jsonb_build_object('status','blocked','reasons',
   jsonb_build_array(jsonb_build_object('reason','sale_document_not_posted')));
 END IF;
 FOR l IN SELECT DISTINCT item_id FROM c10_demo.operational_document_lines_v1
   WHERE document_id=p_document ORDER BY item_id LOOP
  PERFORM c10_demo._cost_lock_v1(d.tenant_id,d.business_id,d.site_id,d.location_id,l.item_id);
 END LOOP;
 IF EXISTS(SELECT 1 FROM c10_demo.cost_events_v1 WHERE source_type='operational_document'
    AND source_id=p_document AND event_type='sale_cogs') THEN
  RETURN jsonb_build_object('status','already_costed','document_id',p_document);
 END IF;
 -- 1st pass: check that VERIFIED costed quantity covers every item (summed across lines).
 FOR l IN SELECT item_id,sum(quantity) AS q FROM c10_demo.operational_document_lines_v1
   WHERE document_id=p_document GROUP BY item_id ORDER BY item_id LOOP
  SELECT quantity INTO v_avail FROM c10_demo.cost_valuation_v1
   WHERE location_id=d.location_id AND item_id=l.item_id;
  IF COALESCE(v_avail,0)<l.q THEN
   v_reasons:=v_reasons||jsonb_build_object('item_id',l.item_id,'reason','insufficient_costed_quantity',
     'needed',l.q,'costed_available',COALESCE(v_avail,0));
  END IF;
 END LOOP;
 IF jsonb_array_length(v_reasons)>0 THEN
  RETURN jsonb_build_object('status','blocked','document_id',p_document,'reasons',v_reasons);
 END IF;
 -- 2nd pass: post in line order; each line issues at the then-current weighted average.
 FOR l IN SELECT * FROM c10_demo.operational_document_lines_v1
   WHERE document_id=p_document ORDER BY line_no LOOP
  v_value:=c10_demo._cost_issue_value_v1(d.location_id,l.item_id,l.quantity);
  v_id:=c10_demo._cost_apply_v1(d.tenant_id,d.business_id,d.site_id,d.location_id,l.item_id,
   'sale_cogs',-l.quantity,-v_value,'operational_document',p_document,l.line_no,
   jsonb_build_object('document_id',p_document,'line_no',l.line_no,'quantity',l.quantity,
     'unit_price',l.unit_price,'revenue_line',l.amount,'document_net',d.net_amount,
     'document_subtotal',d.subtotal,'posted_at',d.posted_at),
   'c10-cost:sale:'||p_document||':'||l.line_no);
  v_events:=v_events||to_jsonb(v_id);v_total:=v_total+v_value;
 END LOOP;
 RETURN jsonb_build_object('status','costed','document_id',p_document,'events',v_events,'cogs',v_total);
END $$;

-- 3) PRODUCTION COST (ingredient + owner-referenced overhead) ------------------------------
CREATE FUNCTION c10_demo.post_production_cost_v1(
 p_batch bigint,p_actual_yield numeric,p_overhead_actual numeric,p_overhead_reference text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE b c10_demo.production_batches_v1%ROWTYPE;r c10_demo.bom_recipes_v1%ROWTYPE;l record;
 v_reasons jsonb:='[]'::jsonb;v_avail numeric;v_ing numeric:=0;v_val numeric;v_qty numeric;
 v_std_ing numeric:=0;v_over numeric:=0;v_cert boolean;v_site bigint;v_total numeric;v_unit numeric;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_batch IS NULL OR p_actual_yield IS NULL OR p_actual_yield<=0
    OR p_actual_yield<>round(p_actual_yield,3)
    OR (p_overhead_actual IS NOT NULL AND (p_overhead_actual<0 OR p_overhead_actual<>round(p_overhead_actual,4)
        OR p_overhead_actual::text IN('NaN','Infinity','-Infinity')))
 THEN RAISE EXCEPTION 'cost_invalid_request'; END IF;
 SELECT * INTO b FROM c10_demo.production_batches_v1 WHERE id=p_batch FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(b.tenant_id,b.business_id)
 THEN RAISE EXCEPTION 'cost_post_denied'; END IF;
 IF b.status<>'posted' THEN
  RETURN jsonb_build_object('status','blocked','reasons',
   jsonb_build_array(jsonb_build_object('reason','production_batch_not_posted')));
 END IF;
 SELECT * INTO r FROM c10_demo.bom_recipes_v1 WHERE id=b.bom_id;
 v_site:=b.site_id;
 FOR l IN SELECT ingredient_item_id FROM c10_demo.bom_ingredients_v1 WHERE bom_id=b.bom_id
   UNION SELECT r.finished_item_id ORDER BY 1 LOOP
  PERFORM c10_demo._cost_lock_v1(b.tenant_id,b.business_id,v_site,b.location_id,l.ingredient_item_id);
 END LOOP;
 IF EXISTS(SELECT 1 FROM c10_demo.production_cost_runs_v1 WHERE batch_id=p_batch) THEN
  RETURN jsonb_build_object('status','already_costed','batch_id',p_batch);
 END IF;
 IF p_actual_yield<>b.expected_output THEN
  v_reasons:=v_reasons||jsonb_build_object('reason','actual_yield_differs_from_posted_stock',
    'posted_output',b.expected_output,'actual_yield',p_actual_yield,
    'action','post a stock adjustment first; cost is never inferred for unposted quantities');
 END IF;
 IF p_overhead_actual IS NOT NULL AND p_overhead_actual>0 AND
    (p_overhead_reference IS NULL OR length(btrim(p_overhead_reference))<3) THEN
  v_reasons:=v_reasons||jsonb_build_object('reason','overhead_requires_reference');
 END IF;
 FOR l IN SELECT * FROM c10_demo.bom_ingredients_v1 WHERE bom_id=b.bom_id ORDER BY line_no LOOP
  v_qty:=l.qty_per_batch*b.multiplier;
  SELECT quantity INTO v_avail FROM c10_demo.cost_valuation_v1
   WHERE location_id=b.location_id AND item_id=l.ingredient_item_id;
  IF COALESCE(v_avail,0)<v_qty THEN
   v_reasons:=v_reasons||jsonb_build_object('item_id',l.ingredient_item_id,
     'reason','ingredient_has_no_verified_cost_coverage','needed',v_qty,'costed_available',COALESCE(v_avail,0));
  END IF;
  v_std_ing:=v_std_ing+round(v_qty*l.estimated_unit_cost,4);
 END LOOP;
 IF jsonb_array_length(v_reasons)>0 THEN
  RETURN jsonb_build_object('status','blocked','batch_id',p_batch,'reasons',v_reasons);
 END IF;
 FOR l IN SELECT * FROM c10_demo.bom_ingredients_v1 WHERE bom_id=b.bom_id ORDER BY line_no LOOP
  v_qty:=l.qty_per_batch*b.multiplier;
  v_val:=c10_demo._cost_issue_value_v1(b.location_id,l.ingredient_item_id,v_qty);
  PERFORM c10_demo._cost_apply_v1(b.tenant_id,b.business_id,v_site,b.location_id,l.ingredient_item_id,
   'production_issue',-v_qty,-v_val,'production_batch',p_batch,l.line_no,
   jsonb_build_object('batch_id',p_batch,'bom_id',b.bom_id,'line_no',l.line_no,'quantity',v_qty,
     'bom_estimated_unit_cost',l.estimated_unit_cost),
   'c10-cost:prod-issue:'||p_batch||':'||l.line_no);
  v_ing:=v_ing+v_val;
 END LOOP;
 v_cert:=COALESCE(p_overhead_actual,0)>0;
 v_over:=CASE WHEN v_cert THEN p_overhead_actual ELSE 0 END;
 v_total:=v_ing+v_over;
 v_unit:=round(v_total/b.expected_output,6);
 PERFORM c10_demo._cost_apply_v1(b.tenant_id,b.business_id,v_site,b.location_id,r.finished_item_id,
  'production_output',b.expected_output,v_total,'production_batch',p_batch,0,
  jsonb_build_object('batch_id',p_batch,'bom_id',b.bom_id,'multiplier',b.multiplier,
    'ingredient_cost',v_ing,'overhead_actual',v_over,'overhead_reference',p_overhead_reference,
    'overhead_certified',v_cert,'expected_output',b.expected_output),
  'c10-cost:prod-output:'||p_batch);
 INSERT INTO c10_demo.production_cost_runs_v1(batch_id,tenant_id,business_id,location_id,finished_item_id,
   output_quantity,ingredient_cost,overhead_actual,overhead_reference,overhead_certified,total_cost,unit_cost,
   standard_ingredient_cost,standard_overhead_cost,ingredient_price_variance,overhead_variance,
   yield_variance_qty,request_key,created_by)
 VALUES(p_batch,b.tenant_id,b.business_id,b.location_id,r.finished_item_id,b.expected_output,v_ing,v_over,
   CASE WHEN v_cert THEN p_overhead_reference END,v_cert,v_total,v_unit,v_std_ing,
   round(r.overhead_estimate*b.multiplier,4),v_ing-v_std_ing,
   CASE WHEN v_cert THEN v_over-round(r.overhead_estimate*b.multiplier,4) ELSE 0 END,
   b.expected_output-round(r.yield_quantity*b.multiplier,3),'c10-cost:prod-run:'||p_batch,c10_demo.actor_uid());
 RETURN jsonb_build_object('status','costed','batch_id',p_batch,'total_cost',v_total,'unit_cost',v_unit,
   'overhead_certified',v_cert);
END $$;

-- 4) TRANSFER: moves cost, never revenue ----------------------------------------------------
CREATE FUNCTION c10_demo.post_transfer_cost_v1(p_transfer bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE t c10_demo.stock_transfers_v1%ROWTYPE;v_value numeric;v_avail numeric;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_transfer IS NULL THEN RAISE EXCEPTION 'cost_invalid_request'; END IF;
 SELECT * INTO t FROM c10_demo.stock_transfers_v1 WHERE id=p_transfer FOR SHARE;
 IF NOT FOUND OR NOT c10_demo.can_manage(t.tenant_id,t.business_id)
 THEN RAISE EXCEPTION 'cost_post_denied'; END IF;
 -- fixed lock order (lower location id first)
 PERFORM c10_demo._cost_lock_v1(t.tenant_id,t.business_id,
   CASE WHEN t.source_location_id<t.destination_location_id THEN t.source_site_id ELSE t.destination_site_id END,
   LEAST(t.source_location_id,t.destination_location_id),t.item_id);
 PERFORM c10_demo._cost_lock_v1(t.tenant_id,t.business_id,
   CASE WHEN t.source_location_id<t.destination_location_id THEN t.destination_site_id ELSE t.source_site_id END,
   GREATEST(t.source_location_id,t.destination_location_id),t.item_id);
 IF EXISTS(SELECT 1 FROM c10_demo.cost_events_v1 WHERE source_type='stock_transfer'
    AND source_id=p_transfer AND event_type='transfer_out') THEN
  RETURN jsonb_build_object('status','already_costed','transfer_id',p_transfer);
 END IF;
 SELECT quantity INTO v_avail FROM c10_demo.cost_valuation_v1
  WHERE location_id=t.source_location_id AND item_id=t.item_id;
 IF COALESCE(v_avail,0)<t.quantity THEN
  RETURN jsonb_build_object('status','blocked','transfer_id',p_transfer,'reasons',
   jsonb_build_array(jsonb_build_object('item_id',t.item_id,'reason','insufficient_costed_quantity',
     'needed',t.quantity,'costed_available',COALESCE(v_avail,0))));
 END IF;
 v_value:=c10_demo._cost_issue_value_v1(t.source_location_id,t.item_id,t.quantity);
 PERFORM c10_demo._cost_apply_v1(t.tenant_id,t.business_id,t.source_site_id,t.source_location_id,t.item_id,
  'transfer_out',-t.quantity,-v_value,'stock_transfer',p_transfer,0,
  jsonb_build_object('transfer_id',p_transfer,'to_location',t.destination_location_id),
  'c10-cost:transfer-out:'||p_transfer);
 PERFORM c10_demo._cost_apply_v1(t.tenant_id,t.business_id,t.destination_site_id,t.destination_location_id,t.item_id,
  'transfer_in',t.quantity,v_value,'stock_transfer',p_transfer,0,
  jsonb_build_object('transfer_id',p_transfer,'from_location',t.source_location_id),
  'c10-cost:transfer-in:'||p_transfer);
 RETURN jsonb_build_object('status','costed','transfer_id',p_transfer,'value',v_value);
END $$;

-- 5) SALE RETURN: reverse at the ORIGINAL snapshot cost, bounded by costed quantity ----------
CREATE FUNCTION c10_demo.post_return_cogs_reversal_v1(p_return bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE r c10_demo.operational_returns_v1%ROWTYPE;d c10_demo.operational_documents_v1%ROWTYPE;
 l c10_demo.operational_return_lines_v1%ROWTYPE;e record;v_prior numeric;v_val numeric;
 v_reasons jsonb:='[]'::jsonb;v_total numeric:=0;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_return IS NULL THEN RAISE EXCEPTION 'cost_invalid_request'; END IF;
 SELECT * INTO r FROM c10_demo.operational_returns_v1 WHERE id=p_return FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(r.tenant_id,r.business_id)
 THEN RAISE EXCEPTION 'cost_post_denied'; END IF;
 IF r.kind<>'sale_return' THEN
  RETURN jsonb_build_object('status','blocked','reasons',
   jsonb_build_array(jsonb_build_object('reason','purchase_return_costing_not_supported_v1')));
 END IF;
 IF r.status<>'posted' THEN
  RETURN jsonb_build_object('status','blocked','reasons',
   jsonb_build_array(jsonb_build_object('reason','return_not_posted')));
 END IF;
 SELECT * INTO d FROM c10_demo.operational_documents_v1 WHERE id=r.source_document_id FOR UPDATE;
 FOR l IN SELECT * FROM c10_demo.operational_return_lines_v1 WHERE return_id=p_return ORDER BY item_id LOOP
  PERFORM c10_demo._cost_lock_v1(d.tenant_id,d.business_id,d.site_id,d.location_id,l.item_id);
 END LOOP;
 IF EXISTS(SELECT 1 FROM c10_demo.cost_events_v1 WHERE source_type='operational_return'
    AND source_id=p_return AND event_type='return_reversal') THEN
  RETURN jsonb_build_object('status','already_costed','return_id',p_return);
 END IF;
 FOR l IN SELECT * FROM c10_demo.operational_return_lines_v1 WHERE return_id=p_return ORDER BY line_no LOOP
  SELECT * INTO e FROM c10_demo.cost_events_v1 WHERE source_type='operational_document'
   AND source_id=d.id AND source_line=l.line_no AND event_type='sale_cogs' AND item_id=l.item_id;
  IF NOT FOUND THEN
   v_reasons:=v_reasons||jsonb_build_object('line_no',l.line_no,'reason','original_sale_not_costed');
  ELSE
   SELECT COALESCE(sum(quantity),0) INTO v_prior FROM c10_demo.cost_events_v1
    WHERE event_type='return_reversal' AND source_type='operational_return'
      AND (source_snapshot->>'sale_document_id')::bigint=d.id
      AND (source_snapshot->>'sale_line_no')::integer=l.line_no;
   IF v_prior+l.quantity>abs(e.quantity) THEN
    v_reasons:=v_reasons||jsonb_build_object('line_no',l.line_no,'reason','reversal_exceeds_costed_quantity',
      'costed',abs(e.quantity),'already_reversed',v_prior,'requested',l.quantity);
   END IF;
  END IF;
 END LOOP;
 IF jsonb_array_length(v_reasons)>0 THEN
  RETURN jsonb_build_object('status','blocked','return_id',p_return,'reasons',v_reasons);
 END IF;
 FOR l IN SELECT * FROM c10_demo.operational_return_lines_v1 WHERE return_id=p_return ORDER BY line_no LOOP
  SELECT * INTO e FROM c10_demo.cost_events_v1 WHERE source_type='operational_document'
   AND source_id=d.id AND source_line=l.line_no AND event_type='sale_cogs' AND item_id=l.item_id;
  v_val:=round(l.quantity*e.unit_cost,4);
  PERFORM c10_demo._cost_apply_v1(d.tenant_id,d.business_id,d.site_id,d.location_id,l.item_id,
   'return_reversal',l.quantity,v_val,'operational_return',p_return,l.line_no,
   jsonb_build_object('return_id',p_return,'sale_document_id',d.id,'sale_line_no',l.line_no,
     'original_unit_cost',e.unit_cost,'original_event_id',e.id),
   'c10-cost:return:'||p_return||':'||l.line_no);
  v_total:=v_total+v_val;
 END LOOP;
 RETURN jsonb_build_object('status','costed','return_id',p_return,'reversed_value',v_total);
END $$;

-- 6) RECONCILIATION & REPORTS (security_invoker: owner-only through the table policies) ------
CREATE VIEW c10_demo.cost_valuation_report_v1 WITH(security_invoker=true) AS
 SELECT COALESCE(v.tenant_id,s.tenant_id) AS tenant_id,COALESCE(v.business_id,s.business_id) AS business_id,
  COALESCE(v.site_id,s.site_id) AS site_id,COALESCE(v.location_id,s.location_id) AS location_id,
  COALESCE(v.item_id,s.item_id) AS item_id,
  COALESCE(s.on_hand,0)::numeric(15,3) AS stock_on_hand,
  COALESCE(v.quantity,0)::numeric(15,3) AS costed_quantity,
  (COALESCE(s.on_hand,0)-COALESCE(v.quantity,0))::numeric(15,3) AS uncosted_quantity,
  COALESCE(v.total_value,0)::numeric(20,4) AS inventory_value,
  COALESCE(v.avg_cost,0)::numeric(18,6) AS avg_cost,
  CASE WHEN COALESCE(s.on_hand,0)=COALESCE(v.quantity,0) THEN 'reconciled'
       WHEN COALESCE(s.on_hand,0)>COALESCE(v.quantity,0) THEN 'uncosted_stock'
       ELSE 'costed_exceeds_stock' END AS reconciliation_status
 FROM c10_demo.cost_valuation_v1 v
 FULL JOIN c10_demo.stock_balances_v1 s ON s.location_id=v.location_id AND s.item_id=v.item_id;

CREATE VIEW c10_demo.cost_ledger_integrity_v1 WITH(security_invoker=true) AS
 SELECT v.tenant_id,v.business_id,v.location_id,v.item_id,v.quantity AS valuation_quantity,
  COALESCE(e.q,0)::numeric(15,3) AS journal_quantity,v.total_value AS valuation_value,
  COALESCE(e.v,0)::numeric(20,4) AS journal_value,
  (v.quantity=COALESCE(e.q,0) AND v.total_value=COALESCE(e.v,0)) AS balanced
 FROM c10_demo.cost_valuation_v1 v
 LEFT JOIN (SELECT location_id,item_id,sum(quantity) q,sum(value) v
            FROM c10_demo.cost_events_v1 GROUP BY location_id,item_id) e
  ON e.location_id=v.location_id AND e.item_id=v.item_id;

CREATE VIEW c10_demo.sale_cogs_margin_v1 WITH(security_invoker=true) AS
 SELECT d.tenant_id,d.business_id,d.id AS document_id,d.location_id,d.net_amount AS revenue,
  COALESCE(c.cogs,0)::numeric(20,4) AS cogs,
  CASE WHEN c.n IS NULL THEN NULL ELSE (d.net_amount-c.cogs)::numeric(20,4) END AS gross_margin,
  CASE WHEN c.n IS NULL THEN 'not_costed' ELSE 'costed' END AS cogs_status
 FROM c10_demo.operational_documents_v1 d
 LEFT JOIN (SELECT source_id,sum(-value) cogs,count(*) n FROM c10_demo.cost_events_v1
            WHERE source_type='operational_document' AND event_type='sale_cogs' GROUP BY source_id) c
  ON c.source_id=d.id
 WHERE d.kind='sale' AND d.status='posted';

REVOKE ALL ON c10_demo.cost_valuation_report_v1,c10_demo.cost_ledger_integrity_v1,
 c10_demo.sale_cogs_margin_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.cost_valuation_report_v1,c10_demo.cost_ledger_integrity_v1,
 c10_demo.sale_cogs_margin_v1 TO authenticated;

REVOKE EXECUTE ON FUNCTION c10_demo._cost_apply_v1(bigint,bigint,bigint,bigint,bigint,text,numeric,numeric,text,bigint,integer,jsonb,text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo._cost_lock_v1(bigint,bigint,bigint,bigint,bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo._cost_issue_value_v1(bigint,bigint,numeric) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.cost_events_immutable_v1() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.post_purchase_receipt_cost_v1(bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.post_sale_cogs_v1(bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.post_production_cost_v1(bigint,numeric,numeric,text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.post_transfer_cost_v1(bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.post_return_cogs_reversal_v1(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION c10_demo.post_purchase_receipt_cost_v1(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.post_sale_cogs_v1(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.post_production_cost_v1(bigint,numeric,numeric,text) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.post_transfer_cost_v1(bigint) TO authenticated;

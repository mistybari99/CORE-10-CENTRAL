-- connect: stores a secret REFERENCE only; the account stays OFF.
CREATE FUNCTION c10_demo.integration_connect_v1(p_business bigint,p_provider text,p_secret_ref text,p_public jsonb DEFAULT '{}')
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE b record;pv record;a bigint;
BEGIN
 IF c10_demo.actor_uid() IS NULL THEN RAISE EXCEPTION 'integration_denied'; END IF;
 SELECT tenant_id INTO b FROM c10_demo.businesses WHERE id=p_business;
 IF NOT FOUND OR NOT c10_demo.can_manage(b.tenant_id,p_business) THEN RAISE EXCEPTION 'integration_denied'; END IF;
 SELECT * INTO pv FROM c10_demo.integration_provider_v1 WHERE code=p_provider;
 IF NOT FOUND THEN RAISE EXCEPTION 'integration_unknown_provider'; END IF;
 IF pv.needs_secret AND p_secret_ref IS NULL THEN RAISE EXCEPTION 'integration_secret_ref_required'; END IF;
 INSERT INTO c10_demo.integration_account_v1(tenant_id,business_id,provider_code,status,secret_ref,public_config,created_by)
 VALUES(b.tenant_id,p_business,p_provider,'connected',p_secret_ref,COALESCE(p_public,'{}'),c10_demo.actor_uid())
 ON CONFLICT(business_id,provider_code) DO UPDATE SET status='connected',secret_ref=EXCLUDED.secret_ref,
   public_config=EXCLUDED.public_config,mode='off',last_test_ok_at=NULL,last_test_detail=NULL,updated_at=now()
 RETURNING id INTO a;
 PERFORM c10_demo._integration_audit_v1(b.tenant_id,p_business,a,'connect',NULL,
   jsonb_build_object('provider',p_provider,'secret_ref',p_secret_ref,'mode','off'));
 RETURN a;
END $$;

-- record the result of a provider test (made by the server adapter, reported here)
CREATE FUNCTION c10_demo.integration_record_test_v1(p_account bigint,p_ok boolean,p_detail text DEFAULT NULL)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE a record;
BEGIN
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'integration_denied'; END IF;
 IF a.status='not_connected' THEN RAISE EXCEPTION 'integration_not_connected'; END IF;
 IF p_ok THEN
  UPDATE c10_demo.integration_account_v1 SET status='connected',last_test_ok_at=now(),
    last_test_detail=left(COALESCE(p_detail,'ok'),200),updated_at=now() WHERE id=p_account;
 ELSE
  UPDATE c10_demo.integration_account_v1 SET status='test_failed',mode='off',last_test_ok_at=NULL,
    last_test_detail=left(COALESCE(p_detail,'failed'),200),updated_at=now() WHERE id=p_account;
 END IF;
 PERFORM c10_demo._integration_audit_v1(a.tenant_id,a.business_id,p_account,'test',NULL,
   jsonb_build_object('ok',p_ok));
 RETURN CASE WHEN p_ok THEN 'passed' ELSE 'failed' END;
END $$;

CREATE FUNCTION c10_demo.integration_set_mode_v1(p_account bigint,p_mode text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE a record;
BEGIN
 IF p_mode NOT IN('off','dry_run','live') THEN RAISE EXCEPTION 'integration_invalid_mode'; END IF;
 SELECT * INTO a FROM c10_demo.integration_account_v1 WHERE id=p_account FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(a.tenant_id,a.business_id) THEN RAISE EXCEPTION 'integration_denied'; END IF;
 IF p_mode<>'off' AND a.status<>'connected' THEN RAISE EXCEPTION 'integration_not_connected'; END IF;
 IF p_mode='live' AND (a.last_test_ok_at IS NULL OR a.last_test_ok_at<now()-interval '30 days')
 THEN RAISE EXCEPTION 'integration_live_needs_recent_test'; END IF;
 UPDATE c10_demo.integration_account_v1 SET mode=p_mode,updated_at=now() WHERE id=p_account;
 PERFORM c10_demo._integration_audit_v1(a.tenant_id,a.business_id,p_account,'mode',
   jsonb_build_object('mode',a.mode),jsonb_build_object('mode',p_mode));
 RETURN p_mode;
END $$;


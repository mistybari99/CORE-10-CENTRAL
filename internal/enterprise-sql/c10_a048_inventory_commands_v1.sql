CREATE TABLE c10_demo.inventory_flow_policy_v1 (
 tenant_id bigint NOT NULL,
 business_id bigint PRIMARY KEY,
 allow_staff_issue boolean NOT NULL DEFAULT false,
 allow_staff_transfer boolean NOT NULL DEFAULT false,
 approval_adjustments boolean NOT NULL DEFAULT true CHECK (approval_adjustments=true),
 max_single_quantity numeric(15,3) NOT NULL DEFAULT 100000 CHECK(max_single_quantity>0 AND max_single_quantity<=1000000),
 version bigint NOT NULL DEFAULT 1,
 changed_by uuid NOT NULL,
 changed_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
CREATE TABLE c10_demo.inventory_commands_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 kind text NOT NULL CHECK(kind IN('receive','issue','transfer','adjust_in','adjust_out')),
 source_location bigint,
 destination_location bigint,
 item_id bigint NOT NULL,
 quantity numeric(15,3) NOT NULL CHECK(quantity>0 AND quantity<=1000000 AND quantity=round(quantity,3)),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','confirmed','posted')),
 version bigint NOT NULL DEFAULT 1,
 request_key text NOT NULL CHECK(length(request_key) BETWEEN 8 AND 100),
 created_by uuid NOT NULL,
 confirmed_by uuid,
 posted_by uuid,
 posted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 UNIQUE(id,tenant_id,business_id),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id),
 CHECK (
 (kind='transfer' AND source_location IS NOT NULL AND destination_location IS NOT NULL AND source_location<>destination_location) OR
 (kind IN('receive','adjust_in') AND source_location IS NULL AND destination_location IS NOT NULL) OR
 (kind IN('issue','adjust_out') AND source_location IS NOT NULL AND destination_location IS NULL)),
 CHECK((status='draft' AND confirmed_by IS NULL AND posted_by IS NULL AND posted_at IS NULL)
 OR (status='confirmed' AND confirmed_by IS NOT NULL AND posted_by IS NULL AND posted_at IS NULL)
 OR (status='posted' AND confirmed_by IS NOT NULL AND posted_by IS NOT NULL AND posted_at IS NOT NULL))
);
CREATE TABLE c10_demo.inventory_command_audit_v1 (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 command_id bigint NOT NULL,
 event text NOT NULL CHECK(event IN('created','confirmed','posted','policy_changed')),
 request_key text NOT NULL,
 actor uuid NOT NULL,
 detail jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(command_id,tenant_id,business_id) REFERENCES c10_demo.inventory_commands_v1(id,tenant_id,business_id)
);

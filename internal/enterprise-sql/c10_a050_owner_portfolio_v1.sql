CREATE TABLE c10_demo.portfolio_layout_v1(
 business_id bigint PRIMARY KEY,tenant_id bigint NOT NULL,
 mode text NOT NULL DEFAULT 'detailed' CHECK(mode IN('compact','detailed')),
 sections text[] NOT NULL DEFAULT ARRAY['sites','operations','modules','governance']::text[],
 version bigint NOT NULL DEFAULT 1,
 actor uuid NOT NULL,
 changed_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 CHECK (cardinality(sections) BETWEEN 1 AND 4),
 CHECK (sections <@ ARRAY['sites','operations','modules','governance']::text[])
);
CREATE TABLE c10_demo.portfolio_layout_audit_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,business_id bigint NOT NULL,
 request_key text NOT NULL,actor uuid NOT NULL,
 mode text NOT NULL,sections text[] NOT NULL,
 old_version bigint NOT NULL,new_version bigint NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id)
);
ALTER TABLE c10_demo.portfolio_layout_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.portfolio_layout_audit_v1 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON c10_demo.portfolio_layout_v1,c10_demo.portfolio_layout_audit_v1 FROM PUBLIC,authenticated,anon;
CREATE FUNCTION c10_demo.set_portfolio_layout_v1(
 p_business bigint,p_mode text,p_sections text[],p_version bigint,p_request text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $fn$
DECLARE t bigint; n bigint; previous c10_demo.portfolio_layout_audit_v1%ROWTYPE;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF c10_demo.actor_uid() IS NULL OR t IS NULL OR NOT c10_demo.can_manage(t,p_business)
 THEN RAISE EXCEPTION 'A050_OWNER_REQUIRED'; END IF;
 IF p_mode IS NULL OR p_mode NOT IN('compact','detailed') OR
 p_sections IS NULL OR cardinality(p_sections) NOT BETWEEN 1 AND 4 OR
 NOT p_sections<@ARRAY['sites','operations','modules','governance']::text[] OR
 (SELECT count(DISTINCT x) FROM unnest(p_sections) x)<>cardinality(p_sections) OR
 p_version IS NULL OR p_version<1 OR p_request IS NULL OR
 p_request !~ '^[A-Za-z0-9_-]{8,100}$'
 THEN RAISE EXCEPTION 'A050_BAD_LAYOUT'; END IF;
 SELECT * INTO previous FROM c10_demo.portfolio_layout_audit_v1
 WHERE business_id=p_business AND request_key=p_request;
 IF FOUND THEN
  IF previous.actor<>c10_demo.actor_uid() OR previous.mode<>p_mode OR
    previous.sections<>p_sections OR previous.old_version<>p_version
  THEN RAISE EXCEPTION 'A050_LAYOUT_REPLAY_CONFLICT'; END IF;
  RETURN jsonb_build_object('business_id',p_business,'version',previous.new_version,'replayed',true);
 END IF;
 INSERT INTO c10_demo.portfolio_layout_v1(business_id,tenant_id,actor)
 VALUES(p_business,t,c10_demo.actor_uid()) ON CONFLICT(business_id) DO NOTHING;
 UPDATE c10_demo.portfolio_layout_v1 SET mode=p_mode,sections=p_sections,
  actor=c10_demo.actor_uid(),changed_at=now(),version=version+1
 WHERE business_id=p_business AND version=p_version RETURNING version INTO n;
 IF n IS NULL THEN RAISE EXCEPTION 'A050_STALE_LAYOUT'; END IF;
 INSERT INTO c10_demo.portfolio_layout_audit_v1(tenant_id,business_id,request_key,actor,mode,sections,old_version,new_version)
 VALUES(t,p_business,p_request,c10_demo.actor_uid(),p_mode,p_sections,p_version,n);
 RETURN jsonb_build_object('business_id',p_business,'version',n,'replayed',false);
END; $fn$;
CREATE FUNCTION c10_demo.read_portfolio_workspace_v1()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $fn$
DECLARE rows jsonb;
BEGIN
 IF c10_demo.actor_uid() IS NULL THEN RAISE EXCEPTION 'A050_SIGNED_USER_REQUIRED'; END IF;
 SELECT COALESCE(jsonb_agg(jsonb_build_object(
 'business_id',b.id,'tenant_id',b.tenant_id,'name',COALESCE(cfg.display_name,b.slug),
 'template_code',b.template_code,'business_status',b.status,
 'can_manage',c10_demo.can_manage(b.tenant_id,b.id),
 'sites',(SELECT COALESCE(jsonb_agg(jsonb_build_object(
  'site_id',s.id,'kind',s.kind,'label',s.label,
  'locations',(SELECT COALESCE(jsonb_agg(jsonb_build_object('id',l.id,'code',l.code) ORDER BY l.id),'[]'::jsonb)
    FROM c10_demo.stock_locations l WHERE l.site_id=s.id)) ORDER BY s.id),'[]'::jsonb)
   FROM c10_demo.sites s WHERE s.business_id=b.id AND
   c10_demo.can_site(s.tenant_id,s.business_id,s.id,'stock.read')),
 'modules',(SELECT COALESCE(jsonb_agg(jsonb_build_object(
  'code',m.module_code,'visibility',m.visibility,'operational_enabled',m.operational_enabled)
  ORDER BY m.module_code),'[]'::jsonb)
  FROM c10_demo.business_module_settings_v1 m WHERE m.business_id=b.id
  AND (c10_demo.can_manage(b.tenant_id,b.id) OR m.visibility='show')),
 'operations_count',(SELECT count(*) FROM c10_demo.operation_orders_v1 o
  WHERE o.business_id=b.id AND c10_demo.can_site(o.tenant_id,o.business_id,o.site_id,'stock.read')),
 'layout',jsonb_build_object('mode',COALESCE(pref.mode,'detailed'),
   'sections',COALESCE(to_jsonb(pref.sections),'["sites","operations","modules","governance"]'::jsonb),
   'version',COALESCE(pref.version,1)),
 'runtime',jsonb_build_object('inventory','source_built_isolated','operations','source_built_isolated',
   'production_accounting','not_certified','A045','draft_PR42','A047','draft_PR45')
 ) ORDER BY b.id),'[]'::jsonb) INTO rows
 FROM c10_demo.businesses b
 LEFT JOIN c10_demo.business_configuration_v1 cfg ON cfg.business_id=b.id
 LEFT JOIN c10_demo.portfolio_layout_v1 pref ON pref.business_id=b.id
 WHERE c10_demo.can_see_business(b.tenant_id,b.id);
 RETURN jsonb_build_object('server_authorized',true,'businesses',rows,'production_ready',false,
 'operationally_certified',false);
END; $fn$;
REVOKE EXECUTE ON FUNCTION c10_demo.set_portfolio_layout_v1(bigint,text,text[],bigint,text),
 c10_demo.read_portfolio_workspace_v1() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION c10_demo.set_portfolio_layout_v1(bigint,text,text[],bigint,text),
 c10_demo.read_portfolio_workspace_v1() TO authenticated;

CREATE FUNCTION c10_demo.setup_business_v1(
 p_legal bigint,p_slug text,p_template text,p_display_name text,
 p_mode text,p_sites jsonb,p_request text,p_brand_hex text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;v_business bigint;v_sites jsonb;v_manifest jsonb;
 v_prev record;v_site jsonb;v_kind text;v_label text;v_ix integer:=0;
 v_site_signatures text[]:='{}';v_sig text;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR
    p_slug IS NULL OR length(btrim(p_slug)) NOT BETWEEN 1 AND 80 OR
    p_display_name IS NULL OR length(btrim(p_display_name)) NOT BETWEEN 1 AND 120 OR
    p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120 OR
    p_mode NOT IN('quick','advanced') OR p_mode IS NULL OR
    p_brand_hex IS NULL OR p_brand_hex !~ '^#[A-Fa-f0-9]{6}$' THEN
  RAISE EXCEPTION 'invalid_setup_request';
 END IF;
 SELECT tenant_id INTO v_tenant FROM c10_demo.legal_entities WHERE id=p_legal;
 IF v_tenant IS NULL OR NOT c10_demo.can_tenant(v_tenant) THEN
  RAISE EXCEPTION 'setup_not_authorized';
 END IF;
 IF p_mode='quick' THEN
  IF p_sites IS NOT NULL AND p_sites<>'[]'::jsonb THEN
   RAISE EXCEPTION 'quick_setup_does_not_accept_custom_sites';
  END IF;
  v_sites:='[{"kind":"showroom","label":"Main Showroom"}]'::jsonb;
 ELSE
  IF p_sites IS NULL OR jsonb_typeof(p_sites)<>'array' OR
    jsonb_array_length(p_sites)<1 OR jsonb_array_length(p_sites)>500 THEN
   RAISE EXCEPTION 'invalid_advanced_sites';
  END IF;
  v_sites:=p_sites;
 END IF;
 FOR v_site IN SELECT value FROM jsonb_array_elements(v_sites) LOOP
  v_ix:=v_ix+1;
  IF jsonb_typeof(v_site)<>'object' OR
    (SELECT count(*) FROM jsonb_object_keys(v_site))<>2 THEN
   RAISE EXCEPTION 'invalid_site_manifest';
  END IF;
  v_kind:=v_site->>'kind';
  v_label:=v_site->>'label';
  IF v_kind IS NULL OR v_kind NOT IN ('showroom','factory','godown','warehouse','project') OR
    v_label IS NULL OR length(btrim(v_label)) NOT BETWEEN 1 AND 120 THEN
   RAISE EXCEPTION 'invalid_site_manifest';
  END IF;
  v_sig:=v_kind||':'||lower(btrim(v_label));
  IF v_sig=ANY(v_site_signatures) THEN RAISE EXCEPTION 'duplicate_site_manifest'; END IF;
  v_site_signatures:=array_append(v_site_signatures,v_sig);
 END LOOP;
 v_manifest:=jsonb_build_object('legal',p_legal,'slug',p_slug,
  'template',p_template,'display_name',p_display_name,'mode',p_mode,
  'sites',v_sites,'brand_hex',p_brand_hex);

 SELECT business_id,payload,created_by INTO v_prev
 FROM c10_demo.business_setup_runs_v1
 WHERE tenant_id=v_tenant AND request_key=p_request;
 IF FOUND THEN
  IF v_prev.payload<>v_manifest OR v_prev.created_by<>c10_demo.actor_uid() THEN
   RAISE EXCEPTION 'idempotency_key_payload_conflict';
  END IF;
  RETURN v_prev.business_id;
 END IF;
 -- All rows are in the caller's single database transaction; any bad site
 -- or retry conflict rolls back business, locations, config, modules and run.
 v_business:=c10_demo.provision_business(
   p_legal,p_slug,p_template,'setup:'||p_request);
 INSERT INTO c10_demo.business_configuration_v1(
    business_id,tenant_id,display_name,brand_hex,setup_mode,setup_status,created_by)
 VALUES(v_business,v_tenant,p_display_name,p_brand_hex,p_mode,'draft',c10_demo.actor_uid())
 ON CONFLICT(business_id) DO NOTHING;
 SELECT display_name,brand_hex,setup_mode,created_by INTO v_prev
  FROM c10_demo.business_configuration_v1 WHERE business_id=v_business;
 IF v_prev.display_name<>p_display_name OR v_prev.brand_hex<>p_brand_hex OR
   v_prev.setup_mode<>p_mode OR v_prev.created_by<>c10_demo.actor_uid() THEN
  RAISE EXCEPTION 'business_config_conflict';
 END IF;
 v_ix:=0;
 FOR v_site IN SELECT value FROM jsonb_array_elements(v_sites) LOOP
  v_ix:=v_ix+1;
  PERFORM c10_demo.provision_site(v_business,v_site->>'kind',v_site->>'label',
    'setup:'||p_request||':site:'||lpad(v_ix::text,4,'0'));
 END LOOP;
 INSERT INTO c10_demo.business_module_settings_v1(
    tenant_id,business_id,module_code,visibility,operational_enabled)
 SELECT v_tenant,v_business,tm.module_code,'locked',false
 FROM c10_demo.template_modules_v1 tm WHERE tm.template_code=p_template
 ON CONFLICT(business_id,module_code) DO NOTHING;
 INSERT INTO c10_demo.business_setup_runs_v1(
    tenant_id,business_id,request_key,payload,created_by)
 VALUES(v_tenant,v_business,p_request,v_manifest,c10_demo.actor_uid())
 ON CONFLICT(tenant_id,request_key) DO NOTHING;
 SELECT business_id,payload,created_by INTO v_prev FROM c10_demo.business_setup_runs_v1
 WHERE tenant_id=v_tenant AND request_key=p_request;
 IF v_prev.business_id<>v_business OR v_prev.payload<>v_manifest OR
   v_prev.created_by<>c10_demo.actor_uid() THEN
  RAISE EXCEPTION 'idempotency_key_payload_conflict';
 END IF;
 RETURN v_business;
END $$;

CREATE VIEW c10_demo.business_setup_overview_v1 WITH(security_invoker=true) AS
 SELECT b.tenant_id,b.id AS business_id,b.slug,b.status,
  c.display_name,c.brand_hex,c.setup_mode,c.setup_status,
  (SELECT count(*) FROM c10_demo.sites s WHERE s.business_id=b.id) AS visible_sites,
  (SELECT count(*) FROM c10_demo.business_module_settings_v1 m
   WHERE m.business_id=b.id) AS visible_modules
 FROM c10_demo.businesses b
 JOIN c10_demo.business_configuration_v1 c ON c.business_id=b.id;

REVOKE EXECUTE ON FUNCTION c10_demo.setup_business_v1(

CREATE TABLE c10_demo.stock_balances_v1(
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 location_id bigint NOT NULL,
 item_id bigint NOT NULL,
 on_hand numeric(15,3) NOT NULL DEFAULT 0
  CHECK(on_hand>=0 AND on_hand::text NOT IN ('NaN','Infinity','-Infinity')),
 PRIMARY KEY(location_id,item_id),
 FOREIGN KEY(location_id,tenant_id,business_id,site_id)
  REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 FOREIGN KEY(item_id,tenant_id,business_id)
  REFERENCES c10_demo.items(id,tenant_id,business_id)
);

CREATE TABLE c10_demo.stock_transfers_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 source_site_id bigint NOT NULL,
 source_location_id bigint NOT NULL,
 destination_site_id bigint NOT NULL,
 destination_location_id bigint NOT NULL,
 item_id bigint NOT NULL,
 quantity numeric(15,3) NOT NULL
  CHECK(quantity>0 AND quantity::text NOT IN ('NaN','Infinity','-Infinity')),
 request_key text NOT NULL CHECK(length(btrim(request_key))>0),
 created_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(tenant_id,business_id,request_key),
 CHECK(source_location_id<>destination_location_id),
 FOREIGN KEY(source_location_id,tenant_id,business_id,source_site_id)
  REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 FOREIGN KEY(destination_location_id,tenant_id,business_id,destination_site_id)
  REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 FOREIGN KEY(item_id,tenant_id,business_id)
  REFERENCES c10_demo.items(id,tenant_id,business_id)
);


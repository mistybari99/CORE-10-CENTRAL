CREATE FUNCTION c10_demo.inventory_action_authorized_v1(p_tenant bigint,p_business bigint,p_location bigint,p_action text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
 SELECT c10_demo.actor_uid() IS NOT NULL AND (
 c10_demo.can_manage(p_tenant,p_business) OR EXISTS (
 SELECT 1 FROM c10_demo.stock_locations l JOIN c10_demo.site_grants g
 ON g.tenant_id=l.tenant_id AND g.business_id=l.business_id AND g.site_id=l.site_id
 WHERE l.id=p_location AND l.tenant_id=p_tenant AND l.business_id=p_business
 AND g.user_id=c10_demo.actor_uid() AND g.active AND p_action=ANY(g.actions)))
$$;
CREATE FUNCTION c10_demo.configure_inventory_flow_v1(
 p_business bigint,p_staff_issue boolean,p_staff_transfer boolean,p_max numeric,p_version bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint; v bigint;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF t IS NULL OR NOT c10_demo.can_manage(t,p_business) THEN RAISE EXCEPTION 'A048_OWNER_REQUIRED'; END IF;
 IF p_staff_issue IS NULL OR p_staff_transfer IS NULL OR p_max IS NULL OR
   p_max<1 OR p_max>1000000 OR p_max<>round(p_max,3) OR p_version IS NULL OR p_version<0
 THEN RAISE EXCEPTION 'A048_INVALID_POLICY'; END IF;
 INSERT INTO c10_demo.inventory_flow_policy_v1(tenant_id,business_id,changed_by)
 VALUES(t,p_business,c10_demo.actor_uid()) ON CONFLICT(business_id) DO NOTHING;
 UPDATE c10_demo.inventory_flow_policy_v1
 SET allow_staff_issue=p_staff_issue,allow_staff_transfer=p_staff_transfer,
 max_single_quantity=p_max,version=version+1,changed_by=c10_demo.actor_uid(),changed_at=now()
 WHERE business_id=p_business AND version=p_version+1 RETURNING version INTO v;
 IF v IS NULL THEN RAISE EXCEPTION 'A048_POLICY_STALE'; END IF;
 RETURN jsonb_build_object('business_id',p_business,'version',v);
END $$;

CREATE FUNCTION c10_demo.create_inventory_command_v1(
 p_business bigint,p_kind text,p_source bigint,p_destination bigint,
 p_item bigint,p_quantity numeric,p_request text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint; c c10_demo.inventory_commands_v1%ROWTYPE; p c10_demo.inventory_flow_policy_v1%ROWTYPE;
 sl c10_demo.stock_locations%ROWTYPE; dl c10_demo.stock_locations%ROWTYPE;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF c10_demo.actor_uid() IS NULL OR t IS NULL OR p_kind IS NULL OR
  p_kind NOT IN('receive','issue','transfer','adjust_in','adjust_out') OR
  p_quantity IS NULL OR p_quantity<=0 OR p_quantity>1000000 OR p_quantity<>round(p_quantity,3)
  OR p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,100}$'
 THEN RAISE EXCEPTION 'A048_INVALID_COMMAND'; END IF;
 SELECT * INTO sl FROM c10_demo.stock_locations WHERE id=p_source;
 SELECT * INTO dl FROM c10_demo.stock_locations WHERE id=p_destination;
 IF (p_kind='transfer' AND (p_source IS NULL OR p_destination IS NULL OR p_source=p_destination)) OR
    (p_kind IN('receive','adjust_in') AND (p_source IS NOT NULL OR p_destination IS NULL)) OR
    (p_kind IN('issue','adjust_out') AND (p_source IS NULL OR p_destination IS NOT NULL))
 THEN RAISE EXCEPTION 'A048_LOCATION_SHAPE'; END IF;
 IF (p_source IS NOT NULL AND (sl.tenant_id<>t OR sl.business_id<>p_business)) OR
    (p_destination IS NOT NULL AND (dl.tenant_id<>t OR dl.business_id<>p_business))
 THEN RAISE EXCEPTION 'A048_CROSS_SCOPE_LOCATION'; END IF;
 IF NOT EXISTS(SELECT 1 FROM c10_demo.items WHERE id=p_item AND tenant_id=t AND business_id=p_business)
 THEN RAISE EXCEPTION 'A048_ITEM_SCOPE'; END IF;
 INSERT INTO c10_demo.inventory_flow_policy_v1(tenant_id,business_id,changed_by)
 VALUES(t,p_business,c10_demo.actor_uid()) ON CONFLICT(business_id) DO NOTHING;
 SELECT * INTO p FROM c10_demo.inventory_flow_policy_v1 WHERE business_id=p_business;
 IF p_quantity>p.max_single_quantity THEN RAISE EXCEPTION 'A048_QUANTITY_LIMIT'; END IF;
 IF NOT c10_demo.can_manage(t,p_business) THEN
  IF p_kind IN('adjust_in','adjust_out') OR
    (p_kind='issue' AND NOT p.allow_staff_issue) OR
    (p_kind='transfer' AND NOT p.allow_staff_transfer) OR
    (p_source IS NOT NULL AND NOT c10_demo.inventory_action_authorized_v1(t,p_business,p_source,'stock.post')) OR
    (p_destination IS NOT NULL AND NOT c10_demo.inventory_action_authorized_v1(t,p_business,p_destination,'stock.post'))
  THEN RAISE EXCEPTION 'A048_PERMISSION_DENIED'; END IF;
 END IF;
 INSERT INTO c10_demo.inventory_commands_v1(
 tenant_id,business_id,kind,source_location,destination_location,item_id,quantity,request_key,created_by)
 VALUES(t,p_business,p_kind,p_source,p_destination,p_item,p_quantity,p_request,c10_demo.actor_uid())
 ON CONFLICT (business_id,request_key) DO NOTHING;
 SELECT * INTO c FROM c10_demo.inventory_commands_v1 WHERE business_id=p_business AND request_key=p_request;
 IF c.kind<>p_kind OR c.source_location IS DISTINCT FROM p_source OR
    c.destination_location IS DISTINCT FROM p_destination OR c.item_id<>p_item OR
    c.quantity<>p_quantity OR c.created_by<>c10_demo.actor_uid()
 THEN RAISE EXCEPTION 'A048_REPLAY_CONFLICT'; END IF;
 INSERT INTO c10_demo.inventory_command_audit_v1(tenant_id,business_id,command_id,event,request_key,actor)
 VALUES(t,p_business,c.id,'created','create-'||p_request,c10_demo.actor_uid())
 ON CONFLICT(business_id,request_key) DO NOTHING;
 RETURN jsonb_build_object('command_id',c.id,'business_id',p_business,'status',c.status,'version',c.version);
END $$;

CREATE FUNCTION c10_demo.advance_inventory_command_v1(
 p_command bigint,p_action text,p_version bigint,p_request text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE c c10_demo.inventory_commands_v1%ROWTYPE; p c10_demo.inventory_flow_policy_v1%ROWTYPE;
 existing c10_demo.inventory_command_audit_v1%ROWTYPE; t bigint; posted_id bigint;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_action IS NULL OR p_action NOT IN('confirm','post') OR
  p_version IS NULL OR p_version<1 OR p_request IS NULL OR p_request !~ '^[A-Za-z0-9_-]{8,100}$'
 THEN RAISE EXCEPTION 'A048_INVALID_ACTION'; END IF;
 SELECT * INTO c FROM c10_demo.inventory_commands_v1 WHERE id=p_command FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'A048_NOT_FOUND'; END IF;
 t:=c.tenant_id;
 IF NOT c10_demo.can_manage(t,c.business_id) AND (
    (c.kind IN('adjust_in','adjust_out')) OR
    NOT (SELECT CASE WHEN c.kind='issue' THEN allow_staff_issue
                      WHEN c.kind='transfer' THEN allow_staff_transfer
                      ELSE true END FROM c10_demo.inventory_flow_policy_v1 WHERE business_id=c.business_id)
    OR (c.source_location IS NOT NULL AND NOT c10_demo.inventory_action_authorized_v1(t,c.business_id,c.source_location,'stock.post'))
    OR (c.destination_location IS NOT NULL AND NOT c10_demo.inventory_action_authorized_v1(t,c.business_id,c.destination_location,'stock.post'))
 ) THEN RAISE EXCEPTION 'A048_PERMISSION_DENIED'; END IF;
 SELECT * INTO existing FROM c10_demo.inventory_command_audit_v1
 WHERE business_id=c.business_id AND request_key='advance-'||p_request;
 IF FOUND THEN
  IF existing.command_id<>p_command OR existing.event<>CASE WHEN p_action='confirm' THEN 'confirmed' ELSE 'posted' END OR
  existing.actor<>c10_demo.actor_uid() OR (existing.detail->>'expected_version')::bigint<>p_version
  THEN RAISE EXCEPTION 'A048_ADVANCE_REPLAY_CONFLICT'; END IF;
  RETURN jsonb_build_object('command_id',c.id,'status',c.status,'version',c.version,'replayed',true);
 END IF;
 IF c.version<>p_version THEN RAISE EXCEPTION 'A048_STALE_VERSION'; END IF;
 IF p_action='confirm' THEN
  IF c.status<>'draft' THEN RAISE EXCEPTION 'A048_INVALID_TRANSITION'; END IF;
  UPDATE c10_demo.inventory_commands_v1
   SET status='confirmed',confirmed_by=c10_demo.actor_uid(),version=version+1 WHERE id=c.id;
 ELSE
  IF c.status<>'confirmed' THEN RAISE EXCEPTION 'A048_CONFIRM_FIRST'; END IF;
  IF c.kind='transfer' THEN
   posted_id:=c10_demo.transfer_stock_v1(c.source_location,c.destination_location,c.item_id,c.quantity,'a048-'||c.id);
  ELSE
   posted_id:=c10_demo.post_stock_event(COALESCE(c.source_location,c.destination_location),c.item_id,
    CASE WHEN c.kind IN('receive','adjust_in') THEN c.quantity ELSE -c.quantity END,'a048-'||c.id);
  END IF;
  UPDATE c10_demo.inventory_commands_v1 SET status='posted',posted_by=c10_demo.actor_uid(),
   posted_at=now(),version=version+1 WHERE id=c.id;
 END IF;
 INSERT INTO c10_demo.inventory_command_audit_v1(
 tenant_id,business_id,command_id,event,request_key,actor,detail)
 VALUES(t,c.business_id,c.id,CASE WHEN p_action='confirm' THEN 'confirmed' ELSE 'posted' END,
 'advance-'||p_request,c10_demo.actor_uid(),
 jsonb_build_object('expected_version',p_version,'stock_ref',posted_id));
 RETURN jsonb_build_object('command_id',c.id,'status',CASE WHEN p_action='confirm' THEN 'confirmed' ELSE 'posted' END,
  'version',c.version+1,'stock_ref',posted_id,'replayed',false);
END $$;

CREATE FUNCTION c10_demo.read_inventory_commands_v1(p_business bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE t bigint; items jsonb;
BEGIN
 SELECT tenant_id INTO t FROM c10_demo.businesses WHERE id=p_business;
 IF t IS NULL OR NOT c10_demo.can_see_business(t,p_business) THEN RAISE EXCEPTION 'A048_READ_DENIED'; END IF;
 SELECT COALESCE(jsonb_agg(to_jsonb(c) ORDER BY c.id DESC),'[]'::jsonb) INTO items
 FROM c10_demo.inventory_commands_v1 c WHERE c.business_id=p_business AND
 (c10_demo.can_manage(t,p_business) OR (
 (c.source_location IS NULL OR EXISTS(SELECT 1 FROM c10_demo.stock_locations l
 WHERE l.id=c.source_location AND c10_demo.can_site(t,p_business,l.site_id,'stock.read'))) AND
 (c.destination_location IS NULL OR EXISTS(SELECT 1 FROM c10_demo.stock_locations l
 WHERE l.id=c.destination_location AND c10_demo.can_site(t,p_business,l.site_id,'stock.read')))));
 RETURN jsonb_build_object('business_id',p_business,'server_authorized',true,'items',items,'operationally_certified',false);
END $$;


CREATE TABLE c10_demo.integration_account_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 provider_code text NOT NULL REFERENCES c10_demo.integration_provider_v1(code),
 mode text NOT NULL DEFAULT 'off' CHECK(mode IN('off','dry_run','live')),
 status text NOT NULL DEFAULT 'not_connected'
   CHECK(status IN('not_connected','connected','test_failed','suspended','expired')),
 secret_ref text CHECK(secret_ref IS NULL OR secret_ref ~ '^[a-z0-9_]{3,80}$'),
 public_config jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(public_config)='object'),
 daily_cap integer NOT NULL DEFAULT 200 CHECK(daily_cap BETWEEN 0 AND 100000),
 quiet_start_hour smallint NOT NULL DEFAULT 22 CHECK(quiet_start_hour BETWEEN 0 AND 23),
 quiet_end_hour smallint NOT NULL DEFAULT 8 CHECK(quiet_end_hour BETWEEN 0 AND 23),
 last_test_ok_at timestamptz,
 last_test_detail text,
 created_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,provider_code),
 UNIQUE(id,tenant_id,business_id),
 -- a non-off port must be connected; live also needs a passed test
 CHECK(mode='off' OR status='connected'),
 CHECK(mode<>'live' OR last_test_ok_at IS NOT NULL),
 -- no secret-looking key may live in public_config (values are never stored anywhere in the DB)
 CHECK(NOT (public_config::text ~* '"[^"]*(secret|token|password|passwd|api_?key|private)[^"]*"\s*:'))
);


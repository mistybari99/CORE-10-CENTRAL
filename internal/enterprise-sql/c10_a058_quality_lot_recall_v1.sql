 VALUES (p_tenant,p_business,p_loc,p_item,p_key,p_delta,c10_demo.actor_uid());
END $$;

CREATE FUNCTION c10_demo.quality_enable_item_v1(p_business bigint,p_item bigint)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;
BEGIN
 SELECT tenant_id INTO v_tenant FROM c10_demo.businesses WHERE id=p_business;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_tenant,p_business)
 THEN RAISE EXCEPTION 'quality_owner_required'; END IF;
 IF NOT EXISTS (SELECT 1 FROM c10_demo.items WHERE id=p_item AND tenant_id=v_tenant AND business_id=p_business)
 THEN RAISE EXCEPTION 'quality_item_scope_mismatch'; END IF;
 -- An already tracked SKU can be enrolled again without changing its traceability policy.
 IF EXISTS(SELECT 1 FROM c10_demo.quality_tracked_items_v1 WHERE business_id=p_business AND item_id=p_item)
 THEN RETURN true; END IF;
 -- Never silently re-label old non-lot events as traceable even if historic stock nets to zero.
 IF EXISTS(SELECT 1 FROM c10_demo.stock_movements WHERE business_id=p_business AND item_id=p_item)
  OR EXISTS(SELECT 1 FROM c10_demo.stock_balances_v1 WHERE business_id=p_business
   AND item_id=p_item AND on_hand<>0)
 THEN RAISE EXCEPTION 'quality_existing_stock_requires_backfill'; END IF;
 INSERT INTO c10_demo.quality_tracked_items_v1(tenant_id,business_id,item_id,enabled_by)
 VALUES(v_tenant,p_business,p_item,c10_demo.actor_uid())
 ON CONFLICT (business_id,item_id) DO NOTHING;
 RETURN true;
END $$;

CREATE FUNCTION c10_demo.quality_register_lot_v1(
 p_business bigint,p_item bigint,p_origin_site bigint,p_code text,p_source text,
 p_reference text,p_made date,p_expiry date,p_key text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;v_cmd bigint;v_lot bigint;v_payload jsonb;
BEGIN
 IF p_code IS NULL OR length(btrim(p_code)) NOT BETWEEN 2 AND 80 OR
  p_source IS NULL OR p_source NOT IN('purchase','production','opening','return','adjustment') OR
  p_reference IS NULL OR length(btrim(p_reference)) NOT BETWEEN 2 AND 120 OR
  (p_made IS NOT NULL AND p_expiry IS NOT NULL AND p_expiry<p_made)
 THEN RAISE EXCEPTION 'quality_invalid_lot'; END IF;
 SELECT tenant_id INTO v_tenant FROM c10_demo.businesses WHERE id=p_business;
 IF NOT FOUND OR NOT c10_demo.can_site(v_tenant,p_business,p_origin_site,'stock.post')
 THEN RAISE EXCEPTION 'quality_register_denied'; END IF;
 IF NOT EXISTS(SELECT 1 FROM c10_demo.quality_tracked_items_v1
   WHERE tenant_id=v_tenant AND business_id=p_business AND item_id=p_item)
 THEN RAISE EXCEPTION 'quality_item_not_tracked'; END IF;
 v_payload:=jsonb_build_object('item',p_item,'site',p_origin_site,'code',p_code,
  'source',p_source,'ref',p_reference,'made',p_made,'expiry',p_expiry);
 v_cmd:=c10_demo.quality_claim_v1(v_tenant,p_business,'register',p_key,v_payload);
 IF v_cmd<0 THEN SELECT result_id INTO v_lot FROM c10_demo.quality_commands_v1 WHERE id=-v_cmd; RETURN v_lot; END IF;
 INSERT INTO c10_demo.quality_lots_v1
 (tenant_id,business_id,item_id,origin_site_id,lot_code,source_kind,source_reference,
  manufacture_date,expiry_date,created_by)
 VALUES(v_tenant,p_business,p_item,p_origin_site,p_code,p_source,p_reference,p_made,p_expiry,c10_demo.actor_uid())
 RETURNING id INTO v_lot;
 UPDATE c10_demo.quality_commands_v1 SET result_id=v_lot WHERE id=v_cmd;
 INSERT INTO c10_demo.quality_audit_v1(tenant_id,business_id,lot_id,operation,command_id,actor_id)
 VALUES(v_tenant,p_business,v_lot,'register',v_cmd,c10_demo.actor_uid());
 RETURN v_lot;
END $$;

CREATE FUNCTION c10_demo.quality_inspect_v1(
 p_lot bigint,p_result text,p_checks jsonb,p_notes text,p_key text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_lot record;v_cmd bigint;v_id bigint;v_check jsonb;
BEGIN
 SELECT * INTO v_lot FROM c10_demo.quality_lots_v1 WHERE id=p_lot FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_business(v_lot.tenant_id,v_lot.business_id)
 THEN RAISE EXCEPTION 'quality_inspect_denied'; END IF;
 IF p_result NOT IN('pass','fail') OR p_checks IS NULL OR jsonb_typeof(p_checks)<>'array'
  OR jsonb_array_length(p_checks) NOT BETWEEN 1 AND 30 OR p_notes IS NULL OR length(p_notes)>1000
 THEN RAISE EXCEPTION 'quality_invalid_inspection'; END IF;
 FOR v_check IN SELECT value FROM jsonb_array_elements(p_checks) LOOP
  IF jsonb_typeof(v_check)<>'object' OR jsonb_typeof(v_check->'code')<>'string'
   OR length(btrim(v_check->>'code')) NOT BETWEEN 1 AND 60
   OR jsonb_typeof(v_check->'ok')<>'boolean'
  THEN RAISE EXCEPTION 'quality_invalid_inspection_check'; END IF;
  IF p_result='pass' AND (v_check->>'ok')::boolean IS NOT TRUE
  THEN RAISE EXCEPTION 'quality_false_pass'; END IF;
 END LOOP;
 v_cmd:=c10_demo.quality_claim_v1(v_lot.tenant_id,v_lot.business_id,'inspect',p_key,
  jsonb_build_object('lot',p_lot,'result',p_result,'checks',p_checks,'notes',p_notes));
 IF v_cmd<0 THEN SELECT result_id INTO v_id FROM c10_demo.quality_commands_v1 WHERE id=-v_cmd; RETURN v_id; END IF;
 INSERT INTO c10_demo.quality_inspections_v1(tenant_id,business_id,lot_id,result,checks,notes,inspected_by)
 VALUES(v_lot.tenant_id,v_lot.business_id,p_lot,p_result,p_checks,p_notes,c10_demo.actor_uid()) RETURNING id INTO v_id;
 UPDATE c10_demo.quality_commands_v1 SET result_id=v_id WHERE id=v_cmd;
 INSERT INTO c10_demo.quality_audit_v1(tenant_id,business_id,lot_id,operation,command_id,actor_id,context)
 VALUES(v_lot.tenant_id,v_lot.business_id,p_lot,'inspect',v_cmd,c10_demo.actor_uid(),
  jsonb_build_object('result',p_result));
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.quality_decide_lot_v1(p_lot bigint,p_decision text,p_reason text,p_key text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_lot record;v_cmd bigint;v_review record;
BEGIN
 SELECT * INTO v_lot FROM c10_demo.quality_lots_v1 WHERE id=p_lot FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_lot.tenant_id,v_lot.business_id)
 THEN RAISE EXCEPTION 'quality_manager_decision_denied'; END IF;
 IF p_decision NOT IN('release','hold','reject') OR p_reason IS NULL OR length(btrim(p_reason))<3
  OR length(p_reason)>1000 THEN RAISE EXCEPTION 'quality_invalid_decision'; END IF;
 v_cmd:=c10_demo.quality_claim_v1(v_lot.tenant_id,v_lot.business_id,'decide',p_key,
  jsonb_build_object('lot',p_lot,'action',p_decision,'reason',p_reason));
 IF v_cmd<0 THEN RETURN p_lot; END IF;
 IF v_lot.status='recalled' OR (v_lot.status='rejected' AND p_decision='release')
 THEN RAISE EXCEPTION 'quality_terminal_lot'; END IF;
 IF p_decision='release' THEN
  IF v_lot.expiry_date IS NOT NULL AND v_lot.expiry_date<CURRENT_DATE
  THEN RAISE EXCEPTION 'quality_expired_lot'; END IF;
  IF v_lot.status='released' THEN RAISE EXCEPTION 'quality_already_released'; END IF;
  SELECT * INTO v_review FROM c10_demo.quality_inspections_v1
   WHERE lot_id=p_lot ORDER BY id DESC LIMIT 1;
  IF NOT FOUND OR v_review.result<>'pass' OR
   (v_lot.released_inspection_id IS NOT NULL AND v_review.id<=v_lot.released_inspection_id)
  THEN RAISE EXCEPTION 'quality_fresh_passing_inspection_required'; END IF;
  UPDATE c10_demo.quality_lots_v1 SET status='released',released_inspection_id=v_review.id,
   updated_at=clock_timestamp() WHERE id=p_lot;
 ELSE
  UPDATE c10_demo.quality_lots_v1 SET status=CASE WHEN p_decision='hold' THEN 'held' ELSE 'rejected' END,
   updated_at=clock_timestamp() WHERE id=p_lot;
 END IF;
 UPDATE c10_demo.quality_commands_v1 SET result_id=p_lot WHERE id=v_cmd;
 INSERT INTO c10_demo.quality_audit_v1(tenant_id,business_id,lot_id,operation,command_id,actor_id,context)
 VALUES(v_lot.tenant_id,v_lot.business_id,p_lot,p_decision,v_cmd,c10_demo.actor_uid(),
 jsonb_build_object('reason',p_reason));
 RETURN p_lot;
END $$;

CREATE FUNCTION c10_demo.quality_stock_v1(
 p_lot bigint,p_location bigint,p_quantity numeric,p_kind text,p_reason text,p_key text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_lot record;v_loc record;v_cmd bigint;v_stock bigint;v_id bigint;v_delta numeric;v_balance numeric;
 v_stock_key text;v_payload jsonb;
BEGIN
 IF p_quantity IS NULL OR p_quantity<=0 OR p_quantity>1000000 OR p_quantity<>round(p_quantity,3)
 OR p_quantity::text IN ('NaN','Infinity','-Infinity')
 OR p_kind NOT IN('receipt','issue','disposal') OR p_reason IS NULL OR
 length(btrim(p_reason)) NOT BETWEEN 3 AND 200 THEN RAISE EXCEPTION 'quality_invalid_stock_operation'; END IF;
 SELECT * INTO v_lot FROM c10_demo.quality_lots_v1 WHERE id=p_lot FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'quality_lot_missing'; END IF;
 SELECT * INTO v_loc FROM c10_demo.stock_locations WHERE id=p_location;
 IF NOT FOUND OR v_loc.tenant_id<>v_lot.tenant_id OR v_loc.business_id<>v_lot.business_id OR
  NOT c10_demo.can_site(v_loc.tenant_id,v_loc.business_id,v_loc.site_id,'stock.post')
 THEN RAISE EXCEPTION 'quality_stock_scope_denied'; END IF;
 IF p_kind='disposal' AND NOT c10_demo.can_manage(v_lot.tenant_id,v_lot.business_id)
 THEN RAISE EXCEPTION 'quality_disposal_owner_required'; END IF;
 IF p_kind='issue' AND (v_lot.status<>'released' OR
   (v_lot.expiry_date IS NOT NULL AND v_lot.expiry_date<CURRENT_DATE))
 THEN RAISE EXCEPTION 'quality_lot_not_sellable'; END IF;
 IF p_kind='disposal' AND v_lot.status NOT IN ('rejected','recalled','held','pending_qc')
   AND NOT (v_lot.expiry_date IS NOT NULL AND v_lot.expiry_date<CURRENT_DATE)
 THEN RAISE EXCEPTION 'quality_disposal_requires_hold'; END IF;
 v_delta:=CASE WHEN p_kind='receipt' THEN p_quantity ELSE -p_quantity END;
 v_payload:=jsonb_build_object('lot',p_lot,'location',p_location,'qty',p_quantity,
  'kind',p_kind,'reason',p_reason);
 v_cmd:=c10_demo.quality_claim_v1(v_lot.tenant_id,v_lot.business_id,p_kind,p_key,v_payload);
 IF v_cmd<0 THEN SELECT result_id INTO v_id FROM c10_demo.quality_commands_v1 WHERE id=-v_cmd; RETURN v_id; END IF;
 INSERT INTO c10_demo.quality_balances_v1
 (tenant_id,business_id,site_id,location_id,item_id,lot_id,on_hand)
 VALUES (v_lot.tenant_id,v_lot.business_id,v_loc.site_id,p_location,v_lot.item_id,p_lot,0)
 ON CONFLICT(location_id,lot_id) DO NOTHING;
 SELECT on_hand INTO v_balance FROM c10_demo.quality_balances_v1
 WHERE location_id=p_location AND lot_id=p_lot FOR UPDATE;
 IF v_balance+v_delta<0 THEN RAISE EXCEPTION 'quality_insufficient_lot_stock'; END IF;
 v_stock_key:='c10-quality:'||v_cmd||':stock';
 PERFORM c10_demo.quality_permit_v1(p_location,v_lot.item_id,v_lot.tenant_id,v_lot.business_id,v_delta,v_stock_key);
 v_stock:=c10_demo.post_stock_event(p_location,v_lot.item_id,v_delta,v_stock_key);
 UPDATE c10_demo.quality_balances_v1 SET on_hand=on_hand+v_delta WHERE location_id=p_location AND lot_id=p_lot;
 INSERT INTO c10_demo.quality_movements_v1
 (tenant_id,business_id,site_id,location_id,item_id,lot_id,command_id,stock_movement_id,kind,delta,actor_id)
 VALUES(v_lot.tenant_id,v_lot.business_id,v_loc.site_id,p_location,v_lot.item_id,p_lot,
 v_cmd,v_stock,p_kind,v_delta,c10_demo.actor_uid()) RETURNING id INTO v_id;
 UPDATE c10_demo.quality_commands_v1 SET result_id=v_id WHERE id=v_cmd;
 INSERT INTO c10_demo.quality_audit_v1(tenant_id,business_id,lot_id,operation,command_id,actor_id,context)
 VALUES(v_lot.tenant_id,v_lot.business_id,p_lot,p_kind,v_cmd,c10_demo.actor_uid(),
  jsonb_build_object('quantity',p_quantity,'reason',p_reason,'location',p_location));
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.quality_transfer_v1(
 p_lot bigint,p_source bigint,p_destination bigint,p_quantity numeric,p_key text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_lot record;v_src record;v_dst record;v_cmd bigint;v_id bigint;v_stock bigint;v_balance numeric;v_key text;
BEGIN
 IF p_source=p_destination OR p_quantity IS NULL OR p_quantity<=0 OR p_quantity>1000000 OR
 p_quantity<>round(p_quantity,3) OR p_quantity::text IN('NaN','Infinity','-Infinity')
 THEN RAISE EXCEPTION 'quality_invalid_transfer'; END IF;
 SELECT * INTO v_lot FROM c10_demo.quality_lots_v1 WHERE id=p_lot FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'quality_lot_missing'; END IF;
 SELECT * INTO v_src FROM c10_demo.stock_locations WHERE id=p_source;
 SELECT * INTO v_dst FROM c10_demo.stock_locations WHERE id=p_destination;
 IF v_src.tenant_id IS DISTINCT FROM v_lot.tenant_id OR v_dst.tenant_id IS DISTINCT FROM v_lot.tenant_id
 OR v_src.business_id IS DISTINCT FROM v_lot.business_id OR v_dst.business_id IS DISTINCT FROM v_lot.business_id
 OR NOT c10_demo.can_site(v_lot.tenant_id,v_lot.business_id,v_src.site_id,'stock.post')
 OR NOT c10_demo.can_site(v_lot.tenant_id,v_lot.business_id,v_dst.site_id,'stock.post')
 THEN RAISE EXCEPTION 'quality_transfer_scope_denied'; END IF;
 -- Quarantine can be relocated by a business manager; released stock by scoped operators.
 IF v_lot.status<>'released' AND NOT c10_demo.can_manage(v_lot.tenant_id,v_lot.business_id)
 THEN RAISE EXCEPTION 'quality_quarantine_transfer_manager_required'; END IF;
 v_cmd:=c10_demo.quality_claim_v1(v_lot.tenant_id,v_lot.business_id,'transfer',p_key,
 jsonb_build_object('lot',p_lot,'source',p_source,'dest',p_destination,'qty',p_quantity));
 IF v_cmd<0 THEN SELECT result_id INTO v_id FROM c10_demo.quality_commands_v1 WHERE id=-v_cmd; RETURN v_id; END IF;
 INSERT INTO c10_demo.quality_balances_v1
 (tenant_id,business_id,site_id,location_id,item_id,lot_id,on_hand)
 VALUES(v_lot.tenant_id,v_lot.business_id,v_dst.site_id,p_destination,v_lot.item_id,p_lot,0)
 ON CONFLICT(location_id,lot_id) DO NOTHING;
 SELECT on_hand INTO v_balance FROM c10_demo.quality_balances_v1
 WHERE location_id=p_source AND lot_id=p_lot FOR UPDATE;
 IF v_balance IS NULL OR v_balance<p_quantity THEN RAISE EXCEPTION 'quality_insufficient_lot_stock'; END IF;
 v_key:='c10-quality:'||v_cmd||':out';
 PERFORM c10_demo.quality_permit_v1(p_source,v_lot.item_id,v_lot.tenant_id,v_lot.business_id,-p_quantity,v_key);
 v_stock:=c10_demo.post_stock_event(p_source,v_lot.item_id,-p_quantity,v_key);
 INSERT INTO c10_demo.quality_movements_v1
 (tenant_id,business_id,site_id,location_id,item_id,lot_id,command_id,stock_movement_id,kind,delta,actor_id)
 VALUES(v_lot.tenant_id,v_lot.business_id,v_src.site_id,p_source,v_lot.item_id,p_lot,
 v_cmd,v_stock,'transfer_out',-p_quantity,c10_demo.actor_uid()) RETURNING id INTO v_id;
 v_key:='c10-quality:'||v_cmd||':in';
 PERFORM c10_demo.quality_permit_v1(p_destination,v_lot.item_id,v_lot.tenant_id,v_lot.business_id,p_quantity,v_key);
 v_stock:=c10_demo.post_stock_event(p_destination,v_lot.item_id,p_quantity,v_key);
 INSERT INTO c10_demo.quality_movements_v1
 (tenant_id,business_id,site_id,location_id,item_id,lot_id,command_id,stock_movement_id,kind,delta,actor_id)
 VALUES(v_lot.tenant_id,v_lot.business_id,v_dst.site_id,p_destination,v_lot.item_id,p_lot,
 v_cmd,v_stock,'transfer_in',p_quantity,c10_demo.actor_uid());
 UPDATE c10_demo.quality_balances_v1 SET on_hand=on_hand-p_quantity WHERE location_id=p_source AND lot_id=p_lot;
 UPDATE c10_demo.quality_balances_v1 SET on_hand=on_hand+p_quantity WHERE location_id=p_destination AND lot_id=p_lot;
 UPDATE c10_demo.quality_commands_v1 SET result_id=v_id WHERE id=v_cmd;
 INSERT INTO c10_demo.quality_audit_v1(tenant_id,business_id,lot_id,operation,command_id,actor_id,context)
 VALUES(v_lot.tenant_id,v_lot.business_id,p_lot,'transfer',v_cmd,c10_demo.actor_uid(),
 jsonb_build_object('from',p_source,'to',p_destination,'qty',p_quantity));
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.quality_link_genealogy_v1(p_parent bigint,p_child bigint,p_key text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_parent record;v_child record;v_cmd bigint;
BEGIN
 -- Serialize graph writes per business to prevent concurrent cycle creation.
 SELECT * INTO v_parent FROM c10_demo.quality_lots_v1 WHERE id=p_parent;
 SELECT * INTO v_child FROM c10_demo.quality_lots_v1 WHERE id=p_child;
 IF v_parent.business_id IS NULL OR v_child.business_id IS DISTINCT FROM v_parent.business_id OR
 v_child.tenant_id IS DISTINCT FROM v_parent.tenant_id OR p_parent=p_child OR
 NOT c10_demo.can_manage(v_parent.tenant_id,v_parent.business_id)
 THEN RAISE EXCEPTION 'quality_genealogy_scope_denied'; END IF;
 PERFORM pg_advisory_xact_lock(1058,v_parent.business_id::integer);
 v_cmd:=c10_demo.quality_claim_v1(v_parent.tenant_id,v_parent.business_id,'link',p_key,
  jsonb_build_object('parent',p_parent,'child',p_child));
 IF v_cmd<0 THEN RETURN p_child; END IF;
 -- An active/closed recall permanently locks recalled lineage: a late new link
 -- must not create an unblocked descendant after the recall snapshot.
 IF EXISTS(SELECT 1 FROM c10_demo.quality_lots_v1
  WHERE id IN (p_parent,p_child) AND status='recalled')
 THEN RAISE EXCEPTION 'quality_recalled_lineage_locked'; END IF;
 IF EXISTS(
  WITH RECURSIVE descendants(id) AS (
   SELECT p_child UNION SELECT g.child_lot_id FROM c10_demo.quality_genealogy_v1 g
   JOIN descendants d ON g.parent_lot_id=d.id
  ) SELECT 1 FROM descendants WHERE id=p_parent)
 THEN RAISE EXCEPTION 'quality_genealogy_cycle'; END IF;
 INSERT INTO c10_demo.quality_genealogy_v1
 (tenant_id,business_id,parent_lot_id,child_lot_id,created_by)
 VALUES(v_parent.tenant_id,v_parent.business_id,p_parent,p_child,c10_demo.actor_uid());
 UPDATE c10_demo.quality_commands_v1 SET result_id=p_child WHERE id=v_cmd;
 INSERT INTO c10_demo.quality_audit_v1(tenant_id,business_id,lot_id,operation,command_id,actor_id,context)
 VALUES(v_parent.tenant_id,v_parent.business_id,p_child,'genealogy_link',v_cmd,c10_demo.actor_uid(),
 jsonb_build_object('parent',p_parent));
 RETURN p_child;
END $$;

CREATE FUNCTION c10_demo.quality_start_recall_v1(
 p_root bigint,p_severity text,p_reason text,p_key text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_lot record;v_cmd bigint;v_id bigint;v_count integer;
BEGIN
 SELECT * INTO v_lot FROM c10_demo.quality_lots_v1 WHERE id=p_root;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_lot.tenant_id,v_lot.business_id)
 THEN RAISE EXCEPTION 'quality_recall_owner_required'; END IF;
 IF p_severity NOT IN('internal','customer','critical') OR p_reason IS NULL OR
 length(btrim(p_reason)) NOT BETWEEN 5 AND 1000 THEN RAISE EXCEPTION 'quality_invalid_recall'; END IF;
 PERFORM pg_advisory_xact_lock(1058,v_lot.business_id::integer);
 v_cmd:=c10_demo.quality_claim_v1(v_lot.tenant_id,v_lot.business_id,'recall',p_key,
  jsonb_build_object('root',p_root,'severity',p_severity,'reason',p_reason));
 IF v_cmd<0 THEN SELECT result_id INTO v_id FROM c10_demo.quality_commands_v1 WHERE id=-v_cmd; RETURN v_id; END IF;
 INSERT INTO c10_demo.quality_recalls_v1(tenant_id,business_id,root_lot_id,reason,severity,created_by)
 VALUES(v_lot.tenant_id,v_lot.business_id,p_root,p_reason,p_severity,c10_demo.actor_uid())
 RETURNING id INTO v_id;
 -- All downstream descendants are blocked, not only the root's current location.
 WITH RECURSIVE descendants(id) AS (
  SELECT p_root UNION SELECT g.child_lot_id FROM c10_demo.quality_genealogy_v1 g
   JOIN descendants d ON g.parent_lot_id=d.id WHERE g.business_id=v_lot.business_id
 )
 INSERT INTO c10_demo.quality_recall_impacts_v1(recall_id,tenant_id,business_id,lot_id)
 SELECT v_id,v_lot.tenant_id,v_lot.business_id,id FROM descendants;
 UPDATE c10_demo.quality_lots_v1 SET status='recalled',updated_at=clock_timestamp()
 WHERE id IN(SELECT lot_id FROM c10_demo.quality_recall_impacts_v1 WHERE recall_id=v_id);
 UPDATE c10_demo.quality_commands_v1 SET result_id=v_id WHERE id=v_cmd;
 SELECT count(*) INTO v_count FROM c10_demo.quality_recall_impacts_v1 WHERE recall_id=v_id;
 INSERT INTO c10_demo.quality_audit_v1(tenant_id,business_id,lot_id,operation,command_id,actor_id,context)
 VALUES(v_lot.tenant_id,v_lot.business_id,p_root,'recall',v_cmd,c10_demo.actor_uid(),
 jsonb_build_object('affected_lots',v_count,'severity',p_severity,'reason',p_reason));
 RETURN v_id;
END $$;

CREATE FUNCTION c10_demo.quality_close_recall_v1(p_recall bigint,p_key text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_recall record;v_cmd bigint;
BEGIN
 SELECT * INTO v_recall FROM c10_demo.quality_recalls_v1 WHERE id=p_recall FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(v_recall.tenant_id,v_recall.business_id)
 THEN RAISE EXCEPTION 'quality_recall_owner_required'; END IF;
 v_cmd:=c10_demo.quality_claim_v1(v_recall.tenant_id,v_recall.business_id,'close_recall',p_key,
 jsonb_build_object('recall',p_recall));
 IF v_cmd<0 THEN RETURN p_recall; END IF;
 IF v_recall.status<>'active' THEN RAISE EXCEPTION 'quality_recall_already_closed'; END IF;
 IF EXISTS(SELECT 1 FROM c10_demo.quality_recall_impacts_v1 i
  JOIN c10_demo.quality_balances_v1 b ON b.lot_id=i.lot_id
  WHERE i.recall_id=p_recall AND b.on_hand>0)
 THEN RAISE EXCEPTION 'quality_recall_stock_remaining'; END IF;
 UPDATE c10_demo.quality_recalls_v1 SET status='closed',closed_by=c10_demo.actor_uid(),
  closed_at=clock_timestamp() WHERE id=p_recall;
 UPDATE c10_demo.quality_commands_v1 SET result_id=p_recall WHERE id=v_cmd;
 INSERT INTO c10_demo.quality_audit_v1(tenant_id,business_id,lot_id,operation,command_id,actor_id)
 VALUES(v_recall.tenant_id,v_recall.business_id,v_recall.root_lot_id,'recall_close',v_cmd,c10_demo.actor_uid());
 RETURN p_recall;
END $$;

-- Scoped view: RLS applies to all underlying tables (PG 17 security_invoker).
CREATE VIEW c10_demo.quality_reconciliation_v1 WITH(security_invoker=true) AS
 SELECT s.tenant_id,s.business_id,s.site_id,s.location_id,s.item_id,
  s.on_hand AS canonical_units,COALESCE(q.quality_units,0)::numeric(15,3) AS lot_units,
  s.on_hand=COALESCE(q.quality_units,0) AS reconciled
 FROM c10_demo.stock_balances_v1 s
 JOIN c10_demo.quality_tracked_items_v1 t ON t.business_id=s.business_id AND t.item_id=s.item_id
 LEFT JOIN (
  SELECT location_id,item_id,sum(on_hand) AS quality_units
  FROM c10_demo.quality_balances_v1 GROUP BY location_id,item_id
 ) q ON q.location_id=s.location_id AND q.item_id=s.item_id;
CREATE VIEW c10_demo.quality_lot_summary_v1 WITH(security_invoker=true) AS
 SELECT l.id,l.tenant_id,l.business_id,l.item_id,l.origin_site_id,l.lot_code,l.status,l.expiry_date,
 COALESCE((SELECT sum(b.on_hand) FROM c10_demo.quality_balances_v1 b WHERE b.lot_id=l.id),0)::numeric(15,3) AS visible_units
 FROM c10_demo.quality_lots_v1 l;

CREATE FUNCTION c10_demo.quality_fefo_v1(p_business bigint,p_item bigint,p_site bigint,p_needed numeric)
RETURNS TABLE(lot_id bigint,lot_code text,expiry_date date,available numeric,suggested numeric)
LANGUAGE plpgsql SECURITY INVOKER SET search_path=c10_demo,pg_catalog AS $$
DECLARE v_tenant bigint;
BEGIN
 SELECT tenant_id INTO v_tenant FROM c10_demo.businesses WHERE id=p_business;
 IF NOT FOUND OR p_needed IS NULL OR p_needed<=0 OR p_needed<>round(p_needed,3) OR
 NOT c10_demo.can_site(v_tenant,p_business,p_site,'stock.read')
 THEN RAISE EXCEPTION 'quality_fefo_scope_denied'; END IF;
 RETURN QUERY
 WITH eligible AS (
  SELECT l.id,l.lot_code,l.expiry_date,sum(b.on_hand) AS qty
  FROM c10_demo.quality_lots_v1 l JOIN c10_demo.quality_balances_v1 b ON b.lot_id=l.id
  WHERE l.business_id=p_business AND l.item_id=p_item AND b.site_id=p_site
   AND l.status='released' AND (l.expiry_date IS NULL OR l.expiry_date>=CURRENT_DATE)
  GROUP BY l.id,l.lot_code,l.expiry_date HAVING sum(b.on_hand)>0
 ), ranked AS (
  SELECT e.*,coalesce(sum(e.qty) OVER(
   ORDER BY e.expiry_date NULLS LAST,e.id ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING),0) AS previous_qty
  FROM eligible e
 )
 SELECT r.id,r.lot_code,r.expiry_date,r.qty,
  greatest(least(r.qty,p_needed-r.previous_qty),0) FROM ranked r
 ORDER BY r.expiry_date NULLS LAST,r.id;
END $$;


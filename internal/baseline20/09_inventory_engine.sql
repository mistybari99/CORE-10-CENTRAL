CREATE FUNCTION core10._inventory_controls_v1(p_business bigint, p_kind text, p_sites bigint[], p_master jsonb) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,core10 AS $$
DECLARE i int; s bigint; m jsonb; k jsonb; v_feature text := core10._inventory_kind_feature_v1(p_kind);
 v_stages int := 0; v_max numeric := 1000000; v_staff boolean := true; v_sep boolean := false;
 v_reason boolean := false; v_cross boolean := true; v_neg boolean := false;
BEGIN
 IF jsonb_typeof(p_master)<>'array' OR jsonb_array_length(p_master)<>cardinality(p_sites) THEN RAISE EXCEPTION 'INV_CONTROL_SHAPE'; END IF;
 FOR i IN 1..cardinality(p_sites) LOOP
  s := p_sites[i]; m := p_master->(i-1);
  k := core10.control_check_v1(p_business, v_feature, s);
  v_stages := greatest(v_stages, (m->>'stages')::int, (k->>'stages')::int);
  IF p_kind IN ('adjust_in','adjust_out') THEN
   v_max := least(v_max, (m->'params'->>'max_adjust_qty')::numeric);
  ELSE
   v_max := least(v_max, (k->'params'->>'max_qty')::numeric);
  END IF;
  v_staff := v_staff AND coalesce((k->'params'->>'staff_allowed')::boolean, false);
  v_sep := v_sep OR coalesce((k->'params'->>'separate_confirmer')::boolean, false);
  v_reason := v_reason OR coalesce((k->'params'->>'reason_required')::boolean, false);
  v_cross := v_cross AND coalesce((k->'params'->>'allow_cross_site')::boolean, true);
  v_neg := v_neg OR coalesce((m->'params'->>'allow_negative_stock')::boolean, false);
 END LOOP;
 RETURN jsonb_build_object('stages',v_stages,'max_qty',v_max,'staff_allowed',v_staff,'separate_confirmer',v_sep,
  'reason_required',v_reason,'allow_cross_site',v_cross,'allow_negative_stock',v_neg);
END $$;


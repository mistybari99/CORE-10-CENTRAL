CREATE FUNCTION c10_demo.a056_validate_config(c jsonb) RETURNS void LANGUAGE plpgsql STABLE AS $f$
#variable_conflict use_column
DECLARE s jsonb; codes text[]:=ARRAY[]::text[]; k text; v text; won int:=0; lost int:=0; n int; x numeric;
BEGIN
 IF c IS NULL OR jsonb_typeof(c)<>'object' THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
 IF jsonb_typeof(c->'stages')<>'array' OR jsonb_array_length(c->'stages') NOT BETWEEN 2 AND 12 THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
 FOR s IN SELECT * FROM jsonb_array_elements(c->'stages') LOOP
  IF jsonb_typeof(s)<>'object' OR (s->>'code') IS NULL OR (s->>'code') !~ '^[a-z][a-z0-9_]{1,30}$' OR
     COALESCE(length(s->>'label'),0) NOT BETWEEN 1 AND 60 OR (s->>'kind') NOT IN('open','won','lost') OR
     (s->>'code')=ANY(codes) OR (s->'approval') IS NOT NULL AND jsonb_typeof(s->'approval')<>'boolean'
  THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
  codes:=codes||(s->>'code');
  IF s->>'kind'='won' THEN won:=won+1; ELSIF s->>'kind'='lost' THEN lost:=lost+1; END IF;
 END LOOP;
 IF won<>1 OR lost<>1 OR (c->'stages'->0->>'kind')<>'open' THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
 IF jsonb_typeof(c->'permissions')<>'object' THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
 FOR k,v IN SELECT key,value FROM jsonb_each_text(c->'permissions') LOOP
  IF NOT k=ANY(c10_demo.a056_known_actions()) OR v NOT IN('owner','manager','site') THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
 END LOOP;
 -- security/consent/financial invariants cannot be weakened by configuration
 IF c->'permissions'->>'settings.write'<>'owner' OR c->'permissions'->>'customer.redact'<>'owner' OR
    c->'permissions'->>'finance.register'<>'owner' OR
    COALESCE(c->'permissions'->>'consent.lift_suppression','manager') NOT IN('owner','manager') OR
    COALESCE(c->'permissions'->>'quote.approve','manager')='site' AND FALSE
 THEN RAISE EXCEPTION 'A056_CONFIG_INVARIANT'; END IF;
 IF jsonb_typeof(c->'approval')<>'object' THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
 IF (c->'approval'->>'discount_pct_over') IS NOT NULL THEN
  x:=(c->'approval'->>'discount_pct_over')::numeric; IF x<0 OR x>100 THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF; END IF;
 IF (c->'approval'->>'total_over') IS NOT NULL THEN
  x:=(c->'approval'->>'total_over')::numeric; IF x<0 THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF; END IF;
 IF jsonb_typeof(c->'sla')<>'object' THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
 FOREACH k IN ARRAY ARRAY['urgent','standard','low'] LOOP
  x:=(c->'sla'->>k)::numeric; IF x IS NULL OR x<1 OR x>2160 THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF; END LOOP;
 IF jsonb_typeof(c->'loyalty')<>'object' OR jsonb_typeof(c->'loyalty'->'enabled')<>'boolean' OR
    (c->'loyalty'->>'points_per_100')::numeric NOT BETWEEN 0 AND 1000 THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
 IF jsonb_typeof(c->'intake')<>'object' OR (c->'intake'->>'default_rate_limit_per_hour')::int NOT BETWEEN 1 AND 10000
 THEN RAISE EXCEPTION 'A056_CONFIG_INVALID'; END IF;
EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range OR null_value_not_allowed OR invalid_parameter_value
 THEN RAISE EXCEPTION 'A056_CONFIG_INVALID';
END $f$;


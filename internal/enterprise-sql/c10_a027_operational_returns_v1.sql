-- C10-A027: atomic, bounded sale/purchase returns; disposable CI only.
-- Financial refunds and credit notes are NOT performed here.
CREATE TABLE c10_demo.operational_returns_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 source_document_id bigint NOT NULL REFERENCES c10_demo.operational_documents_v1(id),
 kind text NOT NULL CHECK(kind IN ('sale_return','purchase_return')),
 reason text NOT NULL CHECK(length(btrim(reason)) BETWEEN 5 AND 500),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 120),
 lines jsonb NOT NULL CHECK(jsonb_typeof(lines)='object' AND jsonb_typeof(lines->'lines')='array'),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','approved','posted')),
 created_by uuid NOT NULL,
 approved_by uuid,
 approved_at timestamptz,
 posted_by uuid,
 posted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(business_id,tenant_id) REFERENCES c10_demo.businesses(id,tenant_id),
 CHECK((status='draft' AND approved_by IS NULL AND posted_by IS NULL)
   OR (status='approved' AND approved_by IS NOT NULL AND posted_by IS NULL)
   OR (status='posted' AND approved_by IS NOT NULL AND posted_by IS NOT NULL))
);
CREATE TABLE c10_demo.operational_return_lines_v1(
 return_id bigint NOT NULL REFERENCES c10_demo.operational_returns_v1(id),
 document_id bigint NOT NULL REFERENCES c10_demo.operational_documents_v1(id),
 line_no integer NOT NULL,
 item_id bigint NOT NULL,
 quantity numeric(15,3) NOT NULL CHECK(quantity>0),
 PRIMARY KEY(return_id,line_no)
);
ALTER TABLE c10_demo.operational_returns_v1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE c10_demo.operational_return_lines_v1 ENABLE ROW LEVEL SECURITY;
CREATE POLICY return_business_read_v1 ON c10_demo.operational_returns_v1
 FOR SELECT TO authenticated USING(c10_demo.can_business(tenant_id,business_id));
CREATE POLICY return_lines_read_v1 ON c10_demo.operational_return_lines_v1
 FOR SELECT TO authenticated USING(EXISTS(
  SELECT 1 FROM c10_demo.operational_returns_v1 r
  WHERE r.id=return_id AND c10_demo.can_business(r.tenant_id,r.business_id)
 ));
REVOKE ALL ON c10_demo.operational_returns_v1,c10_demo.operational_return_lines_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.operational_returns_v1,c10_demo.operational_return_lines_v1 TO authenticated;

CREATE FUNCTION c10_demo.create_operational_return_v1(
 p_document bigint,p_lines jsonb,p_reason text,p_request text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE d c10_demo.operational_documents_v1%ROWTYPE;
 v_line jsonb;v_no integer;v_qty numeric;v_item bigint;v_count integer:=0;
 v_id bigint;v_existing record;v_canonical jsonb;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_document IS NULL OR
  p_lines IS NULL OR jsonb_typeof(p_lines)<>'array' OR
  jsonb_array_length(p_lines) NOT BETWEEN 1 AND 100 OR
  p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 5 AND 500 OR
  p_request IS NULL OR length(btrim(p_request)) NOT BETWEEN 1 AND 120
 THEN RAISE EXCEPTION 'invalid_return_request'; END IF;
 SELECT * INTO d FROM c10_demo.operational_documents_v1 WHERE id=p_document;
 IF NOT FOUND OR NOT c10_demo.can_site(d.tenant_id,d.business_id,d.site_id,'stock.post')
 THEN RAISE EXCEPTION 'return_scope_denied'; END IF;
 IF d.status<>'posted' THEN RAISE EXCEPTION 'return_requires_posted_document'; END IF;
 FOR v_line IN SELECT value FROM jsonb_array_elements(p_lines) LOOP
  v_count:=v_count+1;
  IF jsonb_typeof(v_line)<>'object' OR
   (SELECT count(*) FROM jsonb_object_keys(v_line))<>2 OR
   jsonb_typeof(v_line->'line_no')<>'number' OR
   jsonb_typeof(v_line->'quantity')<>'number'
  THEN RAISE EXCEPTION 'invalid_return_line'; END IF;
  BEGIN
   v_no:=(v_line->>'line_no')::integer;
   v_qty:=(v_line->>'quantity')::numeric;
  EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range THEN
   RAISE EXCEPTION 'invalid_return_line';
  END;
  IF v_no NOT BETWEEN 1 AND 100 OR v_qty<=0 OR
    v_qty<>round(v_qty,3) OR v_qty::text IN('NaN','Infinity','-Infinity') OR
    NOT EXISTS(SELECT 1 FROM c10_demo.operational_document_lines_v1 l
     WHERE l.document_id=p_document AND l.line_no=v_no AND l.quantity>=v_qty)
  THEN RAISE EXCEPTION 'invalid_return_line'; END IF;
 END LOOP;
 IF (SELECT count(DISTINCT (v->>'line_no')::integer)
  FROM jsonb_array_elements(p_lines) v)<>v_count
 THEN RAISE EXCEPTION 'duplicate_return_line'; END IF;
 v_canonical:=jsonb_build_object('document',p_document,'lines',p_lines,
  'reason',btrim(p_reason));
 INSERT INTO c10_demo.operational_returns_v1(
  tenant_id,business_id,source_document_id,kind,reason,request_key,lines,created_by)
 VALUES(d.tenant_id,d.business_id,p_document,
  CASE WHEN d.kind='sale' THEN 'sale_return' ELSE 'purchase_return' END,
  btrim(p_reason),p_request,v_canonical,c10_demo.actor_uid())
 ON CONFLICT(business_id,request_key) DO NOTHING RETURNING id INTO v_id;
 IF v_id IS NULL THEN
  SELECT * INTO v_existing FROM c10_demo.operational_returns_v1
   WHERE business_id=d.business_id AND request_key=p_request;
  IF NOT FOUND OR v_existing.lines<>v_canonical OR
    v_existing.created_by<>c10_demo.actor_uid()
  THEN RAISE EXCEPTION 'return_idempotency_conflict'; END IF;
  RETURN v_existing.id;
 END IF;
 FOR v_line IN SELECT value FROM jsonb_array_elements(p_lines) LOOP
  v_no:=(v_line->>'line_no')::integer;
  v_qty:=(v_line->>'quantity')::numeric;
  SELECT item_id INTO v_item FROM c10_demo.operational_document_lines_v1
   WHERE document_id=p_document AND line_no=v_no;
  INSERT INTO c10_demo.operational_return_lines_v1(
   return_id,document_id,line_no,item_id,quantity)
  VALUES(v_id,p_document,v_no,v_item,v_qty);
 END LOOP;
 RETURN v_id;
END $$;
CREATE FUNCTION c10_demo.approve_operational_return_v1(p_return bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE r c10_demo.operational_returns_v1%ROWTYPE;
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_return IS NULL
 THEN RAISE EXCEPTION 'invalid_return_approval'; END IF;
 SELECT * INTO r FROM c10_demo.operational_returns_v1 WHERE id=p_return FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(r.tenant_id,r.business_id)
 THEN RAISE EXCEPTION 'return_approval_denied'; END IF;
 IF r.status='draft' THEN
  UPDATE c10_demo.operational_returns_v1 SET status='approved',
   approved_by=c10_demo.actor_uid(),approved_at=now() WHERE id=p_return;
  RETURN 'approved';
 END IF;
 RETURN r.status;
END $$;
CREATE FUNCTION c10_demo.post_operational_return_v1(p_return bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER
SET search_path=c10_demo,pg_catalog AS $$
DECLARE r c10_demo.operational_returns_v1%ROWTYPE;
 d c10_demo.operational_documents_v1%ROWTYPE;
 l c10_demo.operational_return_lines_v1%ROWTYPE;
 v_original numeric(15,3);v_prior numeric(15,3);v_delta numeric(15,3);
BEGIN
 IF c10_demo.actor_uid() IS NULL OR p_return IS NULL
 THEN RAISE EXCEPTION 'invalid_return_post'; END IF;
 SELECT * INTO r FROM c10_demo.operational_returns_v1 WHERE id=p_return FOR UPDATE;
 IF NOT FOUND OR NOT c10_demo.can_manage(r.tenant_id,r.business_id)
 THEN RAISE EXCEPTION 'return_post_denied'; END IF;
 IF r.status='posted' THEN RETURN 'posted'; END IF;
 IF r.status<>'approved' THEN RAISE EXCEPTION 'return_not_approved'; END IF;
 -- Source document serializes all return postings for one original invoice.
 SELECT * INTO d FROM c10_demo.operational_documents_v1
  WHERE id=r.source_document_id FOR UPDATE;
 IF d.status<>'posted' OR d.business_id<>r.business_id OR d.tenant_id<>r.tenant_id
 THEN RAISE EXCEPTION 'return_source_invalid'; END IF;
 IF NOT c10_demo.can_site(d.tenant_id,d.business_id,d.site_id,'stock.post')
 THEN RAISE EXCEPTION 'return_stock_permission_denied'; END IF;
 FOR l IN SELECT * FROM c10_demo.operational_return_lines_v1
  WHERE return_id=p_return ORDER BY line_no LOOP
  SELECT quantity INTO v_original FROM c10_demo.operational_document_lines_v1
   WHERE document_id=d.id AND line_no=l.line_no AND item_id=l.item_id;
  SELECT COALESCE(sum(rl.quantity),0) INTO v_prior
  FROM c10_demo.operational_return_lines_v1 rl
  JOIN c10_demo.operational_returns_v1 h ON h.id=rl.return_id
  WHERE rl.document_id=d.id AND rl.line_no=l.line_no AND h.status='posted';
  IF v_original IS NULL OR v_prior+l.quantity>v_original THEN
   RAISE EXCEPTION 'return_exceeds_original_quantity'; END IF;
  v_delta:=CASE WHEN d.kind='sale' THEN l.quantity ELSE -l.quantity END;
  PERFORM c10_demo.post_stock_event(d.location_id,l.item_id,v_delta,
   'c10-return:'||p_return||':line:'||l.line_no);
 END LOOP;
 UPDATE c10_demo.operational_returns_v1
  SET status='posted',posted_by=c10_demo.actor_uid(),posted_at=now()
  WHERE id=p_return;
 RETURN 'posted';
END $$;
CREATE VIEW c10_demo.operational_return_report_v1 WITH(security_invoker=true) AS
 SELECT d.tenant_id,d.business_id,d.id AS document_id,d.kind AS original_kind,
  r.id AS return_id,r.kind AS return_kind,r.status,r.reason,r.created_at,
  COALESCE(sum(l.quantity),0)::numeric(15,3) AS returned_units,
  false::boolean AS refund_verified
 FROM c10_demo.operational_documents_v1 d
 JOIN c10_demo.operational_returns_v1 r ON r.source_document_id=d.id
 JOIN c10_demo.operational_return_lines_v1 l ON l.return_id=r.id
 WHERE c10_demo.can_manage(d.tenant_id,d.business_id)
 GROUP BY d.tenant_id,d.business_id,d.id,d.kind,r.id,r.kind,r.status,r.reason,r.created_at;
REVOKE ALL ON c10_demo.operational_return_report_v1 FROM PUBLIC;
GRANT SELECT ON c10_demo.operational_return_report_v1 TO authenticated;
REVOKE EXECUTE ON FUNCTION c10_demo.create_operational_return_v1(bigint,jsonb,text,text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.approve_operational_return_v1(bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.post_operational_return_v1(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION c10_demo.create_operational_return_v1(bigint,jsonb,text,text) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.approve_operational_return_v1(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.post_operational_return_v1(bigint) TO authenticated;

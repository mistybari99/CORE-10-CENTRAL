-- CORE10 C10-A037 Production Costing, COGS & Inventory Valuation engine (v1)
-- DISPOSABLE PostgreSQL 17 / CI ONLY. NEVER execute on IMG-ERP-SG. Not a production migration.
-- Additive only: no existing BOM, sales, stock, returns, tax-preview, owner/finance table or function is changed.
--
-- DOCUMENTED, DETERMINISTIC COSTING RULE
--   Moving WEIGHTED-AVERAGE cost per (location, item). Every cost change is an immutable journal event;
--   c10_demo.cost_valuation_v1 is a projection that can only be changed by the posting functions below.
--   * Purchase receipt: source = a POSTED kind='purchase' operational document. Line value =
--     line amount reduced pro-rata by the document discount (last line takes the rounding remainder).
--   * Production: ingredients are issued at the current weighted average; finished goods are received at
--     (ingredient value + owner-referenced actual overhead). Variances are measured against the BOM standard.
--   * Sale COGS: quantity * current weighted average of the posted sale document's location, snapshotted.
--   * Transfer: moves value at the source average; never creates revenue or profit.
--   * Return: reverses at the ORIGINAL snapshot unit cost, bounded by the originally costed quantity.
--   BLOCK RULE: when verified source cost (a posted purchase/production cost event) does not cover the
--   quantity being issued, nothing is written and the exact reason is returned. Manual cost rates and
--   uncosted opening stock are NEVER used to certify actual COGS.
-- Precision: quantities numeric(15,3); unit cost numeric(18,6); values numeric(20,4).

CREATE TABLE c10_demo.cost_events_v1(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 location_id bigint NOT NULL,
 item_id bigint NOT NULL,
 event_type text NOT NULL CHECK(event_type IN('purchase_receipt','production_issue','production_output',
   'sale_cogs','transfer_out','transfer_in','return_reversal')),
 quantity numeric(15,3) NOT NULL CHECK(quantity<>0 AND quantity=round(quantity,3)),
 unit_cost numeric(18,6) NOT NULL CHECK(unit_cost>=0),
 value numeric(20,4) NOT NULL,
 source_type text NOT NULL CHECK(source_type IN('operational_document','production_batch','stock_transfer','operational_return')),
 source_id bigint NOT NULL,
 source_line integer NOT NULL DEFAULT 0,
 source_snapshot jsonb NOT NULL CHECK(jsonb_typeof(source_snapshot)='object'),
 request_key text NOT NULL CHECK(length(btrim(request_key)) BETWEEN 1 AND 160),
 created_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK((quantity>0 AND value>=0) OR (quantity<0 AND value<=0)),
 UNIQUE(business_id,request_key),
 UNIQUE(source_type,source_id,source_line,event_type,location_id,item_id),
 FOREIGN KEY(location_id,tenant_id,business_id,site_id)
  REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id)
);
-- Immutable ledger: no update, no delete, no truncate for ANY role (including the owner of the table).
CREATE FUNCTION c10_demo.cost_events_immutable_v1() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'cost_ledger_is_immutable' USING ERRCODE='42501'; END $$;
CREATE TRIGGER cost_events_no_change_v1 BEFORE UPDATE OR DELETE ON c10_demo.cost_events_v1
 FOR EACH ROW EXECUTE FUNCTION c10_demo.cost_events_immutable_v1();
CREATE TRIGGER cost_events_no_truncate_v1 BEFORE TRUNCATE ON c10_demo.cost_events_v1
 FOR EACH STATEMENT EXECUTE FUNCTION c10_demo.cost_events_immutable_v1();

CREATE TABLE c10_demo.cost_valuation_v1(
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 site_id bigint NOT NULL,
 location_id bigint NOT NULL,
 item_id bigint NOT NULL,
 quantity numeric(15,3) NOT NULL DEFAULT 0 CHECK(quantity>=0),
 total_value numeric(20,4) NOT NULL DEFAULT 0 CHECK(total_value>=0),
 avg_cost numeric(18,6) GENERATED ALWAYS AS
  (CASE WHEN quantity>0 THEN round(total_value/quantity,6) ELSE 0 END) STORED,
 PRIMARY KEY(location_id,item_id),
 CHECK(quantity>0 OR total_value=0),
 FOREIGN KEY(location_id,tenant_id,business_id,site_id)
  REFERENCES c10_demo.stock_locations(id,tenant_id,business_id,site_id),
 FOREIGN KEY(item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id)
);

CREATE TABLE c10_demo.production_cost_runs_v1(
 batch_id bigint PRIMARY KEY REFERENCES c10_demo.production_batches_v1(id),
 tenant_id bigint NOT NULL,
 business_id bigint NOT NULL,
 location_id bigint NOT NULL,
 finished_item_id bigint NOT NULL,
 output_quantity numeric(15,3) NOT NULL CHECK(output_quantity>0),
 ingredient_cost numeric(20,4) NOT NULL CHECK(ingredient_cost>=0),
 overhead_actual numeric(20,4) NOT NULL CHECK(overhead_actual>=0),
 overhead_reference text,
 overhead_certified boolean NOT NULL,
 total_cost numeric(20,4) NOT NULL CHECK(total_cost>=0),
 unit_cost numeric(18,6) NOT NULL CHECK(unit_cost>=0),
 standard_ingredient_cost numeric(20,4) NOT NULL,
 standard_overhead_cost numeric(20,4) NOT NULL,
 ingredient_price_variance numeric(20,4) NOT NULL,
 overhead_variance numeric(20,4) NOT NULL,
 yield_variance_qty numeric(15,3) NOT NULL,
 request_key text NOT NULL,
 created_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK((overhead_certified AND overhead_reference IS NOT NULL AND length(btrim(overhead_reference))>=3)
    OR (NOT overhead_certified AND overhead_reference IS NULL AND overhead_actual=0)),
 UNIQUE(business_id,request_key),
 FOREIGN KEY(finished_item_id,tenant_id,business_id) REFERENCES c10_demo.items(id,tenant_id,business_id)
);
CREATE TRIGGER production_cost_runs_no_change_v1 BEFORE UPDATE OR DELETE ON c10_demo.production_cost_runs_v1
 FOR EACH ROW EXECUTE FUNCTION c10_demo.cost_events_immutable_v1();

ALTER TABLE c10_demo.cost_events_v1 ENABLE ROW LEVEL SECURITY;

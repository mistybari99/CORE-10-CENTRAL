REVOKE EXECUTE ON FUNCTION c10_demo.approve_cost_rate_v1(bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.create_tax_preview_profile_v1(bigint,text,integer,text,text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION c10_demo.approve_tax_preview_profile_v1(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION c10_demo.create_cost_rate_v1(bigint,bigint,numeric,text) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.approve_cost_rate_v1(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.create_tax_preview_profile_v1(bigint,text,integer,text,text) TO authenticated;
GRANT EXECUTE ON FUNCTION c10_demo.approve_tax_preview_profile_v1(bigint) TO authenticated;
